//! 🔴 СТОРОЖ Р-7: связка ключей настоящая, а не подделка в памяти процесса.
//!
//! Подделка прожила в продукте с первого дня и не была видна ни одному из 1148 зелёных тестов.
//! `keyring` без платформенной фичи собирается с хранилищем В ПАМЯТИ ПРОЦЕССА: `set_password`
//! отвечает `Ok(())`, `get_password` в том же процессе возвращает записанное — и всё выглядит
//! исправным. Ключ машины при этом не доживал до перезапуска, а обещание §2.2.2 «ключ живёт
//! только в связке ключей ОС» было неправдой.
//!
//! ⚠️ ПОЧЕМУ ПРОВЕРКА ИМЕННО ТАКАЯ. Проверять наличие `apple-native` в `Cargo.toml` —
//! проверять запись о поведении вместо поведения. Фичу можно включить и получить другое
//! хранилище; можно сменить крейт; можно словить регресс в самом `keyring`. Единственное,
//! что здесь имеет значение, — **переживает ли значение границу процесса**.
//!
//! Поэтому тест запускает ВТОРОЙ процесс. Внутри одного любая подделка выглядит рабочей —
//! именно на этом сломалась моя первая диагностика: самопроверка писала и читала в одном
//! процессе и уверенно докладывала, что связка исправна.
//!
//! Вернётся молча при `cargo update`, смене фичи или мажорном обновлении — и снова будет
//! отвечать `Ok(())`. Этот тест — то место, где это станет видно.
//!
//! Запуск: `cargo test --release --test keychain_is_real`

use std::process::Command;

const SERVICE: &str = "plus.flamingo.desktop.selftest";
const VALUE: &str = "значение-из-первого-процесса";

/// Видит ли ЗАПИСЬ второй процесс.
///
/// Берём `security` — системную утилиту, а не второй экземпляр себя: она заведомо ходит
/// в настоящую связку, и совпадение с ней доказывает, что туда же ходил и `keyring`.
///
/// ⚠️ Спрашиваем про СУЩЕСТВОВАНИЕ, а не про значение. `-w` выдаёт секрет и потому требует
/// разрешения владельца связки: в CI и в неинтерактивном прогоне он молча отказывает, и тест
/// краснеет всегда — на исправной связке тоже. Первая версия была написана с `-w` и падала
/// именно так. Существование записи различает настоящую связку и подделку столь же надёжно:
/// подделка не создаёт записи вовсе.
fn exists_in_another_process(account: &str) -> bool {
    Command::new("/usr/bin/security")
        .args(["find-generic-password", "-s", SERVICE, "-a", account])
        .output()
        .map(|o| o.status.success())
        .unwrap_or(false)
}

fn entry(account: &str) -> keyring::Entry {
    keyring::Entry::new(SERVICE, account).expect("Entry::new не должен отказывать")
}

/// ⚠️ У каждого теста СВОЙ аккаунт. Общий на всех делал тесты зависимыми от порядка: они идут
/// параллельно, и `cleanup` одного стирал запись, которую только что сделал другой. Первая
/// версия падала и на этом тоже — тест, мешающий сам себе, доказывает не больше, чем зелёный
/// на пустом множестве.
fn cleanup(account: &str) {
    let _ = entry(account).delete_credential();
    let _ = Command::new("/usr/bin/security")
        .args(["delete-generic-password", "-s", SERVICE, "-a", account])
        .output();
}

#[test]
fn written_value_survives_the_process_boundary() {
    let acct = "survives";
    cleanup(acct);
    entry(acct).set_password(VALUE).expect("запись в связку должна проходить");

    let seen = exists_in_another_process(acct);

    cleanup(acct);
    assert!(
        seen,
        "\n🔴 СВЯЗКА КЛЮЧЕЙ — ПОДДЕЛКА.\n\
         `keyring` ответил `Ok(())`, но другой процесс записи НЕ ВИДИТ.\n\
         Значит ключ машины живёт в памяти процесса и не переживёт перезапуск: \
         приложение перестанет быть связанной машиной, а урок ведётся именно с неё.\n\
         Причина почти наверняка в фиче крейта — на macOS нужна `apple-native`:\n\
             keyring = {{ version = \"3\", features = [\"apple-native\"] }}\n\
         Проверьте `Cargo.toml` и то, что `cargo update` не увёл крейт на мажор без неё."
    );
}

#[test]
fn deletion_is_visible_from_another_process_too() {
    // Обратная сторона: если удаление «удаётся» только внутри процесса, то отзыв ключа на
    // этой машине (§19.4, кнопка для украденного ноутбука) ничего не отзывает.
    let acct = "deletion";
    cleanup(acct);
    entry(acct).set_password(VALUE).expect("запись");
    assert!(exists_in_another_process(acct), "предусловие: запись видна снаружи");

    entry(acct).delete_credential().expect("удаление");

    assert!(
        !exists_in_another_process(acct),
        "\n🔴 Удаление не дошло до связки: «Отозвать» на этой машине ничего не отзывает."
    );
    cleanup(acct);
}

#[test]
fn the_probe_itself_can_fail() {
    // Страховка от зелени на сломанном инструменте: если бы `security` всегда отвечал «нет»,
    // проверка удаления проходила бы идеально и не значила бы ничего.
    let acct = "probe";
    cleanup(acct);
    assert!(
        !exists_in_another_process(acct),
        "перед записью читателю нечего находить — иначе он читает не то, что мы пишем"
    );
    entry(acct).set_password(VALUE).expect("запись");
    assert!(
        exists_in_another_process(acct),
        "после записи читатель обязан находить: иначе он не умеет находить вовсе"
    );
    cleanup(acct);
}
