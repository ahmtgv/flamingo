#!/bin/bash
# 🔴 ОДНА ВЕРСИЯ ПРИЛОЖЕНИЯ — ЖЁСТКО (решение владельца §39.1, наряд 37 §2).
#
# ЧТО ЭТО ЧИНИТ. Трижды за 18.08 в Launchpad оказывались ДВА одинаковых значка: сборка
# оставляет `.app` в каталоге репозитория, Spotlight его индексирует, и система выбирает из
# двух наугад. Владелец дважды открывал вчерашнюю версию, не зная об этом, — и мы дважды
# искали дефекты в коде, которого в его окне не было.
#
# Память тут не помогает: «не забыть запустить install.sh» — это ровно то, что забывают.
# Поэтому копия из репозитория убирается сборкой, а проверка «копий ровно одна» роняет её.
#
# Запуск: bash desktop/one-version.sh [--fix]
#   без ключа — только проверить и назвать все копии;
#   --fix     — убрать копию из каталога сборки (образ .dmg при этом остаётся).

set -uo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BUILT="$REPO/desktop/src-tauri/target/release/bundle/macos/Flamingo.app"

if [ "${1:-}" = "--fix" ] && [ -d "$BUILT" ]; then
  rm -rf "$BUILT"
  echo "  копия из каталога сборки убрана — запускаемой копии в репозитории не осталось"
fi

# Ищем ДВУМЯ способами: Spotlight знает про то, что видит Launchpad, но индекс отстаёт и
# каталоги вне индекса (например `target/`) в него могут не попасть вовсе. Поэтому к нему
# добавлены места, где копия появляется по нашей же вине.
copies=$(
  {
    mdfind "kMDItemFSName == 'Flamingo.app'" 2>/dev/null
    for path in /Applications/Flamingo.app "$HOME/Applications/Flamingo.app" "$BUILT"; do
      [ -d "$path" ] && echo "$path"
    done
  } | sort -u
)
count=$(printf '%s\n' "$copies" | grep -c . )

echo "── Копий приложения на машине: $count ───────"
printf '%s\n' "$copies" | sed 's/^/  /'

if [ "$count" -eq 1 ]; then
  exit 0
fi

echo
if [ "$count" -eq 0 ]; then
  echo "  ⚠️ Установленной копии нет. Поставить:  bash desktop/install.sh"
  exit 0
fi

echo "  ✗ Копий больше одной. Система выберет наугад, и владелец откроет неизвестно какую —"
echo "    именно так 18.08 дважды искали дефекты в коде, которого в его окне не было."
echo
echo "  Убрать лишние и поставить свежую:  bash desktop/install.sh"
exit 1
