/** Караул: два занятия в дне не могут выглядеть одинаково.
 *
 *  🔴 ЗАЧЕМ. Шапка журнала — единственное, чем столбцы различаются: строк
 *  много, столбцов много, а подписан столбец двумя короткими строками. Если две
 *  подписи совпали, точка «был» перестаёт значить что-либо конкретное: видно,
 *  что человек был, и не видно, на каком из двух занятий (ПРАВИЛА 4.11).
 *
 *  Правило «один в дне — день недели, несколько — время» стояло с 02.09 и
 *  разваливалось на двух занятиях в ОДНО время. Найдено 08.09 на боевом:
 *  «Алгеьра» и «Проверка связи», оба 02.09 в 00:00 — два одинаковых столбца.
 *
 *  Караул проверяет не текст подписи, а её СВОЙСТВО: внутри одного дня подписи
 *  обязаны быть разными. Так он переживёт любую смену формулировок и не
 *  превратится в список ожидаемых строк.
 *
 *      node scripts/столбец-check.mjs
 */

import { подписьСтолбца } from '../src/lib/datetime.ts'

const ДНИ = ['вс', 'пн', 'вт', 'ср', 'чт', 'пт', 'сб']

const дни = [
  ['одно занятие в дне',
    [{ время: '10:00', название: 'Алгебра' }], 'вт'],
  ['два, время разное',
    [{ время: '10:00', название: 'Алгебра' }, { время: '15:00', название: 'Геометрия' }], 'ср'],
  ['два, время ОДНО — тот самый случай с боевого',
    [{ время: '00:00', название: 'Алгеьра' }, { время: '00:00', название: 'Проверка связи' }], 'ср'],
  ['три, из них два в одно время',
    [{ время: '00:00', название: 'Алгеьра' }, { время: '00:00', название: 'Проверка связи' },
     { время: '10:00', название: 'Химия' }], 'ср'],
  ['полные двойники: совпало всё',
    [{ время: '09:00', название: 'Химия' }, { время: '09:00', название: 'Химия' }], 'чт'],
  ['три полных двойника',
    [{ время: '09:00', название: 'Химия' }, { время: '09:00', название: 'Химия' },
     { время: '09:00', название: 'Химия' }], 'чт'],
  ['пусто',
    [], 'пт'],
]

let плохо = 0
console.log('\nПодписи столбцов журнала: внутри дня они разные?\n')
for (const [имя, вДне, день] of дни) {
  const подписи = вДне.map((_, i) => подписьСтолбца(вДне, i, день))
  const разных = new Set(подписи).size
  const ок = разных === вДне.length
  if (!ок) плохо += 1
  console.log(`  ${ок ? '✅' : '❌'} ${имя}`)
  console.log(`      ${подписи.length ? подписи.map((п) => `«${п}»`).join('  ') : '— столбцов нет —'}`)
}

/* Отдельно: подпись обязана быть непустой. Пустая строка «различает» столбцы
   не хуже любой другой, и множество выше её пропустит — а на экране это дырка. */
for (const [имя, вДне, день] of дни) {
  for (let i = 0; i < вДне.length; i += 1) {
    const п = подписьСтолбца(вДне, i, день)
    if (!п || !п.trim()) { плохо += 1; console.log(`  ❌ ${имя}: подпись ${i + 1} пустая`) }
  }
}

/* И обратная сторона: там, где различать нечего, день недели должен уцелеть —
   иначе правило «починили» ценой того, ради чего оно писалось. */
const один = подписьСтолбца([{ время: '10:00', название: 'Алгебра' }], 0, 'вт')
const деньЖив = один === 'вт'
if (!деньЖив) плохо += 1
console.log(`\n  ${деньЖив ? '✅' : '❌'} в дне одно занятие — стоит день недели («${один}»)`)
console.log(`  ${ДНИ.includes(один) ? '✅' : '❌'} и это настоящий день недели`)

if (плохо) {
  console.log('\n❌ столбцы журнала неразличимы: точка «был» не говорит, на каком занятии\n')
  process.exit(1)
}
console.log('\n✅ в каждом дне все подписи разные и непустые\n')
