/* Караул перехода на ПЕРГАМЕНТ.
 *
 * 🔴 ЗАЧЕМ ОН НУЖЕН ИМЕННО СЕЙЧАС. Экраны переводятся ПО ОДНОМУ (§3а), значит
 *    два закона живут в продукте одновременно, и самый вероятный дефект перехода —
 *    не «сломалось», а «наполовину». Экран, где половина цветов из `tokens.css`,
 *    а половина из `пергамент.css`, СОБИРАЕТСЯ, ЗАПУСКАЕТСЯ и выглядит почти
 *    правильно: холодный серый рядом с тёплым пергаментом глаз замечает не сразу,
 *    а через неделю, когда таких мест уже двадцать. Ни компилятор, ни браузер,
 *    ни guard-check про это не скажут ни слова — оба имени существуют.
 *
 * 🔴 ЧТО ИМЕННО МЕРЯЕТСЯ. Три вещи, и все три — не вкус, а буква языка:
 *      1. СМЕШЕНИЕ ЗАКОНОВ. Под пергаментом старых `--color-*`, `--space-*`,
 *         `--radius-*`, `--text-*`, `--weight-*`, `--shadow-*` быть не должно.
 *      2. ПОЛУЖИРНОГО НЕТ. «Заголовки шепчут»: вес 400 и 500, больше нечего взять.
 *         Это единственная ошибка языка, которую видно даже непривычному глазу.
 *      3. ТАБЛЕТОК НЕТ. Скругление 4, у окон 8. Всё круглее — либо кружок
 *         (аватар, точка: `50%`), либо таблетка, а таблетка ломает ощущение бумаги.
 *
 * 🔴 ЧЕГО КАРАУЛ НЕ ДЕЛАЕТ. Он не решает, красиво ли. Контраст, акценты и
 *    геометрию меряет `docs/дизайн/листы/audit.js` в браузере — там видно
 *    вычисленный цвет, здесь только текст файла.
 *
 * 🔴 ГЕОМЕТРИЯ ПАЛЬЦА ОСТАЁТСЯ СТАРОЙ И ЭТО РЕШЕНИЕ, А НЕ НЕДОСМОТР.
 *    `--tap-min` и `--control-height-*` живут в `tokens.css` и разрешены здесь
 *    списком. Cursor — настольный инструмент для взрослых; Flamingo открывают
 *    дети, часто с планшета. Размер цели нажатия — физиология, а не язык, и
 *    вместе с палитрой он не менялся.
 *
 * Запуск:  node scripts/пергамент-check.mjs [--selftest]
 */
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { join, dirname, resolve, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const SRC = join(ROOT, 'src')

/* 🔴 КОММЕНТАРИЙ — НЕ КОД, И ЭТОТ УРОК ЗДЕСЬ УЖЕ ОПЛАЧЕН ДВАЖДЫ. `ведущий-check`
   в прошлый раз обругал `useRoom.ts` за слово `withLead` в объяснении, почему
   этой функции больше нет. Здесь то же самое: `main.tsx` в комментарии пишет
   «экран не помечен data-язык="пергамент"» — и караул объявил переведённым
   ВЕСЬ продукт, 1953 «дефекта» на ровном месте.
   Вырезаем комментарии ПРОБЕЛАМИ, сохраняя переводы строк: номера строк в
   отчёте обязаны совпадать с файлом, иначе по отчёту нельзя открыть место.
   Построчная регулярка тут не годится — она не видит многострочный комментарий. */
export function безКомментариев(текст) {
  let out = ''
  let i = 0
  const пусто = (кусок) => кусок.replace(/[^\n]/g, ' ')
  while (i < текст.length) {
    const б = текст.indexOf('/' + '*', i)
    // `//` внутри `https://` — не комментарий: перед ним стоит двоеточие
    let л = текст.indexOf('//', i)
    while (л > 0 && текст[л - 1] === ':') л = текст.indexOf('//', л + 2)
    if (б === -1 && л === -1) return out + текст.slice(i)
    if (б !== -1 && (л === -1 || б < л)) {
      const к = текст.indexOf('*' + '/', б + 2)
      out += текст.slice(i, б)
      if (к === -1) return out + пусто(текст.slice(б))
      out += пусто(текст.slice(б, к + 2))
      i = к + 2
    } else {
      const к = текст.indexOf('\n', л)
      out += текст.slice(i, л)
      if (к === -1) return out + пусто(текст.slice(л))
      out += пусто(текст.slice(л, к))
      i = к
    }
  }
  return out
}

/* Признак переведённого экрана — `data-язык="пергамент"` на его корне.
   Перечня переведённых экранов НЕТ намеренно: перечень забывают пополнить,
   и караул тихо перестаёт смотреть ровно туда, куда только что переехали. */
export const ПРИЗНАК = /data-язык\s*=\s*(?:["']пергамент["']|\{\s*["']пергамент["']\s*\})/u

/* Имена, которые остаются от старого закона по решению, а не по недосмотру. */
export const ОСТАВЛЕНЫ = new Set(['--tap-min', '--control-height-sm', '--control-height-md', '--control-height-lg'])

const ЧУЖОЙ = /var\((--(?:color|space|radius|text|weight|tracking|shadow|font|leading|fl)-[\w-]+)/gu
const ЖИРНЫЙ = /font-weight\s*:\s*(600|700|800|900|bold|bolder)\b|var\(--weight-(bold|semibold)\)/giu
const СКРУГЛЕНИЕ = /border-radius\s*:\s*([^;}]+)/giu

/** Осмотр одного файла стилей. Возвращает список дефектов строками. */
export function осмотр(имя, css) {
  const беды = []
  const строки = безКомментариев(css).split('\n')
  строки.forEach((чисто, i) => {
    const n = i + 1

    /* 🔴 ОДНА БЕДА — ОДНА СТРОКА ОТЧЁТА. `var(--weight-bold)` подходит под оба
       правила сразу: это и чужой токен, и полужирный. Прибор, который считает
       одно место дважды, врёт числом — а числу и верят. Точное объяснение
       («полужирный») перекрывает общее («чужой токен») для того же имени. */
    const чужие = new Set()
    for (const m of чисто.matchAll(ЧУЖОЙ)) if (!ОСТАВЛЕНЫ.has(m[1])) чужие.add(m[1])
    for (const m of чисто.matchAll(ЖИРНЫЙ)) {
      if (m[2]) чужие.delete(`--weight-${m[2]}`)
      беды.push(`${имя}:${n} — полужирный ${m[0].trim()}: у пергамента вес 400 и 500, иерархию несёт кегль`)
    }
    for (const имяТокена of чужие) беды.push(`${имя}:${n} — под пергаментом взят токен старого закона: ${имяТокена}`)
    for (const m of чисто.matchAll(СКРУГЛЕНИЕ)) {
      const значение = m[1].trim()
      if (/50%/.test(значение)) continue // кружок: аватар, точка состояния
      for (const px of значение.matchAll(/(\d+(?:\.\d+)?)px/g)) {
        if (Number(px[1]) > 8) беды.push(`${имя}:${n} — скругление ${px[0]}: у пергамента 4, у окон 8, таблеток нет`)
      }
    }
  })
  return беды
}

/* ── обход дерева ──────────────────────────────────────────────────────────── */

function walk(dir, out = []) {
  for (const nm of readdirSync(dir)) {
    const p = join(dir, nm)
    if (statSync(p).isDirectory()) walk(p, out)
    else out.push(p)
  }
  return out
}

const СУФФИКСЫ = ['', '.tsx', '.ts', '/index.tsx', '/index.ts']

/**
 * Модули стилей, до которых экран дотягивается через ввоз. Считаем по графу,
 * а не по соседству имён: панель переписки лежит в другой папке, но входит в
 * кабинет — и её стили под пергаментом такие же переведённые, как свои.
 */
export function модулиЭкрана(входТsx, читать, есть) {
  const собрано = new Set()
  const пройдено = new Set()
  const очередь = [входТsx]
  while (очередь.length) {
    const путь = очередь.pop()
    if (пройдено.has(путь)) continue
    пройдено.add(путь)
    const текст = читать(путь)
    if (текст == null) continue
    for (const m of текст.matchAll(/from\s+['"](\.[^'"]*)['"]/g)) {
      const цель = resolve(dirname(путь), m[1])
      if (цель.endsWith('.module.css')) { собрано.add(цель); continue }
      if (/\.css$/.test(цель)) continue
      const найден = СУФФИКСЫ.map((с) => цель + с).find((к) => есть(к))
      if (найден) очередь.push(найден)
    }
  }
  return собрано
}

function run() {
  const файлы = walk(SRC)
  const набор = new Set(файлы)
  const читать = (п) => (набор.has(п) ? readFileSync(п, 'utf8') : null)
  const есть = (п) => набор.has(п)

  const экраны = файлы.filter((ф) => ф.endsWith('.tsx') && ПРИЗНАК.test(безКомментариев(readFileSync(ф, 'utf8'))))
  if (!экраны.length) {
    console.log('ok · переведённых экранов пока нет (признак data-язык="пергамент" не встретился)')
    return
  }

  const модули = new Set()
  for (const э of экраны) for (const м of модулиЭкрана(э, читать, есть)) модули.add(м)

  const беды = []
  for (const м of модули) беды.push(...осмотр(relative(ROOT, м), readFileSync(м, 'utf8')))

  if (беды.length) {
    console.error(`ДЕФЕКТ · ${беды.length}\n`)
    беды.forEach((б) => console.error('  ' + б))
    process.exit(1)
  }
  console.log(`ok · экранов под пергаментом ${экраны.length}, модулей осмотрено ${модули.size}`)
}

/* ── самопроверка: подкладываем СТАРОЕ поведение и требуем красного ─────────── */

function selftest() {
  const случаи = [
    ['чужой токен', '.x { color: var(--color-text); }', 1],
    ['свой токен', '.x { color: var(--п-текст); }', 0],
    ['оставленный по решению', '.x { min-height: var(--tap-min); }', 0],
    ['полужирный числом', '.x { font-weight: 600; }', 1],
    ['полужирный словом', '.x { font-weight: bold; }', 1],
    ['полужирный токеном', '.x { font-weight: var(--weight-bold); }', 1],
    ['средний вес', '.x { font-weight: var(--п-вес-средний); }', 0],
    ['таблетка', '.x { border-radius: 999px; }', 1],
    ['скругление окна', '.x { border-radius: var(--п-скругление-окно); }', 0],
    ['скругление числом в норме', '.x { border-radius: 4px; }', 0],
    ['кружок', '.x { border-radius: 50%; }', 0],
    ['старый закон в комментарии', '/* было var(--color-text) и 999px */', 0],
    ['старый закон в ПРОДОЛЖЕНИИ комментария', '/* было\n   var(--color-text) и 999px\n   вот так */', 0],
    ['код после закрытия комментария', '/* было\n   иначе */ .x { border-radius: 999px; }', 1],
  ]
  let плохо = 0
  for (const [имя, текст, ждали] of случаи) {
    const было = осмотр('образец', текст).length
    const ок = было === ждали
    if (!ок) плохо += 1
    console.log(`${ок ? 'ok  ' : 'ПЛОХО'} ${имя}: ждали ${ждали}, получили ${было}`)
  }

  /* Граф ввоза: экран обязан дотянуться до модуля соседа через посредника. */
  const дерево = {
    '/п/Экран.tsx': `import s from './Экран.module.css'\nimport Панель from '../общее/Панель'`,
    '/п/Экран.module.css': '',
    '/общее/Панель.tsx': `import s from './Панель.module.css'`,
    '/общее/Панель.module.css': '',
    '/п/Чужой.module.css': '',
  }
  const собрано = модулиЭкрана('/п/Экран.tsx', (п) => дерево[п] ?? null, (п) => п in дерево)
  const графОк = собрано.has('/п/Экран.module.css') && собрано.has('/общее/Панель.module.css') && собрано.size === 2
  console.log(`${графОк ? 'ok  ' : 'ПЛОХО'} граф ввоза: ждали свой и соседний модуль, получили ${[...собрано].join(' ')}`)
  if (!графОк) плохо += 1

  /* Ровно тот образец, на котором караул опозорился: признак ВНУТРИ комментария. */
  const вКомментарии = `/* экран не помечен data-язык="пергамент", они только в сборке */`
  const признакОк =
    ПРИЗНАК.test(безКомментариев('<div data-язык="пергамент">')) &&
    !ПРИЗНАК.test(безКомментариев('<div data-язык="воздух">')) &&
    !ПРИЗНАК.test(безКомментариев(вКомментарии)) &&
    !ПРИЗНАК.test(безКомментариев('// сюда придёт data-язык="пергамент"')) &&
    безКомментариев('a\n/* два\n   ряда */\nb').split('\n').length === 4 &&
    безКомментариев("const u = 'https://api.flamingo.plus'").includes('api.flamingo.plus')
  console.log(`${признакОк ? 'ok  ' : 'ПЛОХО'} признак экрана и вырезка комментариев`)
  if (!признакОк) плохо += 1

  if (плохо) {
    console.error(`\nСАМОПРОВЕРКА ПРОВАЛЕНА · ${плохо}`)
    process.exit(1)
  }
  console.log(`\nсамопроверка: ${случаи.length + 2} из ${случаи.length + 2}`)
}

if (process.argv.includes('--selftest')) selftest()
else run()
