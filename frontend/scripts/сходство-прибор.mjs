/** Сходство: одна ли вещь на разных экранах, или их несколько под одним именем.
 *
 *  🔴 ЭТО ПРИБОР, А НЕ КАРАУЛ. Он ничего не заваливает и стоит вне `guards`.
 *  Причина прямая: разнобой, который он меряет, — это наряд «правило против
 *  листов» (находки 26–33 аудита), и починка его меняет вид всех экранов
 *  разом. Такое решает владелец (CLAUDE.md §3а), а не караул в сборке.
 *  Караул из прибора делается одной строкой в тот день, когда решение есть.
 *
 *  Что меряет: берёт классы, которые в разных файлах называют ОДНУ И ТУ ЖЕ
 *  вещь продукта (главная кнопка, верхняя полоса, тихая кнопка, карточка), и
 *  показывает, по каким свойствам файлы расходятся. Не «похоже ли» — а
 *  буквально: какое свойство, какие значения, в каких файлах.
 *
 *  Наряд 5.3 аудита 07.09, пункт 6: «Геометрия между экранами: четыре шапки,
 *  четыре главные кнопки, четыре поля кадра». Поле кадра держит `кадр-check`;
 *  шапки и кнопки — здесь.
 *
 *      node scripts/сходство-прибор.mjs [--selftest]
 */

import { readFileSync, readdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ИСХОД = fileURLToPath(new URL('../src', import.meta.url))

/** 🔴 ЭТАЛОН ЕСТЬ, И ЭТО ГЛАВНОЕ, ЧТО ПОКАЗЫВАЕТ ПРИБОР. `ui/Button.module.css`
 *  собран правильно: `.b` держит геометрию (рост, поля, скругление, кегль), а
 *  `.go`/`.quiet` — только цвет. То есть кнопка в продукте одна и уже решена.
 *  Экраны её не берут: шесть файлов пишут свою `.go` заново. Значит разнобой —
 *  это не «не договорились», а «договорились и не применили». */
const ЭТАЛОН = ['ui/Button.module.css', 'b']

/** Значения токенов — чтобы отчёт называл числа, а не имена. `var(--space-5)`
 *  и `var(--space-6)` спорить не о чем; «20 px против 24» — есть. */
function токены() {
  const т = {}
  /* 🔴 ТОЛЬКО СВЕТЛАЯ ТЕМА, И РЕЗАТЬ НАДО ПО ПЕРВОМУ ЖЕ ЧУЖОМУ СЕЛЕКТОРУ.
     Первый заход резал по `.тема-тьма` — такого селектора в файле нет вовсе, и
     прибор молча набирал значения из `[data-mode="kids"]` (детский режим,
     последний в файле): показывал `--tap-min = 48px` вместо 44 и
     `--text-small = 16` вместо 14. Ошибка того же рода, что весь этот прибор
     ищет: правило написано, выглядит работающим, меряет не то. */
  const весь = readFileSync(`${ИСХОД}/styles/tokens.css`, 'utf8')
  const конец = весь.search(/\n\[data-(theme|mode)=/)
  const текст = конец > 0 ? весь.slice(0, конец) : весь
  for (const м of текст.matchAll(/(--[\w-]+):\s*([^;]+);/g)) т[м[1]] = м[2].trim()
  const развернуть = (v, глубина = 0) => глубина > 6 ? v
    : v.replace(/var\((--[\w-]+)\)/g, (_, имя) => т[имя] ? развернуть(т[имя], глубина + 1) : `var(${имя})`)
  return (v) => {
    const р = развернуть(v).replace(/\/\*[\s\S]*?\*\//g, '').trim()
    return р === v ? '' : ` = ${р}`
  }
}

/** Вещи продукта и класс, которым их зовут. Смысл — в третьей колонке: она
 *  объясняет, ПОЧЕМУ расхождение здесь дорого, а не просто некрасиво. */
const ВЕЩИ = [
  ['go', 'главная кнопка',
   'ПРАВИЛА 11.1: одно зелёное действие на экране. Если оно на каждом экране '
   + 'своего роста и кегля, человек не узнаёт его как одно и то же.'],
  ['quiet', 'тихая кнопка', 'Пара к главной. Расходится вместе с ней.'],
  ['head', 'верхняя полоса',
   'ПРАВИЛА 9.5: шапка говорит, где я. Она стоит на каждом экране и потому '
   + 'заметнее всех: разная высота шапки читается как «другое приложение».'],
]

/** Панели внутри комнаты — не экраны. У них своё поле (`--space-4`), и мерить
 *  их одной меркой с экранами значит выдумать расхождение. */
const НЕ_ЭКРАНЫ = new Set(['Chat', 'HubPick', 'ShowList', 'Note', 'InkTools', 'Shelf',
  /* 🔴 `Mark` — ЗНАК, А НЕ КНОПКА. У него есть класс `.quiet`, но означает он
     «приглушённый знак» (логотип на видео), а не тихую кнопку. Прибор сверял
     его геометрию с кнопочной и честно докладывал расхождение, которого нет:
     это два разных предмета под одним именем. Совпадение имён — не сходство. */
  'Mark'])

/* Свойства, по которым расхождение — вопрос, а не вкус. `display`, `cursor`,
   `touch-action` сюда не входят: они говорят о роли, а не о виде. */
const ВИДИМЫЕ = new Set([
  'min-height', 'height', 'padding', 'padding-inline', 'gap', 'row-gap',
  'font-size', 'font-weight', 'border', 'border-radius', 'background', 'color',
])

function файлы() {
  const из = []
  for (const п of ['screens', 'room', 'board', 'ui']) {
    let список
    try { список = readdirSync(`${ИСХОД}/${п}`) } catch { continue }
    for (const f of список) if (f.endsWith('.module.css')) из.push([п, f])
  }
  return из
}

/** Объявления верхнего правила `.имя { … }`. Вложенные и составные селекторы
 *  (`.имя:hover`, `.имя .что-то`) нарочно не берём: они про состояние. */
export function объявления(текст, имя) {
  const re = new RegExp(`(?:^|\\n)\\.${имя}\\s*\\{([^}]*)\\}`)
  const m = re.exec(текст)
  if (!m) return null
  const о = {}
  const тело = m[1].replace(/\/\*[\s\S]*?\*\//g, '')
  for (const стр of тело.split(';')) {
    const i = стр.indexOf(':')
    if (i < 0) continue
    const k = стр.slice(0, i).trim()
    if (!k) continue
    о[k] = стр.slice(i + 1).trim().replace(/\s+/g, ' ')
  }
  return о
}

function прогон() {
  let расхождений = 0
  const число = токены()
  const базаТекст = readFileSync(`${ИСХОД}/${ЭТАЛОН[0]}`, 'utf8')
  const база = объявления(базаТекст, ЭТАЛОН[1]) ?? {}
  for (const [класс, имяВещи, почему] of ВЕЩИ) {
    const собрано = []
    for (const [п, f] of файлы()) {
      const экран = f.replace('.module.css', '')
      if (НЕ_ЭКРАНЫ.has(экран)) continue
      const текст = readFileSync(`${ИСХОД}/${п}/${f}`, 'utf8')
      const о = объявления(текст, класс)
      /* Эталонной кнопке достаётся геометрия из `.b`: она её носит, просто не
         в том же правиле. Без слияния прибор сообщал бы, что эталон «не задал»
         рост и поля, — и врал бы ровно про то место, которое всё делает верно. */
      if (о) собрано.push([`${п}/${f}` === ЭТАЛОН[0] ? `${экран} ← ЭТАЛОН` : экран,
        `${п}/${f}` === ЭТАЛОН[0] ? { ...база, ...о } : о])
    }
    if (собрано.length < 2) continue

    const строки = []
    const ключи = [...new Set(собрано.flatMap(([, о]) => Object.keys(о)))]
      .filter((k) => ВИДИМЫЕ.has(k)).sort()
    for (const k of ключи) {
      const виды = new Map()
      for (const [экран, о] of собрано) {
        const v = о[k] ?? '— не задано'
        if (!виды.has(v)) виды.set(v, [])
        виды.get(v).push(экран)
      }
      if (виды.size > 1) {
        строки.push([k, [...виды.entries()]])
        расхождений += виды.size - 1
      }
    }

    console.log(`\n── ${имяВещи} (.${класс}) — ${собрано.length} мест: `
      + собрано.map(([э]) => э).join(', '))
    if (!строки.length) { console.log('   ✅ по виду сходятся везде'); continue }
    console.log(`   ${почему}`)
    for (const [k, виды] of строки) {
      console.log(`   ${k}:`)
      for (const [v, где] of виды) {
        console.log(`      ${String(v).padEnd(32)}${число(v).padEnd(12)} ${где.join(', ')}`)
      }
    }
  }
  return расхождений
}

if (process.argv.includes('--selftest')) {
  const т = '.go {\n  padding: 0 var(--space-5);\n  /* заметка: не трогать */\n  min-height: var(--tap-min);\n}\n.go:hover { background: red; }\n'
  const о = объявления(т, 'go')
  const надо = { padding: '0 var(--space-5)', 'min-height': 'var(--tap-min)' }
  const сошлось = JSON.stringify(о) === JSON.stringify(надо)
  console.log(сошлось ? '✅ самопроверка: комментарии и :hover не попадают в объявления'
    : `❌ самопроверка: ${JSON.stringify(о)}`)
  if (!сошлось) process.exit(1)
  if (объявления(т, 'нетТакого') !== null) { console.log('❌ самопроверка: несуществующий класс'); process.exit(1) }
  process.exit(0)
}

console.log('Сходство: одна ли вещь на разных экранах')
console.log('Эталон — ui/Button.module.css: там кнопка собрана верно и решена один раз.')
const n = прогон()
console.log(`\n${n ? '⚠️' : '✅'}  расхождений по виду: ${n}`)
console.log('   Прибор ничего не заваливает: это наряд «правило против листов»,')
console.log('   и он ждёт решения владельца (CLAUDE.md §3а).')
