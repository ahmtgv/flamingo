/** Прибор для исследования внимания SEduM: протокол, тексты и формат записи.
 *
 *  🔴 ЗАЧЕМ. Проверку проходят живые люди — друзья и близкие владельца, — и
 *  каждая сломанная проверка стоит им пяти минут, а нам — потерянной записи,
 *  которую не переснять в тех же условиях. Поэтому всё, что можно проверить
 *  без человека, проверяется здесь:
 *
 *    · сценарии: каждый вид собирается, укладывается в свои минуты, одно
 *      зерно даёт один и тот же сценарий, «ждём» — только настоящие состояния;
 *    · тексты: длина, вопросы, поровну «пишем» и «не пишем»;
 *    · формат кадра: туда-обратно без потерь сверх шага квантования, битый
 *      хвост не роняет чтение;
 *    · обе стороны провода: версия согласия и виды проверок совпадают с тем,
 *      что принимает сервер (`backend/science/views.py`).
 *
 *      node scripts/наука-check.mjs
 */
import { existsSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import { ЦЕНА } from '../src/sedum/внимание.ts'
import {
  ПРОВЕРКИ, СОГЛАСИЕ_ВЕРСИЯ, ЧТЕНИЕ_СЕК, гдеТочка, длительность, моментыВопросов, собрать, случай,
} from '../src/наука/протокол.ts'
import { ВОПРОСЫ_ДУМАЙ, ПЕРЕПИСАТЬ, СИТУАЦИИ, ТЕКСТЫ, ФРАЗЫ } from '../src/наука/тексты.ts'
import {
  ИМЕНА_МИМИКИ, КАЧЕСТВА, МИМИКИ, СОСТОЯНИЯ, ТОЧЕК, ФЛАГ, записатьКадр, прочитатьКадры, размерЗаписи,
} from '../src/наука/формат.ts'

let всего = 0
let плохо = 0
function да(что, условие, ещё = '') {
  всего += 1
  if (условие) console.log(`  ✅ ${что}`)
  else {
    плохо += 1
    console.log(`  ❌ ${что}${ещё ? `\n       ${typeof ещё === 'string' ? ещё : JSON.stringify(ещё)}` : ''}`)
  }
}

const ВСЕ = Object.keys(ЦЕНА)
const ЗЁРНА = Array.from({ length: 60 }, (_, i) => i * 7919 + 13)

console.log('\nСценарии:')

for (const п of ПРОВЕРКИ) {
  const с = собрать(п.вид, 42)
  const длины = ЗЁРНА.map((з) => длительность(собрать(п.вид, з)))
  const мин = Math.min(...длины)
  const макс = Math.max(...длины)
  /* Пять минут — решение владельца; голос — отдельный разговор, он у учителя. */
  const предел = п.вид === 'голос' ? [300, 720] : [150, 340]
  да(`«${п.название}»: ${мин}–${макс} с по часам, в пределах ${предел[0]}–${предел[1]}`, мин >= предел[0] && макс <= предел[1], { мин, макс })
  да(`«${п.название}»: одно зерно — один сценарий`, JSON.stringify(собрать(п.вид, 777)) === JSON.stringify(собрать(п.вид, 777)))
  да(`«${п.название}»: разные зёрна — разный порядок`, new Set(ЗЁРНА.slice(0, 10).map((з) => JSON.stringify(собрать(п.вид, з).шаги))).size > 1 || п.вид === 'чтение')
  const чужие = с.шаги.flatMap((ш) => ш.ждём).filter((x) => !ВСЕ.includes(x))
  да(`«${п.название}»: «ждём» — только настоящие состояния движка`, чужие.length === 0, чужие)
  да(`«${п.название}»: у каждого шага есть подсказка`, с.шаги.every((ш) => ш.текст.trim().length > 3))
  const немые = с.шаги.filter((ш) => ш.сигнал && (ш.стимул.вид === 'вопрос' || ш.сек === 0))
  да(`«${п.название}»: сигнал «вернитесь» — только у шагов со временем`, немые.length === 0, немые.map((ш) => ш.метка))
}

{
  /* «Куда я смотрю»: через один — на экране и мимо, иначе балл не успевает вернуться. */
  const ok = ЗЁРНА.every((з) => собрать('взгляд', з).шаги.every((ш, i) => (i % 2 === 0) === ш.ждём.includes('на экране')))
  да('«Куда я смотрю»: на экране и мимо идут через один', ok)
}
{
  const ш = собрать('тетрадь', 5).шаги
  const пишем = ш.filter((x) => x.метка === 'пишет')
  да('«Тетрадь»: одно письмо в режиме «пишем», одно — без', пишем.length === 2 && пишем.filter((x) => x.пишем).length === 1, пишем.map((x) => x.пишем))
  да('«Тетрадь»: с режимом ждём «пишет», без — «смотрит вниз»',
    пишем.find((x) => x.пишем)?.ждём.join() === 'пишет' && пишем.find((x) => !x.пишем)?.ждём.join() === 'смотрит вниз')
}
{
  const ш = собрать('голос', 9).шаги
  const фразы = ш.filter((x) => x.стимул.вид === 'фраза')
  const ситуации = ш.filter((x) => x.стимул.вид === 'ситуация')
  const пишет = (м) => м.filter((x) => x.стимул.пишем).length
  да('«Голос»: фраз 16, поровну «пишем» и «не пишем»', фразы.length === 16 && пишет(фразы) === 8, [фразы.length, пишет(фразы)])
  да('«Голос»: ситуаций 12, поровну', ситуации.length === 12 && пишет(ситуации) === 6, [ситуации.length, пишет(ситуации)])
  да('«Голос»: кусочек урока — последним', ш.at(-1).стимул.вид === 'урок')
  да('«Голос»: без калибровки — камеры нет', собрать('голос', 9).калибровка === 0)
}
{
  const ок = ЗЁРНА.every((з) => {
    const м = моментыВопросов(случай(з), ЧТЕНИЕ_СЕК)
    return м.length >= 2 && м[0] >= 60 && м[0] <= 90 && м.every((t, i) => i === 0 || t - м[i - 1] >= 60) && м.at(-1) <= ЧТЕНИЕ_СЕК - 20
  })
  да('«Чтение»: вопросы «где внимание» — с 60–90 с, не чаще раза в минуту, не в последние 20 с', ок)
}

console.log('\nТочка-стимул:')
{
  const формы = ['круг', 'зигзаг', 'восьмёрка', 'блуждание']
  let вне = []
  for (const форма of формы) {
    for (let t = 0; t <= 15; t += 0.05) {
      const [x, y] = гдеТочка({ вид: 'путь', форма, сек: 15 }, t)
      if (!(x >= 0.05 && x <= 0.95 && y >= 0.05 && y <= 0.95)) вне.push([форма, t, x, y])
    }
  }
  да('движущаяся точка не уходит к краям ближе 5% экрана', вне.length === 0, вне.slice(0, 3))
  const с = собрать('точка', 3).шаги[0].стимул
  да('прыгающая точка: в секунду 0 и 17,9 — первая и девятая', JSON.stringify(гдеТочка(с, 0)) === JSON.stringify(с.точки[0]) && JSON.stringify(гдеТочка(с, 17.9)) === JSON.stringify(с.точки[8]))
  да('без точки — null', гдеТочка({ вид: 'учитель' }, 3) === null)
}

console.log('\nТексты:')
for (const т of ТЕКСТЫ) {
  const слов = т.абзацы.join(' ').split(/\s+/).filter(Boolean).length
  да(`«${т.название}»: ${слов} слов — на 3–5 минут`, слов >= 600 && слов <= 1000, слов)
  да(`«${т.название}»: три вопроса, у каждого верный ответ из четырёх`, т.вопросы.length === 3 && т.вопросы.every((в) => в.ответы.length === 4 && в.верный >= 0 && в.верный < 4))
}
да('фраз «пишем» и «не пишем» поровну — по 20', ФРАЗЫ.filter((ф) => ф.пишем).length === 20 && ФРАЗЫ.filter((ф) => !ф.пишем).length === 20)
да('ситуаций поровну — по 8', СИТУАЦИИ.filter((с) => с.пишем).length === 8 && СИТУАЦИИ.filter((с) => !с.пишем).length === 8)
да('вопросов «подумайте» хватает на два разных прохода', ВОПРОСЫ_ДУМАЙ.length >= 20 && new Set(ВОПРОСЫ_ДУМАЙ).size === ВОПРОСЫ_ДУМАЙ.length)
да('предложений для тетради хватает на два письма', ПЕРЕПИСАТЬ.length >= 2)

console.log('\nФормат кадра:')
да('мимики 52 имени, все разные', ИМЕНА_МИМИКИ.length === МИМИКИ && new Set(ИМЕНА_МИМИКИ).size === МИМИКИ)
да('все состояния движка есть в формате', ВСЕ.every((x) => СОСТОЯНИЯ.includes(x)) && СОСТОЯНИЯ.length === ВСЕ.length)
{
  const r = случай(5)
  const кадры = []
  for (let i = 0; i < 40; i++) {
    const лицо = i % 3 !== 0
    кадры.push({
      t: i * 33.3, стена: 1_790_000_000_000 + i * 33, флаги: (лицо ? ФЛАГ.лицо : 0) | ФЛАГ.видна | (i % 2 ? ФЛАГ.фокус : 0),
      шаг: i % 5 === 0 ? 255 : i % 7, стимул: i % 4 === 0 ? [r(), r()] : null,
      сейчас: СОСТОЯНИЯ[i % СОСТОЯНИЯ.length], засчитано: СОСТОЯНИЯ[(i + 3) % СОСТОЯНИЯ.length], балл: i * 2.4,
      качество: КАЧЕСТВА[i % 4], веко: i % 6 ? r() * 0.5 : null, перклос: i % 5 ? r() : null, яркость: r(),
      лицо: лицо ? {
        матрица: Array.from({ length: 16 }, () => r() * 2 - 1),
        мимика: Array.from({ length: МИМИКИ }, () => r()),
        точки: Array.from({ length: ТОЧЕК * 3 }, () => r() * 1.2 - 0.1),
      } : null,
    })
  }
  const буфер = new ArrayBuffer(кадры.reduce((с, к) => с + размерЗаписи(Boolean(к.лицо)), 0))
  const в = new DataView(буфер)
  let п = 0
  for (const к of кадры) п = записатьКадр(в, п, к)
  да('записано ровно столько байт, сколько обещано', п === буфер.byteLength, [п, буфер.byteLength])
  const назад = прочитатьКадры(new Uint8Array(буфер))
  да('прочитано столько же кадров', назад.length === кадры.length, назад.length)
  let худшее = 0
  let бед = []
  назад.forEach((н, i) => {
    const к = кадры[i]
    if (Math.abs(н.t - к.t) > 1e-9 || н.шаг !== к.шаг || н.сейчас !== к.сейчас || н.засчитано !== к.засчитано || н.качество !== к.качество) бед.push(i)
    if (н.балл !== Math.round(к.балл)) бед.push(`балл ${i}`)
    if ((н.веко === null) !== (к.веко === null) || (н.перклос === null) !== (к.перклос === null)) бед.push(`null ${i}`)
    if (Boolean(н.лицо) !== Boolean(к.лицо)) бед.push(`лицо ${i}`)
    if (к.лицо && н.лицо) {
      for (let j = 0; j < ТОЧЕК * 3; j++) худшее = Math.max(худшее, Math.abs(н.лицо.точки[j] - к.лицо.точки[j]))
      for (let j = 0; j < МИМИКИ; j++) худшее = Math.max(худшее, Math.abs(н.лицо.мимика[j] - к.лицо.мимика[j]) / 2)
    }
  })
  да('поля кадра возвращаются как были', бед.length === 0, бед.slice(0, 5))
  да(`точки и мимика — с погрешностью шага квантования (худшее ${худшее.toExponential(1)})`, худшее <= 0.5 / 10000 + 1e-7, худшее)
  /* Последний кадр — без лица, 49 байт: отрезаем 10 — ломается только он. */
  const обрезано = прочитатьКадры(new Uint8Array(буфер, 0, буфер.byteLength - 10))
  да('оборванный хвост: читаются все целые кадры, битый отброшен', обрезано.length === кадры.length - 1, обрезано.length)
}

console.log('\nОбе стороны провода:')
{
  const путь = fileURLToPath(new URL('../../backend/science/views.py', import.meta.url))
  if (!existsSync(путь)) {
    да('сервер рядом — backend/science/views.py', false, путь)
  } else {
    const py = readFileSync(путь, 'utf8')
    const согласия = /СОГЛАСИЯ\s*=\s*\{([^}]*)\}/.exec(py)?.[1] ?? ''
    да(`сервер принимает согласие версии ${СОГЛАСИЕ_ВЕРСИЯ}`, согласия.includes(`"${СОГЛАСИЕ_ВЕРСИЯ}"`), согласия)
    const виды = [...(/ВИДЫ_ПРОВЕРОК\s*=\s*\{([^}]*)\}/.exec(py)?.[1] ?? '').matchAll(/"([^"]+)"/g)].map((m) => m[1]).sort()
    const наши = ПРОВЕРКИ.map((п) => п.вид).sort()
    да('виды проверок на сервере и на странице — одни и те же', JSON.stringify(виды) === JSON.stringify(наши), { сервер: виды, страница: наши })
  }
}

console.log(`\n${плохо ? `❌ бед ${плохо}` : '✅ всё сходится'} · проверок ${всего}\n`)
process.exit(плохо ? 1 : 0)
