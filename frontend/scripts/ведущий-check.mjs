/** Караул: откуда берётся роль ведущего.
 *
 *  🔴 Заведён по решению владельца 02.09: «если ученик заходит раньше учителя,
 *  он становится в статусе учителя со всеми доступными учителю опциями — это не
 *  должно быть априори; не блокировать скриптом, а исключить как сценарий
 *  программно, чтобы не было даже намёка на такую возможность».
 *
 *  Так и было: комната считала ведущим того, кто вошёл первым. Правку легко
 *  отменить обратно одной строкой — «ну надо же кому-то быть ведущим, пока
 *  сервер молчит», — и она вернётся незаметно, потому что на экране разницы
 *  не видно, пока в комнату не зайдут двое в неудачном порядке.
 *
 *  Поэтому караул проверяет не поведение, а ТЕКСТ: в исходниках не должно
 *  остаться ни одного места, где право берётся из порядка входа. `--selftest`
 *  скармливает ему СТАРЫЙ код и требует красного.
 */

import { readFileSync } from 'node:fs'

const ФАЙЛЫ = {
  useRoom: 'src/room/useRoom.ts',
  Room: 'src/screens/Room.tsx',
  Faces: 'src/room/Faces.tsx',
  Stage: 'src/room/Stage.tsx',
  Tiles: 'src/room/Tiles.tsx',
}

/** Каждое правило: что ищем, и что это значило бы, если бы нашлось. */
const ЗАПРЕТЫ = [
  {
    имя: 'ведущий не вычисляется по времени входа',
    где: ['useRoom'],
    нельзя: /withLead|\.sort\([\s\S]{0,120}joinedAt/,
    цена: 'вошедший раньше снова получает права ведущего',
  },
  {
    имя: 'никто не объявляется ведущим по месту в списке',
    где: ['useRoom', 'Faces', 'Stage', 'Tiles'],
    нельзя: /lead:\s*true/,
    цена: 'роль раздаётся кодом, а не сервером',
  },
  {
    имя: 'права не достаются «по умолчанию»',
    где: ['Room'],
    нельзя: /\?\.lead\s*\?\?\s*true|iLead\s*=\s*true/,
    цена: 'пока сервер молчит, права у всех',
  },
  {
    имя: 'подпись «ведёт занятие» не вешается на первого безусловно',
    где: ['Faces', 'Stage', 'Tiles'],
    нельзя: /faces\[0\][\s\S]{0,200}<Tile[^>]*\slead\s*(\/?>|big)/,
    цена: 'первый вошедший снова подписан ведущим',
  },
]

/** Обязательное: роль приходит от сервера, и это видно в коде. */
const ОБЯЗАНО = [
  {
    имя: 'право ведущего берётся из ответа сервера',
    где: 'Room',
    надо: /const iLead = веду/,
    цена: 'источник роли снова не назван',
  },
  {
    имя: 'ответ сервера про роль вообще запрашивается',
    где: 'Room',
    надо: /setВеду\(о\.веду\)/,
    цена: 'сервер не спрошен — ведущего не будет ни у кого',
  },
]

/** 🔴 Проверяем КОД, а не разговор о коде. Разбор в комментариях обязан
 *  называть старое поведение своими словами — иначе следующий не поймёт,
 *  почему функции нет. Караул, который спотыкается о собственный разбор,
 *  заставляет вычищать объяснения — и правило остаётся без причины.
 *  Обратная сторона честная: нарушение, спрятанное в комментарий, не
 *  сработает — но комментарий ничего и не делает. */
function безРазговоров(т) {
  return т.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1 ')
}

function прогон(сырые) {
  const тексты = {}
  for (const [имя, т] of Object.entries(сырые)) тексты[имя] = безРазговоров(т)
  const беды = []
  for (const п of ЗАПРЕТЫ) {
    for (const имя of п.где) {
      const т = тексты[имя]
      if (т !== undefined && п.нельзя.test(т)) беды.push(`${п.имя} — нарушено в ${имя}: ${п.цена}`)
    }
  }
  for (const п of ОБЯЗАНО) {
    const т = тексты[п.где]
    if (т !== undefined && !п.надо.test(т)) беды.push(`${п.имя} — не найдено в ${п.где}: ${п.цена}`)
  }
  return беды
}

/* ── самопроверка: старый код обязан дать красное ────────────────────────── */
if (process.argv.includes('--selftest')) {
  const старое = {
    useRoom: `
      function withLead(list) {
        const known = list.every((f) => f.joinedAt > 0)
        const ordered = known ? [...list].sort((a, b) => a.joinedAt - b.joinedAt) : list
        return ordered.map((f, i) => (i === 0 ? { ...f, lead: true } : f))
      }`,
    Room: `const iLead = faces.find((f) => f.isLocal)?.lead ?? true`,
    Faces: `const lead = faces.find((f) => f.lead) ?? faces[0]
      return <Tile key={lead.identity} face={lead} lead />`,
    Stage: `const lead = faces.find((f) => f.lead) ?? faces[0]`,
    Tiles: `const lead = faces.find((f) => f.lead) ?? faces[0]`,
  }
  const беды = прогон(старое)
  if (беды.length < 3) {
    console.error(`❌ КАРАУЛ СЛЕПОЙ: на старом коде нашёл всего ${беды.length} бед. Чинить караул.`)
    process.exit(1)
  }
  console.log(`✅ Караул ведущего зряч: на старом коде красных ${беды.length}.`)
  for (const б of беды) console.log(`     · ${б}`)
  process.exit(0)
}

/* ── боевой прогон ───────────────────────────────────────────────────────── */
const тексты = {}
for (const [имя, путь] of Object.entries(ФАЙЛЫ)) тексты[имя] = readFileSync(путь, 'utf8')

console.log('\nОткуда берётся роль ведущего:\n')
const беды = прогон(тексты)
for (const п of [...ЗАПРЕТЫ, ...ОБЯЗАНО]) {
  const сломано = беды.some((б) => б.startsWith(п.имя))
  console.log(`  ${сломано ? '❌' : '✅'} ${п.имя}`)
}
if (беды.length) {
  console.log('')
  for (const б of беды) console.log(`     ${б}`)
}
console.log(беды.length ? `\n❌ Красных: ${беды.length}\n` : `\n✅ Роль приходит только от сервера.\n`)
process.exit(беды.length ? 1 : 0)
