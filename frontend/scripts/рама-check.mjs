/** Караул: постоянная навигация не врёт.
 *
 *  🔴 ЗАЧЕМ. Меню — это обещания. Их три вида, и все три ломаются молча:
 *
 *   1. ПУНКТ, ВЕДУЩИЙ В НИКУДА. Адрес, которого `App.tsx` не знает, отдаёт
 *      человека на титул или на вход — то есть продукт требует регистрации
 *      там, где человек просто нажал пункт меню.
 *   2. ДВА ПУНКТА НА ОДИН АДРЕС. Ровно эту беду мы нашли в кабинете 09.09:
 *      слово «Расписание» стояло на экране дважды и вело в одно место.
 *   3. ЦИФРА РЯДОМ С ПУНКТОМ. Цифра — обещание, что раздел её честно знает.
 *      Пока раздела нет, цифре взяться неоткуда, а нарисовать её легко.
 *
 *  Караул читает исходники, а не выполняет их: `Рама.tsx` — это JSX, и node
 *  его не ввезёт. Ему довольно того, что адрес назван в обоих местах.
 *
 *  `--selftest` скармливает караулу заведомо плохое меню и требует красного.
 */

import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const РАМА = fileURLToPath(new URL('../src/ui/Рама.tsx', import.meta.url))
const APP = fileURLToPath(new URL('../src/App.tsx', import.meta.url))

/** Пункты меню: имя и, если есть, адрес. */
export function пункты(текст) {
  const из = []
  /* `{ имя: '…' }` и `{ имя: '…', адрес: '/…' }` — обе формы в одной записи. */
  const рег = /\{\s*имя:\s*'([^']+)'(?:\s*,\s*адрес:\s*'([^']+)')?/g
  let м
  while ((м = рег.exec(текст))) из.push({ имя: м[1], адрес: м[2] })
  return из
}

/** Адреса, которые `App.tsx` действительно разбирает. */
export function адресаApp(текст) {
  const из = new Set()
  for (const м of текст.matchAll(/path === '([^']+)'/g)) из.add(м[1])
  for (const м of текст.matchAll(/path\.startsWith\('([^']+)'\)/g)) из.add(м[1])
  return из
}

/** Меню у ученика и у преподавателя РАЗНЫЕ, и один адрес в двух из них —
 *  не двойник: «Кабинет ученика» и «Кабинет преподавателя» — это одна дверь,
 *  подписанная по роли. Поэтому режем текст на два меню по тем же опорам,
 *  которые стоят в коде, и считаем двойников внутри каждого.
 *  Опоры пропали — караул краснеет, а не притворяется зрячим. */
export function меню(текст) {
  const и = текст.indexOf('if (!учитель) {')
  const т = текст.lastIndexOf('return [')
  if (и < 0 || т < 0 || т < и) return null
  const общее = пункты(текст.slice(0, и))
  return {
    ученик: [...общее, ...пункты(текст.slice(и, т))],
    учитель: [...общее, ...пункты(текст.slice(т))],
  }
}

export function беды(текстРамы, текстApp) {
  const найдено = []
  const меню2 = меню(текстРамы)
  if (!меню2) {
    найдено.push('в Рама.tsx не нашлось опор «if (!учитель) {» и «return [» — караул ослеп')
    return найдено
  }
  const живые = адресаApp(текстApp)

  for (const [роль, список] of Object.entries(меню2)) {
    if (!список.length) найдено.push(`меню «${роль}» пустое — караул ослеп`)
    const видели = new Map()
    for (const п of список) {
      if (/\d/.test(п.имя)) {
        найдено.push(`пункт «${п.имя}» обещает цифру, а цифра — это обещание`)
      }
      if (!п.адрес) continue
      if (!живые.has(п.адрес)) {
        найдено.push(`пункт «${п.имя}» ведёт на ${п.адрес}, а App.tsx такого адреса не знает`)
      }
      if (видели.has(п.адрес)) {
        найдено.push(`меню «${роль}»: два пункта на один адрес ${п.адрес} — «${видели.get(п.адрес)}» и «${п.имя}»`)
      } else {
        видели.set(п.адрес, п.имя)
      }
    }
  }

  /* Пункт без адреса обязан быть подписан словом, а не молчать. */
  if (!/скоро/.test(текстРамы)) {
    найдено.push('в раме нет слова «скоро» — пункт без адреса молчит, а молчание неотличимо от дефекта')
  }
  return найдено
}

const самопроверка = process.argv.includes('--selftest')

if (самопроверка) {
  const плохаяРама = `
    { имя: 'Избранное', адрес: '/hub' }
    if (!учитель) {
      { имя: 'Кабинет ученика', адрес: '/кабинет' }
    }
    return [
      { имя: 'Кабинет преподавателя', адрес: '/кабинет' }
      { имя: 'Журнал', адрес: '/журнал' }
      { имя: 'Расписание', адрес: '/кабинет' }
      { имя: 'Уроки 12', адрес: '/журнал' }
      { имя: 'Курсы', адрес: '/курсы' }
    ]
    скоро
  `
  const плохойApp = `if (path === '/кабинет') {} if (path === '/журнал') {}`
  const найдено = беды(плохаяРама, плохойApp)
  const ждём = ['ведёт на /курсы', 'два пункта на один адрес /кабинет', 'обещает цифру']
  const нехватка = ждём.filter((ж) => !найдено.some((н) => н.includes(ж)))
  if (нехватка.length) {
    console.error('❌ самопроверка: караул не увидел', нехватка)
    process.exit(1)
  }
  if (беды(readFileSync(РАМА, 'utf8'), readFileSync(APP, 'utf8')).length) {
    console.error('❌ самопроверка: караул красный на здоровом дереве')
    process.exit(1)
  }
  console.log('✅ самопроверка рамы: караул краснеет на плохом меню и молчит на нашем')
  process.exit(0)
}

const найдено = беды(readFileSync(РАМА, 'utf8'), readFileSync(APP, 'utf8'))
if (найдено.length) {
  console.error('❌ рама обещает то, чего нет:')
  for (const б of найдено) console.error('  ·', б)
  process.exit(1)
}
const м = меню(readFileSync(РАМА, 'utf8'))
console.log(`✅ рама: у преподавателя ${м.учитель.length} пунктов, у ученика ${м.ученик.length}; `
  + 'все двери ведут туда, куда обещают, и цифр никто не обещает')
