/** Проверка того, что подставляется в пустую форму урока.
 *
 *  Заведена после живого дефекта: в 23:33 форма предлагала «01.09.2026, 00:00»
 *  — час перевалил за полночь, а день остался вчерашним. Урок вставал на 23
 *  часа в прошлое, и человек этого не замечал: поля заполнены, всё выглядит
 *  разумно. Обычный прогон такое пропускает — в полдень всё сходится, а тесты
 *  редко гоняют в половине двенадцатого ночи.
 *
 *  Поэтому здесь время не берётся из часов: каждый случай — заданный момент. */

import { доПолуночи, когдаПоУмолчанию, ключСуток } from '../src/lib/datetime.ts'

const случаи = [
  // [что за момент,                 момент,                          ждём]
  ['утро, 10:20',                    new Date(2026, 8, 1, 10, 20),    '01.09.2026 11:00'],
  ['ровно в час, 14:00',             new Date(2026, 8, 1, 14, 0),     '01.09.2026 14:00'],
  ['за минуту до часа, 13:59',       new Date(2026, 8, 1, 13, 59),    '01.09.2026 14:00'],
  ['ночь, 00:10',                    new Date(2026, 8, 1, 0, 10),     '01.09.2026 01:00'],
  ['ровно полночь, 00:00',           new Date(2026, 8, 1, 0, 0),      '01.09.2026 00:00'],
  ['вечер, 23:33 — тот самый',       new Date(2026, 8, 1, 23, 33),    '02.09.2026 00:00'],
  ['23:59',                          new Date(2026, 8, 1, 23, 59),    '02.09.2026 00:00'],
  ['конец месяца, 30.09 в 23:40',    new Date(2026, 8, 30, 23, 40),   '01.10.2026 00:00'],
  ['конец года, 31.12 в 23:40',      new Date(2026, 11, 31, 23, 40),  '01.01.2027 00:00'],
  ['29 февраля високосного, 23:40',  new Date(2028, 1, 29, 23, 40),   '01.03.2028 00:00'],
]

let плохо = 0
console.log('\nЧто подставляем в пустую форму урока:\n')
for (const [имя, момент, ждём] of случаи) {
  const { дата, время } = когдаПоУмолчанию(момент)
  const вышло = `${дата} ${время}`
  const сошлось = вышло === ждём
  if (!сошлось) плохо++
  console.log(`  ${сошлось ? '✅' : '❌'} ${имя.padEnd(30)} → ${вышло}${сошлось ? '' : `   ждали ${ждём}`}`)
}

// Отдельно: предложенный момент никогда не в прошлом.
console.log('\nПредложенное время не бывает в прошлом:')
for (const [имя, момент] of случаи) {
  const { дата, время } = когдаПоУмолчанию(момент)
  const [д, м, г] = дата.split('.')
  const [ч, мин] = время.split(':')
  const предложено = new Date(+г, +м - 1, +д, +ч, +мин)
  const впрошлом = предложено.getTime() < момент.getTime() - 60 * 60 * 1000
  if (впрошлом) плохо++
  console.log(`  ${впрошлом ? '❌' : '✅'} ${имя}`)
}


/* ── сутки, которые не замерзают ────────────────────────────────────────────
   Наряд 5, пункт 11: караул смотрел ОДНУ функцию из трёх мест. Вторая — здесь.
   Находка 17 аудита: кабинет считал «сегодня» один раз при открытии и не менял
   никогда; экран, оставленный с вечера, в 00:20 показывал вчера. Проверять это
   на живых часах бессмысленно ровно по той же причине, что и всё выше: в
   полдень сходится любая ошибка. Поэтому — заданные моменты. */

const сутки = [
  ['полдень',                       new Date(2026, 8, 1, 12, 0, 0)],
  ['за секунду до полуночи',        new Date(2026, 8, 1, 23, 59, 59)],
  ['ровно полночь',                 new Date(2026, 8, 1, 0, 0, 0)],
  ['23:33 — тот самый случай',      new Date(2026, 8, 1, 23, 33, 0)],
  ['конец месяца, 30.09',           new Date(2026, 8, 30, 23, 40, 0)],
  ['конец года, 31.12',             new Date(2026, 11, 31, 23, 40, 0)],
  ['28 февраля високосного',        new Date(2028, 1, 28, 23, 40, 0)],
  ['29 февраля високосного',        new Date(2028, 1, 29, 23, 40, 0)],
]

console.log('\nБудильник до полуночи попадает в СЛЕДУЮЩИЕ сутки:\n')
for (const [имя, момент] of сутки) {
  const через = доПолуночи(момент)
  const проснулись = new Date(момент.getTime() + через)
  const завтра = new Date(момент.getFullYear(), момент.getMonth(), момент.getDate() + 1)
  const вЗавтра = ключСуток(проснулись) === ключСуток(завтра)
  /* Не «после полуночи», а именно в следующие сутки: если бы запас был нулевым,
     на границе можно проснуться в тех же сутках и заснуть ещё на день. */
  const разумно = через > 0 && через <= 24 * 60 * 60 * 1000 + 1000
  const сошлось = вЗавтра && разумно
  if (!сошлось) плохо++
  console.log(`  ${сошлось ? '✅' : '❌'} ${имя.padEnd(30)} через ${(через / 1000 / 60).toFixed(1)} мин → ${ключСуток(проснулись)}`)
}

console.log('\nКлюч суток различает дни, а не миллисекунды:')
{
  const утро = new Date(2026, 8, 1, 0, 0, 1)
  const вечер = new Date(2026, 8, 1, 23, 59, 59)
  const завтра = new Date(2026, 8, 2, 0, 0, 1)
  const пары = [
    ['начало и конец одних суток — один ключ', ключСуток(утро) === ключСуток(вечер)],
    ['через полночь — ключи разные',           ключСуток(вечер) !== ключСуток(завтра)],
    ['ключ читается как дата',                 ключСуток(утро) === '2026-09-01'],
  ]
  for (const [имя, сошлось] of пары) {
    if (!сошлось) плохо++
    console.log(`  ${сошлось ? '✅' : '❌'} ${имя}`)
  }
}

console.log(плохо ? `\n❌ расхождений: ${плохо}\n` : '\n✅ всё сходится\n')
process.exit(плохо ? 1 : 0)
