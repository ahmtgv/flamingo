/** Хеш пароля — тем же кодом, каким его считает боевой сервер.
 *
 *  Зачем: пароль в базе лежит только как PBKDF2 с личной солью, и обратно его
 *  не достать никому — ни нам, ни тому, кто украдёт базу. Так и задумано.
 *  Значит забытый пароль не «смотрят», а ЗАМЕНЯЮТ: здесь считается новый хеш,
 *  и он одной строкой кладётся в D1 вместо старого.
 *
 *  🔴 Пароль набирается прямо здесь, ничего не показывается и никуда не пишется:
 *  ни в историю оболочки, ни в аргументы (их видно в `ps`), ни в файл. Наружу
 *  уходит только хеш — по нему пароль не восстановить.
 *
 *      node scripts/пароль-хеш.mjs
 */
import { hashPass } from '../functions/api/_people.js'

/** Читаем посимвольно с выключенным эхом. Через readline не выйдет: он отдаёт
 *  строку уже после того, как оболочка её напечатала, — пароль успевает
 *  засветиться на экране и остаться в прокрутке терминала. */
function втайне(вопрос) {
  return new Promise((готово, беда) => {
    if (!process.stdin.isTTY) {
      беда(new Error('Запускать вживую в терминале: пароль читается только с клавиатуры.'))
      return
    }
    process.stdout.write(вопрос)
    process.stdin.setRawMode(true)
    process.stdin.resume()
    process.stdin.setEncoding('utf8')
    let набрано = ''
    const слышим = (кусок) => {
      for (const з of кусок) {
        if (з === '\r' || з === '\n' || з === '\u0004') {
          process.stdin.setRawMode(false)
          process.stdin.pause()
          process.stdin.off('data', слышим)
          process.stdout.write('\n')
          готово(набрано)
          return
        }
        if (з === '\u0003') { process.stdout.write('\n'); process.exit(130) }
        /* Стирание — Backspace и Delete: без него опечатку не поправить вслепую. */
        if (з === '\u007f' || з === '\b') { набрано = набрано.slice(0, -1); continue }
        if (з >= ' ') набрано += з
      }
    }
    process.stdin.on('data', слышим)
  })
}

const пароль = await втайне('Новый пароль (не показывается): ')
/* Та же мерка, что на регистрации: длина честнее сложности. */
if (пароль.length < 8) {
  console.error('Короче восьми знаков. Возьмите четыре обычных слова — так надёжнее.')
  process.exit(1)
}
const ещё = await втайне('Ещё раз, чтобы не ошибиться: ')
if (ещё !== пароль) {
  console.error('Два раза набралось по-разному. Ничего не посчитал.')
  process.exit(1)
}

console.log('\nХеш — его и кладём в базу, пароль в нём не читается:\n')
console.log(await hashPass(пароль))
console.log('')
