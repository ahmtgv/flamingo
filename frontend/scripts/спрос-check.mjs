/** Караул: спрашивает ли вошедший, на что смотрит класс.
 *
 *  Заведён после живого дефекта 02.09 — «ученик не видит трансляцию учебных
 *  пособий и доски». Разбор в `src/room/спрос.ts`.
 *
 *  Проверять глазами тут нечего: оба прежних механизма выглядели написанными и
 *  правильными, а срабатывали в тот единственный миг, когда данные-канал ещё
 *  закрыт. Поэтому проверяем поведением, а не текстом, и отдельно проверяем сам
 *  караул: `--selftest` подсовывает ему СТАРОЕ поведение и требует красного.
 *  Зелёный караул при сломанном продукте мы уже ловили дважды. */

import { планСпроса, СРОКИ } from '../src/room/спрос.ts'

const случаи = [
  // [что за случай,                                     состояние,                                                          ждём попыток]
  ['ученик вошёл на «Лица», сцена не приехала — ТОТ САМЫЙ', { фаза: 'live', веду: false, соседей: 1, сценаПришла: false }, СРОКИ.length],
  ['ученик, сцена уже приехала',                            { фаза: 'live', веду: false, соседей: 1, сценаПришла: true  }, 0],
  ['ведущий: он сам сцена',                                 { фаза: 'live', веду: true,  соседей: 1, сценаПришла: false }, 0],
  ['один в комнате: отвечать некому',                       { фаза: 'live', веду: false, соседей: 0, сценаПришла: false }, 0],
  ['связь ещё поднимается',                                 { фаза: 'connecting', веду: false, соседей: 1, сценаПришла: false }, 0],
  ['связь отвалилась',                                      { фаза: 'failed', веду: false, соседей: 1, сценаПришла: false }, 0],
  ['ученик, класс большой',                                 { фаза: 'live', веду: false, соседей: 7, сценаПришла: false }, СРОКИ.length],
]

/** Как было до правки: спрашивала только смонтированная доска и только один
 *  раз, а входят на «Лица» — значит не спрашивал никто. */
const староеПоведение = () => []

function прогон(план, шумно) {
  let плохо = 0
  for (const [имя, состояние, ждём] of случаи) {
    const вышло = план(состояние).length
    const сошлось = вышло === ждём
    if (!сошлось) плохо++
    if (шумно) {
      console.log(`  ${сошлось ? '✅' : '❌'} ${имя.padEnd(52)} → ${вышло} попыток${сошлось ? '' : `   ждали ${ждём}`}`)
    }
  }
  return плохо
}

if (process.argv.includes('--selftest')) {
  const плохо = прогон(староеПоведение, false)
  if (плохо === 0) {
    console.error('❌ КАРАУЛ СЛЕПОЙ: старое поведение прошло проверку. Чинить караул, а не продукт.')
    process.exit(1)
  }
  console.log(`✅ Караул спроса зряч: на старом поведении красных ${плохо}.`)
  process.exit(0)
}

console.log('\nСпрашивает ли вошедший, на что смотрит класс:\n')
let плохо = прогон(планСпроса, true)

// Сроки: растут, начинаются быстро, кончаются до того, как урок уедет вперёд.
console.log('\nСроки повторов:')
const рост = СРОКИ.every((м, i) => i === 0 || м > СРОКИ[i - 1])
const быстро = СРОКИ[0] <= 500
const недолго = СРОКИ[СРОКИ.length - 1] <= 10_000
for (const [имя, ок] of [
  ['растут, а не долбят одинаково', рост],
  ['первый вопрос — в первые полсекунды', быстро],
  ['все попытки укладываются в 10 с', недолго],
]) {
  if (!ок) плохо++
  console.log(`  ${ок ? '✅' : '❌'} ${имя}`)
}

console.log(плохо ? `\n❌ Красных: ${плохо}\n` : `\n✅ Спрос сходится: ${случаи.length + 3} проверки.\n`)
process.exit(плохо ? 1 : 0)
