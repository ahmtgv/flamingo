function прогонТекста(сырые) {
  const т = Object.fromEntries(Object.entries(сырые).map(([к, в]) => [к, безРазговоров(в)]))
  const беды = []
  for (const п of ПРАВИЛА) if (т[п.где] !== undefined && !п.надо.test(т[п.где])) беды.push(п.имя)
  for (const п of ЗАПРЕТЫ) for (const где of п.где) if (т[где] !== undefined && п.нельзя.test(т[где])) беды.push(`${п.имя} (${где})`)
  return беды
}

