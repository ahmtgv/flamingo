/** Караул: внимание SEduM в комнате урока (`src/room/внимание.ts`).
 *
 *  Решения владельца, на которых это стоит (05.10):
 *   — учитель видит число и причину, ученик — только свою полоску;
 *   — чужого внимания ученик не видит никогда;
 *   — данные идут только на экран: никуда больше, ни хранения, ни уведомлений;
 *   — коралл — только «заснул» и «ушёл»;
 *   — пока тестируем на взрослых из команды: опыт включается по слову.
 *
 *  Две половины. ПОВЕДЕНИЕ — чистые функции канала и плиток гоняются вживую:
 *  что уходит в канал, что из него принимается, на какой плитке что видно.
 *  ТЕКСТ — то, что поведением не проверить без медиасервера: кому уходит
 *  знак, от чьего имени он принимается, что опыт выключен по умолчанию.
 *  `--selftest` скармливает текстовой половине опасные правки и требует
 *  красного.
 *
 *      node scripts/внимание-комната-check.mjs [--selftest]
 */
