/** Караул: каталог источников не говорит о том, чего не проверял.
 *
 *  🔴 ПОЧЕМУ ЭТО ЗАКОН, А НЕ ВКУСОВЩИНА. До 08.09 три экрана хором сообщали
 *  человеку: «отвечает · проверено сегодня», «молчит с 09:40 · показываем
 *  последнюю проверку», «Ответили 29 из 36», «молчат 1 из 36», «в прошлый раз
 *  молчал». За всеми этими словами не стояло ни одного запроса. Доступность
 *  каждого из 36 источников была БУКВОЙ, набранной руками в `hub/sources.ts`,
 *  время «09:40» выдумано, а числа «29» и «1» посчитаны по выдуманным буквам.
 *
 *  Опросить эти сайты со страницы нельзя в принципе: чужой сервер не отвечает
 *  на запрос из браузера (CORS). Настоящий опрос — работа на стороне сервера,
 *  и её нет. Значит слов о доступности быть не должно: экран, который говорит
 *  «проверено», обещает проверку, а обещание без проверки — обман (ПРАВИЛА 6.3).
 *
 *  Врать здесь особенно дёшево и особенно вредно: выдуманное «отвечает» никогда
 *  не покраснеет и не сломается — караул и есть единственный, кто это заметит.
 *
 *  Караул падает, если:
 *    · у источника в каталоге снова появилось поле состояния;
 *    · на экранах хаба снова зазвучали слова о доступности.
 *
 *  🔴 КОГДА ОПРОС ПОЯВИТСЯ — этот караул правится ВМЕСТЕ с ним, одним куском:
 *  слова разрешаются ровно тогда, когда за ними встаёт запрос и время ответа.
 *  Отдельно ослабить его нельзя: это и будет возврат к выдумке.
 *
 *      node scripts/хаб-check.mjs [--selftest]
 */

import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ФАЙЛЫ = [
  'src/hub/sources.ts',
  'src/screens/Hub.tsx',
  'src/screens/Титул.tsx',
  'src/room/HubPick.tsx',
]

/** 🔴 ЗАПРЕЩЕНО НЕ СЛОВО, А УТВЕРЖДЕНИЕ. Первая версия караула запрещала корень
 *  «молч-» целиком — и поймала тринадцать честных мест: «если замолчит» (что
 *  БУДЕТ, если источник пропадёт — это ПРАВИЛА 8.10 и они обязательны) и признак
 *  `молчит` на титуле, которым отмечен НАШ сервер учётных записей, а не чужой
 *  сайт. Запрет по корню запрещает и правду тоже; здесь запрещены ровно те
 *  обороты, за которыми обязан стоять запрос: проверка, время проверки и счёт
 *  «сколько из скольких». */
/* 🔴 НИ `\\w`, НИ `\\b` — ОНИ ЗДЕСЬ НЕ РАБОТАЮТ. В JavaScript `\\w` это
   `[A-Za-z0-9_]`, кириллица в него не входит: `/проверено\\b/` не совпало НИ
   РАЗУ ни с одной строкой каталога, и первая версия караула отрапортовала
   «чисто» на файле, где выдумка стояла на месте. Поймано самопроверкой 08.09 —
   ровно за этим она и написана раньше самого караула. Границы слова набраны
   явным кириллическим классом. */
const ЗАПРЕТ = [
  [/проверен[оаы](?![а-яё])/i, 'заявлено, что проверяли'],
  [/последн[а-яё]*\s+проверк[а-яё]*/i, 'обещана «последняя проверка»'],
  [/в\s+прошлый\s+раз/i, '«в прошлый раз» — значит, раз был; его не было'],
  [/молч[а-яё]*\s+с\s+\d/i, 'названо время, с которого молчит'],
  [/(?:молч|ответил)[а-яё]*\s+(?:\{[^}\n]*\}|\d+)\s*из(?![а-яё])/i, 'счёт «сколько из скольких» по невыполненному опросу'],
]

/** 🔴 КОММЕНТАРИИ ВЫРЕЗАЮТСЯ, И ВЫРЕЗАЮТСЯ ЧЕСТНО. В комментариях эти слова
 *  стоят нарочно — там объяснено, что именно убрано и почему; запрещать их там
 *  значит запрещать объяснение. А наивная вырезка `//` спотыкается о `https://`
 *  внутри строки: в `sources.ts` таких адресов 36. Поэтому идём посимвольно и
 *  помним, внутри строки мы или нет. */
export function безКомментариев(код) {
  let вне = ''
  let i = 0
  let строка = null // "'" | '"' | '`'
  while (i < код.length) {
    const c = код[i]
    const д = код[i + 1]
    if (строка) {
      if (c === '\\') { вне += '  '; i += 2; continue }
      if (c === строка) строка = null
      вне += c
      i += 1
      continue
    }
    if (c === "'" || c === '"' || c === '`') { строка = c; вне += c; i += 1; continue }
    if (c === '/' && д === '/') {
      while (i < код.length && код[i] !== '\n') { вне += ' '; i += 1 }
      continue
    }
    if (c === '/' && д === '*') {
      i += 2
      вне += '  '
      while (i < код.length && !(код[i] === '*' && код[i + 1] === '/')) {
        вне += код[i] === '\n' ? '\n' : ' '
        i += 1
      }
      i += 2
      вне += '  '
      continue
    }
    вне += c
    i += 1
  }
  return вне
}

export function беды(файлы) {
  const из = []
  for (const { имя, код } of файлы) {
    const чисто = безКомментариев(код)

    if (имя.endsWith('sources.ts')) {
      const поле = /(^|[\s{,])state\s*[:?]/m.exec(чисто)
      if (поле) {
        из.push(`${имя}: у источника снова есть поле состояния — а опроса по-прежнему нет`)
      }
    }

    const строки = чисто.split('\n')
    for (let n = 0; n < строки.length; n += 1) {
      for (const [что, чем] of ЗАПРЕТ) {
        const м = что.exec(строки[n])
        if (м) из.push(`${имя}:${n + 1}: «${м[0].trim()}» — ${чем}`)
      }
    }

    /* Обратное правило: честная строка обязана быть на месте. Убрать выдумку и
       не поставить взамен ничего — это молча отнять у карточки строку, ради
       которой в каталог и приходят. */
    if (/(?:Hub|Титул)\.tsx$/.test(имя) && !чисто.includes('RIGHTS[')) {
      из.push(`${имя}: карточка источника больше не говорит, что с ним можно (ПРАВИЛА 8.10)`)
    }
  }
  return из
}

