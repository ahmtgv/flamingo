/** Разбор записей исследования внимания SEduM.
 *
 *      node scripts/наука-прогон.mjs <папка с записями> [--отчёт отчёт.md] [--json итог.json]
 *
 *  Папка — распакованная выгрузка (`manage.py наука_выгрузка`, внутри неё
 *  `наука/<код>/<проверка>/…`) или сама папка записей сервера.
 *
 *  🔴 ДВИЖОК ЗДЕСЬ ТОТ ЖЕ САМЫЙ. Прогон ввозит `src/sedum/внимание.ts` и
 *  `src/sedum/числа.ts` — те же файлы, что работают у человека в браузере.
 *  Из записанных точек лица, мимики и поворота он заново собирает каждый кадр
 *  и заново спрашивает движок — с теми же порогами или с другими. Поэтому
 *  «а что было бы при терпении 4 секунды» проверяется за секунды, без людей.
 *
 *  Что считает (docs/SEDUM-ИССЛЕДОВАНИЕ.md, «План разбора»):
 *    1. Точность по шагам: что движок говорил, когда мы точно знали правду.
 *    2. Подбор порогов «по людям»: подбираем на всех, кроме одного, проверяем
 *       на нём; так по кругу. Число, которое мы честно можем обещать.
 *    3. «Думающий» взгляд: сколько длятся отводы глаз, когда человек думает, —
 *       проверка П1 (терпение 5 с) на наших людях, а не на чужой статье.
 *    4. Сонливость: доля закрытых глаз против того, как человек себя оценил.
 *    5. Чтение: предсказывает ли балл ответ «где было внимание».
 *    6. Взгляд по зонам и слежение за точкой: что реально различает камера.
 */
