/* ── 1. Точность по шагам ────────────────────────────────────────────── */

const ОТСТУП = 2000 // первые 2 с шага — человек ещё поворачивается

function оценитьПроверку(п, з, итоги) {
  const шаги = отрезки(п.события)
  const строки = []
  for (const ш of шаги) {
    if (!ш.ждём?.length) continue
    const в = []
    for (let i = 0; i < з.length; i++) {
      const t = з[i].кадр.t
      if (t >= ш.с + ОТСТУП && t < ш.по) в.push(i)
    }
    if (!в.length) continue
    const сейчас = в.filter((i) => ш.ждём.includes(итоги[i].сейчас)).length / в.length
    const засчитано = ш.ждём.includes(итоги[в.at(-1)].состояние)
    строки.push({ метка: ш.метка, ждём: ш.ждём, кадров: в.length, сейчас, засчитано })
  }
  return строки
}

/** Сводка по меткам: средняя доля верных мгновений по людям (макро). */
function сводка(все) {
  const по = {}
  for (const с of все) {
    по[с.метка] ??= { люди: {}, засчитано: [] }
    по[с.метка].люди[с.код] ??= []
    по[с.метка].люди[с.код].push(с.сейчас)
    по[с.метка].засчитано.push(с.засчитано ? 1 : 0)
  }
  return Object.entries(по).map(([метка, д]) => {
    const полюдям = Object.values(д.люди).map((м) => среднее(м))
    return { метка, людей: полюдям.length, верно: среднее(полюдям), ди: бутстреп(полюдям), решение: среднее(д.засчитано) }
  }).sort((а, б) => а.верно - б.верно)
}

const среднее = (м) => (м.length ? м.reduce((а, б) => а + б, 0) / м.length : NaN)
const медиана = (м) => { const с = [...м].sort((а, б) => а - б); const i = с.length >> 1; return с.length ? (с.length % 2 ? с[i] : (с[i - 1] + с[i]) / 2) : NaN }
const доля = (м, f) => (м.length ? м.filter(f).length / м.length : NaN)
const пр = (x) => (Number.isFinite(x) ? `${Math.round(x * 100)}%` : '—')

/** 95% доверительный интервал среднего бутстрепом по людям. */
function бутстреп(м, раз = 1000) {
  if (м.length < 2) return [NaN, NaN]
  let зерно = 12345
  const r = () => ((зерно = (зерно * 1103515245 + 12345) >>> 0) / 4294967296)
  const ср = []
  for (let k = 0; k < раз; k++) {
    let s = 0
    for (let j = 0; j < м.length; j++) s += м[Math.floor(r() * м.length)]
    ср.push(s / м.length)
  }
  ср.sort((а, б) => а - б)
  return [ср[Math.floor(раз * 0.025)], ср[Math.floor(раз * 0.975)]]
}

