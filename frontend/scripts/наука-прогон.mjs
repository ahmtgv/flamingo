function куски(папка, приставка) {
  return readdirSync(папка).filter((f) => f.startsWith(приставка)).sort()
}

function прочитатьПроверку(папка) {
  const meta = JSON.parse(readFileSync(join(папка, 'meta.json'), 'utf8'))
  const события = куски(папка, 'events-').flatMap((f) => readFileSync(join(папка, f), 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)))
  события.sort((а, б) => а.t - б.t)
  const кадры = []
  for (const f of куски(папка, 'frames-')) {
    const б = readFileSync(join(папка, f))
    const сырые = б[0] === 0x1f && б[1] === 0x8b ? gunzipSync(б) : б
    кадры.push(...прочитатьКадры(new Uint8Array(сырые.buffer, сырые.byteOffset, сырые.byteLength)))
  }
  кадры.sort((а, б) => а.t - б.t)
  return { папка, meta, события, кадры }
}

