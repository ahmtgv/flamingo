/* ── 3. «Думающий» взгляд ────────────────────────────────────────────── */

function отводы(п, з, пороги = ПОРОГИ) {
  const н = нормаПроверки(п) ?? БЕЗ_НОРМЫ
  const длины = []
  for (const ш of отрезки(п.события).filter((x) => x.метка === 'думает')) {
    let начало = null
    for (const x of з) {
      const t = x.кадр.t
      if (t < ш.с || t > ш.по) continue
      const ч = x.числа
      const мимо = !ч || Math.abs(ч.рыск - н.рыск) >= пороги.мимо || ч.взглядВбок >= пороги.взгляд
        || ч.тангаж - н.тангаж >= пороги.вниз || ч.тангаж - н.тангаж <= -пороги.вверх
      if (мимо && начало === null) начало = t
      if (!мимо && начало !== null) { длины.push((t - начало) / 1000); начало = null }
    }
    /* Отвод, не кончившийся к ответу, — тоже отвод: обрезаем концом шага. */
    if (начало !== null && Number.isFinite(ш.по)) длины.push((ш.по - начало) / 1000)
  }
  return длины.filter((д) => д >= 0.3)
}

/* ── 4. Сонливость ───────────────────────────────────────────────────── */

function спирмен(x, y) {
  const ранг = (м) => { const п = м.map((v, i) => [v, i]).sort((а, б) => а[0] - б[0]); const р = []; п.forEach(([, i], k) => { р[i] = k }); return р }
  const rx = ранг(x), ry = ранг(y)
  const mx = среднее(rx), my = среднее(ry)
  let a = 0, b = 0, c = 0
  for (let i = 0; i < x.length; i++) { a += (rx[i] - mx) * (ry[i] - my); b += (rx[i] - mx) ** 2; c += (ry[i] - my) ** 2 }
  return a / Math.sqrt(b * c)
}

/* ── 5. Чтение: балл перед вопросом ──────────────────────────────────── */

function ауроК(положительные, отрицательные) {
  if (!положительные.length || !отрицательные.length) return NaN
  let s = 0
  for (const p of положительные) for (const q of отрицательные) s += p > q ? 1 : p === q ? 0.5 : 0
  return s / (положительные.length * отрицательные.length)
}

/* ── 6. Взгляд по зонам ──────────────────────────────────────────────── */

/** Признаки взгляда: поворот головы, мимика глаз и положение радужек между
 *  уголками глаз. Радужки — точки 468 (правая) и 473 (левая) сетки 478. */
function признакиВзгляда(x) {
  const к = x.кадр.лицо
  if (!к) return null
  const т = (i) => [к.точки[i * 3], к.точки[i * 3 + 1]]
  const доляМежду = (радужка, угол1, угол2) => {
    const [rx, ry] = т(радужка), [ax, ay] = т(угол1), [bx, by] = т(угол2)
    const dx = bx - ax, dy = by - ay
    const длина2 = dx * dx + dy * dy || 1
    return [((rx - ax) * dx + (ry - ay) * dy) / длина2, ((rx - ax) * -dy + (ry - ay) * dx) / длина2]
  }
  const [пx, пy] = доляМежду(468, 33, 133)
  const [лx, лy] = доляМежду(473, 362, 263)
  const м = (имя) => к.мимика[НОМЕР[имя]]
  return [
    1, x.числа.рыск / 30, x.числа.тангаж / 30, (пx + лx) / 2, (пy + лy) / 2,
    м('eyeLookOutLeft') - м('eyeLookInLeft'), м('eyeLookInRight') - м('eyeLookOutRight'),
    м('eyeLookUpLeft') + м('eyeLookUpRight') - м('eyeLookDownLeft') - м('eyeLookDownRight'),
  ]
}

/** Гребневая регрессия: (XᵀX + λI) w = Xᵀy. */
function гребень(X, y, λ = 0.05) {
  const n = X[0].length
  const A = Array.from({ length: n }, () => new Array(n).fill(0))
  const b = new Array(n).fill(0)
  for (let k = 0; k < X.length; k++) {
    for (let i = 0; i < n; i++) {
      b[i] += X[k][i] * y[k]
      for (let j = 0; j < n; j++) A[i][j] += X[k][i] * X[k][j]
    }
  }
  for (let i = 1; i < n; i++) A[i][i] += λ * X.length
  for (let i = 0; i < n; i++) {
    let m = i
    for (let r = i + 1; r < n; r++) if (Math.abs(A[r][i]) > Math.abs(A[m][i])) m = r
    ;[A[i], A[m]] = [A[m], A[i]]; [b[i], b[m]] = [b[m], b[i]]
    const p = A[i][i] || 1e-9
    for (let r = 0; r < n; r++) {
      if (r === i) continue
      const f = A[r][i] / p
      for (let c = i; c < n; c++) A[r][c] -= f * A[i][c]
      b[r] -= f * b[i]
    }
  }
  return b.map((v, i) => v / (A[i][i] || 1e-9))
}

const применить = (w, x) => x.reduce((с, v, i) => с + v * w[i], 0)

function зоны(п, з) {
  const шаги = отрезки(п.события)
  const выборка = (фильтр) => з.filter((x) => x.кадр.стимул && x.кадр.лицо && шаги.some((ш) => фильтр(ш) && x.кадр.t >= ш.с + 600 && x.кадр.t < ш.по))
  /* Учимся на первой сетке из девяти точек, проверяем на зонах. */
  const первая = шаги.find((ш) => ш.метка === 'точка' && ш.стимул?.точки?.length === 9)
  if (!первая) return null
  const учёба = выборка((ш) => ш === первая)
  const проверка = выборка((ш) => ш.метка === 'точка' && ш.стимул?.точки?.length === 18)
  if (учёба.length < 20 || проверка.length < 20) return null
  const X = учёба.map(признакиВзгляда)
  const wx = гребень(X, учёба.map((x) => x.кадр.стимул[0]))
  const wy = гребень(X, учёба.map((x) => x.кадр.стимул[1]))
  let колонки = 0, ряды = 0, шесть = 0
  const ошибки = []
  for (const x of проверка) {
    const ф = признакиВзгляда(x)
    const px = применить(wx, ф), py = применить(wy, ф)
    const [tx, ty] = x.кадр.стимул
    const кол = (v) => (v < 1 / 3 ? 0 : v < 2 / 3 ? 1 : 2)
    const ряд = (v) => (v < 0.5 ? 0 : 1)
    if (кол(px) === кол(tx)) колонки += 1
    if (ряд(py) === ряд(ty)) ряды += 1
    if (кол(px) === кол(tx) && ряд(py) === ряд(ty)) шесть += 1
    ошибки.push(Math.hypot(px - tx, py - ty))
  }
  /* Слежение: совпадение хода точки и хода взгляда в окнах по 2 с. */
  const слежение = (метка) => {
    const r = []
    for (const ш of шаги.filter((x) => x.метка === метка)) {
      const в = з.filter((x) => x.кадр.стимул && x.кадр.лицо && x.кадр.t >= ш.с + 500 && x.кадр.t < ш.по)
      for (let i = 0; i + 1 < в.length; i++) {
        const окно = в.filter((x) => x.кадр.t >= в[i].кадр.t && x.кадр.t < в[i].кадр.t + 2000)
        if (окно.length < 8) continue
        const gx = окно.map((x) => применить(wx, признакиВзгляда(x)))
        const sx = окно.map((x) => x.кадр.стимул[0])
        r.push(пирсон(gx, sx))
        i += окно.length - 1
      }
    }
    return r.filter(Number.isFinite)
  }
  const да = слежение('слежение')
  const нет = слежение('не следит')
  return {
    кадровУчёбы: учёба.length, кадровПроверки: проверка.length,
    колонки: колонки / проверка.length, ряды: ряды / проверка.length, шестьЗон: шесть / проверка.length,
    ошибкаДолейЭкрана: медиана(ошибки),
    слежениеR: медиана(да), неСледитR: медиана(нет), слежениеAUC: ауроК(да, нет),
  }
}

function пирсон(a, b) {
  const ma = среднее(a), mb = среднее(b)
  let x = 0, y = 0, z = 0
  for (let i = 0; i < a.length; i++) { x += (a[i] - ma) * (b[i] - mb); y += (a[i] - ma) ** 2; z += (b[i] - mb) ** 2 }
  return x / Math.sqrt(y * z)
}

