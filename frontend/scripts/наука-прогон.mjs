/* ── Шаги: когда что было на экране ──────────────────────────────────── */

/** Отрезки активных шагов из событий: [с, по] в мс записи, метка, ждём. */
function отрезки(события) {
  const итог = []
  let текущий = null
  for (const с of события) {
    if (с.что === 'шаг') {
      if (текущий) { текущий.по = с.t; итог.push(текущий) }
      текущий = { i: с.i, метка: с.метка, ждём: с.ждём ?? [], пишем: с.пишем, с: с.t, по: null, стимул: с.стимул }
    } else if ((с.что === 'шаг-конец' || с.что === 'подготовка' || с.что === 'конец' || с.что === 'ответил' || с.что === 'готово' || с.что === 'пропуск' || с.что === 'не ответил') && текущий) {
      текущий.по = с.t
      итог.push(текущий)
      текущий = null
    }
  }
  if (текущий) { текущий.по = Infinity; итог.push(текущий) }
  return итог
}

