const РАСШИРЕНИЯ = ['.tsx', '.ts']

/** Куда ведут импорты файла — только свои, относительные. */
export function импорты(текст) {
  return [...текст.matchAll(/from\s+'(\.[^']+)'/g)].map((m) => m[1])
}

function разрешить(откуда, куда) {
  const база = `${откуда.slice(0, откуда.lastIndexOf('/'))}/${куда}`.replace(/\/\.\//g, '/')
  const части = []
  for (const ч of база.split('/')) {
    if (ч === '..') части.pop()
    else if (ч !== '.') части.push(ч)
  }
  const путь = части.join('/')
  for (const р of РАСШИРЕНИЯ) if (existsSync(путь + р)) return путь + р
  if (existsSync(путь)) return путь
  return null
}

/** Всё, до чего продукт дотягивается импортами из `App.tsx`, минус сам стенд. */
function достижимое(корень) {
  const виделось = new Set()
  const очередь = [корень]
  while (очередь.length) {
    const ф = очередь.pop()
    if (виделось.has(ф) || ф === СТЕНД) continue
    виделось.add(ф)
    let текст
    try { текст = readFileSync(ф, 'utf8') } catch { continue }
    for (const и of импорты(текст)) {
      const п = разрешить(ф, и)
      if (п) очередь.push(п)
    }
  }
  return виделось
}

/** Пути, которые App.tsx разбирает сам. Берём и `=== '/x'`, и `startsWith('/x/')`. */
function путиПродукта(текст) {
  const из = new Set()
  for (const m of текст.matchAll(/path\s*===\s*'([^']+)'/g)) из.add(m[1])
  for (const m of текст.matchAll(/path\.startsWith\('([^']+)'\)/g)) из.add(m[1])
  return [...из]
}

/** Пути, объявленные в реестре стенда. */
function путиСтенда(текст) {
  const из = new Set()
  for (const m of текст.matchAll(/путь:\s*'([^']+)'/g)) из.add(m[1])
  return [...из]
}

function имена(текст) {
  return [...текст.matchAll(/имя:\s*'([^']+)',\s*путь:/g)].map((m) => m[1])
}

function проверить(приложение, стенд) {
  const надо = путиПродукта(приложение)
  const есть = путиСтенда(стенд)
  /* `*` в реестре — «этот экран показывается на любом непонятном адресе»
     (BadLink). Он закрывает всё, чего App.tsx не разобрал явно. */
  const любой = есть.includes('*')
  return надо.filter((п) => !есть.includes(п) && !(любой && п === '*'))
}

