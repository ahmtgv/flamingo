/* Все свои модули под `src/`. */
function всеМодули(корень) {
  const из = []
  for (const имя of readdirSync(корень)) {
    const п = `${корень}/${имя}`
    if (statSync(п).isDirectory()) из.push(...всеМодули(п))
    else if (РАСШИРЕНИЯ.some((р) => имя.endsWith(р))) из.push(п)
  }
  return из
}

