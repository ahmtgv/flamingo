/** Караул: кадр экрана — поле, кегль, половина починки.
 *
 *  🔴 ЗАЧЕМ. Аудит 07.09 нашёл, что поля экранов разъехались на пять значений
 *  (20, 24, 32, 41, 80), кегли заголовков — на четыре (56, 32, 24, 19), а на
 *  360×740 кнопка «Войти» стояла на 804 px и не доставалась ничем. Последнее
 *  вышло из ПОЛОВИНЫ ПОЧИНКИ: в узком кадре у листа стоял
 *  `align-content: safe center` — и ни одной строки прокрутки. Центрирование
 *  без прокрутки не спасает, оно только прячет обрыв.
 *
 *  Караул читает исходники и держит три правила:
 *
 *  1. `align-content: safe center` без `overflow-y: auto|scroll` в том же
 *     блоке — половина починки, красный.
 *  2. Рамочный блок экрана (`.screen`, `.экран`, `.head`, `.шапка`, `.body`,
 *     `.top`, `.один`) берёт горизонтальное поле только из `var(--поле)` или
 *     `var(--центр)` — либо ноль (ПРАВИЛА 2.2).
 *  3. В экранах нет `--text-display` и `--text-h1`: заголовок страницы —
 *     `--text-h2` (ПРАВИЛА 4.1, решение владельца 07.09).
 *
 *  Исключение оформляется словами в комментарии перед блоком:
 *  `поле-исключение: ...` или `кегль-исключение: ...`. Причина обязана быть
 *  написана — молчаливых исключений тут нет.
 *
 *  Чего караул НЕ умеет: он не открывает браузер и геометрию не меряет.
 *  Настоящий замер — `node scripts/кадр-прибор.mjs` по стенду; он ходит по
 *  двадцати экранам в четырёх кадрах и ищет нажимаемые цели за краем, у
 *  которых ни один предок не прокручивается по нужной оси.
 *
 *  `--selftest` скармливает караулу три заведомо больных куска и требует
 *  красного на каждом.
 */

import { readFileSync, readdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ПАПКА = fileURLToPath(new URL('../src/screens/', import.meta.url))

const РАМОЧНЫЕ = new Set(['screen', 'экран', 'head', 'шапка', 'body', 'top', 'один'])
const ПОЛЕ_МОЖНО = new Set(['var(--поле)', 'var(--центр)', '0'])
const КЕГЛИ_НЕЛЬЗЯ = ['var(--text-display)', 'var(--text-h1)']

/** Куски вида «селектор { тело }» без вложенных фигурных скобок. */
function блоки(css) {
  const без = css.replace(/\/\*[\s\S]*?\*\//g, (м) => ' '.repeat(м.length))
  const из = []
  for (const м of без.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const селектор = м[1].trim().split('\n').pop().trim()
    из.push({ селектор, тело: м[2], начало: м.index, конецСелектора: м.index + м[1].length })
  }
  return из
}

/** Имена классов селектора без псевдо и вложенности. */
function классы(селектор) {
  return [...селектор.matchAll(/\.([A-Za-zА-Яа-яЁё][\w-]*)/g)].map((м) => м[1])
}

/** Горизонтальные значения из объявления padding. */
function поБокам(тело) {
  const из = []
  for (const м of тело.matchAll(/(^|[;{\s])padding(-inline|-left|-right)?\s*:\s*([^;]+)/g)) {
    const свойство = м[2] || ''
    const части = м[3].trim().match(/var\([^)]*\)|calc\([^)]*\)|[^\s]+/g) || []
    if (свойство === '-left' || свойство === '-right') из.push(части[0])
    else if (свойство === '-inline') из.push(части[0], части[1] ?? части[0])
    else if (части.length === 1) из.push(части[0])
    else из.push(части[1], части[3] ?? части[1])
  }
  return из.filter(Boolean)
}

/* 🔴 ОГОВОРКА ЛЕЖИТ МЕЖДУ БЛОКАМИ, А НЕ ПЕРЕД НАЧАЛОМ. Комментарии для
   разбора забиты пробелами, и `начало` блока указывает на место сразу за
   предыдущей `}` — то есть ПЕРЕД комментарием, а не после него. Первая
   версия искала слово левее начала и не находила ничего. */
function оговорка(css, б, слово) {
  const от = Math.max(0, б.начало - 200)
  const до = б.конецСелектора + б.тело.length + 2
  return css.slice(от, до).includes(слово)
}

export function проверить(css, файл) {
  const беды = []
  for (const б of блоки(css)) {
    if (/align-content\s*:\s*safe\s+center/.test(б.тело) && !/overflow-y\s*:\s*(auto|scroll)/.test(б.тело)) {
      беды.push({ файл, селектор: б.селектор, что: 'центрирование без прокрутки — половина починки' })
    }
    if (классы(б.селектор).some((к) => РАМОЧНЫЕ.has(к))) {
      for (const з of поБокам(б.тело)) {
        if (!ПОЛЕ_МОЖНО.has(з) && !оговорка(css, б, 'поле-исключение')) {
          беды.push({ файл, селектор: б.селектор, что: `поле кадра «${з}» вместо var(--поле)` })
        }
      }
    }
    for (const к of КЕГЛИ_НЕЛЬЗЯ) {
      if (б.тело.includes(к) && !оговорка(css, б, 'кегль-исключение')) {
        беды.push({ файл, селектор: б.селектор, что: `кегль ${к}: заголовок страницы — var(--text-h2)` })
      }
    }
  }
  return беды
}

if (process.argv.includes('--selftest')) {
  const больной = [
    '.body { align-content: safe center; padding: var(--space-8) var(--поле); }',
    '.head { padding: var(--space-3) var(--space-5); }',
    '.title { font-size: var(--text-display); }',
  ].join('\n')
  const найдено = проверить(больной, 'самопроверка.css')
  const ждём = ['половина починки', 'поле кадра', 'кегль']
  const мимо = ждём.filter((ж) => !найдено.some((б) => б.что.includes(ж)))
  if (мимо.length) {
    console.log(`❌ самопроверка: караул не заметил — ${мимо.join(', ')}`)
    process.exit(1)
  }
  const здоровый = [
    '.body { align-content: safe center; overflow-y: auto; padding: var(--space-8) var(--поле); }',
    '/* поле-исключение: рабочая поверхность идёт от края до края */',
    '.head { padding: var(--space-1) var(--space-4); }',
  ].join('\n')
  if (проверить(здоровый, 'самопроверка.css').length) {
    console.log('❌ самопроверка: караул ругается на здоровый кусок')
    process.exit(1)
  }
  console.log('✅ самопроверка: половина починки, чужое поле и чужой кегль замечены; оговорка принята')
  process.exit(0)
}

const файлы = readdirSync(ПАПКА).filter((и) => и.endsWith('.module.css'))
const беды = []
for (const и of файлы) беды.push(...проверить(readFileSync(ПАПКА + и, 'utf8'), и))

console.log(`\nКадр: просмотрено модулей экранов — ${файлы.length}`)

if (беды.length) {
  console.log('\n❌ кадр разъехался:\n')
  for (const б of беды) console.log(`   ${б.файл} · ${б.селектор} — ${б.что}`)
  console.log('\n   Поле кадра одно на все экраны (ПРАВИЛА 2.2), заголовок страницы — 24 (ПРАВИЛА 4.1).')
  console.log('   Если экран правда особенный, напишите причину: /* поле-исключение: ... */\n')
  process.exit(1)
}
console.log('✅ поле кадра одно, кегль заголовка один, починок наполовину нет\n')
