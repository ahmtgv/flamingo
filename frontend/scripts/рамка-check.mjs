/** Караул: слой пометок на увеличенной странице.
 *
 *  Заведён вместе с увеличением показа (решение владельца 02.09). Ломается
 *  незаметно: пока страница влезает в кадр, прокрутки нет и всё сходится; беда
 *  вылезает только на увеличенной и прокрученной странице — то есть ровно
 *  тогда, когда преподаватель показывает мелкое место и обводит его.
 *
 *  `--selftest` скармливает караулу СТАРУЮ формулу (без поправки на прокрутку)
 *  и требует красного.
 */

import { рамкаПометок } from '../src/room/рамка.ts'

/** Как было до увеличения: разность прямоугольников, прокрутка не учтена. */
const староеПоведение = (показ, к) => ({
  left: к.left - показ.left,
  top: к.top - показ.top,
  width: к.width,
  height: к.height,
})

// Кадр показа стоит в окне на (100, 50) и имеет 800×600.
const ПОКАЗ = { left: 100, top: 50 }

const случаи = [
  {
    имя: 'страница влезает в кадр, прокрутки нет',
    показ: { ...ПОКАЗ, scrollLeft: 0, scrollTop: 0 },
    // Картинка 600×450 стоит по центру: отступ слева 100, сверху 75.
    картинка: { left: 200, top: 125, width: 600, height: 450 },
    ждём: { left: 100, top: 75, width: 600, height: 450 },
  },
  {
    имя: 'увеличена вдвое, ещё не прокручена',
    показ: { ...ПОКАЗ, scrollLeft: 0, scrollTop: 0 },
    картинка: { left: 100, top: 50, width: 1200, height: 900 },
    ждём: { left: 0, top: 0, width: 1200, height: 900 },
  },
  {
    имя: 'увеличена и прокручена вправо на 400 — ТОТ САМЫЙ',
    показ: { ...ПОКАЗ, scrollLeft: 400, scrollTop: 0 },
    // Прокрутка сдвинула картинку влево: её левый край ушёл за кадр.
    картинка: { left: -300, top: 50, width: 1200, height: 900 },
    ждём: { left: 0, top: 0, width: 1200, height: 900 },
  },
  {
    имя: 'увеличена и прокручена вниз на 300',
    показ: { ...ПОКАЗ, scrollLeft: 0, scrollTop: 300 },
    картинка: { left: 100, top: -250, width: 1200, height: 900 },
    ждём: { left: 0, top: 0, width: 1200, height: 900 },
  },
  {
    имя: 'прокручена и вправо, и вниз',
    показ: { ...ПОКАЗ, scrollLeft: 400, scrollTop: 300 },
    картинка: { left: -300, top: -250, width: 1200, height: 900 },
    ждём: { left: 0, top: 0, width: 1200, height: 900 },
  },
  {
    имя: 'увеличение полтора, прокручена наполовину',
    показ: { ...ПОКАЗ, scrollLeft: 50, scrollTop: 20 },
    картинка: { left: 100, top: 40, width: 900, height: 675 },
    ждём: { left: 50, top: 10, width: 900, height: 675 },
  },
]

function прогон(формула, шумно) {
  let плохо = 0
  for (const с of случаи) {
    const вышло = формула(с.показ, с.картинка)
    const сошлось = ['left', 'top', 'width', 'height'].every((k) => вышло[k] === с.ждём[k])
    if (!сошлось) плохо++
    if (шумно) {
      console.log(`  ${сошлось ? '✅' : '❌'} ${с.имя}`
        + (сошлось ? '' : `\n       вышло ${JSON.stringify(вышло)}\n       ждали ${JSON.stringify(с.ждём)}`))
    }
  }
  return плохо
}

if (process.argv.includes('--selftest')) {
  const плохо = прогон(староеПоведение, false)
  if (плохо < 3) {
    console.error(`❌ КАРАУЛ СЛЕПОЙ: на старой формуле нашёл всего ${плохо} бед. Чинить караул.`)
    process.exit(1)
  }
  console.log(`✅ Караул рамки зряч: на старой формуле красных ${плохо}.`)
  process.exit(0)
}

console.log('\nСлой пометок на увеличенной странице:\n')
const плохо = прогон(рамкаПометок, true)
console.log(плохо ? `\n❌ Красных: ${плохо}\n` : `\n✅ Рамка сходится: ${случаи.length} проверок.\n`)
process.exit(плохо ? 1 : 0)
