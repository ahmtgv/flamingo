/** Караул: пересчёт времени между поясами.
 *
 *  🔴 ПОЧЕМУ ЭТО ПРОВЕРЯЕТСЯ, А НЕ «ВЫГЛЯДИТ ПРАВИЛЬНО». Ошибка в поясах не
 *  видна глазом: 17:00 выглядит как 17:00 всегда. Аудит 07.09 нашёл находку 18
 *  только тем, что открыл один урок в трёх поясах браузера подряд. Здесь то же
 *  самое, но без браузера и на заданных моментах — в том числе на переводе
 *  часов, куда живой прогон почти никогда не попадает.
 *
 *      node scripts/пояс-check.mjs
 */

import { имяПояса, когдаУрок, момент, смещение, уМеня } from '../src/lib/пояс.ts'

let плохо = 0
const проба = (имя, вышло, ждём) => {
  const сошлось = String(вышло) === String(ждём)
  if (!сошлось) плохо++
  console.log(`  ${сошлось ? '✅' : '❌'} ${имя.padEnd(52)} ${вышло}${сошлось ? '' : `   ждали ${ждём}`}`)
}
console.log('\nСмещение считается НА МОМЕНТ, а не «у пояса вообще»:\n')
проба('Москва, сентябрь', смещение('Europe/Moscow', new Date('2026-09-09T00:00:00Z')), 180)
проба('Москва, январь — перевода нет с 2014', смещение('Europe/Moscow', new Date('2026-01-09T00:00:00Z')), 180)
проба('Владивосток', смещение('Asia/Vladivostok', new Date('2026-09-09T00:00:00Z')), 600)
проба('Калининград', смещение('Europe/Kaliningrad', new Date('2026-09-09T00:00:00Z')), 120)
проба('Берлин ЛЕТОМ', смещение('Europe/Berlin', new Date('2026-07-01T00:00:00Z')), 120)
проба('Берлин ЗИМОЙ — тот же пояс, другое смещение', смещение('Europe/Berlin', new Date('2026-01-01T00:00:00Z')), 60)
проба('UTC', смещение('UTC', new Date('2026-09-09T00:00:00Z')), 0)
проба('Катманду — не целый час', смещение('Asia/Kathmandu', new Date('2026-09-09T00:00:00Z')), 345)

console.log('\nНастенные часы + пояс → настоящий момент:\n')
проба('Москва 09.09 10:00', момент('2026-09-09', '10:00', 'Europe/Moscow').toISOString(), '2026-09-09T07:00:00.000Z')
проба('Владивосток 09.09 10:00', момент('2026-09-09', '10:00', 'Asia/Vladivostok').toISOString(), '2026-09-09T00:00:00.000Z')
проба('Берлин 01.07 10:00 (лето)', момент('2026-07-01', '10:00', 'Europe/Berlin').toISOString(), '2026-07-01T08:00:00.000Z')
проба('Берлин 01.01 10:00 (зима)', момент('2026-01-01', '10:00', 'Europe/Berlin').toISOString(), '2026-01-01T09:00:00.000Z')
/* 🔴 ВОТ РАДИ ЧЕГО ХРАНИМ НАСТЕННЫЕ ЧАСЫ, А НЕ МОМЕНТ. Один и тот же «10:00
   по Берлину» до и после перевода часов — это РАЗНЫЕ моменты в UTC. Если бы
   в базе лежал момент, второе занятие уехало бы на час. */
проба('Берлин 28.03 10:00 — накануне перевода', момент('2026-03-28', '10:00', 'Europe/Berlin').toISOString(), '2026-03-28T09:00:00.000Z')
проба('Берлин 30.03 10:00 — после перевода', момент('2026-03-30', '10:00', 'Europe/Berlin').toISOString(), '2026-03-30T08:00:00.000Z')

console.log('\nЧитатель в другом поясе видит СВОИ часы:\n')
{
  const прежний = process.env.TZ
  const вПоясе = (tz, f) => { process.env.TZ = tz; const r = f(); process.env.TZ = прежний; return r }
  // урок поставлен во Владивостоке на 17:00
  const влд = ['2026-09-09', '17:00', 'Asia/Vladivostok']
  проба('во Владивостоке у самого преподавателя',
    вПоясе('Asia/Vladivostok', () => { const у = уМеня(...влд); return `${у.дата} ${у.время} иначе=${у.иначе}` }),
    '2026-09-09 17:00 иначе=false')
  проба('в Калининграде — тот же урок',
    вПоясе('Europe/Kaliningrad', () => { const у = уМеня(...влд); return `${у.дата} ${у.время} иначе=${у.иначе}` }),
    '2026-09-09 09:00 иначе=true')
  проба('в Москве — тот же урок',
    вПоясе('Europe/Moscow', () => { const у = уМеня(...влд); return `${у.дата} ${у.время} иначе=${у.иначе}` }),
    '2026-09-09 10:00 иначе=true')
  /* Через полночь: у ученика это уже ДРУГОЙ ДЕНЬ, и дату показывать обязательно. */
  проба('урок 09.09 09:00 по Владивостоку — в Калининграде это ВЧЕРА',
    вПоясе('Europe/Kaliningrad', () => { const у = уМеня('2026-09-09', '09:00', 'Asia/Vladivostok'); return `${у.дата} ${у.время}` }),
    '2026-09-09 01:00')
  проба('урок 09.09 05:00 по Владивостоку — в Калининграде 08.09',
    вПоясе('Europe/Kaliningrad', () => { const у = уМеня('2026-09-09', '05:00', 'Asia/Vladivostok'); return `${у.дата} ${у.время}` }),
    '2026-09-08 21:00')
}

console.log('\nПустой пояс — «не знаем», и ничего не утверждаем:\n')
{
  const у = уМеня('2026-09-09', '10:00', '')
  проба('время как есть', `${у.дата} ${у.время}`, '2026-09-09 10:00')
  проба('и никакого «иначе»', у.иначе, 'false')
  проба('имя пояса пустое', имяПояса(''), '')
}

console.log('\nИмя пояса для человека:\n')
проба('Москва', имяПояса('Europe/Moscow', new Date('2026-09-09T00:00:00Z')), 'Moscow, UTC+3')
проба('Владивосток', имяПояса('Asia/Vladivostok', new Date('2026-09-09T00:00:00Z')), 'Vladivostok, UTC+10')
проба('Катманду — с минутами', имяПояса('Asia/Kathmandu', new Date('2026-09-09T00:00:00Z')), 'Kathmandu, UTC+5:45')
проба('Нью-Йорк — минус', имяПояса('America/New_York', new Date('2026-01-09T00:00:00Z')), 'New York, UTC−5')

console.log('\nКак это показывается человеку:\n')
{
  const прежний = process.env.TZ
  const вПоясе = (tz, f) => { process.env.TZ = tz; const r = f(); process.env.TZ = прежний; return r }
  const п = (о) => `${о.время}${о.сноска ? ` (${о.сноска})` : ''}`
  проба('свой урок — крупно своё время, приписки нет',
    вПоясе('Asia/Vladivostok', () => п(когдаУрок('2026-09-09', '17:00', 'Asia/Vladivostok'))),
    '17:00')
  проба('чужой пояс — крупно СВОЁ время, рядом чьё оно',
    вПоясе('Europe/Kaliningrad', () => п(когдаУрок('2026-09-09', '17:00', 'Asia/Vladivostok'))),
    '09:00 (17:00 — Vladivostok, UTC+10)')
  проба('через полночь — в приписке появляется ДЕНЬ',
    вПоясе('Europe/Kaliningrad', () => п(когдаУрок('2026-09-09', '05:00', 'Asia/Vladivostok'))),
    '21:00 (09.09 05:00 — Vladivostok, UTC+10)')
  проба('пояса не знаем — ничего не утверждаем',
    вПоясе('Europe/Kaliningrad', () => п(когдаУрок('2026-09-09', '17:00', ''))),
    '17:00')
}

console.log(плохо ? `\n❌ расхождений: ${плохо}\n` : '\n✅ пересчёт сходится\n')
process.exit(плохо ? 1 : 0)
