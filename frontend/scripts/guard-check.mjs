/* Прибор, а не осмотр.
 *
 * Меряет то, что можно померить без браузера, и падает громко. Три проверки — по числу
 * способов, которыми на прошлом проекте молча расходились код и правила:
 *
 *   1. ИМЯ ТОКЕНА, КОТОРОГО НЕТ. `var(--color-text-tertiaty)` работает: CSS молчит,
 *      цвет просто не применяется. В Board.tsx имена токенов читаются ещё и из строки —
 *      опечатка там даёт чёрный штрих вместо зелёного и ни одной ошибки в консоли.
 *   2. ГОЛОЕ ЗНАЧЕНИЕ (ПРАВИЛА 2.8). Разрешены только волосяные 0–3 px и проценты:
 *      всё прочее обязано браться токеном, иначе сетка разъезжается по одному экрану.
 *   3. МОЛЧАЩАЯ КНОПКА (ПРАВИЛА 14.1). Кнопка либо отвечает, либо объявлена немой
 *      словами. Необъявленное молчание неотличимо от дефекта.
 *
 * Запуск:  npm run guards        · npm run guards -- --selftest
 *
 * ⚠️ ПРИБОР ДОКАЗАН ПРОВАЛОМ, А НЕ ОСМОТРОМ (ПРАВИЛА 14.8). В первом же прогоне он
 * объявил дефектом каждый `--space-*`: имена токенов он искал только в начале строки,
 * а в tokens.css они стоят по четыре в ряд. Прибор, который врёт, хуже отсутствующего —
 * поэтому у него есть самопроверка, и она обязана падать на заведомо плохом образце.
 */

import { readdirSync, readFileSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

// В пути проекта есть пробел, а `URL.pathname` отдаёт его как `%20` — и прибор
// падал бы «папки нет» на совершенно здоровом дереве.
const ROOT = fileURLToPath(new URL('..', import.meta.url))
const SRC = join(ROOT, 'src')

/* 🔴 ИМЯ ТОКЕНА БЫВАЕТ КИРИЛЛИЧЕСКИМ. `\w` в JS — это [A-Za-z0-9_], и `--п-текст`
   под него не подходит ни одной буквой после дефисов. Пока класс был `[\w-]`,
   прибор не видел новый набор ВООБЩЕ: ни объявления (значит имя считалось
   неизвестным), ни обращения (значит опечатка в нём проходила молча). Поймано
   самопроверкой на подкладном образце до того, как переведён первый экран. */
const ЧАСТЬ_ИМЕНИ = '[\\p{L}\\p{N}_-]'
const ИМЯ_ОБЪЯВЛЕНИЯ = new RegExp(`(--${ЧАСТЬ_ИМЕНИ}+)\\s*:`, 'gu')
const ИМЯ_В_VAR = new RegExp(`var\\((--${ЧАСТЬ_ИМЕНИ}+)`, 'gu')
const ИМЯ_В_СТРОКЕ = new RegExp(`['"](--${ЧАСТЬ_ИМЕНИ}+)['"]`, 'gu')
/* 🔴 МЕСТНАЯ ПЕРЕМЕННАЯ — НЕ ТОКЕН. Журнал ставит ширину столбца на сам элемент:
   `style={{ ['--скольких']: String(n) }}`, а модуль её читает. Такое имя в наборе
   отсутствует по замыслу, и требовать его там — требовать невозможного. Отличаем
   по синтаксису: объявление — вычисляемый ключ, за которым стоит двоеточие;
   обращение — просто строка. Опечатка при этом ловится по-прежнему: имя, которого
   нет ни в наборах, ни среди объявленных, остаётся дефектом. */
const ОБЪЯВЛЕНИЕ_В_TSX = new RegExp(`\\[\\s*['"](--${ЧАСТЬ_ИМЕНИ}+)['"][^\\]]*\\]\\s*:`, 'gu')

/** Имена, объявленные не в наборе, а на месте: у элемента или внутри модуля. */
export function местные(текст, kind) {
  const out = new Set()
  const re = kind === 'css' ? ИМЯ_ОБЪЯВЛЕНИЯ : ОБЪЯВЛЕНИЕ_В_TSX
  for (const m of текст.matchAll(re)) out.add(m[1])
  return out
}

/** Имена токенов стоят в наборе по нескольку в строке — ищем везде, не в начале. */
export function tokenNames(css) {
  return new Set([...css.matchAll(ИМЯ_ОБЪЯВЛЕНИЯ)].map((m) => m[1]))
}

/** Одна проверка одного файла. Возвращает список дефектов строками. */
export function inspect({ name, text, kind, known }) {
  const out = []
  const say = (line, what) => out.push(`${name}:${line} — ${what}`)
  const lines = text.split('\n')

  /* 🔴 Комментарий определяется СОСТОЯНИЕМ, а не началом строки. Раньше
     строка считалась комментарием, только если сама начиналась с `/*` или `*`.
     Продолжение многострочного комментария под это не подходило — и прибор
     ругался на «раздувала панель на 58px» внутри объяснения. Ругань на прозу
     заставляет писать хуже: значения из комментариев исчезают, а вместе с ними
     и смысл. Поэтому ведём флаг «мы внутри блочного комментария».

     (Границы комментария здесь и ниже собираются из двух половинок строкой —
     иначе они закрыли бы этот самый комментарий раньше времени.) */
  let вКомментарии = false
  const тоже = (line) => {
    let вне = ''
    let i = 0
    while (i < line.length) {
      if (вКомментарии) {
        const к = line.indexOf('*' + '/', i)
        if (к === -1) return вне
        вКомментарии = false
        i = к + 2
      } else {
        const н = line.indexOf('/' + '*', i)
        if (н === -1) return вне + line.slice(i)
        вне += line.slice(i, н)
        вКомментарии = true
        i = н + 2
      }
    }
    return вне
  }

  lines.forEach((строкаЦеликом, i) => {
    const n = i + 1
    const line = kind === 'css' ? тоже(строкаЦеликом) : строкаЦеликом

    for (const m of line.matchAll(ИМЯ_В_VAR)) {
      if (!known.has(m[1])) say(n, `токена нет ни в одном наборе: ${m[1]}`)
    }
    for (const m of line.matchAll(ИМЯ_В_СТРОКЕ)) {
      if (!known.has(m[1])) say(n, `токена нет ни в одном наборе: ${m[1]} (в строке)`)
    }

    if (kind !== 'css') return
    /* 🔴 Условие @media — единственное место в CSS, куда токен подставить НЕЛЬЗЯ:
       медиазапрос читается до каскада и переменных не видит. Прибор, который
       требует здесь токен, требует невозможного — и его начинают обходить, а
       обойдённый прибор перестаёт ловить настоящие голые значения. */
    if (/^\s*@media\b/.test(line)) return

    for (const m of line.matchAll(/(?<![\w-])(\d+(?:\.\d+)?)px/g)) {
      if (Number(m[1]) > 3) say(n, `голый размер ${m[0]} — берётся токеном (ПРАВИЛА 2.8)`)
    }
    for (const m of line.matchAll(/#[0-9a-fA-F]{3,8}\b/g)) {
      say(n, `голый цвет ${m[0]} — берётся токеном (ПРАВИЛА 2.8)`)
    }
  })

  if (kind === 'tsx') {
    for (const m of tags(text, 'button')) {
      const tag = m.tag
      const n = text.slice(0, m.at).split('\n').length
      const answers =
        /onClick=/.test(tag) ||
        /type="submit"/.test(tag) ||
        /data-still=/.test(tag) ||
        /\{\.\.\.rest\}/.test(tag)
      if (!answers) say(n, 'кнопка молчит и не объявлена немой (ПРАВИЛА 14.1)')
    }
  }

  return out
}

/** 🔴 Тег ищется СЧЁТОМ СКОБОК, а не регуляркой до первого «>».
 *  Регулярка `/<button\b[\s\S]*?>/` обрывалась на «>» внутри атрибута — а он там
 *  бывает постоянно: `disabled={i >= n - 1}` и `onClick={() => …}`. Тег обрезался
 *  до `onClick`, и прибор объявлял живую кнопку молчащей. Две таких ложных тревоги
 *  он выдал 01.09 на документе доски. Прибор, который врёт, хуже отсутствующего:
 *  его перестают слушать, и он больше не ловит настоящие дефекты.
 */
export function tags(text, name) {
  const out = []
  const re = new RegExp(`<${name}\\b`, 'g')
  for (const m of text.matchAll(re)) {
    let i = m.index + m[0].length
    let depth = 0
    let quote = ''
    for (; i < text.length; i += 1) {
      const c = text[i]
      if (quote) {
        if (c === quote) quote = ''
        continue
      }
      if (c === '"' || c === "'" || c === '`') quote = c
      else if (c === '{') depth += 1
      else if (c === '}') depth -= 1
      else if (c === '>' && depth === 0) break
    }
    out.push({ at: m.index, tag: text.slice(m.index, i + 1) })
  }
  return out
}

/* ── самопроверка: каждому правилу — свой подкладной образец ─────────────────── */

function selftest() {
  const known = tokenNames(':root { --a: 1px;  --b: 2px;  --п-текст: #26251e; }')
  const cases = [
    ['имя токена есть', { kind: 'css', text: '.x { color: var(--a); }' }, 0],
    ['имени токена нет', { kind: 'css', text: '.x { color: var(--nope); }' }, 1],
    ['имя токена в строке', { kind: 'tsx', text: `const c = '--nope'` }, 1],
    ['волосяная линия', { kind: 'css', text: '.x { border: 1px solid var(--a); }' }, 0],
    ['голый размер', { kind: 'css', text: '.x { padding: 24px; }' }, 1],
    ['голый цвет', { kind: 'css', text: '.x { color: #ff0000; }' }, 1],
    ['значение в комментарии', { kind: 'css', text: '  /* было 24px и #fff */' }, 0],
    /* Ради этих трёх строк правило и переписано: продолжение многострочного
       комментария не начинается ни с /*, ни с *, и раньше считалось кодом. */
    ['значение в продолжении комментария', { kind: 'css', text: '/* панель\n   росла на 58px и цвет был #fff\n   вот так */' }, 0],
    ['код после закрытия комментария', { kind: 'css', text: '/* было\n   иначе */ .x { padding: 24px; }' }, 1],
    ['код перед открытием комментария', { kind: 'css', text: '.x { padding: 24px; } /* было\n   так */' }, 1],
    ['порог медиазапроса', { kind: 'css', text: '@media (max-width: 900px) {' }, 0],
    ['голое значение под медиазапросом', { kind: 'css', text: '@media (min-width: 900px) {\n  .x { padding: 24px; }' }, 1],
    ['кнопка отвечает', { kind: 'tsx', text: '<button onClick={go}>Да</button>' }, 0],
    ['кнопка объявлена немой', { kind: 'tsx', text: '<button data-still="показ">Да</button>' }, 0],
    ['кнопка молчит', { kind: 'tsx', text: '<button className={s.b}>Да</button>' }, 1],
    ['живая кнопка со стрелкой в атрибуте', { kind: 'tsx', text: '<button disabled={i >= n} onClick={() => go(1)}>→</button>' }, 0],
    ['немая кнопка со стрелкой в атрибуте', { kind: 'tsx', text: '<button disabled={i >= n} className={s.b}>→</button>' }, 1],
    ['общая строка токенов', { kind: 'css', text: '.x { margin: var(--b); }' }, 0],
    /* Кириллические имена. Раньше обе строки давали 0 — прибор их не видел вовсе. */
    ['кириллическое имя есть', { kind: 'css', text: '.x { color: var(--п-текст); }' }, 0],
    ['кириллического имени нет', { kind: 'css', text: '.x { color: var(--п-нету); }' }, 1],
    ['кириллическое имя в строке', { kind: 'tsx', text: `const c = '--п-нету'` }, 1],
  ]

  /* Местные имена: объявление у элемента — не дефект, простое обращение — дефект. */
  const объявлено = местные(`style={{ ['--скольких' as string]: String(n) }}`, 'tsx')
  const неОбъявлено = местные(`const c = '--п-нету'`, 'tsx')
  const местноеОк = объявлено.has('--скольких') && объявлено.size === 1 && неОбъявлено.size === 0
  console.log(`${местноеОк ? 'ok  ' : 'ПЛОХО'} местное имя: ждали объявление и не ждали обращение, получили ${объявлено.size}/${неОбъявлено.size}`)

  /* Союз наборов проверяется отдельно от разбора строк: он живёт в другой
     функции, и без этой проверки «прибор знает пергамент» осталось бы словами.
     Подкладывается заведомо РАЗДЕЛЬНОЕ содержимое: если союз склеится не так,
     одно из двух имён потеряется и счёт разойдётся. */
  const союз = наборы((н) => (н.includes('пергамент') ? ':root { --п-текст: #26251e; }' : ':root { --color-text: #111; }'))
  const союзОк = союз.has('--color-text') && союз.has('--п-текст') && союз.size === 2
  console.log(`${союзОк ? 'ok  ' : 'ПЛОХО'} союз наборов: ждали оба имени, получили ${[...союз].join(' ')}`)

  let bad = (союзОк ? 0 : 1) + (местноеОк ? 0 : 1)
  for (const [title, f, expected] of cases) {
    const got = inspect({ name: 'образец', known, ...f }).length
    const ok = got === expected
    if (!ok) bad += 1
    console.log(`${ok ? 'ok  ' : 'ПЛОХО'} ${title}: ждали ${expected}, получили ${got}`)
  }
  if (bad) {
    console.error(`\nСАМОПРОВЕРКА ПРОВАЛЕНА · ${bad} из ${cases.length}`)
    process.exit(1)
  }
  console.log(`\nсамопроверка: ${cases.length} из ${cases.length}`)
}

/* ── прогон по дереву ────────────────────────────────────────────────────────── */

function walk(dir) {
  const out = []
  for (const nm of readdirSync(dir)) {
    const p = join(dir, nm)
    if (statSync(p).isDirectory()) out.push(...walk(p))
    else out.push(p)
  }
  return out
}

/* 🔴 НАБОРОВ ДВА, И ЭТО НАДОЛГО. `tokens.css` держит экраны старого закона,
   `пергамент.css` — переведённые (решение владельца 03.09, docs/ПЕРГАМЕНТ.md).
   Переход идёт по одному экрану, поэтому оба набора живут одновременно, и знать
   прибор обязан оба: иначе первый же переведённый экран краснеет весь целиком.
   Сами наборы из проверки на «голое значение» исключены — объявление токена и
   ЕСТЬ то место, где голому значению положено стоять. */
export const НАБОРЫ = ['styles/tokens.css', 'styles/пергамент.css']

export function наборы(читать) {
  const out = new Set()
  for (const н of НАБОРЫ) for (const имя of tokenNames(читать(н))) out.add(имя)
  return out
}

function run() {
  const known = наборы((н) => readFileSync(join(SRC, н), 'utf8'))
  const defects = []
  let seen = 0

  const файлы = []
  for (const file of walk(SRC)) {
    const kind = file.endsWith('.css') ? 'css' : /\.tsx?$/.test(file) ? 'tsx' : null
    if (!kind) continue
    if (НАБОРЫ.some((н) => file.endsWith(н))) continue
    файлы.push({ file, kind, text: readFileSync(file, 'utf8') })
  }

  // Первый проход — собрать местные имена; второй — проверять. Порядок обхода
  // дерева не должен решать, объявлено имя или нет.
  const свои = new Set()
  for (const ф of файлы) for (const имя of местные(ф.text, ф.kind)) свои.add(имя)
  const всё = new Set([...known, ...свои])

  for (const ф of файлы) {
    seen += 1
    defects.push(
      ...inspect({ name: relative(ROOT, ф.file), text: ф.text, kind: ф.kind, known: всё }),
    )
  }

  if (defects.length) {
    console.error(`ДЕФЕКТ · ${defects.length}\n`)
    defects.forEach((d) => console.error('  ' + d))
    process.exit(1)
  }
  console.log(`ok · токенов известно ${known.size}, местных имён ${свои.size}, файлов просмотрено ${seen}`)
}

if (process.argv.includes('--selftest')) selftest()
else run()
