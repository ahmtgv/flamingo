/** Прибор для правил внимания SEduM (`src/sedum/внимание.ts`).
 *
 *  Живое лицо правилам не нужно: каждый сценарий — это поток придуманных
 *  замеров «как будто камера видела вот это», и прибор проверяет, что балл и
 *  причина ведут себя так, как договорились с владельцем 05.10 и 06.10.
 *
 *  🔴 ПОЧЕМУ ПРИБОР ДО ЖИВОГО ЛИЦА. Пороги будут крутить на стенде, глядя в
 *  камеру. Без прибора каждая такая правка — лотерея: подкрутил «вниз», а
 *  сломалось «пишет». Здесь соседнее ломается громко и сразу.
 *
 *  Сценарии П1–П7 — правки 06.10 (docs/SEDUM-ВНИМАНИЕ-RND.md). У каждой есть
 *  пара: «правка работает» и «соседнее не сломалось».
 *
 *      node scripts/внимание-check.mjs
 */
import { Внимание, ПОРОГИ, БЕЗ_НОРМЫ, СборНормы } from '../src/sedum/внимание.ts'

const ЭКРАН = { экран: true, лицо: true, рыск: 0, тангаж: 0, глаза: 0.1, рот: 0.05, взглядВниз: 0.1, взглядВбок: 0.05 }

/** Прогон: [секунд, замер-поправка, пишем?] … шаг 250 мс, как на стенде.
 *  `норма` не передана — двигатель собирает её сам (П4), как в жизни. */
function прогон(куски, норма, пороги = {}) {
  const в = new Внимание({ ...ПОРОГИ, ...пороги }, норма)
  let t = 0
  let итог
  for (const [сек, поправка, пишем = false] of куски) {
    for (let i = 0; i < сек * 4; i++) {
      t += 250
      итог = в.шаг({ ...ЭКРАН, ...поправка, t }, пишем)
    }
  }
  return { ...итог, в }
}

/** Мигание двух видов кадров: [секунд всего, кадр А, кадр Б, шагов А, шагов Б]. */
function мигание(сек, а, б, шагА, шагБ) {
  const куски = []
  let всего = 0
  while (всего < сек) {
    куски.push([шагА / 4, а], [шагБ / 4, б])
    всего += (шагА + шагБ) / 4
  }
  return куски
}

let всего = 0
let плохо = 0
function да(что, условие, итог) {
  всего += 1
  if (условие) console.log(`  ✅ ${что}`)
  else {
    плохо += 1
    const { в: _, ...видно } = итог ?? {}
    console.log(`  ❌ ${что}\n       ${JSON.stringify(видно)}`)
  }
}

