/** Прибор для правил внимания SEduM (`src/sedum/внимание.ts`).
 *
 *  Живое лицо правилам не нужно: каждый сценарий — это поток придуманных
 *  замеров «как будто камера видела вот это», и прибор проверяет, что балл и
 *  причина ведут себя так, как договорились с владельцем 05.10.
 *
 *  🔴 ПОЧЕМУ ПРИБОР ДО ЖИВОГО ЛИЦА. Пороги будут крутить на стенде, глядя в
 *  камеру. Без прибора каждая такая правка — лотерея: подкрутил «вниз», а
 *  сломалось «пишет». Здесь соседнее ломается громко и сразу.
 *
 *      node scripts/внимание-check.mjs
 */
import { Внимание, ПОРОГИ } from '../src/sedum/внимание.ts'

const ЭКРАН = { экран: true, лицо: true, рыск: 0, тангаж: 0, глаза: 0.1, рот: 0.05, взглядВниз: 0.1, взглядВбок: 0.05 }

/** Прогон: [секунд, замер-поправка, пишем?] … шаг 250 мс, как на стенде. */
function прогон(куски, норма) {
  const в = new Внимание({ ...ПОРОГИ }, норма)
  let t = 0
  let итог
  for (const [сек, поправка, пишем = false] of куски) {
    for (let i = 0; i < сек * 4; i++) {
      t += 250
      итог = в.шаг({ ...ЭКРАН, ...поправка, t }, пишем)
    }
  }
  return итог
}

let всего = 0
let плохо = 0
function да(что, условие, итог) {
  всего += 1
  if (условие) console.log(`  ✅ ${что}`)
  else {
    плохо += 1
    console.log(`  ❌ ${что}\n       ${JSON.stringify(итог)}`)
  }
}

console.log('\nВнимание SEduM:')

let и = прогон([[60, {}]])
да('минуту смотрит на экран — балл высокий, «на экране»', и.балл >= 95 && и.состояние === 'на экране', и)

и = прогон([[30, {}], [2, { рыск: 25 }], [5, {}]])
да('отвёл глаза на 2 секунды — подумал, не в счёт', и.балл >= 95 && и.состояние === 'на экране', и)

и = прогон([[30, {}], [20, { рыск: 50 }]])
да('отвернулся на 20 секунд — «отвернулся», балл ниже 70', и.состояние === 'отвернулся' && и.балл < 70, и)
да('отвернулся — это не тревога', и.тревога === false, и)

и = прогон([[30, {}], [0.25, { глаза: 0.9 }], [5, {}]])
да('моргнул — не в счёт', и.состояние === 'на экране' && и.балл >= 95, и)

и = прогон([[30, {}], [4, { глаза: 0.9 }]])
{
  да('глаза закрыты 4 секунды — «глаза закрыты», без тревоги', и.состояние === 'глаза закрыты' && !и.тревога, и)
}

и = прогон([[30, {}], [12, { глаза: 0.9 }]])
да('глаза закрыты 12 секунд — «заснул», это тревога', и.состояние === 'заснул' && и.тревога, и)

и = прогон([[30, {}], [70, { лицо: false }]])
да('нет в кадре больше минуты — «ушёл», тревога', и.состояние === 'ушёл' && и.тревога, и)
да('…и балл низкий', и.балл < 20, и)

и = прогон([[30, {}], [20, { лицо: false }]])
да('нет в кадре 20 секунд — «нет в кадре», ещё не тревога', и.состояние === 'нет в кадре' && !и.тревога, и)

и = прогон([[30, {}], [10, { тангаж: 30, глаза: 0.7 }]])
да('голова вниз 10 секунд без режима — «смотрит вниз»', и.состояние === 'смотрит вниз', и)

и = прогон([[30, {}], [60, { тангаж: 30, глаза: 0.7 }, true]])
да('голова вниз минуту в режиме «пишем» — «пишет», балл не падает', и.состояние === 'пишет' && и.балл >= 95, и)
да('опущенные веки над тетрадью — не «заснул»', !и.тревога, и)

и = прогон([[30, {}], [3, { экран: false }]])
{
  да('ушёл в другое окно — «другое окно»', и.состояние === 'другое окно', и)
}

и = прогон([[30, {}], [30, { рыск: 50 }], [90, {}]])
да('вернулся после отвлечения — балл восстанавливается', и.состояние === 'на экране' && и.балл >= 85, и)

и = прогон([[60, { тангаж: 12 }]], { рыск: 0, тангаж: 12, взглядВниз: 0.1 })
да('камера над экраном: с нормой взгляд в экран — не «вниз»', и.состояние === 'на экране', и)
и = прогон([[60, { тангаж: 22 }]])
да('…а без нормы тот же наклон считается «вниз»', и.состояние === 'смотрит вниз', и)

/* Свёрнутая вкладка засыпает: между замерами может пройти полминуты. */
{
  const в = new Внимание()
  let t = 0
  for (let i = 0; i < 120; i++) { t += 250; в.шаг({ ...ЭКРАН, t }, false) }
  t += 30_000
  const итог = в.шаг({ ...ЭКРАН, t, экран: false }, false)
  да('пауза в 30 секунд не роняет балл одним прыжком', итог.балл >= 90, итог)
}

console.log(`\n${плохо ? `❌ бед ${плохо}` : '✅ всё сходится'} · проверок ${всего}\n`)
process.exit(плохо ? 1 : 0)
