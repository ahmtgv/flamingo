/** SEduM · внимание на уроке. Чистая логика: ни камеры, ни React, ни сети.
 *
 *  ВНЕ ПРОДУКТА: пока его тянет только стенд внимания (`СтендВнимания.tsx`);
 *  в комнату урока модуль войдёт следующим шагом, после настройки порогов.
 *
 *  🔴 ЗАЧЕМ ОТДЕЛЬНО ОТ КАМЕРЫ. Камера даёт числа, а решение «отвлёкся ли
 *  ученик» — это правила поверх чисел. Правила проверяются прибором
 *  (`scripts/внимание-check.mjs`) на придуманных сценариях: «отвернулся на
 *  20 секунд», «закрыл глаза на 12», «опустил голову в режиме „пишем“». Живое
 *  лицо для этого не нужно — и правка порога не требует садиться перед
 *  камерой, чтобы узнать, не сломалось ли соседнее.
 *
 *  🔴 ЧТО ПРИНЯТО ВЛАДЕЛЬЦЕМ 05.10 И НА ЧЁМ ЭТО СТОИТ.
 *   — Ученик НЕ обязан смотреть в камеру: он смотрит на учителя, на доску, за
 *     курсором, в показ, в методичку. Поэтому меряем «смотрит на экран или
 *     нет», а не «смотрит ли в объектив». Куда именно на экране — следующий
 *     шаг, когда комната начнёт сообщать, что у ученика сейчас открыто.
 *   — Балл 0–100. Учитель видит число и причину, ученик — полоску без цифр.
 *   — Коралловый (тревога) — только «заснул» и «ушёл» (дольше минуты).
 *   — Режим «пишем»: опущенная голова в нём — работа, а не рассеянность.
 *
 *  🔴 ОДИН ОТВЕДЁННЫЙ ВЗГЛЯД НЕ В СЧЁТ. Люди отводят глаза, когда думают, — и
 *  это признак работы. Поэтому отвлечение засчитывается, только если длится
 *  дольше «терпения» (по умолчанию 3 секунды), а сам балл — сглаженный: он
 *  приходит к новому уровню за «память» секунд, а не прыгает за кадром.
 */

export type Замер = {
  /** Время замера, мс. */
  t: number
  /** Страница видна и в фокусе. Нет — ученик в другом окне или свернул. */
  экран: boolean
  /** Лицо в кадре. */
  лицо: boolean
  /** Поворот головы влево-вправо, градусы. Важна величина, знак — нет. */
  рыск: number
  /** Наклон головы, градусы: плюс — вниз, минус — вверх. */
  тангаж: number
  /** Закрытость глаз 0..1, среднее по двум. */
  глаза: number
  /** Открытый рот 0..1 — зевота. */
  рот: number
  /** Взгляд глазами вниз 0..1 (без головы). */
  взглядВниз: number
  /** Взгляд глазами вбок 0..1 (без головы). */
  взглядВбок: number
}

export type Состояние =
  | 'на экране' | 'пишет' | 'зевает' | 'мимо экрана' | 'смотрит вниз'
  | 'отвернулся' | 'глаза закрыты' | 'заснул' | 'нет в кадре' | 'ушёл' | 'другое окно'

export type Пороги = {
  /** Градусы поворота, дальше которых — «отвернулся». */
  поворот: number
  /** Градусы поворота, дальше которых — «мимо экрана». */
  мимо: number
  /** Градусы наклона вниз — «смотрит вниз» (или «пишет» в режиме «пишем»). */
  вниз: number
  /** Градусы наклона вверх — «отвернулся». */
  вверх: number
  /** Закрытость глаз 0..1, выше которой глаза считаются закрытыми. */
  глаза: number
  /** Открытый рот 0..1 — зевок. */
  рот: number
  /** Взгляд глазами вниз или вбок 0..1 сверх нормы. */
  взгляд: number
  /** Секунд отвлечения, которые не в счёт: подумал и вернулся. */
  терпение: number
  /** Секунд с закрытыми глазами до «глаза закрыты». Моргание короче. */
  закрыты: number
  /** Секунд с закрытыми глазами до «заснул». */
  заснул: number
  /** Секунд без лица до «ушёл». */
  ушёл: number
  /** Секунд, за которые балл приходит к новому уровню. */
  память: number
}

export const ПОРОГИ: Пороги = {
  поворот: 35,
  мимо: 18,
  вниз: 20,
  вверх: 25,
  глаза: 0.55,
  рот: 0.55,
  взгляд: 0.45,
  терпение: 3,
  закрыты: 2,
  заснул: 10,
  ушёл: 60,
  память: 30,
}

/** Сколько стоит секунда в каждом состоянии. */
export const ЦЕНА: Record<Состояние, number> = {
  'на экране': 100,
  'пишет': 100,
  'зевает': 70,
  'мимо экрана': 45,
  'смотрит вниз': 35,
  'отвернулся': 10,
  'глаза закрыты': 10,
  'заснул': 0,
  'нет в кадре': 0,
  'ушёл': 0,
  'другое окно': 0,
}

/** Тревога — коралловым. Решение владельца 05.10: только эти два. */
export const ТРЕВОГА: ReadonlySet<Состояние> = new Set<Состояние>(['заснул', 'ушёл'])

/** Как человек смотрит на экран, когда смотрит на экран. Камера ноутбука
 *  стоит над экраном, и взгляд в середину экрана — это голова чуть вниз.
 *  Без нормы такой ученик весь урок числился бы «смотрит вниз». */
export type Норма = { рыск: number; тангаж: number; взглядВниз: number }
export const БЕЗ_НОРМЫ: Норма = { рыск: 0, тангаж: 0, взглядВниз: 0 }

export type Итог = {
  /** 0–100, целое. */
  балл: number
  /** Засчитанное состояние: то, что видит учитель. */
  состояние: Состояние
  /** Сырое состояние этого мгновения — для стенда, не для учителя. */
  сейчас: Состояние
  тревога: boolean
}

/** Хорошие состояния обнуляют счёт отвлечения. */
const ХОРОШО: ReadonlySet<Состояние> = new Set<Состояние>(['на экране', 'пишет'])

/** Сколько секунд отвлечение должно продлиться, чтобы его засчитали.
 *  У «закрыты/заснул/ушёл» своя выдержка уже внутри — второй не нужно. */
function выдержка(с: Состояние, п: Пороги): number {
  if (с === 'другое окно') return 1
  if (с === 'нет в кадре') return 2
  if (с === 'глаза закрыты' || с === 'заснул' || с === 'ушёл') return 0
  return п.терпение
}

/** Состояние одного мгновения, без истории. */
export function мгновение(
  з: Замер, п: Пороги, н: Норма, пишем: boolean, закрытыСек: number, безЛицаСек: number,
): Состояние {
  if (!з.экран) return 'другое окно'
  if (!з.лицо) return безЛицаСек >= п.ушёл ? 'ушёл' : 'нет в кадре'

  const рыск = Math.abs(з.рыск - н.рыск)
  const тангаж = з.тангаж - н.тангаж

  if (рыск >= п.поворот || тангаж <= -п.вверх) return 'отвернулся'

  /* 🔴 НАКЛОН ВНИЗ ПРОВЕРЯЕТСЯ РАНЬШЕ ЗАКРЫТЫХ ГЛАЗ. Когда человек смотрит в
     тетрадь, веки опускаются, и камера видит их почти закрытыми. Проверь мы
     глаза первыми — пишущий ученик через десять секунд «заснул бы». */
  const вниз = тангаж >= п.вниз || з.взглядВниз - н.взглядВниз >= п.взгляд
  if (вниз) return пишем ? 'пишет' : 'смотрит вниз'

  if (з.глаза >= п.глаза) {
    if (закрытыСек >= п.заснул) return 'заснул'
    if (закрытыСек >= п.закрыты) return 'глаза закрыты'
    return 'на экране' // моргнул
  }

  if (рыск >= п.мимо || з.взглядВбок >= п.взгляд) return 'мимо экрана'
  if (з.рот >= п.рот) return 'зевает'
  return 'на экране'
}

export class Внимание {
  пороги: Пороги
  норма: Норма
  private балл = 100
  private прошлое: number | null = null
  private засчитано: Состояние = 'на экране'
  private вне: number | null = null
  private закрытыС: number | null = null
  private безЛицаС: number | null = null

  constructor(пороги: Пороги = ПОРОГИ, норма: Норма = БЕЗ_НОРМЫ) {
    this.пороги = пороги
    this.норма = норма
  }

  сброс(): void {
    this.балл = 100
    this.прошлое = null
    this.засчитано = 'на экране'
    this.вне = null
    this.закрытыС = null
    this.безЛицаС = null
  }

  шаг(з: Замер, пишем: boolean): Итог {
    const п = this.пороги

    /* Таймеры «сколько уже»: глаза закрыты подряд и лица нет подряд. */
    const закрыты = з.экран && з.лицо && з.глаза >= п.глаза
    this.закрытыС = закрыты ? (this.закрытыС ?? з.t) : null
    this.безЛицаС = з.экран && !з.лицо ? (this.безЛицаС ?? з.t) : null
    const закрытыСек = this.закрытыС === null ? 0 : (з.t - this.закрытыС) / 1000
    const безЛицаСек = this.безЛицаС === null ? 0 : (з.t - this.безЛицаС) / 1000

    const сейчас = мгновение(з, п, this.норма, пишем, закрытыСек, безЛицаСек)

    if (ХОРОШО.has(сейчас)) {
      this.вне = null
      this.засчитано = сейчас
    } else {
      this.вне = this.вне ?? з.t
      if ((з.t - this.вне) / 1000 >= выдержка(сейчас, п)) this.засчитано = сейчас
    }

    /* 🔴 ШАГ ВРЕМЕНИ НЕ БОЛЬШЕ СЕКУНДЫ. Свёрнутая вкладка засыпает, и между
       замерами может пройти полминуты. Посчитай мы их разом — балл рухнул бы
       одним прыжком на возвращении, хотя «другое окно» уже было засчитано. */
    const dt = this.прошлое === null ? 0 : Math.min(1, Math.max(0, (з.t - this.прошлое) / 1000))
    this.прошлое = з.t
    const цель = ЦЕНА[this.засчитано]
    this.балл += (цель - this.балл) * (1 - Math.exp(-dt / Math.max(1, п.память)))

    return {
      балл: Math.round(this.балл),
      состояние: this.засчитано,
      сейчас,
      тревога: ТРЕВОГА.has(this.засчитано),
    }
  }
}
