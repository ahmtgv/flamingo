/** SEduM · внимание на уроке. Чистая логика: ни камеры, ни React, ни сети.
 *
 *  Где живёт: комната урока (`room/внимание.ts` — опыт по слову `?внимание=1`,
 *  09.10), страница исследования и стенд внимания (`СтендВнимания.tsx`).
 *
 *  🔴 ЗАЧЕМ ОТДЕЛЬНО ОТ КАМЕРЫ. Камера даёт числа, а решение «отвлёкся ли
 *  ученик» — это правила поверх чисел. Правила проверяются прибором
 *  (`scripts/внимание-check.mjs`) на придуманных сценариях: «отвернулся на
 *  20 секунд», «закрыл глаза на 12», «опустил голову в режиме „пишем“». Живое
 *  лицо для этого не нужно — и правка порога не требует садиться перед
 *  камерой, чтобы узнать, не сломалось ли соседнее. И тот же модуль, без единой
 *  правки, прогоняется по записям исследования (`scripts/наука-прогон.mjs`).
 *
 *  🔴 ЧТО ПРИНЯТО ВЛАДЕЛЬЦЕМ 05.10 И НА ЧЁМ ЭТО СТОИТ.
 *   — Ученик НЕ обязан смотреть в камеру: он смотрит на учителя, на доску, за
 *     курсором, в показ, в методичку. Поэтому меряем «смотрит на экран или
 *     нет», а не «смотрит ли в объектив».
 *   — Балл 0–100. Учитель видит число и причину, ученик — полоску без цифр.
 *   — Коралловый (тревога) — только «заснул» и «ушёл» (дольше минуты).
 *   — Режим «пишем»: опущенная голова в нём — работа, а не рассеянность.
 *
 *  🔴 ПРАВКИ П1–П7 ПРИНЯТЫ ВЛАДЕЛЬЦЕМ 06.10 (docs/SEDUM-ВНИМАНИЕ-RND.md).
 *   П1 Терпение 5 секунд. «Думающий» отвод взгляда длится 3,54 ± 1,26 с
 *      (Andrist 2013): при трёх секундах мы штрафовали бы двое из трёх таких
 *      «дай подумать», при пяти — примерно одно из восьми.
 *   П2 Голова вниз — глаза «не видно». Над тетрадью веки опускаются, и камера
 *      видит их почти закрытыми. Раньше счётчик закрытых глаз в это время
 *      тикал, и поднявший голову ученик мгновенно «засыпал».
 *   П3 Зевок засчитывается через 1,5 с, а не через общее терпение: зевок длится
 *      3–3,8 с (Provine 1986), при терпении 5 с он перестал бы считаться. Речь
 *      открывает рот короче.
 *   П4 Личная норма век и рта. Единый порог 0,55 врёт узким глазам и очкам:
 *      глаза закрыты, когда раскрытие век (EAR, Soukupová 2016) меньше 75% от
 *      своего; рот — 140% от своего (Ersoy 2026). Норма собирается сама за
 *      первые полминуты, если её не запомнили вручную.
 *   П5 Доля закрытых глаз за минуту (PERCLOS, Dinges 1998) — только по кадрам,
 *      где глаза видно. Учителю не показывается: решение владельца — пока
 *      только стенд.
 *   П6 Плохо видно (темно, лицо обрезано, далеко) — балл и причина замирают:
 *      плохая камера — не вина ученика. Новой подписи нет — решение владельца.
 *   П7 «Глаза закрыты» и «заснул» — только если глаза было видно хотя бы в 70%
 *      времени: не тревожить коралловым, когда камера сама не уверена.
 */

export type Качество = 'хорошо' | 'обрезано' | 'далеко' | 'темно'

export type Замер = {
  /** Время замера, мс. */
  t: number
  /** Страница видна и в фокусе. Нет — ученик в другом окне или свернул. */
  экран: boolean
  /** Лицо в кадре. */
  лицо: boolean
  /** Поворот головы влево-вправо, градусы. Важна величина, знак — нет. */
  рыск: number
  /** Наклон головы, градусы: плюс — вниз, минус — вверх. */
  тангаж: number
  /** Закрытость глаз 0..1 по модели (blendshape), среднее по двум. */
  глаза: number
  /** Открытый рот 0..1 — зевота. */
  рот: number
  /** Взгляд глазами вниз 0..1 (без головы). */
  взглядВниз: number
  /** Взгляд глазами вбок 0..1 (без головы). */
  взглядВбок: number
  /** Раскрытие век по точкам (EAR) — у более открытого глаза. Нет — не посчитано. */
  веко?: number | null
  /** Можно ли верить кадру. Нет поля — значит «хорошо». */
  качество?: Качество
}

export type Состояние =
  | 'на экране' | 'пишет' | 'зевает' | 'мимо экрана' | 'смотрит вниз'
  | 'отвернулся' | 'глаза закрыты' | 'заснул' | 'нет в кадре' | 'ушёл' | 'другое окно'

export type Пороги = {
  /** Градусы поворота, дальше которых — «отвернулся». */
  поворот: number
  /** Градусы поворота, дальше которых — «мимо экрана». */
  мимо: number
  /** Градусы наклона вниз — «смотрит вниз» (или «пишет» в режиме «пишем»). */
  вниз: number
  /** Градусы наклона вверх — «отвернулся». */
  вверх: number
  /** Закрытость глаз 0..1 по модели — пока нет личной нормы век. */
  глаза: number
  /** Раскрытие век меньше этой доли от своего — глаза закрыты (П4). */
  веко: number
  /** Открытый рот 0..1 — зевок, если своя норма меньше. */
  рот: number
  /** Рот больше этой доли от своего — зевок (П4). */
  ротДоля: number
  /** Взгляд глазами вниз или вбок 0..1 сверх нормы. */
  взгляд: number
  /** Секунд отвлечения, которые не в счёт: подумал и вернулся (П1). */
  терпение: number
  /** Секунд открытого рта до «зевает» (П3). */
  зевок: number
  /** Секунд с закрытыми глазами до «глаза закрыты». Моргание короче. */
  закрыты: number
  /** Секунд с закрытыми глазами до «заснул». */
  заснул: number
  /** Доля времени, когда глаза было видно, без которой сна не засчитываем (П7). */
  видимых: number
  /** Секунд без лица до «ушёл». */
  ушёл: number
  /** Секунд, за которые балл приходит к новому уровню. */
  память: number
  /** Окно доли закрытых глаз, секунд (П5). */
  окноСна: number
  /** Секунд кадров «на экран» для личной нормы, собираемой самой (П4). */
  сборНормы: number
}

