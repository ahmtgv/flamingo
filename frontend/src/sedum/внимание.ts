/** Как человек смотрит на экран, когда смотрит на экран. Камера ноутбука
 *  стоит над экраном, и взгляд в середину экрана — это голова чуть вниз.
 *  Без нормы такой ученик весь урок числился бы «смотрит вниз».
 *  `веко` и `рот` — личные: раскрытие век и положение рта в покое (П4). */
export type Норма = { рыск: number; тангаж: number; взглядВниз: number; веко: number | null; рот: number }
export const БЕЗ_НОРМЫ: Норма = { рыск: 0, тангаж: 0, взглядВниз: 0, веко: null, рот: 0 }

export type Итог = {
  /** 0–100, целое. */
  балл: number
  /** Засчитанное состояние: то, что видит учитель. */
  состояние: Состояние
  /** Сырое состояние этого мгновения — для стенда, не для учителя. */
  сейчас: Состояние
  тревога: boolean
  /** Доля закрытых глаз за окно 0..1 (П5) — только стенд. Нет — мало видимых кадров. */
  перклос: number | null
  /** Качество кадра (П6) — только стенд. Не «хорошо» — балл и причина замерли. */
  качество: Качество
}

/** Хорошие состояния обнуляют счёт отвлечения. */
const ХОРОШО: ReadonlySet<Состояние> = new Set<Состояние>(['на экране', 'пишет'])

/** Сколько секунд отвлечение должно продлиться, чтобы его засчитали.
 *  У «закрыты/заснул/ушёл» своя выдержка уже внутри — второй не нужно. */
function выдержка(с: Состояние, п: Пороги): number {
  if (с === 'другое окно') return 1
  if (с === 'нет в кадре') return 2
  if (с === 'зевает') return п.зевок
  if (с === 'глаза закрыты' || с === 'заснул' || с === 'ушёл') return 0
  return п.терпение
}

/** Голова или взгляд опущены: веки камере не видны (П2). */
export function глазаВидно(з: Замер, п: Пороги, н: Норма): boolean {
  if (!з.экран || !з.лицо) return false
  const тангаж = з.тангаж - н.тангаж
  return тангаж < п.вниз && з.взглядВниз - н.взглядВниз < п.взгляд
}

/** Закрыты ли глаза в этом кадре. С личной нормой век — по ней (П4); без неё —
 *  по общему порогу модели, как было. */
export function глазаЗакрыты(з: Замер, п: Пороги, н: Норма): boolean {
  if (н.веко !== null && н.веко > 0 && з.веко != null) return з.веко < п.веко * н.веко
  return з.глаза >= п.глаза
}

/** Порог рта: общий или 140% от своего — что больше (П4). */
function порогРта(п: Пороги, н: Норма): number {
  return Math.max(п.рот, п.ротДоля * н.рот)
}

/** Состояние одного мгновения, без истории.
 *  `закрытыСек` — сколько глаза закрыты подряд, уже с поправкой на видимость. */
export function мгновение(
  з: Замер, п: Пороги, н: Норма, пишем: boolean, закрытыСек: number, безЛицаСек: number,
): Состояние {
  if (!з.экран) return 'другое окно'
  if (!з.лицо) return безЛицаСек >= п.ушёл ? 'ушёл' : 'нет в кадре'

  const рыск = Math.abs(з.рыск - н.рыск)
  const тангаж = з.тангаж - н.тангаж

  if (рыск >= п.поворот || тангаж <= -п.вверх) return 'отвернулся'

  /* 🔴 НАКЛОН ВНИЗ ПРОВЕРЯЕТСЯ РАНЬШЕ ЗАКРЫТЫХ ГЛАЗ. Когда человек смотрит в
     тетрадь, веки опускаются, и камера видит их почти закрытыми. Проверь мы
     глаза первыми — пишущий ученик через десять секунд «заснул бы». */
  if (!глазаВидно(з, п, н)) return пишем ? 'пишет' : 'смотрит вниз'

  if (глазаЗакрыты(з, п, н)) {
    if (закрытыСек >= п.заснул) return 'заснул'
    if (закрытыСек >= п.закрыты) return 'глаза закрыты'
    return 'на экране' // моргнул
  }

  if (рыск >= п.мимо || з.взглядВбок >= п.взгляд) return 'мимо экрана'
  if (з.рот >= порогРта(п, н)) return 'зевает'
  return 'на экране'
}

/* ── Личная норма, собираемая самой (П4) ──────────────────────────────── */

const медиана = (ч: number[]): number => {
  const с = [...ч].sort((а, б) => а - б)
  const м = с.length >> 1
  return с.length % 2 ? с[м] : (с[м - 1] + с[м]) / 2
}

/** Копит кадры «человек спокойно смотрит в экран» и отдаёт норму медианами.
 *
 *  🔴 МЕДИАНА, А НЕ СРЕДНЕЕ. Моргание, взгляд в сторону, кашель попадают в
 *  выборку всегда. Среднее они сдвигают, медиана их не замечает, пока их
 *  меньше половины. И кадры заведомо «не туда» сюда не попадают вовсе: голова
 *  повёрнута больше чем на 20°, наклонена больше чем на 18° вниз или 10° вверх.
 *  18° — потому что камера ноутбука над экраном: взгляд в середину экрана — это
 *  голова на 5–15° вниз, а дальше начинается тетрадь, и норма «научилась бы»
 *  считать тетрадь экраном. */
export class СборНормы {
  private кадры: Замер[] = []
  private набрано = 0
  private прошлое: number | null = null
  /* 🔴 Не `constructor(readonly нужно)`: прибор и прогон записей читают этот
     файл голым Node, а он не понимает «свойств в параметрах» TypeScript. */
  readonly нужно: number
  constructor(нужно: number) { this.нужно = нужно }

  /** Подходит ли кадр для нормы. Абсолютные углы — норма ещё неизвестна. */
  static годится(з: Замер): boolean {
    return з.экран && з.лицо && (з.качество ?? 'хорошо') === 'хорошо'
      && Math.abs(з.рыск) < 20 && з.тангаж < 18 && з.тангаж > -10
      && з.взглядВниз < 0.45 && з.взглядВбок < 0.45
  }

  добавить(з: Замер): void {
    const dt = this.прошлое === null ? 0 : Math.min(1, Math.max(0, (з.t - this.прошлое) / 1000))
    this.прошлое = з.t
    if (!СборНормы.годится(з)) return
    this.кадры.push(з)
    this.набрано += dt
  }

  get секунд(): number { return this.набрано }
  get готово(): boolean { return this.набрано >= this.нужно && this.кадры.length >= 5 }

  норма(): Норма | null {
    if (this.кадры.length < 5) return null
    const к = this.кадры
    const века = к.map((з) => з.веко).filter((в): в is number => typeof в === 'number' && в > 0)
    return {
      рыск: медиана(к.map((з) => з.рыск)),
      тангаж: медиана(к.map((з) => з.тангаж)),
      взглядВниз: медиана(к.map((з) => з.взглядВниз)),
      веко: века.length >= 5 ? медиана(века) : null,
      рот: медиана(к.map((з) => з.рот)),
    }
  }
}

/* ── Двигатель ────────────────────────────────────────────────────────── */

/** Откуда норма: нет, собрана сама (П4) или запомнена человеком. */
export type Откуда = 'нет' | 'сама' | 'вручную'

/** Сколько секунд глаза могут быть «не видно» внутри одного закрытия.
 *  Дольше — закрытие начинается заново: долгое «голова вниз» — это уже не
 *  «моргнул на опущенной голове», а другое состояние. */
const ПРОБЕЛ_СЕК = 2

export class Внимание {
  пороги: Пороги
  private _норма: Норма
  private _откуда: Откуда
  private сбор: СборНормы | null
  private балл = 100
  private прошлое: number | null = null
  private засчитано: Состояние = 'на экране'
  private сейчас: Состояние = 'на экране'
  private вне: number | null = null
  private безЛицаС: number | null = null
  /* Закрытие глаз подряд: начало, сколько из него глаза было видно, и с какого
     мгновения их не видно сейчас (П2, П7). */
  private закрытыС: number | null = null
  private закрытоВидно = 0
  private невидноС: number | null = null
  /* Окно доли закрытых глаз: только видимые кадры (П5). */
  private окно: { t: number; dt: number; закрыты: boolean; видно: boolean }[] = []
  private начало: number | null = null

  /** `норма` передана — она «вручную», и сама не собирается. Не передана —
   *  собирается из первых `сборНормы` секунд спокойного взгляда в экран. */
  constructor(пороги: Пороги = ПОРОГИ, норма?: Норма) {
    this.пороги = пороги
    this._норма = норма ?? БЕЗ_НОРМЫ
    this._откуда = норма ? 'вручную' : 'нет'
    this.сбор = норма ? null : new СборНормы(пороги.сборНормы)
  }

  get норма(): Норма { return this._норма }
  get откуда(): Откуда { return this._откуда }
  /** Сколько секунд нормы уже собрано сама — для стенда. */
  get собраноСек(): number { return this.сбор?.секунд ?? 0 }

  /** Норма, запомненная человеком: сама больше не собирается. */
  задатьНорму(н: Норма): void {
    this._норма = н
    this._откуда = 'вручную'
    this.сбор = null
  }

  /** Забыть норму и собрать её заново самой. */
  забытьНорму(): void {
    this._норма = БЕЗ_НОРМЫ
    this._откуда = 'нет'
    this.сбор = new СборНормы(this.пороги.сборНормы)
  }

  сброс(): void {
    this.балл = 100
    this.прошлое = null
    this.засчитано = 'на экране'
    this.сейчас = 'на экране'
    this.вне = null
    this.безЛицаС = null
    this.закрытыС = null
    this.закрытоВидно = 0
    this.невидноС = null
    this.окно = []
    this.начало = null
  }

  шаг(з: Замер, пишем: boolean): Итог {
    const п = this.пороги
    const качество = з.качество ?? 'хорошо'

    /* 🔴 ШАГ ВРЕМЕНИ НЕ БОЛЬШЕ СЕКУНДЫ. Свёрнутая вкладка засыпает, и между
       замерами может пройти полминуты. Посчитай мы их разом — балл рухнул бы
       одним прыжком на возвращении, хотя «другое окно» уже было засчитано. */
    const dt = this.прошлое === null ? 0 : Math.min(1, Math.max(0, (з.t - this.прошлое) / 1000))
    this.прошлое = з.t
    this.начало ??= з.t

    /* П4: норма собирается сама, пока её не запомнили вручную. */
    if (this.сбор) {
      this.сбор.добавить(з)
      if (this.сбор.готово) {
        const н = this.сбор.норма()
        if (н) { this._норма = н; this._откуда = 'сама' }
        this.сбор = null
      }
    }
    const н = this._норма

    /* П6: камера плохо видит — замираем. Счётчики начнутся заново, когда
       видно станет хорошо: копить «отвлечение» вслепую нечестно. */
    if (з.экран && з.лицо && качество !== 'хорошо') {
      this.вне = null
      this.закрытыС = null
      this.закрытоВидно = 0
      this.невидноС = null
      this.безЛицаС = null
      return this.итог(качество)
    }

    /* Лицо пропало — считаем подряд. */
    this.безЛицаС = з.экран && !з.лицо ? (this.безЛицаС ?? з.t) : null
    const безЛицаСек = this.безЛицаС === null ? 0 : (з.t - this.безЛицаС) / 1000

    /* П2, П7: закрытые глаза считаем только там, где их видно. Короткое «не
       видно» внутри закрытия терпим, долгое — начинает счёт заново. */
    const видно = глазаВидно(з, п, н)
    const закрыты = видно && глазаЗакрыты(з, п, н)
    if (!з.экран || !з.лицо) {
      this.закрытыС = null
      this.закрытоВидно = 0
      this.невидноС = null
    } else if (видно) {
      this.невидноС = null
      if (закрыты) {
        if (this.закрытыС === null) { this.закрытыС = з.t; this.закрытоВидно = 0 } else this.закрытоВидно += dt
      } else {
        this.закрытыС = null
        this.закрытоВидно = 0
      }
    } else if (this.закрытыС !== null) {
      this.невидноС ??= з.t
      if ((з.t - this.невидноС) / 1000 > ПРОБЕЛ_СЕК) {
        this.закрытыС = null
        this.закрытоВидно = 0
        this.невидноС = null
      }
    }
    const длится = this.закрытыС === null ? 0 : (з.t - this.закрытыС) / 1000
    const доля = длится > 0 ? this.закрытоВидно / длится : 1
    const закрытыСек = доля >= п.видимых ? длится : 0

    /* П5: окно доли закрытых глаз. */
    if (з.экран && з.лицо) this.окно.push({ t: з.t, dt, закрыты, видно })
    const край = з.t - п.окноСна * 1000
    while (this.окно.length && this.окно[0].t < край) this.окно.shift()

    const сейчас = мгновение(з, п, н, пишем, закрытыСек, безЛицаСек)
    this.сейчас = сейчас

    if (ХОРОШО.has(сейчас)) {
      this.вне = null
      this.засчитано = сейчас
    } else {
      this.вне = this.вне ?? з.t
      if ((з.t - this.вне) / 1000 >= выдержка(сейчас, п)) this.засчитано = сейчас
    }

    const цель = ЦЕНА[this.засчитано]
    this.балл += (цель - this.балл) * (1 - Math.exp(-dt / Math.max(1, п.память)))

    return this.итог('хорошо')
  }

  /** Доля закрытых глаз за окно, только по видимым кадрам (П5). Видимых
   *  меньше 70% окна — числа нет: по такому окну о сне не судят. */
  перклос(): number | null {
    const п = this.пороги
    if (!this.окно.length || this.начало === null || this.прошлое === null) return null
    const прожито = Math.min(п.окноСна, (this.прошлое - this.начало) / 1000)
    if (прожито < 20) return null
    let видно = 0
    let закрыто = 0
    for (const к of this.окно) {
      if (!к.видно) continue
      видно += к.dt
      if (к.закрыты) закрыто += к.dt
    }
    if (видно < п.видимых * прожито) return null
    return закрыто / видно
  }

  private итог(качество: Качество): Итог {
    return {
      балл: Math.round(this.балл),
      состояние: this.засчитано,
      сейчас: this.сейчас,
      тревога: ТРЕВОГА.has(this.засчитано),
      перклос: this.перклос(),
      качество,
    }
  }
}
