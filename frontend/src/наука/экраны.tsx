/* ── О вас ────────────────────────────────────────────────────────────── */

export type Анкета = Record<string, string>

export function ОВас({ имя, занят, ошибка, onДальше }: { имя: string | null; занят?: boolean; ошибка?: string; onДальше: (анкета: Анкета) => void }) {
  const [возраст, setВозраст] = useState('')
  const [пол, setПол] = useState<string | null>(null)
  const [очки, setОчки] = useState<string | null>(null)
  const [рука, setРука] = useState<string | null>(null)
  const [заметка, setЗаметка] = useState('')
  const собрать = (): Анкета => {
    const а: Анкета = {}
    if (возраст.trim()) а['возраст'] = возраст.trim()
    if (пол) а['пол'] = пол
    if (очки) а['очки'] = очки
    if (рука) а['рука'] = рука
    if (заметка.trim()) а['заметка'] = заметка.trim()
    return а
  }
  return (
    <Рама раздел={тр("Исследование внимания")} место={тр("о вас")} право={<Шаги сейчас={2} />}
      низ={(
        <>
          <span className={`${s.низСлова} ${ошибка ? s.ошибка : ''}`} role="status">{ошибка || тр("Всё по желанию — можно пропустить.")}</span>
          <Button kind="quiet" disabled={занят} onClick={() => onДальше({})}>{тр("Пропустить")}</Button>
          <Button kind="go" disabled={занят} onClick={() => onДальше(собрать())}>{занят ? тр("Сохраняем…") : тр("Дальше — к пути")}</Button>
        </>
      )}
    >
      <div className={s.анкета}>
        <div className={s.анкетаШапка}>
          <div className={s.шапкаТекста}>
            <h1 className={`${s.заголовок} ${s.наБелом}`}>{имя ? тр("Немного о вас, {1}", { 1: имя }) : тр("Немного о вас")}</h1>
            <p className={`${s.лид} ${s.наБелом}`}>{тр("Всё по желанию. Ответы помогают понять, где система ошибается: например, чаще ли у тех, кто в очках.")}</p>
          </div>
          <Очки />
        </div>
        <div className={`${s.листок} ${s.анкетаЛисток}`}>
          <div className={s.возраст}>
            <Field label={тр("Возраст")} inputMode="numeric" maxLength={3} value={возраст} onChange={(e) => setВозраст(e.target.value.replace(/\D/g, ''))} />
          </div>
          <Выбор подпись={тр("Пол")} значение={пол} onВыбор={setПол} варианты={[{ ключ: 'ж', слова: тр("Женский") }, { ключ: 'м', слова: тр("Мужской") }, { ключ: '—', слова: тр("Не скажу") }]} />
          <Выбор подпись={тр("Очки или линзы")} значение={очки} onВыбор={setОчки} варианты={[{ ключ: 'нет', слова: тр("Нет") }, { ключ: 'очки', слова: тр("Очки") }, { ключ: 'линзы', слова: тр("Линзы") }, { ключ: 'иногда', слова: тр("Иногда") }]} />
          <Выбор подпись={тр("Какой рукой пишете")} значение={рука} onВыбор={setРука} варианты={[{ ключ: 'правая', слова: тр("Правой") }, { ключ: 'левая', слова: тр("Левой") }]} />
          {/* «Кто вы на уроке» убран (владелец, 06.10): для сбора записей не важно. */}
          <div className={s.воВсюШирину}>
            <Field label={тр("Что ещё нам стоит знать")} placeholder={тр("Например: ноутбук на коленях, одна камера на двоих")} maxLength={500} value={заметка} onChange={(e) => setЗаметка(e.target.value)} />
          </div>
        </div>
      </div>
    </Рама>
  )
}

