/** Выбор одного из нескольких — нейтральной рамкой, как роль при регистрации. */
export function Выбор<T extends string | number>({ подпись, пояснение, варианты, значение, onВыбор, столбцом, крупно, className, кнопкаКласс }: {
  подпись: string
  /** Мелко под вопросом — например, что значат края шкалы. */
  пояснение?: string
  /** Подпись — целый вопрос, а не метка поля: обычным шрифтом, не прописными. */
  крупно?: boolean
  варианты: { ключ: T; слова: string; ещё?: string }[]
  значение: T | null
  onВыбор: (к: T) => void
  столбцом?: boolean
  className?: string
  кнопкаКласс?: string
}) {
  return (
    <fieldset className={s.выбор}>
      <legend className={крупно ? s.подписьВопрос : s.подпись}>
        {подпись}
        {пояснение ? <span className={s.пояснение}>{пояснение}</span> : null}
      </legend>
      <div className={className ?? `${s.варианты} ${столбцом ? s.столбцом : ''}`} role="radiogroup" aria-label={подпись}>
        {варианты.map((в) => (
          <button
            key={String(в.ключ)}
            type="button"
            role="radio"
            aria-checked={значение === в.ключ}
            className={`${s.вариант} ${значение === в.ключ ? s.вариантДа : ''} ${кнопкаКласс ?? ''}`}
            onClick={() => onВыбор(в.ключ)}
          >
            {в.слова}
            {в.ещё ? <span className={s.вариантЕщё}>{в.ещё}</span> : null}
          </button>
        ))}
      </div>
    </fieldset>
  )
}

/** Подпись в шапке: «Адель · это не я». На личной ссылке «не я» некуда вести. */
export function КтоЯ({ имя, onНеЯ }: { имя: string | null; onНеЯ?: () => void }) {
  if (!имя && !onНеЯ) return null
  return (
    <>
      {имя ? <span>{имя}</span> : null}
      {имя && onНеЯ ? <span aria-hidden>·</span> : null}
      {onНеЯ ? <button type="button" className={s.строчно} onClick={onНеЯ}>это не я</button> : null}
    </>
  )
}

