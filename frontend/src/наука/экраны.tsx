/** «1 раз», «2 раза», «5 раз». */
export const раз = (n: number) => {
  const д = n % 100
  const е = n % 10
  return `${n} ${д >= 11 && д <= 14 ? 'раз' : е >= 2 && е <= 4 ? 'раза' : 'раз'}`
}

/** Проверка пройдена — дошла до конца, а не остановлена на полпути. */
export const пройдена = (п: ОДоброволеце['проверки'][number]) => Boolean(п.закончена) && !п.прервана

/** Какую проверку предложить: сначала «Точную настройку», дальше ту, что проходили реже, по порядку пути. */
export function следующая(проверки: ОДоброволеце['проверки']): ВидПроверки {
  const сколько = (в: ВидПроверки) => проверки.filter((п) => п.вид === в && пройдена(п)).length
  if (!сколько('настройка')) return 'настройка'
  return [...ПРОВЕРКИ].filter((п) => п.вид !== 'голос').sort((а, б) => сколько(а.вид) - сколько(б.вид))[0].вид
}

const часть = (iso: string): 'утро' | 'день' | 'вечер' | null => {
  const ч = new Date(iso).getHours()
  if (Number.isNaN(ч)) return null
  return ч < 12 ? 'утро' : ч < 18 ? 'день' : 'вечер'
}

export function Путь({ имя, проверки, onНачать, onНеЯ }: {
  имя: string | null
  проверки: ОДоброволеце['проверки']
  onНачать: (вид: ВидПроверки) => void
  onНеЯ?: () => void
}) {
  const [выбрано, setВыбрано] = useState<ВидПроверки>(() => следующая(проверки))
  const готовые = проверки.filter(пройдена)
  const сколько = (в: ВидПроверки) => готовые.filter((п) => п.вид === в).length
  const описание = ПРОВЕРКИ.find((п) => п.вид === выбрано)!
  const пройдено = ПРОВЕРКИ.filter((п) => сколько(п.вид) > 0).length
  /* «Записано» — всё, что доехало до нас, и остановленные проверки тоже. */
  const минут = Math.round(проверки.filter((п) => п.закончена).reduce((сумма, п) => сумма + Math.max(0, (Date.parse(п.закончена!) - Date.parse(п.начата)) / 60_000), 0))
  const части = { утро: 0, день: 0, вечер: 0 }
  for (const п of готовые) { const ч = часть(п.начата); if (ч) части[ч] += 1 }
  const неБыло = (['вечер', 'утро', 'день'] as const).find((ч) => !части[ч])
  const виды = ПРОВЕРКИ.map((п) => п.вид)

  return (
    <Рама раздел="Исследование внимания" место="путь" справа={<КтоЯ имя={имя} onНеЯ={onНеЯ} />}
      право={<Огонёк>камера пока выключена</Огонёк>}
      низ={(
        <>
          <span className={`${s.низСлова} ${s.моно}`}>пройдено {пройдено} из {ПРОВЕРКИ.length} · записано {минут} мин</span>
          <Button kind="go" onClick={() => onНачать(выбрано)}>
            {сколько(выбрано) ? `Пройти «${описание.название}» ещё раз` : `Начать «${описание.название}»`}
          </Button>
        </>
      )}
    >
      <div className={s.путь}>
        <div className={s.путьСлева}>
          <div className={s.шапкаТекста}>
            <h1 className={`${s.заголовок} ${s.наБелом}`}>{имя ? `Ваш путь, ${имя}` : 'Ваш путь'}</h1>
            <p className={`${s.лид} ${s.наБелом}`}>Восемь проверок. Любую можно пройти снова — в другое время дня, при другом свете, бодрым или уставшим.</p>
          </div>
          <div className={s.картаМесто}>
            <div className={s.карта}>
              <svg className={s.картаЛинии} viewBox="0 0 760 420" aria-hidden>
                {ДОРОГА.map((d, i) => {
                  const пройден = сколько(виды[i]) > 0 && сколько(виды[i + 1]) > 0
                  return <path key={d} d={d} className={пройден ? s.пероЗел : s.перо} strokeWidth={пройден ? 3.2 : 2.4} strokeDasharray={пройден ? undefined : '2 10'} />
                })}
              </svg>
              {ПРОВЕРКИ.map((п) => {
                const [x, y] = МЕСТА[п.вид]
                const n = сколько(п.вид)
                const ещё = п.вид === выбрано && !n ? `${п.вид === следующая(проверки) ? 'следующая' : 'выбрана'} · ≈${п.минут} мин`
                  : n ? `пройдено ×${n}` : `${п.для ? `${п.для} · ` : ''}≈${п.минут} мин`
                return (
                  <button key={п.вид} type="button" className={s.станция} style={{ left: `${(x / 760) * 100}%`, top: `${(y / 420) * 100}%` }}
                    aria-pressed={п.вид === выбрано} onClick={() => setВыбрано(п.вид)}>
                    <span className={`${s.кольцо} ${n ? s.кольцоПройдено : ''} ${п.вид === выбрано ? s.кольцоВыбрано : ''}`}>
                      <ЗнакПроверки вид={п.вид} />
                      {n ? (
                        <span className={s.галочка} aria-hidden>
                          <svg width="12" height="12" viewBox="0 0 12 12"><path d="M2 6.5 L 5 9 L 10 3" className={s.перо} style={{ stroke: 'var(--color-on-go)' }} strokeWidth={2} /></svg>
                        </span>
                      ) : null}
                    </span>
                    <span className={s.станцияИмя}>{п.название}</span>
                    <span className={s.станцияЕщё}>{ещё}</span>
                  </button>
                )
              })}
            </div>
          </div>
        </div>

        <div className={s.путьСправа}>
          <div className={`${s.листок} ${s.выбранная}`}>
            <span className={s.бровь}>{выбрано === следующая(проверки) ? 'Следующая' : 'Выбрана'}{выбрано === 'настройка' && !сколько('настройка') ? ' · новая' : ''}</span>
            <span className={s.выбраннаяИмя}>{описание.название}</span>
            <p className={s.тихо}>{описание.суть}</p>
            {описание.понадобится ? <p className={s.тихо}>Понадобится: {описание.понадобится}</p> : null}
            <span className={`${s.моно} ${s.тихо}`}>≈{описание.минут} мин · {описание.камера ? 'камера' : 'микрофон'}{сколько(выбрано) ? ` · пройдена ${раз(сколько(выбрано))}` : ''}</span>
          </div>
          <div className={`${s.листок} ${s.когда}`}>
            <span className={s.бровь}>Когда вы проходили</span>
            <div className={s.время}>
              {(['утро', 'день', 'вечер'] as const).map((ч) => (
                <span key={ч} className={`${s.часть} ${части[ч] ? '' : s.частьНет}`}>
                  {ч[0].toUpperCase() + ч.slice(1)}
                  <span className={s.частьСчёт}>{части[ч] ? `×${части[ч]}` : 'ещё нет'}</span>
                </span>
              ))}
            </div>
            <p className={s.тихо}>
              {неБыло ? `Загляните ${неБыло === 'утро' ? 'утром' : неБыло === 'день' ? 'днём' : 'вечером'}: уставший и бодрый взгляд системе нужны одинаково.` : 'Утро, день и вечер — все есть. Спасибо!'}
            </p>
          </div>
        </div>
      </div>
    </Рама>
  )
}

/* ── Как вы сейчас ───────────────────────────────────────────────────── */

export type Перед = Record<string, string>

export function КакВы({ описание, имя, onДальше, onНазад }: { описание: Описание; имя?: string | null; onДальше: (п: Перед) => void; onНазад: () => void }) {
  const [сон, setСон] = useState<number | null>(null)
  const [бегунок, setБегунок] = useState(5)
  const [свет, setСвет] = useState<string | null>(null)
  const [очки, setОчки] = useState<string | null>(null)
  const [где, setГде] = useState<string | null>(null)
  const готово = сон !== null && свет !== null && (очки !== null || !описание.камера) && где !== null
  /* Бегунок отвечает, только когда его тронули: щелчок по нему на месте — тоже ответ. */
  const тронул = (значение: number) => { setБегунок(значение); setСон(значение) }
  const дальше = () => {
    const п: Перед = { сонливость: String(сон), свет: свет!, где: где! }
    if (очки) п['очки'] = очки
    onДальше(п)
  }
  const словами = сон ? СОНЛИВОСТЬ.find((с) => с.балл === сон)?.слова ?? '' : ''
  return (
    <Рама раздел={описание.название} справа={<КтоЯ имя={имя ?? null} />} место="перед проверкой" право={<Огонёк>камера пока выключена</Огонёк>}
      низ={(
        <>
          <span className={s.низСлова} role="status">{готово ? 'Дальше — проверка камеры и звука.' : 'Ответьте на все вопросы — они займут полминуты.'}</span>
          <Button kind="quiet" onClick={onНазад}>Назад к пути</Button>
          <Button kind="go" disabled={!готово} onClick={дальше}>Дальше</Button>
        </>
      )}
    >
      <div className={s.какВы}>
        <div className={s.шапкаТекста}>
          <h1 className={`${s.заголовок} ${s.наБелом}`}>Как вы сейчас?</h1>
          <p className={`${s.лид} ${s.наБелом}`}>Четыре быстрых вопроса — о том, в каких условиях идёт эта проверка. Ответ запомним на два часа.</p>
        </div>
        <div className={`${s.листок} ${s.какВыЛисток}`}>
          <div className={s.сонБлок}>
            <span className={s.подпись} id="как-вы-сон">Насколько вас клонит в сон</span>
            <span className={`${s.сонСлова} ${сон ? '' : s.сонЖдёт}`} aria-hidden>{сон ? словами : 'Передвиньте бегунок'}</span>
            <input
              type="range" min={1} max={9} step={1} value={бегунок}
              className={`${s.бегунок} ${сон ? s.бегунокДа : ''}`}
              style={{ '--доля': `${((бегунок - 1) / 8) * 100}%` } as CSSProperties}
              aria-labelledby="как-вы-сон" aria-valuetext={сон ? словами : 'не выбрано'}
              onChange={(e) => тронул(Number(e.currentTarget.value))}
              onPointerUp={(e) => тронул(Number(e.currentTarget.value))}
            />
            <span className={s.бегунокМетки} aria-hidden>{СОНЛИВОСТЬ.map((с) => <i key={с.балл} />)}</span>
            <span className={s.шкалаКонцы}><span>совсем бодро</span><span>очень сонно</span></span>
          </div>
          <div className={s.какВыРяд}>
            <Выбор подпись="Свет в комнате" значение={свет} onВыбор={setСвет}
              варианты={[{ ключ: 'день', слова: 'Дневной' }, { ключ: 'лампа', слова: 'Лампа' }, { ключ: 'полумрак', слова: 'Полумрак' }]} />
            {описание.камера ? (
              <Выбор подпись="Вы сейчас в очках" значение={очки} onВыбор={setОчки} варианты={[{ ключ: 'да', слова: 'Да' }, { ключ: 'нет', слова: 'Нет' }]} />
            ) : null}
            <Выбор подпись="Где вы" значение={где} onВыбор={setГде}
              варианты={[{ ключ: 'дом', слова: 'Дома' }, { ключ: 'работа', слова: 'На работе' }, { ключ: 'другое', слова: 'В другом месте' }]} />
          </div>
          {описание.понадобится ? <p className={s.приготовьте}>Приготовьте: {описание.понадобится}</p> : null}
        </div>
      </div>
    </Рама>
  )
}

/* ── Итог: что система заметила ───────────────────────────────────────── */

const мс = (сек: number) => `${Math.floor(сек / 60)}:${String(Math.round(сек % 60)).padStart(2, '0')}`

/** «Ваши глаза за 4 минуты 40 секунд»: штрих — моргание, плашка — глаза закрыты. */
export function Глаза({ л }: { л: Ленточка }) {
  const ш = 1000
  const x = (t: number) => (л.сек ? (t / л.сек) * ш : 0)
  return (
    <svg className={s.ленточкаРисунок} viewBox={`0 0 ${ш} 64`} role="img" aria-label={`Морганий: ${л.моргания.length}, долгих закрытий глаз: ${л.закрытия.length}`}>
      <path d={`M0 30 H ${ш}`} className={s.нить} />
      {л.моргания.map((t) => <path key={t} d={`M${x(t).toFixed(1)} 19 V 41`} className={s.морг} />)}
      {л.закрытия.map(([с, по]) => <rect key={с} x={x(с)} y={21} width={Math.max(4, x(по) - x(с))} height={18} rx={3} className={s.закрыты} />)}
      <text x="0" y="62" className={s.ленточкаСлова}>0:00</text>
      <text x={ш} y="62" textAnchor="end" className={s.ленточкаСлова}>{мс(л.сек)}</text>
    </svg>
  )
}

export function Итог({ описание, имя, карточки, ленточка, пройдена, отправка, готово, прервано, onДальше }: {
  описание: Описание
  имя?: string | null
  карточки: Карточка[]
  ленточка: Ленточка | null
  /** Сколько раз эта проверка пройдена — вместе с этой. */
  пройдена: number
  отправка: Отправка
  готово: boolean
  прервано: boolean
  onДальше: () => void
}) {
  const мб = (б: number) => `${дробь(б / 1024 / 1024)} МБ`
  const слова = готово
    ? (прервано ? 'Проверка остановлена — записанное уже у нас.' : 'Запись уже на сервере. Можно пройти другую проверку сейчас или вернуться позже.')
    : `Отправляем запись: ${отправка.ушло} из ${отправка.всего} · ${мб(отправка.байтУшло)} из ${мб(отправка.байтВсего)} — не закрывайте вкладку.`
  return (
    <Рама раздел={описание.название} счёт={прервано ? 'остановлена' : 'пройдена'} справа={<КтоЯ имя={имя ?? null} />} место="итог"
      право={<Огонёк идёт={!готово}>{готово ? 'запись на сервере' : 'отправляем запись'}</Огонёк>}
      низ={(
        <>
          <span className={`${s.низСлова} ${отправка.ошибка ? s.ошибка : ''}`} role="status">{отправка.ошибка && !готово ? `${слова} ${отправка.ошибка}` : слова}</span>
          <Button kind="go" disabled={!готово} onClick={onДальше}>К пути</Button>
        </>
      )}
    >
      <div className={s.итог}>
        <div className={s.итогСлева}>
          <div className={s.шапкаТекста}>
            <h1 className={`${s.заголовок} ${s.наБелом}`}>Вот что система о вас заметила</h1>
            <p className={`${s.лид} ${s.наБелом}`}>Это не оценка — просто то, как вы смотрите. Рядом для сравнения — данные исследований.</p>
          </div>
          <div className={s.три}>
            {карточки.map((к) => (
              <section key={к.над} className={`${s.листок} ${s.число}`}>
                <span className={s.бровь}>{к.над}</span>
                <span><span className={s.числоБольшое}>{к.число}</span>{к.ед && к.число !== '—' ? <span className={s.числоЕд}> {к.ед}</span> : null}</span>
                <p className={s.тихо}>{к.текст}</p>
              </section>
            ))}
          </div>
          {ленточка && ленточка.сек > 0 ? (
            <section className={`${s.листок} ${s.ленточка}`}>
              <span className={s.бровь}>Ваши глаза за {мс(ленточка.сек)}</span>
              <Глаза л={ленточка} />
              <span className={s.тихо}>{ленточка.моргания.length || ленточка.закрытия.length
                ? 'Штрих — моргание, плашка — глаза закрыты дольше секунды. Цифры о морганиях: Bentivoglio и др., 1997.'
                : 'Морганий система в этот раз не разглядела — так бывает, когда лицо далеко или в тени.'}</span>
            </section>
          ) : null}
        </div>
        <div className={s.значокМесто}>
          <Значок вид={описание.вид} получен={!прервано} />
          {прервано
            ? <span className={s.бровь}>значок — в другой раз</span>
            : <span className={`${s.бровь} ${s.бровьЗел}`}>{пройдена > 1 ? `пройдена ${раз(пройдена)}` : 'новый значок'}</span>}
          <span className={s.выбраннаяИмя}>{описание.название}</span>
        </div>
      </div>
    </Рама>
  )
}

