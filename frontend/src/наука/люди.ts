/** Исследование внимания SEduM: кто проходил проверки на ЭТОМ устройстве.
 *
 *  Решение владельца 06.10: «нужна одна ссылка для всех, но так, чтобы мы
 *  могли данные различать и не путать». По общей ссылке каждый называет себя
 *  и получает свой код. Устройство запоминает, кто им пользовался, — и в
 *  следующий раз спрашивает «Кто сейчас проходит?», а не заводит человека
 *  заново: иначе один и тот же человек на одном ноутбуке распался бы на
 *  несколько, а двое за одним ноутбуком слились бы в одного.
 *
 *  🔴 ЭТО УДОБСТВО, А НЕ ХРАНИЛИЩЕ. Память браузера бывает пустой (другой
 *  браузер, чистка, приватное окно) — тогда человек просто входит снова под
 *  своим именем, а Адель видит в кабинете двоих с одинаковым именем и может
 *  их склеить. Записи живут на сервере, здесь — только код, имя и галочки.
 */

export type Человек = {
  код: string
  имя: string
  /** Какие проверки уже пройдены — для шариков на карточке, без похода на сервер. */
  пройдено: string[]
  /** Когда был здесь последний раз, ISO. */
  когда: string
}

const КЛЮЧ = 'flamingo.наука.люди'

export function людиЗдесь(): Человек[] {
  try {
    const сырое = JSON.parse(window.localStorage.getItem(КЛЮЧ) ?? '[]')
    if (!Array.isArray(сырое)) return []
    return сырое
      .filter((ч): ч is Человек => Boolean(ч) && typeof ч.код === 'string' && typeof ч.имя === 'string')
      .map((ч) => ({ ...ч, пройдено: Array.isArray(ч.пройдено) ? ч.пройдено : [], когда: String(ч.когда ?? '') }))
      .sort((а, б) => (а.когда < б.когда ? 1 : -1))
  } catch {
    return []
  }
}

export function запомнить(ч: Человек): void {
  try {
    const другие = людиЗдесь().filter((x) => x.код !== ч.код)
    window.localStorage.setItem(КЛЮЧ, JSON.stringify([ч, ...другие].slice(0, 12)))
  } catch {
    /* память браузера закрыта — войдут по имени ещё раз */
  }
}

/** «2 из 8 · вчера вечером» — подпись на карточке человека. */
export function когдаСловами(iso: string, сейчас = new Date()): string {
  const д = new Date(iso)
  if (Number.isNaN(д.getTime())) return ''
  const часть = (ч: number) => (ч < 12 ? 'утром' : ч < 18 ? 'днём' : 'вечером')
  const день = (x: Date) => new Date(x.getFullYear(), x.getMonth(), x.getDate()).getTime()
  const разница = Math.round((день(сейчас) - день(д)) / 86_400_000)
  if (разница === 0) return `сегодня ${часть(д.getHours())}`
  if (разница === 1) return `вчера ${часть(д.getHours())}`
  return д.toLocaleDateString('ru-RU', { day: 'numeric', month: 'long' })
}

/* ── «Как вы сейчас?» — один раз на два часа ─────────────────────────────
   Решение владельца 06.10: «не надо повторять перед каждым заданием — одного
   раза достаточно, если идёт непрерывно; если прошло больше двух часов — да».
   Ответ помним по коду человека: другой человек на том же устройстве ответит
   сам. В запись проверки уходит и время ответа («спрошено») — по нему видно,
   насколько ответ свежий. */

export type Ответ = Record<string, string>

const КЛЮЧ_ОТВЕТ = 'flamingo.наука.как-вы'
export const ОТВЕТ_ЖИВЁТ_МС = 2 * 60 * 60 * 1000
/** Запасная память на случай, если браузер не даёт хранить: хватает до перезагрузки. */
const ответыЗдесь = new Map<string, Ответ>()

function всеОтветы(): Record<string, Ответ> {
  try {
    const сырое = JSON.parse(window.localStorage.getItem(КЛЮЧ_ОТВЕТ) ?? '{}')
    return сырое && typeof сырое === 'object' && !Array.isArray(сырое) ? сырое : {}
  } catch {
    return {}
  }
}

export function запомнитьОтвет(код: string, ответ: Ответ): void {
  ответыЗдесь.set(код, ответ)
  try {
    window.localStorage.setItem(КЛЮЧ_ОТВЕТ, JSON.stringify({ ...всеОтветы(), [код]: ответ }))
  } catch {
    /* браузер не даёт хранить — спросим ещё раз после перезагрузки */
  }
}

/** Ответ моложе двух часов — или null, и тогда спрашиваем снова. Для проверки
 *  с камерой нужен и ответ про очки: после «Голоса учителя» его могло не быть. */
export function свежийОтвет(код: string, сКамерой: boolean, сейчас = Date.now()): Ответ | null {
  const о = всеОтветы()[код] ?? ответыЗдесь.get(код)
  if (!о || typeof о.спрошено !== 'string') return null
  const возраст = сейчас - Date.parse(о.спрошено)
  if (!(возраст >= 0 && возраст < ОТВЕТ_ЖИВЁТ_МС)) return null
  if (сКамерой && !о.очки) return null
  return о
}

/* ── Подготовка — тоже раз в два часа ─────────────────────────────────────
   Владелец, 06.10: «Подготовку я просил убрать — каждый раз она не нужна».
   Камеру, свет и звук человек уже проверил. Если с последней удачной записи
   прошло меньше двух часов, следующая проверка начинается сама, как только
   камера увидит лицо; не увидела — подготовка, как в первый раз. «Голос
   учителя» проверяет микрофон отдельно: у него своя отметка. */

const КЛЮЧ_ПОДГОТОВКА = 'flamingo.наука.подготовка'
const подготовкиЗдесь = new Map<string, number>()
const ключПодготовки = (код: string, сКамерой: boolean) => `${код}:${сКамерой ? 'камера' : 'микрофон'}`

function всеПодготовки(): Record<string, number> {
  try {
    const сырое = JSON.parse(window.localStorage.getItem(КЛЮЧ_ПОДГОТОВКА) ?? '{}')
    return сырое && typeof сырое === 'object' && !Array.isArray(сырое) ? сырое : {}
  } catch {
    return {}
  }
}

/** Запись началась — камера (или микрофон) в порядке, отметим время. */
export function запомнитьПодготовку(код: string, сКамерой: boolean, сейчас = Date.now()): void {
  const к = ключПодготовки(код, сКамерой)
  подготовкиЗдесь.set(к, сейчас)
  try {
    window.localStorage.setItem(КЛЮЧ_ПОДГОТОВКА, JSON.stringify({ ...всеПодготовки(), [к]: сейчас }))
  } catch {
    /* браузер не даёт хранить — после перезагрузки покажем подготовку снова */
  }
}

/** Готовились меньше двух часов назад — подготовку можно не показывать. */
export function свежаяПодготовка(код: string, сКамерой: boolean, сейчас = Date.now()): boolean {
  const к = ключПодготовки(код, сКамерой)
  const когда = всеПодготовки()[к] ?? подготовкиЗдесь.get(к)
  if (typeof когда !== 'number') return false
  const прошло = сейчас - когда
  return прошло >= 0 && прошло < ОТВЕТ_ЖИВЁТ_МС
}
