/** Разбор одной проверки — чистые вычисления без экрана (их же читает стенд).
 *
 *  Имя файла — глагол, а не «разбор»: рядом лежит экран `Разбор.tsx`, и на
 *  маке (файловая система без различия регистра) `./Разбор` находил этот файл.
 *
 *  Из событий и кадров проверки собирается то, что владелец видит на экране
 *  «Разбор проверки» (экран 11 холста): что просили на каждом шаге, что в это
 *  время решала система, раскрытие век, совпадения, числа в любой момент.
 *  Время везде одно — миллисекунды от начала записи: от этой же точки
 *  начинается видео (`запись.ts`: часы и рекордер заводятся одним вызовом).
 */
import type { Качество, Состояние } from '../sedum/внимание.ts'
import { ИМЕНА_МИМИКИ, ФЛАГ, type ЗаписьКадра } from './формат.ts'
import type { Шаг } from './протокол.ts'

export type Событие = { t: number; что: string } & Record<string, unknown>

export type Отрезок = { с: number; по: number }
export type ШагРазбора = Отрезок & { i: number; метка: string; текст: string; ждём: Состояние[] }
export type РешениеРазбора = Отрезок & { что: Состояние }
export type Совпадение = { i: number; метка: string; да: boolean }

export type Разбор = {
  длина: number
  калибровка: Отрезок | null
  шаги: ШагРазбора[]
  решения: РешениеРазбора[]
  /** Раскрытие век: точки [t, веко]; null — лица нет, линия рвётся. */
  веки: [number, number | null][]
  /** Личная норма века из калибровки — для «0,06 · норма 0,29». */
  нормаВека: number | null
  совпадения: Совпадение[]
  всегоШагов: number
}

/** Как система называет состояние на ленте — словами человека. */
export const СЛОВАМИ: Record<string, string> = {
  'на экране': 'смотрит', 'пишет': 'пишет', 'зевает': 'зевает', 'мимо экрана': 'мимо экрана',
  'смотрит вниз': 'смотрит вниз', 'отвернулся': 'отвернулся', 'глаза закрыты': 'глаза закрыты',
  'заснул': 'заснул', 'нет в кадре': 'нет в кадре', 'ушёл': 'ушёл', 'другое окно': 'другое окно',
}
export const словами = (с: string) => СЛОВАМИ[с] ?? с

const КОНЕЦ_ШАГА = new Set(['шаг-конец', 'подготовка', 'шаг', 'конец', 'готово', 'пропуск', 'ответил', 'не ответил', 'понимание'])

export function разобрать(события: Событие[], кадры: ЗаписьКадра[], длинаСек: number | null): Разбор {
  const с = [...события].sort((а, б) => а.t - б.t)
  const к = [...кадры].sort((а, б) => а.t - б.t)
  const начало = с.find((е) => е.что === 'начало')
  const сценарий = (начало?.сценарий ?? null) as { шаги?: Шаг[] } | null
  const шагиСценария = сценарий?.шаги ?? []
  const конецЗаписи = Math.max(длинаСек ? длинаСек * 1000 : 0, к.at(-1)?.t ?? 0, с.at(-1)?.t ?? 0)

  const калНачало = с.find((е) => е.что === 'калибровка' && е.начало)
  const калКонец = [...с].reverse().find((е) => е.что === 'калибровка' && е.конец)
  const норма = (калКонец?.норма ?? null) as { веко?: number } | null

  const шаги: ШагРазбора[] = []
  с.forEach((е, n) => {
    if (е.что !== 'шаг') return
    const i = Number(е.i)
    const по = с.slice(n + 1).find((x) => КОНЕЦ_ШАГА.has(x.что))?.t ?? конецЗаписи
    const ш = шагиСценария[i]
    шаги.push({
      i, с: е.t, по,
      метка: String(е.метка ?? ш?.метка ?? ''),
      текст: ш?.текст ?? String(е.метка ?? ''),
      ждём: (Array.isArray(е.ждём) ? е.ждём : ш?.ждём ?? []) as Состояние[],
    })
  })

  const решения: РешениеРазбора[] = []
  for (const кадр of к) {
    const последнее = решения.at(-1)
    if (последнее && последнее.что === кадр.засчитано && кадр.t - последнее.по < 1500) последнее.по = кадр.t
    else решения.push({ с: кадр.t, по: кадр.t, что: кадр.засчитано })
  }

  const веки: [number, number | null][] = к.map((кадр) => [кадр.t, кадр.флаги & ФЛАГ.лицо && кадр.веко !== null ? кадр.веко : null])

  const совпадения: Совпадение[] = шаги.filter((ш) => ш.ждём.length).map((ш) => {
    const внутри = к.filter((кадр) => кадр.t >= ш.с && кадр.t < ш.по)
    if (!внутри.length) return { i: ш.i, метка: ш.метка, да: false }
    const да = ш.ждём.includes('на экране')
      ? внутри.filter((кадр) => ш.ждём.includes(кадр.засчитано)).length / внутри.length >= 0.5
      : внутри.some((кадр) => ш.ждём.includes(кадр.засчитано))
    return { i: ш.i, метка: ш.метка, да }
  })

  return {
    длина: конецЗаписи,
    // Калибровку не закончили (человек остановил проверку) — она шла до конца записи.
    калибровка: калНачало ? { с: калНачало.t, по: калКонец && калКонец.t >= калНачало.t ? калКонец.t : конецЗаписи } : null,
    шаги,
    решения,
    веки,
    нормаВека: typeof норма?.веко === 'number' ? норма.веко : null,
    совпадения,
    всегоШагов: шагиСценария.length || шаги.length,
  }
}

/** Последний кадр не позже `t` — то, что система видела в этот момент. */
export function кадрВ(кадры: ЗаписьКадра[], t: number): ЗаписьКадра | null {
  let мало = 0
  let много = кадры.length - 1
  let ответ: ЗаписьКадра | null = null
  while (мало <= много) {
    const середина = (мало + много) >> 1
    if (кадры[середина].t <= t) { ответ = кадры[середина]; мало = середина + 1 } else много = середина - 1
  }
  return ответ
}

export const внутри = <Т extends Отрезок>(отрезки: Т[], t: number): Т | null => отрезки.find((о) => t >= о.с && t < о.по) ?? null

const град = (р: number) => (р * 180) / Math.PI
const НОМЕР = Object.fromEntries(ИМЕНА_МИМИКИ.map((и, i) => [и, i]))

/** Числа кадра для панели «Числа в этот момент». Матрица — по столбцам (как в `sedum/числа.ts`). */
export function числаМомента(кадр: ЗаписьКадра | null): {
  веко: number | null; рыск: number | null; тангаж: number | null; вниз: number | null; закрыты: number | null; качество: Качество | null; лицо: boolean
} {
  if (!кадр) return { веко: null, рыск: null, тангаж: null, вниз: null, закрыты: null, качество: null, лицо: false }
  const л = кадр.лицо
  let рыск: number | null = null
  let тангаж: number | null = null
  let вниз: number | null = null
  if (л && л.матрица.length === 16 && Number.isFinite(л.матрица[0])) {
    const r = (i: number, j: number) => л.матрица[j * 4 + i]
    тангаж = град(Math.asin(Math.max(-1, Math.min(1, -r(1, 2)))))
    рыск = град(Math.atan2(r(0, 2), r(2, 2)))
  }
  if (л) вниз = ((л.мимика[НОМЕР.eyeLookDownLeft] ?? 0) + (л.мимика[НОМЕР.eyeLookDownRight] ?? 0)) / 2
  return {
    веко: кадр.веко, рыск, тангаж, вниз, закрыты: кадр.перклос, качество: кадр.качество, лицо: Boolean(кадр.флаги & ФЛАГ.лицо),
  }
}

/** Разобрать ndjson-куски событий. Битая строка пропускается, а не роняет разбор. */
export function прочитатьСобытия(тексты: string[]): Событие[] {
  const итог: Событие[] = []
  for (const текст of тексты) {
    for (const строка of текст.split('\n')) {
      if (!строка.trim()) continue
      try {
        const е = JSON.parse(строка)
        if (е && typeof е.t === 'number' && typeof е.что === 'string') итог.push(е)
      } catch {
        /* кусок дописывался, когда вкладку закрыли, — строка оборвана */
      }
    }
  }
  return итог.sort((а, б) => а.t - б.t)
}
