/** Исследование внимания SEduM: одна проверка — от камеры до итога.
 *
 *  Три части, и каждая отвечает на свой вопрос:
 *
 *    Подготовка  видит ли камера лицо, хватает ли света, слышен ли сигнал
 *    Ход         шаги сценария: подсказка, стимул на доске, сигнал «вернитесь»
 *    Сцена       что именно на доске: учитель, доска, точка, вопрос, книга
 *
 *  🔴 СВОЁ ЛИЦО ВО ВРЕМЯ ШАГОВ НЕ ПОКАЗЫВАЕМ. Человек, который видит себя,
 *  смотрит на себя — и «смотрит на учителя» превращается в «смотрит в угол, где
 *  его плитка». Камера видит его по-прежнему; внизу — тихая отметка «камера
 *  видит лицо».
 *
 *  🔴 ИТОГ СЧИТАЕТСЯ ПО ХОДУ. Каждый кадр движка уходит не только в запись,
 *  но и в сводку (`итоги.ts`): к концу проверки числа «что система заметила»
 *  уже готовы, и человек видит их сразу, пока запись доезжает до сервера.
 */
