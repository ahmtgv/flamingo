/* ── Книга: тексты разворотами ────────────────────────────────────────── */

/** Где читатель в книге: левая страница разворота (с нуля), сколько страниц всего,
 *  до какой страницы дошёл (самый дальний разворот) и сколько слов примерно прочитал:
 *  всё до этого разворота и половину его самого — человек обычно где-то посередине. */
export type Листы = { страница: number; всего: number; слов: number; прочитано: number; наРазвороте: 1 | 2 }

type Кусок = { ключ: string; вид: 'имя' | 'абзац' | 'конец'; текст: string; слов: number; новыйТекст: boolean }
/** Кусок на странице: абзац целиком или его часть, если абзац перешёл на следующую. */
type НаСтранице = Кусок & { часть: number }

const слова = (т: string) => т.split(/\s+/).filter(Boolean).length
const КОНЕЦ_КНИГИ = 'Конец книги. Перечитайте место, которое понравилось, — чтение закончится само.'

/** Книга режется на страницы по живой мерке: невидимая страница той же ширины
 *  и того же шрифта, в неё кладутся абзацы. Не влез абзац — он переходит на
 *  следующую страницу посередине, как в настоящей книге: на этой остаётся
 *  столько слов, сколько поместилось (не меньше двух строк здесь и там).
 *  Новый текст всегда начинается с новой страницы. Ширина окна изменилась —
 *  режем заново и встаём на ту страницу, где был первый абзац разворота. */
export function Книга({ тексты, onСтраница, onЛистать, начало = 0 }: {
  тексты: ТекстДляЧтения[]
  onСтраница?: (н: Листы) => void
  onЛистать?: (л: { вперёд: () => void; назад: () => void } | null) => void
  /** Для стенда: с какой страницы открыть. */
  начало?: number
}) {
  /* Тексты приходят новым массивом на каждой перерисовке хода — книгу режем
     заново только когда сменились сами тексты, иначе страницы бегут по кругу. */
  const какие = тексты.map((т) => т.id).join('|')
  const куски = useMemo<Кусок[]>(() => [
    ...тексты.flatMap((т) => [
      { ключ: `${т.id}:имя`, вид: 'имя' as const, текст: т.название, слов: 0, новыйТекст: true },
      ...т.абзацы.map((а, i) => ({ ключ: `${т.id}:${i}`, вид: 'абзац' as const, текст: а, слов: слова(а), новыйТекст: false })),
    ]),
    { ключ: 'конец', вид: 'конец' as const, текст: КОНЕЦ_КНИГИ, слов: 0, новыйТекст: false },
  // eslint-disable-next-line react-hooks/exhaustive-deps -- тексты различаем по id
  ], [какие])
  const книга = useRef<HTMLDivElement>(null)
  const лист = useRef<HTMLDivElement>(null)
  const мерило = useRef<HTMLDivElement>(null)
  const [страницы, setСтраницы] = useState<НаСтранице[][]>([])
  const [две, setДве] = useState(true)
  const [левая, setЛевая] = useState(начало)
  const дальше = useRef(0)
  const дальшеСтраниц = useRef(0)
  /** Первый кусок открытого разворота — по нему встаём на место после перерезки. */
  const якорь = useRef<string | null>(null)

  useLayoutEffect(() => {
    const к = книга.current
    if (!к) return
    const разрезать = () => {
      const тело = лист.current
      const м = мерило.current
      if (!тело || !м) return
      const ширина = тело.clientWidth
      const высота = тело.clientHeight
      setДве(к.clientWidth >= 720)
      if (!ширина || !высота) return
      м.style.width = `${ширина}px`
      const промежуток = parseFloat(getComputedStyle(тело).rowGap || '0') || 0
      const мерить = (вид: Кусок['вид'], текст: string) => {
        м.replaceChildren()
        const эл = document.createElement(вид === 'имя' ? 'h2' : 'p')
        if (вид === 'имя') эл.className = s.страницаИмя
        if (вид === 'конец') эл.className = s.конецКниги
        эл.textContent = текст
        м.appendChild(эл)
        return эл.getBoundingClientRect().height
      }
      const строка = мерить('абзац', 'М')
      const стр: НаСтранице[][] = []
      let текущая: НаСтранице[] = []
      let занято = 0
      const перевернуть = () => { стр.push(текущая); текущая = []; занято = 0 }
      for (const кус of куски) {
        if (кус.новыйТекст && текущая.length) перевернуть()
        let остаток = кус.текст.split(/\s+/).filter(Boolean)
        let часть = 0
        for (;;) {
          const текст = остаток.join(' ')
          const своя = мерить(кус.вид, текст)
          const сверху = текущая.length ? промежуток : 0
          const места = высота - занято - сверху
          const положить = (т: string, h: number) => {
            текущая.push({ ...кус, ключ: `${кус.ключ}~${часть}`, текст: т, слов: кус.вид === 'абзац' ? слова(т) : 0, часть })
            занято += сверху + h
          }
          if (своя <= места) { положить(текст, своя); break }
          /* Не влез: абзац делим по словам — сколько войдёт, но не меньше двух строк тут и там. */
          if (кус.вид === 'абзац' && места >= 2 * строка) {
            let мало = 1
            let много = остаток.length - 1
            let влезло = 0
            while (мало <= много) {
              const середина = (мало + много) >> 1
              if (мерить('абзац', остаток.slice(0, середина).join(' ')) <= места) { влезло = середина; мало = середина + 1 } else много = середина - 1
            }
            while (влезло > 0 && мерить('абзац', остаток.slice(влезло).join(' ')) < 2 * строка - 1) влезло -= 2
            if (влезло > 0) {
              const т = остаток.slice(0, влезло).join(' ')
              положить(т, мерить('абзац', т))
              перевернуть()
              остаток = остаток.slice(влезло)
              часть += 1
              continue
            }
          }
          if (!текущая.length) { положить(текст, своя); break }
          перевернуть()
        }
      }
      if (текущая.length) стр.push(текущая)
      м.replaceChildren()
      setСтраницы(стр)
      const где = якорь.current
      if (где) {
        /* Та же ширина — тот же кусок; другая — страница, где начался его абзац. */
        const точно = стр.findIndex((с) => с.some((к) => к.ключ === где))
        const абзац = стр.findIndex((с) => с.some((к) => к.ключ.startsWith(`${где.split('~')[0]}~`)))
        const n = точно >= 0 ? точно : абзац
        if (n >= 0) setЛевая(n)
      }
    }
    разрезать()
    const набл = new ResizeObserver(() => разрезать())
    набл.observe(к)
    return () => набл.disconnect()
  }, [куски])

  const шаг = две ? 2 : 1
  const всего = страницы.length
  const крайняя = Math.min(левая, Math.max(0, всего - 1))
  const слева = крайняя - (крайняя % шаг)
  const вперёд = useCallback(() => setЛевая((л) => (л + шаг < всего ? л - (л % шаг) + шаг : л)), [шаг, всего])
  const назад = useCallback(() => setЛевая((л) => Math.max(0, л - (л % шаг) - шаг)), [шаг])

  useEffect(() => {
    onЛистать?.({ вперёд, назад })
    return () => onЛистать?.(null)
  }, [вперёд, назад, onЛистать])

  useEffect(() => {
    if (!всего) return
    якорь.current = страницы[слева]?.[0]?.ключ ?? null
    /* «Прочитано слов» — всё до самого дальнего разворота и половина его самого;
       копим словами, а не страницами: при перерезке страницы сдвигаются. */
    const видноСтраниц = Math.min(всего, слева + шаг)
    const словВ = (с: НаСтранице[][]) => с.flat().reduce((сумма, к) => сумма + к.слов, 0)
    const видно = словВ(страницы.slice(0, слева)) + Math.round(словВ(страницы.slice(слева, видноСтраниц)) / 2)
    дальше.current = Math.max(дальше.current, видно)
    дальшеСтраниц.current = Math.max(дальшеСтраниц.current, видноСтраниц)
    onСтраница?.({ страница: слева, всего, слов: дальше.current, прочитано: дальшеСтраниц.current, наРазвороте: две ? 2 : 1 })
  }, [слева, шаг, всего, страницы, две, onСтраница])

  const страница = (n: number, справа: boolean) => (
    <section className={s.страница} key={n}>
      <div className={s.страницаТекст} ref={n === слева ? лист : undefined}>
        {(страницы[n] ?? []).map((к) => (к.вид === 'имя'
          ? <h2 key={к.ключ} className={s.страницаИмя}>{к.текст}</h2>
          : <p key={к.ключ} className={к.вид === 'конец' ? s.конецКниги : undefined}>{к.текст}</p>))}
      </div>
      <span className={`${s.номер} ${справа ? s.номерСправа : ''}`}>{n < всего ? n + 1 : ''}</span>
    </section>
  )

  return (
    <div className={s.книгаМесто}>
      <article className={`${s.книга} ${две ? '' : s.книгаОдна}`} ref={книга}>
        {две ? <span className={s.сгиб} aria-hidden /> : null}
        {страница(слева, false)}
        {две ? страница(слева + 1, true) : null}
        <div className={`${s.страницаТекст} ${s.мерило}`} ref={мерило} aria-hidden />
      </article>
    </div>
  )
}

