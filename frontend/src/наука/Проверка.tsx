/** Исследование внимания SEduM: одна проверка — от камеры до последнего шага.
 *
 *  Три части, и каждая отвечает на свой вопрос:
 *
 *    Подготовка  видит ли камера лицо, хватает ли света, слышен ли сигнал
 *    Ход         шаги сценария: подсказка, стимул на экране, сигнал «вернитесь»
 *    Стимулы     что именно на экране: учитель, доска, точка, вопрос, текст
 *
 *  🔴 СВОЁ ЛИЦО ВО ВРЕМЯ ШАГОВ НЕ ПОКАЗЫВАЕМ. Человек, который видит себя,
 *  смотрит на себя — и «смотрит на учителя» превращается в «смотрит в угол, где
 *  его плитка». Камера видит его по-прежнему; на экране — только тихая отметка
 *  «камера видит вас».
 */
