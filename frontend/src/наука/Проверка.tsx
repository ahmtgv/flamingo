export const ммсс = (сек: number) => {
  const с = Math.max(0, Math.ceil(сек))
  return `${Math.floor(с / 60)}:${String(с % 60).padStart(2, '0')}`
}

/** Глаза закрыты и видны — по личной норме движка (П4), как считает он сам. */
function глаза(к: Кадр | null, запись: Запись): { видно: boolean; закрыты: boolean } {
  if (!к || !к.лицо) return { видно: false, закрыты: false }
  const з: Замер = { ...к, t: 0, экран: true }
  const видно = глазаВидно(з, запись.движок.пороги, запись.движок.норма)
  return { видно, закрыты: видно && глазаЗакрыты(з, запись.движок.пороги, запись.движок.норма) }
}

function Ход({ сценарий, запись, описание, имя, onКонец }: {
  сценарий: Сценарий
  запись: Запись
  описание: Описание
  имя: string | null
  onКонец: (конец: Конец) => void
}) {
  const [фаза, setФаза] = useState<Фаза>(() => (сценарий.калибровка > 0 ? { что: 'калибровка' } : { что: 'подготовка', i: 0 }))
  const сводка = useMemo(() => new Сводка(сценарий), [сценарий])
  const начало = useRef(performance.now())
  const пауза = useRef(0)
  const паузаС = useRef<number | null>(null)
  const [тик, setТик] = useState(0)
  const [лицо, setЛицо] = useState<{ есть: boolean; качество: Качество }>({ есть: true, качество: 'хорошо' })
  const [стоп, setСтоп] = useState(false)
  const [вопрос, setВопрос] = useState<{ n: number; с: number } | null>(null)
  const [моргнул, setМоргнул] = useState(0)
  const [листы, setЛисты] = useState<Листы>({ страница: 0, всего: 0, слов: 0, прочитано: 0, наРазвороте: 2 })
  const листыСейчас = useRef(листы)
  const [листать, setЛистать] = useState<{ вперёд: () => void; назад: () => void } | null>(null)
  const заданоВопросов = useRef(0)
  const ответы = useRef<Record<string, unknown>[]>([])
  const точка = useRef<HTMLSpanElement>(null)
  const конец = useRef(false)
  const текущий = useRef(-1)

  const шаг: Шаг | null = фаза.что === 'шаг' || фаза.что === 'подготовка' ? сценарий.шаги[фаза.i] : null
  const прошло = () => (performance.now() - начало.current - пауза.current) / 1000

  /* Каждый кадр движка — в сводку итога; лицо — для отметки внизу; моргания — для счётчика. */
  useEffect(() => {
    let закрыты = false
    let закрылись = 0
    return запись.слушать((и, к) => {
      const г = глаза(к, запись)
      const t = запись.сейчас() / 1000
      сводка.кадр({
        t, i: текущий.current, лицо: Boolean(к?.лицо), видно: г.видно, закрыты: г.закрыты,
        сейчас: и.сейчас, засчитано: и.состояние, рыск: к?.рыск ?? 0, до: к?.до ?? null,
      })
      if (г.закрыты && !закрыты) закрылись = t
      if (!г.закрыты && закрыты && t - закрылись >= 0.04 && t - закрылись <= 0.5) setМоргнул((n) => n + 1)
      закрыты = г.закрыты
      setЛицо((было) => {
        const есть = и.сейчас !== 'нет в кадре' && и.сейчас !== 'ушёл'
        return было.есть === есть && было.качество === и.качество ? было : { есть, качество: и.качество }
      })
    })
  }, [запись, сводка])

  const завершить = useCallback(async (прервано: boolean) => {
    if (конец.current) return
    конец.current = true
    /* Остановили посреди чтения — в итог всё равно то, что успели прочитать. */
    if (сценарий.шаги[текущий.current]?.стимул.вид === 'чтение') сводка.прочитал(листыСейчас.current.прочитано, листыСейчас.current.слов, прошло(), листыСейчас.current.всего)
    setФаза({ что: 'конец' })
    const карточки = сводка.карточки()
    const ленточка = описание.камера ? сводка.ленточка() : null
    await запись.остановить({ прервано, ответы: ответы.current, шагов: сценарий.шаги.length, карточки })
    onКонец({ очередь: запись.очередь, прервано, карточки, ленточка })
  }, [запись, сценарий, сводка, описание.камера, onКонец])

  const перейти = useCallback((новая: Фаза) => {
    начало.current = performance.now()
    пауза.current = 0
    if (новая.что === 'подготовка') {
      const ш = сценарий.шаги[новая.i]
      текущий.current = -1
      запись.поставить({ шаг: новая.i, стимул: null, пишем: false })
      запись.событие('подготовка', { i: новая.i, метка: ш.метка })
    }
    if (новая.что === 'шаг') {
      const ш = сценарий.шаги[новая.i]
      текущий.current = новая.i
      сводка.начатьШаг(новая.i, запись.сейчас() / 1000)
      запись.поставить({ шаг: новая.i, пишем: Boolean(ш.пишем) })
      запись.событие('шаг', { i: новая.i, метка: ш.метка, ждём: ш.ждём, пишем: Boolean(ш.пишем), сек: ш.сек, стимул: ш.стимул, ...(ш.имитировать ? { имитировать: true } : {}) })
      if (ш.стимул.вид === 'моргай') setМоргнул(0)
      if (ш.стимул.вид === 'фраза' || ш.стимул.вид === 'ситуация' || ш.стимул.вид === 'урок') {
        запись.начатьКлип({ i: новая.i, метка: ш.метка, ...ш.стимул })
      }
    }
    setФаза(новая)
  }, [сценарий, запись, сводка])

  const следующий = useCallback((i: number) => {
    сводка.закончитьШаг(i, запись.сейчас() / 1000)
    текущий.current = -1
    if (i + 1 < сценарий.шаги.length) перейти({ что: 'подготовка', i: i + 1 })
    else if (сценарий.вид === 'чтение') { запись.поставить({ шаг: 255, стимул: null }); setФаза({ что: 'понимание' }) }
    else void завершить(false)
  }, [сценарий, перейти, завершить, запись, сводка])

  /* Калибровка начинается сразу. */
  useEffect(() => {
    if (фаза.что !== 'калибровка') return
    запись.поставить({ шаг: 255, стимул: [0.5, 0.5] })
    запись.начатьКалибровку()
  }, [фаза.что, запись])

  /* 🔴 ЧАСЫ — НА ТАЙМЕРЕ, ТОЧКА — НА КАДРАХ ЭКРАНА. Пока вкладка спрятана
     (шаг «переключитесь на другое окно»), браузер не рисует кадры вовсе, и
     часы на них остановились бы: шаг не кончился бы, сигнал «вернитесь» не
     прозвучал бы, человек ждал бы его в другом окне вечно. Таймер в спрятанной
     вкладке тоже замедляют — но до раза в секунду, а не до нуля. */
  useEffect(() => {
    const id = window.setInterval(() => {
      if (конец.current) return
      const t = прошло()
      if (фаза.что === 'калибровка') {
        if (t >= сценарий.калибровка) {
          запись.закончитьКалибровку()
          перейти({ что: 'подготовка', i: 0 })
        }
        return
      }
      if (фаза.что === 'подготовка') {
        if (t >= ПОДГОТОВКА_СЕК) перейти({ что: 'шаг', i: фаза.i })
        return
      }
      if (фаза.что !== 'шаг' || !шаг || вопрос) return
      /* Чтение: вопрос «где было внимание» в заранее выбранные мгновения. */
      const n = заданоВопросов.current
      if (сценарий.вид === 'чтение' && n < сценарий.вопросы.length && t >= сценарий.вопросы[n]) {
        заданоВопросов.current = n + 1
        паузаС.current = performance.now()
        запись.событие('вопрос', { n, сек: t })
        setВопрос({ n, с: performance.now() })
        return
      }
      if (шаг.сек > 0 && t >= шаг.сек) {
        if (шаг.стимул.вид === 'урок') { void запись.закончитьКлип(); сводка.записал('урок', t) }
        if (шаг.стимул.вид === 'чтение') сводка.прочитал(листы.прочитано, листы.слов, t, листы.всего)
        if (шаг.сигнал) { сигнал(); запись.событие('сигнал', { i: фаза.i }) }
        запись.событие('шаг-конец', { i: фаза.i })
        следующий(фаза.i)
        return
      }
      /* Вопрос «подумайте» без ответа — дальше через минуту. */
      if (шаг.сек === 0 && шаг.метка === 'думает' && t >= 60) {
        запись.событие('не ответил', { i: фаза.i })
        следующий(фаза.i)
      }
    }, 100)
    return () => window.clearInterval(id)
  }, [фаза, вопрос, шаг, сценарий, запись, перейти, следующий, сводка, листы])

  /* Точка и часы на экране — с каждым кадром экрана. */
  useEffect(() => {
    let id = 0
    let последний = 0
    const цикл = () => {
      id = requestAnimationFrame(цикл)
      if (конец.current) return
      if (фаза.что === 'шаг' && шаг && !вопрос) {
        const pos = гдеТочка(шаг.стимул, прошло())
        if (pos && точка.current) {
          точка.current.style.left = `${pos[0] * 100}%`
          точка.current.style.top = `${pos[1] * 100}%`
        }
        запись.поставить({ стимул: pos })
      }
      if (performance.now() - последний > 200) { последний = performance.now(); setТик((x) => x + 1) }
    }
    цикл()
    return () => cancelAnimationFrame(id)
  }, [фаза, вопрос, шаг, запись])

  /* «Ответил» / «Готово» — кнопкой и пробелом. */
  const готово = useCallback(async () => {
    if (фаза.что !== 'шаг' || !шаг || шаг.сек > 0) return
    if (шаг.стимул.вид === 'фраза' || шаг.стимул.вид === 'ситуация') {
      await запись.закончитьКлип()
      сводка.записал(шаг.стимул.вид)
    }
    if (шаг.метка === 'думает') сводка.ответил(фаза.i, прошло())
    запись.событие(шаг.метка === 'думает' ? 'ответил' : 'готово', { i: фаза.i, через: прошло() })
    следующий(фаза.i)
  }, [фаза, шаг, запись, следующий, сводка])

  useEffect(() => {
    const клавиша = (e: KeyboardEvent) => {
      if (e.repeat) return
      if (e.code === 'Space' && фаза.что === 'шаг' && шаг && шаг.сек === 0) { e.preventDefault(); void готово() }
      if (листать && !вопрос && (e.code === 'ArrowRight' || e.code === 'ArrowLeft')) {
        e.preventDefault()
        if (e.code === 'ArrowRight') листать.вперёд(); else листать.назад()
      }
    }
    window.addEventListener('keydown', клавиша)
    return () => window.removeEventListener('keydown', клавиша)
  }, [фаза, шаг, готово, листать, вопрос])

  const заново = () => {
    if (фаза.что !== 'шаг' || !шаг) return
    запись.отменитьКлип()
    запись.начатьКлип({ i: фаза.i, метка: шаг.метка, ...шаг.стимул, заново: true })
  }
  const пропустить = () => {
    if (фаза.что !== 'шаг') return
    запись.отменитьКлип()
    запись.событие('пропуск', { i: фаза.i })
    следующий(фаза.i)
  }

  const ответитьНаВопрос = (где: string, собранность: number) => {
    if (!вопрос) return
    const ответ = { n: вопрос.n, где, собранность, думал: (performance.now() - вопрос.с) / 1000 }
    ответы.current.push({ вид: 'где внимание', ...ответ })
    запись.событие('ответ', ответ)
    if (паузаС.current !== null) пауза.current += (performance.now() - паузаС.current)
    паузаС.current = null
    setВопрос(null)
  }

  const [ответПонимания, setОтветПонимания] = useState<ОтветПонимания | null>(null)
  const понял = (верных: number, выбор: number[]) => {
    ответы.current.push({ вид: 'понимание', верных, выбор })
    сводка.понял(верных)
    запись.событие('понимание', { верных, выбор })
    void завершить(false)
  }

  /* В запись — только настоящая смена страницы, а не каждая перерисовка книги. */
  const былоЛисты = useRef('')
  const страница = useCallback((н: Листы) => {
    const ключ = JSON.stringify(н)
    if (ключ === былоЛисты.current) return
    былоЛисты.current = ключ
    листыСейчас.current = н
    setЛисты(н)
    запись.событие('страница', н)
  }, [запись])

  void тик
  const t = прошло()
  const всего = сценарий.шаги.length
  const номер = фаза.что === 'шаг' || фаза.что === 'подготовка' ? фаза.i + 1 : фаза.что === 'калибровка' ? 0 : всего
  const осталось = фаза.что === 'калибровка' ? сценарий.калибровка - t
    : фаза.что === 'подготовка' ? ПОДГОТОВКА_СЕК - t
    : шаг && шаг.сек > 0 ? шаг.сек - t : null
  const доля = фаза.что === 'шаг' && шаг && шаг.сек > 0 ? Math.min(1, t / шаг.сек) : 0
  const чтение = фаза.что === 'шаг' && шаг?.стимул.вид === 'чтение'

  const состояниеКамеры = !описание.камера ? 'Микрофон пишет'
    : !лицо.есть ? 'Камера не видит лицо — вернитесь в кадр, когда шаг это позволяет'
    : лицо.качество === 'хорошо' ? 'Камера видит лицо целиком · света достаточно'
    : ЛИЦО_НЕ_ВИДНО[лицо.качество]

  const низ = фаза.что === 'понимание' ? <НизПонимания ответ={ответПонимания} onГотово={(о) => понял(о.верных, о.выбор)} /> : стоп ? (
    <>
      <span className={s.низСлова}>Остановить проверку? Записанное сохранится.</span>
      <Button kind="quiet" onClick={() => setСтоп(false)}>Продолжить</Button>
      <Button kind="leave" onClick={() => void завершить(true)}>Остановить</Button>
    </>
  ) : вопрос ? (
    <span className={s.низСлова}>Ответьте на вопрос — и читайте дальше. Время на ответ не считается.</span>
  ) : чтение && листать ? (
    <>
      <span className={`${s.низСлова} ${s.моно}`}>{листы.наРазвороте === 2
        ? `разворот ${Math.floor(листы.страница / 2) + 1} из ${Math.max(1, Math.ceil(листы.всего / 2))}`
        : `страница ${листы.страница + 1} из ${Math.max(1, листы.всего)}`} · пару раз спросим, где было внимание</span>
      <Button kind="ghost" onClick={() => setСтоп(true)}>Остановить</Button>
      <Button kind="quiet" onClick={листать.назад}>Назад</Button>
      <Button kind="go" onClick={листать.вперёд}>Перевернуть страницу</Button>
    </>
  ) : (
    <>
      <span className={s.низСлова}><Отметка да={лицо.есть && лицо.качество === 'хорошо'} />{состояниеКамеры}</span>
      <Button kind="quiet" onClick={() => setСтоп(true)}>Остановить проверку</Button>
    </>
  )

  return (
    <ХодВид
      название={описание.название}
      счёт={(номер ? `шаг ${номер} из ${всего}` : 'калибровка') + (осталось !== null ? ` · ${ммсс(осталось)}` : '')}
      имя={имя}
      отрезков={всего}
      пройдено={фаза.что === 'шаг' || фаза.что === 'подготовка' ? фаза.i : фаза.что === 'калибровка' ? 0 : всего}
      доля={доля}
      идёт={ммсс(запись.сейчас() / 1000)}
      низ={низ}
    >
      {фаза.что === 'понимание' && сценарий.текст ? <Понимание текст={сценарий.текст} onОтвет={setОтветПонимания} /> : (
        <Сцена фаза={фаза} сценарий={сценарий} t={t} осталось={осталось} точка={точка} моргнул={моргнул}
          готово={() => void готово()} заново={заново} пропустить={пропустить}
          отметить={() => запись.событие('попросил записать', { i: фаза.что === 'шаг' ? фаза.i : -1 })}
          закончитьУрок={() => {
            if (фаза.что !== 'шаг') return
            void запись.закончитьКлип()
            сводка.записал('урок', прошло())
            запись.событие('шаг-конец', { i: фаза.i, раньше: true })
            следующий(фаза.i)
          }}
          onСтраница={страница} onЛистать={setЛистать} />
      )}
      {вопрос ? <ГдеВнимание onОтвет={ответитьНаВопрос} /> : null}
    </ХодВид>
  )
}

/** Рама проверки: шапка «шаг N из M», полоска с отрезками и огоньком записи. Без часов и камеры — для стенда. */
export function ХодВид({ название, счёт, имя, отрезков, пройдено, доля, идёт, низ, children }: {
  название: string
  счёт: string
  имя?: string | null
  отрезков: number
  пройдено: number
  /** Доля текущего отрезка 0..1. */
  доля: number
  /** «02:14» — сколько идёт запись. */
  идёт: string
  низ: ReactNode
  children: ReactNode
}) {
  return (
    <Рама раздел={название} счёт={счёт} справа={<КтоЯ имя={имя ?? null} />} место={название.toLowerCase()}
      право={(
        <>
          <span className={`${s.отрезки} ${s.полоскаСправа}`} aria-label={`Пройдено шагов: ${пройдено} из ${отрезков}`}>
            {Array.from({ length: Math.min(отрезков, 24) }, (_, n) => (
              <span key={n} className={`${s.отрезок} ${n < пройдено ? s.отрезокПройден : ''}`}>
                {n === пройдено && доля > 0 ? <span className={s.отрезокЗаливка} style={{ width: `${Math.round(доля * 100)}%` }} /> : null}
              </span>
            ))}
          </span>
          <Огонёк идёт>идёт запись · {идёт}</Огонёк>
        </>
      )}
      низ={низ}
    >
      <div className={s.ход}>{children}</div>
    </Рама>
  )
}

/** Что на доске в эту фазу: калибровка, подсказка перед шагом или сам шаг. */
export function Сцена({ фаза, сценарий, t, осталось, точка, моргнул, готово, заново, пропустить, отметить, закончитьУрок, onСтраница, onЛистать }: {
  фаза: Фаза
  сценарий: Сценарий
  t: number
  осталось: number | null
  точка?: React.RefObject<HTMLSpanElement | null>
  моргнул?: number
  готово?: () => void
  заново?: () => void
  пропустить?: () => void
  отметить?: () => void
  закончитьУрок?: () => void
  onСтраница?: (н: Листы) => void
  onЛистать?: (л: { вперёд: () => void; назад: () => void } | null) => void
}) {
  if (фаза.что === 'калибровка') {
    return (
      <>
        <span className={`${s.точка} ${s.точкаЦентр}`} aria-hidden />
        <Подсказка текст="Сядьте как на уроке и спокойно смотрите на точку" подробно="Так система узнаёт, как выглядит ваш взгляд на экран." />
      </>
    )
  }
  if (фаза.что === 'конец') return <Крупно текст="Заканчиваем запись…" />
  if (фаза.что === 'понимание') return null
  const шаг = сценарий.шаги[фаза.i]
  if (фаза.что === 'подготовка') {
    return <Крупно сейчас текст={шаг.текст} подробно={шаг.подробно} сигналом={шаг.сигнал} осталось={осталось} />
  }
  const с = шаг.стимул
  switch (с.вид) {
    case 'пусто': return <Крупно текст={шаг.текст} подробно={шаг.подробно} сигналом={шаг.сигнал} />
    case 'камера':
      return (
        <>
          <КСамере />
          <Крупно текст={шаг.текст} подробно={шаг.подробно} сигналом={шаг.сигнал} />
        </>
      )
    case 'моргай':
      return (
        <div className={s.моргай}>
          <Моргание />
          <div className={s.моргайСлова}>
            <h2 className={`${s.крупно} ${s.наБелом}`}>{шаг.текст}</h2>
            <p className={`${s.крупноЕщё} ${s.наБелом}`}>{шаг.подробно}</p>
            <div className={`${s.листок} ${s.счётчик}`} role="status">
              <span className={s.счётчикЧисло}>{моргнул ?? 0}</span>
              <span className={s.шапкаТекста}>
                <span className={s.бровь}>Система насчитала</span>
                <span className={s.тихо}>морганий — так она учится узнавать именно ваши</span>
              </span>
            </div>
          </div>
        </div>
      )
    case 'учитель': return <><Учитель /><Подсказка текст={шаг.текст} подробно={шаг.подробно} /></>
    case 'доска':
      return (
        <>
          <div className={`${s.листок} ${s.доскаУрока}`}>{с.текст.split('\n').map((строка) => <p key={строка}>{строка}</p>)}</div>
          <Подсказка текст={шаг.текст} подробно={шаг.подробно} />
        </>
      )
    case 'текст': return <><div className={`${s.листок} ${s.текстНаЭкране}`}><p>{с.текст}</p></div><Подсказка текст={шаг.текст} подробно={шаг.подробно} /></>
    case 'путь':
    case 'точки': {
      const нач = гдеТочка(с, t) ?? [0.5, 0.5]
      return <span ref={точка} className={s.точка} style={{ left: `${нач[0] * 100}%`, top: `${нач[1] * 100}%` }} aria-hidden />
    }
    case 'вопрос':
      return (
        <div className={`${s.листок} ${s.вопрос}`}>
          <span className={s.бровь}>{шаг.текст}</span>
          <p className={s.вопросТекст}>{с.текст}</p>
          <span className={s.тихо}>{шаг.подробно}</span>
          <Button kind="go" onClick={готово}>Ответил(а)</Button>
        </div>
      )
    case 'чтение': {
      const тексты = (сценарий.тексты ?? [с.текст]).map((id) => ТЕКСТЫ.find((x) => x.id === id)).filter((x): x is ТекстДляЧтения => Boolean(x))
      return <Книга тексты={тексты} onСтраница={onСтраница} onЛистать={onЛистать} />
    }
    case 'фраза':
    case 'ситуация':
      return (
        <div className={`${s.листок} ${s.вопрос}`}>
          <span className={s.бровь}>{шаг.текст}</span>
          <p className={s.вопросТекст}>{с.вид === 'фраза' ? `«${с.текст}»` : с.текст}</p>
          {шаг.подробно ? <span className={s.тихо}>{шаг.подробно}</span> : null}
          <span className={s.идётЗапись}><span className={`${s.огонёк} ${s.огонёкИдёт}`} aria-hidden />идёт запись фразы</span>
          <div className={s.ряд}>
            <Button kind="quiet" onClick={пропустить}>Пропустить</Button>
            <Button kind="quiet" onClick={заново}>Записать заново</Button>
            <Button kind="go" onClick={готово}>Готово</Button>
          </div>
        </div>
      )
    case 'урок':
      return <Урок шаг={шаг} t={t} отметить={отметить} закончитьУрок={закончитьУрок} />
  }
}

