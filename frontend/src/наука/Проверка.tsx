export function Понимание({ текст, onГотово }: { текст: string; onГотово: (верных: number, выбор: number[]) => void }) {
  const т = useMemo(() => ТЕКСТЫ.find((x) => x.id === текст), [текст])
  const [выбор, setВыбор] = useState<(number | null)[]>(() => т?.вопросы.map(() => null) ?? [])
  if (!т) return null
  const все = выбор.every((в) => в !== null)
  return (
    <div className={s.понимание}>
      <span className={s.бровь}>Чтение закончено</span>
      <h2 className={s.h2}>Три вопроса по тексту</h2>
      {т.вопросы.map((в, i) => (
        <Выбор key={в.вопрос} столбцом подпись={`${i + 1}. ${в.вопрос}`} значение={выбор[i]}
          onВыбор={(к) => setВыбор((б) => б.map((x, j) => (j === i ? к : x)))}
          варианты={в.ответы.map((о, j) => ({ ключ: j, слова: о }))} />
      ))}
      <Button kind="go" disabled={!все} onClick={() => onГотово(т.вопросы.filter((в, i) => выбор[i] === в.верный).length, выбор as number[])}>
        Готово
      </Button>
    </div>
  )
}
