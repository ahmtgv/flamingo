export type Камера = 'просим' | 'запрещено' | 'нет камеры' | 'модель' | 'модель не завелась' | 'готова'

const ЛИЦО_НЕ_ВИДНО: Record<Качество, string> = {
  'хорошо': '',
  'обрезано': 'Лицо касается края кадра — сядьте чуть дальше или по центру.',
  'далеко': 'Вы далеко от камеры — сядьте ближе.',
  'темно': 'Темновато — включите свет или повернитесь к окну.',
}

export function Проверка({ код, описание, перед, onКонец, onНазад }: {
  код: string
  описание: Описание
  перед: Перед
  onКонец: (очередь: Очередь, прервано: boolean) => void
  onНазад: () => void
}) {
  /* 🔴 ВИДЕО — ОДНО НА ВСЮ ПРОВЕРКУ, И ЗАВОДИТСЯ РУКАМИ, А НЕ РАЗМЕТКОЙ. На
     подготовке оно стоит в окне камеры, во время шагов — в невидимом тайнике
     (не display:none: спрятанному так видео браузер может перестать отдавать
     кадры). React переносить живой элемент между родителями не умеет, поэтому
     элемент наш, а React только даёт ему место. */
  const видео = useMemo(() => {
    const в = document.createElement('video')
    в.playsInline = true
    в.muted = true
    в.className = s.видео
    return в
  }, [])
  const тайник = useRef<HTMLDivElement>(null)
  const поток = useRef<MediaStream | null>(null)
  const модель = useRef<Awaited<ReturnType<typeof завести>> | null>(null)
  const [камера, setКамера] = useState<Камера>('просим')
  const [беда, setБеда] = useState('')
  const [запись, setЗапись] = useState<Запись | null>(null)
  const [сценарий, setСценарий] = useState<Сценарий | null>(null)
  const [начинаем, setНачинаем] = useState(false)

  /* Камера (или только микрофон для голоса) и модель лица. */
  useEffect(() => {
    let живо = true
    ;(async () => {
      try {
        поток.current = await открыть(описание.камера, true)
      } catch (e) {
        if (!живо) return
        const имя = e instanceof DOMException ? e.name : ''
        setКамера(имя === 'NotFoundError' || имя === 'OverconstrainedError' ? 'нет камеры' : 'запрещено')
        return
      }
      if (!живо) { поток.current.getTracks().forEach((т) => т.stop()); return }
      if (описание.камера) {
        видео.srcObject = поток.current
        await видео.play().catch(() => undefined)
        setКамера('модель')
        try {
          модель.current = await завести(new URLSearchParams(window.location.search).get('модель') || undefined)
        } catch (e) {
          if (!живо) return
          setБеда(String(e instanceof Error ? e.message : e))
          setКамера('модель не завелась')
          return
        }
      }
      if (живо) setКамера('готова')
    })()
    return () => {
      живо = false
      поток.current?.getTracks().forEach((т) => т.stop())
      модель.current?.модель.close()
    }
  }, [описание.камера, видео])

  /* 🔴 Нельзя молча закрыть вкладку посреди записи: последние секунды не доедут. */
  useEffect(() => {
    if (!запись) return
    const стоп = (e: BeforeUnloadEvent) => { e.preventDefault() }
    window.addEventListener('beforeunload', стоп)
    return () => window.removeEventListener('beforeunload', стоп)
  }, [запись])

  const начать = useCallback(async () => {
    if (!поток.current) return
    завестиЗвук()
    setНачинаем(true)
    setБеда('')
    const зерно = Math.floor(Math.random() * 2 ** 31)
    const с = собрать(описание.вид, зерно)
    let id: string
    try {
      id = (await наука.начать(код, { вид: описание.вид, протокол: с.протокол, перед, устройство: обУстройстве(поток.current) })).id
    } catch (e) {
      setБеда(e instanceof ОтказНауки ? e.message : 'Сервер не ответил. Попробуйте ещё раз.')
      setНачинаем(false)
      return
    }
    const очередь = new Очередь(код, id)
    const з = new Запись(очередь, поток.current, модель.current, описание.камера ? видео : null)
    з.начать({ вид: описание.вид, протокол: с.протокол, зерно, перед, сценарий: с }, описание.камера)
    щелчок()
    setСценарий(с)
    setЗапись(з)
  }, [код, описание, перед])

  /* Пока идёт запись — видео в тайнике. */
  useLayoutEffect(() => {
    if (запись && тайник.current) тайник.current.appendChild(видео)
  }, [запись, видео])

  return (
    <>
      <div ref={тайник} className={s.тайник} aria-hidden />
      {запись && сценарий ? (
        <Ход
          сценарий={сценарий}
          запись={запись}
          описание={описание}
          onКонец={(прервано) => onКонец(запись.очередь, прервано)}
        />
      ) : (
        <Подготовка
          описание={описание}
          камера={камера}
          беда={беда}
          видео={видео}
          модель={модель.current?.модель ?? null}
          поток={поток.current}
          начинаем={начинаем}
          onНачать={начать}
          onНазад={onНазад}
        />
      )}
    </>
  )
}

/* ── Подготовка ───────────────────────────────────────────────────────── */

type Проба = { лицо: boolean; качество: Качество; до: number | null }

export function Подготовка({ описание, камера, беда, видео, модель, поток, начинаем, onНачать, onНазад }: {
  описание: Описание
  камера: Камера
  беда: string
  видео: HTMLVideoElement | null
  модель: FaceLandmarker | null
  поток: MediaStream | null
  начинаем: boolean
  onНачать: () => void
  onНазад: () => void
}) {
  const [проба, setПроба] = useState<Проба | null>(null)
  const [лицоБыло, setЛицоБыло] = useState(false)
  const [слышно, setСлышно] = useState(false)
  const [проверилЗвук, setПроверилЗвук] = useState(false)
  const [громкость, setГромкость] = useState(0)
  const [голосБыл, setГолосБыл] = useState(false)
  const слот = useRef<HTMLDivElement>(null)

  /* Живое видео — в окно камеры. */
  useLayoutEffect(() => {
    if (видео && слот.current) слот.current.prepend(видео)
  }, [видео])

  /* Проба лица: восемь раз в секунду, пока человек усаживается. */
  useEffect(() => {
    if (камера !== 'готова' || !модель || !видео) return
    const яркомер = new Яркомер()
    let id = 0
    let прошлое = 0
    const цикл = () => {
      id = requestAnimationFrame(цикл)
      const сейчас = performance.now()
      if (сейчас - прошлое < 120 || видео.readyState < 2) return
      прошлое = сейчас
      const к: Кадр = разобрать(модель.detectForVideo(видео, сейчас), видео.videoWidth / (видео.videoHeight || 1))
      const кач = оценить(к, яркомер.замерить(видео, сейчас))
      setПроба({ лицо: к.лицо, качество: кач, до: к.до })
      if (к.лицо && кач === 'хорошо') setЛицоБыло(true)
    }
    цикл()
    return () => cancelAnimationFrame(id)
  }, [камера, модель, видео])

  /* Микрофон: уровень звука — чтобы человек увидел, что его слышно. */
  useEffect(() => {
    if (!поток || !поток.getAudioTracks().length) return
    let ctx: AudioContext
    try { ctx = new AudioContext() } catch { return }
    const ан = ctx.createAnalyser()
    ан.fftSize = 512
    ctx.createMediaStreamSource(поток).connect(ан)
    const данные = new Uint8Array(ан.fftSize)
    let id = 0
    const цикл = () => {
      id = requestAnimationFrame(цикл)
      ан.getByteTimeDomainData(данные)
      let сумма = 0
      for (const д of данные) сумма += ((д - 128) / 128) ** 2
      const уровень = Math.sqrt(сумма / данные.length)
      setГромкость(уровень)
      if (уровень > 0.04) setГолосБыл(true)
    }
    цикл()
    return () => { cancelAnimationFrame(id); void ctx.close() }
  }, [поток])

  const проверитьЗвук = () => {
    завестиЗвук()
    сигнал()
    setПроверилЗвук(true)
  }

  const до = проба?.до ?? null
  const пункты: { что: string; да: boolean; как?: string }[] = описание.камера
    ? [
        { что: 'Камера работает', да: камера === 'готова' },
        { что: 'Лицо видно целиком', да: Boolean(проба?.лицо) && проба?.качество !== 'обрезано' && проба?.качество !== 'далеко',
          как: !проба?.лицо ? 'Сядьте так, чтобы лицо было в кадре.' : ЛИЦО_НЕ_ВИДНО[проба.качество] },
        { что: 'Света достаточно', да: Boolean(проба?.лицо) && проба?.качество !== 'темно', как: ЛИЦО_НЕ_ВИДНО['темно'] },
        { что: 'Расстояние до экрана — как на уроке', да: до !== null && до >= 35 && до <= 95,
          как: до === null ? 'Дождитесь, пока камера найдёт лицо.' : до < 35 ? 'Слишком близко — отодвиньтесь.' : 'Далековато — сядьте ближе.' },
        { что: 'Сигнал слышно', да: слышно, как: 'Нажмите «Проверить звук» и отметьте, что слышите.' },
      ]
    : [
        { что: 'Микрофон работает', да: камера === 'готова' },
        { что: 'Вас слышно', да: голосБыл, как: 'Скажите что-нибудь — полоска громкости должна дрогнуть.' },
      ]
  const можно = описание.камера ? камера === 'готова' && лицоБыло && слышно : камера === 'готова' && голосБыл

  const отказ: Partial<Record<Камера, { что: string; как: string }>> = {
    'просим': { что: описание.камера ? 'Разрешите камеру и микрофон' : 'Разрешите микрофон', как: 'Браузер спрашивает разрешение в окошке у адресной строки.' },
    'запрещено': { что: 'Доступ запрещён', как: 'Разрешите камеру и микрофон в настройках сайта — значок замка в адресной строке — и обновите страницу.' },
    'нет камеры': { что: описание.камера ? 'Камера не найдена' : 'Микрофон не найден', как: 'Подключите её и обновите страницу. Проверки идут только с камерой: по ней система и учится.' },
    'модель': { что: 'Загружаем модель лица', как: 'Около 15 МБ в первый раз; дальше браузер помнит её сам.' },
    'модель не завелась': { что: 'Модель лица не загрузилась', как: `Попробуйте обновить страницу или открыть её в Chrome. Ответ браузера: ${беда}` },
  }
  const сейчас = отказ[камера]

  return (
    <Лист бровь={`Проверка «${описание.название}»`} заголовок="Подготовка"
      лид={описание.камера
        ? 'Сядьте как обычно на уроке, разверните окно браузера на весь экран и проверьте пункты справа. Запись начнётся только по кнопке.'
        : 'Проверьте микрофон. Запись начнётся только по кнопке.'}
    >
      <div className={s.подготовка}>
        {описание.камера ? (
          <div className={s.окноКамеры} ref={слот}>
            {сейчас ? (
              <div className={s.пока} role="status">
                <span className={s.покаЧто}>{сейчас.что}</span>
                <span className={s.покаКак}>{сейчас.как}</span>
                {камера === 'запрещено' || камера === 'нет камеры' || камера === 'модель не завелась'
                  ? <Button kind="quiet" onClick={() => window.location.reload()}>Обновить страницу</Button>
                  : null}
              </div>
            ) : null}
          </div>
        ) : (
          <div className={s.микрофон}>
            {сейчас ? <p className={s.покаЧто}>{сейчас.что}</p> : <p className={s.покаЧто}>Скажите что-нибудь</p>}
            <span className={s.полоса} aria-hidden><span className={s.полосаЗаливка} style={{ width: `${Math.min(100, Math.round(громкость * 400))}%` }} /></span>
            {сейчас ? <p className={s.тихо}>{сейчас.как}</p> : null}
          </div>
        )}

        <div className={s.пункты}>
          <ul className={s.список}>
            {пункты.map((п) => (
              <li key={п.что} className={п.да ? s.пунктДа : s.пункт}>
                <span className={s.отметка} aria-hidden>{п.да ? '✓' : '·'}</span>
                <span>
                  {п.что}
                  {!п.да && п.как ? <span className={s.пунктКак}>{п.как}</span> : null}
                </span>
              </li>
            ))}
          </ul>
          {описание.камера ? (
            <div className={s.ряд}>
              <Button kind="quiet" onClick={проверитьЗвук}>Проверить звук</Button>
              <label className={s.галка}>
                <input type="checkbox" checked={слышно} disabled={!проверилЗвук} onChange={(e) => setСлышно(e.target.checked)} />
                <span>Слышу сигнал</span>
              </label>
            </div>
          ) : null}
          <p className={s.тихо}>
            {описание.камера
              ? 'Сигнал звучит, когда пора вернуться к экрану: во многих шагах вы будете смотреть в сторону или с закрытыми глазами.'
              : 'Фразы записываются по одной: прочитали — «Готово», следующая.'}
          </p>
        </div>
      </div>

      <div className={s.действия}>
        <p className={s.строка} role="status">
          {беда || (можно ? 'Всё готово. Запись начнётся по кнопке.' : 'Когда все пункты отмечены, кнопка станет доступна.')}
        </p>
        <div className={s.ряд}>
          <Button kind="quiet" onClick={onНазад}>Назад к списку</Button>
          <Button kind="go" disabled={!можно || начинаем} onClick={onНачать}>
            {начинаем ? 'Начинаем…' : 'Начать запись'}
          </Button>
        </div>
      </div>
    </Лист>
  )
}

/* ── Ход проверки ─────────────────────────────────────────────────────── */

type Фаза =
  | { что: 'калибровка' }
  | { что: 'подготовка'; i: number }
  | { что: 'шаг'; i: number }
  | { что: 'понимание' }
  | { что: 'конец' }

const ммсс = (сек: number) => {
  const с = Math.max(0, Math.ceil(сек))
  return `${Math.floor(с / 60)}:${String(с % 60).padStart(2, '0')}`
}

function Ход({ сценарий, запись, описание, onКонец }: {
  сценарий: Сценарий
  запись: Запись
  описание: Описание
  onКонец: (прервано: boolean) => void
}) {
  const [фаза, setФаза] = useState<Фаза>(() => (сценарий.калибровка > 0 ? { что: 'калибровка' } : { что: 'подготовка', i: 0 }))
  const начало = useRef(performance.now())
  const пауза = useRef(0)
  const паузаС = useRef<number | null>(null)
  const [тик, setТик] = useState(0)
  const [видимЛицо, setВидимЛицо] = useState(true)
  const [стоп, setСтоп] = useState(false)
  const [вопрос, setВопрос] = useState<{ n: number; с: number; где: string | null } | null>(null)
  const заданоВопросов = useRef(0)
  const ответы = useRef<Record<string, unknown>[]>([])
  const точка = useRef<HTMLSpanElement>(null)
  const конец = useRef(false)

  const шаг: Шаг | null = фаза.что === 'шаг' || фаза.что === 'подготовка' ? сценарий.шаги[фаза.i] : null
  const прошло = () => (performance.now() - начало.current - пауза.current) / 1000

  /* Камера видит лицо? — для тихой отметки в шапке. */
  useEffect(() => запись.слушать((и) => setВидимЛицо(и.сейчас !== 'нет в кадре' && и.сейчас !== 'ушёл')), [запись])

  const завершить = useCallback(async (прервано: boolean) => {
    if (конец.current) return
    конец.current = true
    setФаза({ что: 'конец' })
    await запись.остановить({ прервано, ответы: ответы.current, шагов: сценарий.шаги.length })
    onКонец(прервано)
  }, [запись, сценарий, onКонец])

  const перейти = useCallback((новая: Фаза) => {
    начало.current = performance.now()
    пауза.current = 0
    if (новая.что === 'подготовка') {
      const ш = сценарий.шаги[новая.i]
      запись.поставить({ шаг: новая.i, стимул: null, пишем: false })
      запись.событие('подготовка', { i: новая.i, метка: ш.метка })
    }
    if (новая.что === 'шаг') {
      const ш = сценарий.шаги[новая.i]
      запись.поставить({ шаг: новая.i, пишем: Boolean(ш.пишем) })
      запись.событие('шаг', { i: новая.i, метка: ш.метка, ждём: ш.ждём, пишем: Boolean(ш.пишем), сек: ш.сек, стимул: ш.стимул })
      if (ш.стимул.вид === 'фраза' || ш.стимул.вид === 'ситуация' || ш.стимул.вид === 'урок') {
        запись.начатьКлип({ i: новая.i, метка: ш.метка, ...ш.стимул })
      }
    }
    setФаза(новая)
  }, [сценарий, запись])

  const следующий = useCallback((i: number) => {
    if (i + 1 < сценарий.шаги.length) перейти({ что: 'подготовка', i: i + 1 })
    else if (сценарий.вид === 'чтение') { запись.поставить({ шаг: 255, стимул: null }); setФаза({ что: 'понимание' }) }
    else void завершить(false)
  }, [сценарий, перейти, завершить, запись])

  /* Калибровка начинается сразу. */
  useEffect(() => {
    if (фаза.что !== 'калибровка') return
    запись.поставить({ шаг: 255, стимул: [0.5, 0.5] })
    запись.начатьКалибровку()
  }, [фаза.что, запись])

  /* 🔴 ЧАСЫ — НА ТАЙМЕРЕ, ТОЧКА — НА КАДРАХ ЭКРАНА. Пока вкладка спрятана
     (шаг «переключитесь на другое окно»), браузер не рисует кадры вовсе, и
     часы на них остановились бы: шаг не кончился бы, сигнал «вернитесь» не
     прозвучал бы, человек ждал бы его в другом окне вечно. Таймер в спрятанной
     вкладке тоже замедляют — но до раза в секунду, а не до нуля. */
  useEffect(() => {
    const id = window.setInterval(() => {
      if (конец.current) return
      const t = прошло()
      if (фаза.что === 'калибровка') {
        if (t >= сценарий.калибровка) {
          запись.закончитьКалибровку()
          перейти({ что: 'подготовка', i: 0 })
        }
        return
      }
      if (фаза.что === 'подготовка') {
        if (t >= ПОДГОТОВКА_СЕК) перейти({ что: 'шаг', i: фаза.i })
        return
      }
      if (фаза.что !== 'шаг' || !шаг || вопрос) return
      /* Чтение: вопрос «где было внимание» в заранее выбранные мгновения. */
      const n = заданоВопросов.current
      if (сценарий.вид === 'чтение' && n < сценарий.вопросы.length && t >= сценарий.вопросы[n]) {
        заданоВопросов.current = n + 1
        паузаС.current = performance.now()
        запись.событие('вопрос', { n, сек: t })
        setВопрос({ n, с: performance.now(), где: null })
        return
      }
      if (шаг.сек > 0 && t >= шаг.сек) {
        if (шаг.стимул.вид === 'урок') void запись.закончитьКлип()
        if (шаг.сигнал) { сигнал(); запись.событие('сигнал', { i: фаза.i }) }
        запись.событие('шаг-конец', { i: фаза.i })
        следующий(фаза.i)
        return
      }
      /* Вопрос «подумайте» без ответа — дальше через минуту. */
      if (шаг.сек === 0 && шаг.метка === 'думает' && t >= 60) {
        запись.событие('не ответил', { i: фаза.i })
        следующий(фаза.i)
      }
    }, 100)
    return () => window.clearInterval(id)
  }, [фаза, вопрос, шаг, сценарий, запись, перейти, следующий])

  /* Точка и цифры на экране — с каждым кадром экрана. */
  useEffect(() => {
    let id = 0
    let последний = 0
    const цикл = () => {
      id = requestAnimationFrame(цикл)
      if (конец.current) return
      if (фаза.что === 'шаг' && шаг && !вопрос) {
        const pos = гдеТочка(шаг.стимул, прошло())
        if (pos && точка.current) {
          точка.current.style.left = `${pos[0] * 100}%`
          точка.current.style.top = `${pos[1] * 100}%`
        }
        запись.поставить({ стимул: pos })
      }
      if (performance.now() - последний > 200) { последний = performance.now(); setТик((x) => x + 1) }
    }
    цикл()
    return () => cancelAnimationFrame(id)
  }, [фаза, вопрос, шаг, запись])

  /* «Ответил» / «Готово» — кнопкой и пробелом. */
  const готово = useCallback(async () => {
    if (фаза.что !== 'шаг' || !шаг || шаг.сек > 0) return
    if (шаг.стимул.вид === 'фраза' || шаг.стимул.вид === 'ситуация') await запись.закончитьКлип()
    запись.событие(шаг.метка === 'думает' ? 'ответил' : 'готово', { i: фаза.i, через: прошло() })
    следующий(фаза.i)
  }, [фаза, шаг, запись, следующий])

  useEffect(() => {
    const клавиша = (e: KeyboardEvent) => {
      if (e.code !== 'Space' || e.repeat) return
      if (фаза.что === 'шаг' && шаг && шаг.сек === 0) { e.preventDefault(); void готово() }
    }
    window.addEventListener('keydown', клавиша)
    return () => window.removeEventListener('keydown', клавиша)
  }, [фаза, шаг, готово])

  const заново = () => {
    if (фаза.что !== 'шаг' || !шаг) return
    запись.отменитьКлип()
    запись.начатьКлип({ i: фаза.i, метка: шаг.метка, ...шаг.стимул, заново: true })
  }
  const пропустить = () => {
    if (фаза.что !== 'шаг') return
    запись.отменитьКлип()
    запись.событие('пропуск', { i: фаза.i })
    следующий(фаза.i)
  }

  const ответитьНаВопрос = (где: string, собранность: number) => {
    if (!вопрос) return
    const ответ = { n: вопрос.n, где, собранность, думал: (performance.now() - вопрос.с) / 1000 }
    ответы.current.push({ вид: 'где внимание', ...ответ })
    запись.событие('ответ', ответ)
    if (паузаС.current !== null) пауза.current += (performance.now() - паузаС.current)
    паузаС.current = null
    setВопрос(null)
  }

  const понял = (верных: number, выбор: number[]) => {
    ответы.current.push({ вид: 'понимание', верных, выбор })
    запись.событие('понимание', { верных, выбор })
    void завершить(false)
  }

  void тик
  const t = прошло()
  const всего = сценарий.шаги.length
  const номер = фаза.что === 'шаг' || фаза.что === 'подготовка' ? фаза.i + 1 : фаза.что === 'калибровка' ? 0 : всего
  const осталось = фаза.что === 'калибровка' ? сценарий.калибровка - t
    : фаза.что === 'подготовка' ? ПОДГОТОВКА_СЕК - t
    : шаг && шаг.сек > 0 ? шаг.сек - t : null

  return (
    <ХодВид
      название={описание.название}
      счёт={номер ? `шаг ${номер} из ${всего}` : 'калибровка'}
      осталось={осталось}
      запись={описание.камера ? (видимЛицо ? 'идёт запись · камера видит вас' : 'идёт запись · лица не видно') : 'идёт запись'}
      стоп={стоп}
      onСтоп={setСтоп}
      onОстановить={() => void завершить(true)}
    >
      {фаза.что === 'калибровка' ? (
        <>
          <span className={`${s.точка} ${s.точкаЦентр}`} aria-hidden />
          <Подсказка текст="Сядьте как на уроке и спокойно смотрите на точку" подробно="Так система узнаёт, как выглядит ваш взгляд на экран." осталось={осталось} />
        </>
      ) : null}

      {фаза.что === 'подготовка' && шаг ? (
        <Подсказка крупно сейчас текст={шаг.текст} подробно={шаг.подробно} осталось={осталось} />
      ) : null}

      {фаза.что === 'шаг' && шаг ? (
        <>
          <Стимул шаг={шаг} точка={точка} t={t} готово={() => void готово()} заново={заново} пропустить={пропустить}
            отметить={() => запись.событие('попросил записать', { i: фаза.i })}
            закончитьУрок={() => { void запись.закончитьКлип(); запись.событие('шаг-конец', { i: фаза.i, раньше: true }); следующий(фаза.i) }} />
          {СВОЯ_ПОДСКАЗКА.has(шаг.стимул.вид) ? null : <Подсказка текст={шаг.текст} подробно={шаг.подробно} осталось={осталось} />}
        </>
      ) : null}

      {вопрос ? <ГдеВнимание onОтвет={ответитьНаВопрос} /> : null}

      {фаза.что === 'понимание' && сценарий.текст ? (
        <Понимание текст={сценарий.текст} onГотово={понял} />
      ) : null}

      {фаза.что === 'конец' ? <Подсказка крупно текст="Заканчиваем запись…" /> : null}
    </ХодВид>
  )
}

/** У этих стимулов подсказка внутри них самих — второй не нужно. У точки
 *  подсказки во время шага нет вовсе: точка ходит по всему экрану, в том числе
 *  по низу, где стояла бы подсказка, — подсказка была крупно перед шагом, а
 *  время осталось в шапке. */
export const СВОЯ_ПОДСКАЗКА = new Set(['вопрос', 'фраза', 'ситуация', 'урок', 'чтение', 'точки', 'путь'])

/** Шапка проверки и сцена под ней. Без часов и камеры — открывается на стенде. */
export function ХодВид({ название, счёт, осталось, запись, стоп, onСтоп, onОстановить, children }: {
  название: string
  счёт: string
  осталось: number | null
  запись: string
  стоп: boolean
  onСтоп: (да: boolean) => void
  onОстановить: () => void
  children: ReactNode
}) {
  return (
    <div className={s.ход}>
      <header className={s.ходШапка}>
        <span className={s.ходИмя}>{название}</span>
        <span className={s.ходСчёт}>{счёт}{осталось !== null ? ` · ${ммсс(осталось)}` : ''}</span>
        <span className={s.запись}>
          <span className={s.записьТочка} aria-hidden />
          {запись}
        </span>
        {стоп ? (
          <span className={s.ходСтоп}>
            Остановить? Записанное сохранится.
            <Button kind="quiet" onClick={() => onСтоп(false)}>Продолжить</Button>
            <Button kind="leave" onClick={onОстановить}>Остановить</Button>
          </span>
        ) : (
          <Button kind="leave" onClick={() => onСтоп(true)}>Остановить</Button>
        )}
      </header>
      <div className={s.сцена}>{children}</div>
    </div>
  )
}

export function Подсказка({ текст, подробно, осталось, крупно, сейчас }: { текст: string; подробно?: string; осталось?: number | null; крупно?: boolean; сейчас?: boolean }) {
  return (
    <div className={крупно ? s.подсказкаКрупно : s.подсказка} role="status">
      {сейчас ? <span className={s.бровь}>Сейчас</span> : null}
      <span className={s.подсказкаТекст}>{текст}</span>
      {подробно ? <span className={s.подсказкаЕщё}>{подробно}</span> : null}
      {осталось !== null && осталось !== undefined ? <span className={s.подсказкаВремя}>{ммсс(осталось)}</span> : null}
    </div>
  )
}

/* ── Стимулы ─────────────────────────────────────────────────────────── */

export function Стимул({ шаг, точка, t, готово, заново, пропустить, отметить, закончитьУрок }: {
  шаг: Шаг
  точка?: React.RefObject<HTMLSpanElement | null>
  t: number
  готово?: () => void
  заново?: () => void
  пропустить?: () => void
  отметить?: () => void
  закончитьУрок?: () => void
}) {
  const с = шаг.стимул
  const [отмечено, setОтмечено] = useState(0)
  switch (с.вид) {
    case 'пусто': return null
    case 'учитель': return <Учитель />
    case 'доска': return <div className={s.доска}>{с.текст.split('\n').map((строка) => <p key={строка}>{строка}</p>)}</div>
    case 'текст': return <p className={s.текстНаЭкране}>{с.текст}</p>
    case 'путь':
    case 'точки': {
      const нач = гдеТочка(с, t) ?? [0.5, 0.5]
      return <span ref={точка} className={s.точка} style={{ left: `${нач[0] * 100}%`, top: `${нач[1] * 100}%` }} aria-hidden />
    }
    case 'вопрос':
      return (
        <div className={s.вопрос}>
          <span className={s.бровь}>{шаг.текст}</span>
          <p className={s.вопросТекст}>{с.текст}</p>
          <span className={s.подсказкаЕщё}>{шаг.подробно}</span>
          <Button kind="go" onClick={готово}>Ответил(а)</Button>
        </div>
      )
    case 'чтение': {
      const текст = ТЕКСТЫ.find((x) => x.id === с.текст)
      return (
        <article className={s.чтение}>
          <h2 className={s.чтениеИмя}>{текст?.название}</h2>
          {текст?.абзацы.map((а, i) => <p key={i}>{а}</p>)}
          <p className={s.тихо}>Дочитали раньше времени — перечитайте место, которое понравилось. Чтение закончится само.</p>
        </article>
      )
    }
    case 'фраза':
    case 'ситуация':
      return (
        <div className={s.вопрос}>
          <span className={s.бровь}>{шаг.текст}</span>
          <p className={s.вопросТекст}>{с.вид === 'фраза' ? `«${с.текст}»` : с.текст}</p>
          {шаг.подробно ? <span className={s.подсказкаЕщё}>{шаг.подробно}</span> : null}
          <span className={s.запись}><span className={s.записьТочка} aria-hidden />идёт запись фразы</span>
          <div className={s.ряд}>
            <Button kind="quiet" onClick={пропустить}>Пропустить</Button>
            <Button kind="quiet" onClick={заново}>Записать заново</Button>
            <Button kind="go" onClick={готово}>Готово</Button>
          </div>
        </div>
      )
    case 'урок':
      return (
        <div className={s.вопрос}>
          <span className={s.бровь}>{шаг.текст}</span>
          <p className={s.подсказкаЕщё}>{шаг.подробно}</p>
          <span className={s.подсказкаВремя}>{ммсс(шаг.сек - t)}</span>
          <div className={s.ряд}>
            <Button kind="quiet" onClick={() => { отметить?.(); setОтмечено((n) => n + 1) }}>
              Сейчас попросил записать{отмечено ? ` · ${отмечено}` : ''}
            </Button>
            <Button kind="go" onClick={закончитьУрок}>Закончить</Button>
          </div>
        </div>
      )
  }
}

