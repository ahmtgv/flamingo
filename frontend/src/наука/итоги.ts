/** Исследование внимания SEduM: «Вот что система о вас заметила».
 *
 *  Решение владельца 06.10: сделать увлекательнее — после каждой проверки
 *  человек видит, что о нём узнала система. Это не оценка («хорошо/плохо»), а
 *  числа о том, как он смотрит, и рядом — с чем их сравнить.
 *
 *  🔴 ЧИСТЫЙ МОДУЛЬ. Страница кормит сводку кадрами и событиями по ходу
 *  проверки; прибор (`scripts/наука-check.mjs`) кормит её придуманными
 *  кадрами и сверяет числа. Сравнение с людьми берём только проверенное:
 *  частота морганий — Bentivoglio и др., 1997 (в покое около 17 в минуту, в
 *  разговоре около 26, за чтением 4–5).
 */
import type { Состояние } from '../sedum/внимание.ts'
import type { Сценарий } from './протокол.ts'

/** Один кадр глазами сводки. `t` — секунды от начала записи. */
export type Отсчёт = {
  t: number
  /** Номер шага или −1 (калибровка, подготовка, вопрос). */
  i: number
  лицо: boolean
  /** Глаза камере видно (голова не опущена). */
  видно: boolean
  закрыты: boolean
  сейчас: Состояние
  засчитано: Состояние
  рыск: number
  до: number | null
}

export type Карточка = { над: string; число: string; ед?: string; текст: string }

export type Ленточка = { сек: number; моргания: number[]; закрытия: [number, number][] }

const МОРГАНИЕ = [0.04, 0.5] as const
const ДОЛГО = 1

/** «5,2» — десятичная запятая, как в остальном продукте. */
export const дробь = (х: number, знаков = 1) => х.toFixed(знаков).replace('.', ',')

/** Слово к целому числу: 1 градус, 2 градуса, 5 градусов. */
export const форма = (n: number, одно: string, два: string, пять: string) => {
  const д = Math.abs(n) % 100
  const е = д % 10
  return д >= 11 && д <= 14 ? пять : е === 1 ? одно : е >= 2 && е <= 4 ? два : пять
}

export class Сводка {
  readonly сценарий: Сценарий
  private кадры: Отсчёт[] = []
  private шаги = new Map<number, { с: number; по: number | null }>()
  private ответы: { i: number; через: number }[] = []
  private клипы = { фраз: 0, ситуаций: 0, урокСек: 0 }
  /** До какой страницы книги дошёл человек и сколько в ней страниц всего. */
  страниц = 0
  всегоСтраниц = 0
  слов = 0
  читалСек = 0
  верных: number | null = null

  constructor(сценарий: Сценарий) {
    this.сценарий = сценарий
  }

  кадр(о: Отсчёт): void { this.кадры.push(о) }
  начатьШаг(i: number, t: number): void { this.шаги.set(i, { с: t, по: null }) }
  закончитьШаг(i: number, t: number): void { const ш = this.шаги.get(i); if (ш && ш.по === null) ш.по = t }
  ответил(i: number, через: number): void { this.ответы.push({ i, через }) }
  записал(вид: 'фраза' | 'ситуация' | 'урок', сек = 0): void {
    if (вид === 'фраза') this.клипы.фраз += 1
    else if (вид === 'ситуация') this.клипы.ситуаций += 1
    else this.клипы.урокСек += сек
  }
  прочитал(страниц: number, слов: number, сек: number, всегоСтраниц = 0): void {
    this.страниц = страниц
    this.всегоСтраниц = всегоСтраниц
    this.слов = слов
    this.читалСек = сек
  }
  понял(верных: number): void { this.верных = верных }

  /** Сколько секунд шла запись — по последнему кадру. */
  get сек(): number { return this.кадры.at(-1)?.t ?? 0 }

  /** Моргания и долгие закрытия: отрезки «глаза видно и закрыты». */
  private глаза(): { моргания: number[]; закрытия: [number, number][] } {
    const моргания: number[] = []
    const закрытия: [number, number][] = []
    let с: number | null = null
    const закрыть = (по: number) => {
      if (с === null) return
      const д = по - с
      if (д >= МОРГАНИЕ[0] && д <= МОРГАНИЕ[1]) моргания.push(с)
      else if (д >= ДОЛГО) закрытия.push([с, по])
      с = null
    }
    for (const к of this.кадры) {
      if (!к.лицо || !к.видно) { с = null; continue }
      if (к.закрыты) с ??= к.t
      else закрыть(к.t)
    }
    return { моргания, закрытия }
  }

  /** Секунды, когда глаза было видно — знаменатель частоты морганий. */
  private видноСек(): number {
    let сумма = 0
    for (let n = 1; n < this.кадры.length; n++) {
      const а = this.кадры[n - 1]
      const б = this.кадры[n]
      if (а.лицо && а.видно) сумма += Math.min(0.5, б.t - а.t)
    }
    return сумма
  }

  морганийВМинуту(): number | null {
    const сек = this.видноСек()
    if (сек < 20) return null
    return (this.глаза().моргания.length / сек) * 60
  }

  private кадрыШага(i: number, отступ = 0): Отсчёт[] {
    const ш = this.шаги.get(i)
    if (!ш) return []
    const по = ш.по ?? Infinity
    return this.кадры.filter((к) => к.i === i && к.t >= ш.с + отступ && к.t <= по)
  }

  private номера(метки: string[]): number[] {
    return this.сценарий.шаги.flatMap((ш, i) => (метки.includes(ш.метка) && this.шаги.has(i) ? [i] : []))
  }

  /** Совпало ли решение движка с просьбой — по каждому оцениваемому шагу. */
  совпадения(): { i: number; да: boolean; через: number | null }[] {
    return this.сценарий.шаги.flatMap((ш, i) => {
      if (!ш.ждём.length || !this.шаги.has(i)) return []
      const кадры = this.кадрыШага(i)
      if (!кадры.length) return []
      const начало = this.шаги.get(i)!.с
      if (ш.ждём.includes('на экране')) {
        const да = кадры.filter((к) => ш.ждём.includes(к.засчитано)).length / кадры.length >= 0.5
        return [{ i, да, через: null }]
      }
      const первый = кадры.find((к) => ш.ждём.includes(к.засчитано))
      return [{ i, да: Boolean(первый), через: первый ? первый.t - начало : null }]
    })
  }

  /** Для кабинета владельца: доля кадров, где лицо видно, и сколько шагов совпало.
   *  Уходит на сервер вместе с итогом — в таблице проверок без похода за кадрами. */
  замеры(): { лицо: number | null; совпало: { да: number; из: number } | null } {
    const лицо = this.кадры.length ? this.кадры.filter((к) => к.лицо).length / this.кадры.length : null
    const с = this.совпадения()
    return {
      лицо: лицо === null ? null : Math.round(лицо * 1000) / 1000,
      совпало: с.length ? { да: с.filter((x) => x.да).length, из: с.length } : null,
    }
  }

  ленточка(): Ленточка {
    const г = this.глаза()
    return { сек: this.сек, моргания: г.моргания, закрытия: г.закрытия }
  }

  /** Три карточки итога — свои у каждой проверки. */
  карточки(): Карточка[] {
    const морг = this.морганийВМинуту()
    const моргания: Карточка = морг === null
      ? { над: 'Моргания', число: '—', текст: 'Глаза было видно слишком недолго, чтобы посчитать моргания. Так тоже бывает — это полезно знать.' }
      : { над: 'Моргания', число: String(Math.round(морг)), ед: 'в минуту', текст: 'В покое люди моргают в среднем 17 раз в минуту, в разговоре — 26, а за чтением — всего 4–5.' }
    const совп = this.совпадения()
    const совпало: Карточка = совп.length
      ? { над: 'Совпало', число: `${совп.filter((x) => x.да).length} из ${совп.length}`, ед: 'шагов', текст: 'Столько раз система решила то же, что вы делали на самом деле.' }
      : { над: 'Совпало', число: '—', текст: 'Шагов, которые можно сверить, в этот раз не набралось.' }
    const задержки = совп.flatMap((x) => (x.через !== null ? [x.через] : []))
    const отвод: Карточка = задержки.length
      ? { над: 'Заметила отвод', число: дробь(задержки.reduce((а, б) => а + б, 0) / задержки.length), ед: 'секунды',
          текст: 'Через столько система замечала, что вы смотрите не на экран. Раньше пяти секунд она не спешит — вдруг человек просто задумался.' }
      : { над: 'Заметила отвод', число: '—', текст: 'В этот раз система не заметила, что вы отводили взгляд. Это и есть то, что мы ищем.' }

    switch (this.сценарий.вид) {
      case 'настройка': {
        const [моргай] = this.номера(['моргай'])
        const г = this.глаза()
        const ш = моргай !== undefined ? this.шаги.get(моргай) : undefined
        const раз = ш ? г.моргания.filter((t) => t >= ш.с && t <= (ш.по ?? Infinity)).length : 0
        const [без] = this.номера(['не моргай'])
        const шБез = без !== undefined ? this.шаги.get(без) : undefined
        let рекорд = 0
        const видноБез = без !== undefined && this.кадрыШага(без).some((к) => к.лицо && к.видно)
        if (шБез && видноБез) {
          const внутри = [шБез.с, ...г.моргания.filter((t) => t > шБез.с && t < (шБез.по ?? this.сек)), шБез.по ?? this.сек]
          for (let n = 1; n < внутри.length; n++) рекорд = Math.max(рекорд, внутри[n] - внутри[n - 1])
        }
        const повороты = this.номера(['голова вбок']).flatMap((i) => this.кадрыШага(i)).filter((к) => к.лицо).map((к) => Math.abs(к.рыск))
        return [
          { над: 'Моргания', число: ш ? String(раз) : '—', ед: ш ? 'за 10 секунд' : undefined,
            текст: раз ? 'Так система учится узнавать именно ваши моргания. В покое люди моргают в среднем 17 раз в минуту.' : 'Морганий система не разглядела — возможно, лицо было далеко или в тени. Это тоже полезно знать.' },
          шБез && видноБез
            ? { над: 'Без моргания', число: дробь(рекорд), ед: 'секунды',
              текст: 'Столько вы продержались, не моргнув. В покое между морганиями обычно проходит около трёх с половиной секунд.' }
            : { над: 'Без моргания', число: '—', текст: 'Глаз в этом шаге система не разглядела — рекорд в другой раз.' },
          повороты.length
            ? { над: 'Поворот головы', число: String(Math.round(Math.max(...повороты))), ед: форма(Math.round(Math.max(...повороты)), 'градус', 'градуса', 'градусов'), текст: 'До такого поворота система ещё видела ваше лицо. Дальше она скажет «отвернулся».' }
            : { над: 'Поворот головы', число: '—', текст: 'Во время поворота лицо пропало из кадра совсем — значит, граница ближе, чем кажется.' },
        ]
      }
      case 'взгляд': return [совпало, отвод, моргания]
      case 'тетрадь': {
        const пишет = this.сценарий.шаги.flatMap((ш, i) => (ш.пишем ? this.кадрыШага(i, 3) : []))
        const доля = пишет.length ? пишет.filter((к) => к.засчитано === 'пишет').length / пишет.length : null
        return [
          совпало,
          доля === null
            ? { над: 'Письмо в тетради', число: '—', текст: 'Шаг с письмом в этот раз не дошёл до конца.' }
            : { над: 'Письмо в тетради', число: String(Math.round(доля * 100)), ед: '%', текст: 'Столько времени письма система засчитала работой, а не отвлечением: учитель сказал «запишите».' },
          моргания,
        ]
      }
      case 'сон': {
        const [двенадцать] = this.номера(['глаза 12 с'])
        let засыпаю: number | null = null
        if (двенадцать !== undefined) {
          const кадры = this.кадрыШага(двенадцать)
          const закрылись = кадры.find((к) => к.закрыты && к.видно)
          const заснул = кадры.find((к) => к.засчитано === 'заснул')
          if (закрылись && заснул) засыпаю = заснул.t - закрылись.t
        }
        const эпизоды = this.номера(['зевает']).reduce((n, i) => {
          let было = false
          let счёт = 0
          for (const к of this.кадрыШага(i)) {
            const сейчас = к.засчитано === 'зевает'
            if (сейчас && !было) счёт += 1
            было = сейчас
          }
          return n + счёт
        }, 0)
        return [
          моргания,
          засыпаю === null
            ? { над: '«Засыпаю»', число: '—', текст: 'В этот раз система не сказала «заснул» — значит, глаза ей было видно не всё время.' }
            : { над: '«Засыпаю»', число: дробь(засыпаю), ед: 'секунды', текст: 'Через столько система решила, что вы засыпаете. Раньше пяти секунд она не спешит — вдруг человек просто задумался.' },
          { над: 'Зевки', число: String(Math.min(эпизоды, 2)), ед: 'из 2', текст: 'Чтобы не спутать зевок с улыбкой или речью, система ждёт полторы секунды.' },
        ]
      }
      case 'думай': {
        const через = this.ответы.map((о) => о.через)
        const отводы = this.номера(['думает']).map((i) => {
          const кадры = this.кадрыШага(i)
          let сек = 0
          for (let n = 1; n < кадры.length; n++) if (кадры[n - 1].сейчас !== 'на экране') сек += Math.min(0.5, кадры[n].t - кадры[n - 1].t)
          return сек
        })
        const всего = this.номера(['думает']).length
        return [
          { над: 'Вопросов', число: String(через.length), ед: `из ${всего}`,
            текст: через.length ? `В среднем вы отвечали за ${дробь(через.reduce((а, б) => а + б, 0) / через.length)} с.` : 'Ответов в этот раз не было.' },
          отводы.length
            ? { над: 'Взгляд в сторону', число: дробь(отводы.reduce((а, б) => а + б, 0) / отводы.length), ед: 'секунды',
                текст: 'Столько в среднем вы смотрели мимо экрана, обдумывая ответ. Когда вопрос труднее, люди чаще отводят взгляд — так легче сосредоточиться.' }
            : { над: 'Взгляд в сторону', число: '—', текст: 'Вопросов в этот раз не было.' },
          через.length
            ? { над: 'Дольше всего', число: дробь(Math.max(...через)), ед: 'секунды', текст: 'Столько вы думали над самым трудным для вас вопросом.' }
            : { над: 'Дольше всего', число: '—', текст: 'Ответов в этот раз не было.' },
        ]
      }
      case 'точка': {
        const кадры = this.номера(['точка', 'слежение']).flatMap((i) => this.кадрыШага(i, 1))
        const доля = кадры.length ? кадры.filter((к) => к.засчитано === 'на экране').length / кадры.length : null
        return [
          доля === null
            ? { над: 'С точкой', число: '—', текст: 'Шаги с точкой в этот раз не дошли до конца.' }
            : { над: 'С точкой', число: String(Math.round(доля * 100)), ед: '%', текст: 'Столько времени система считала, что вы смотрите на экран, пока точка прыгала и двигалась.' },
          отвод,
          моргания,
        ]
      }
      case 'чтение': {
        const скорость = this.слов && this.читалСек >= 30 ? Math.round(this.слов / (this.читалСек / 60)) : null
        return [
          { над: 'Дошли до страницы', число: String(this.страниц), ед: this.всегоСтраниц ? `из ${this.всегоСтраниц}` : undefined,
            текст: this.слов ? `Это около ${this.слов} ${форма(this.слов, 'слова', 'слов', 'слов')}.` : 'Книга ждёт — в следующий раз можно начать сначала.' },
          скорость === null
            ? { над: 'Слов в минуту', число: '—', текст: 'Читали слишком недолго, чтобы посчитать скорость.' }
            : { над: 'Слов в минуту', число: String(скорость), текст: 'Считаем по страницам и времени чтения, без пауз на вопросы.' },
          this.верных === null
            ? { над: 'Ответы', число: '—', текст: 'Вопросы о тексте — в конце чтения. В этот раз до них не дошло.' }
            : { над: 'Ответы', число: String(this.верных), ед: 'из 3', текст: 'Столько ответов о первом тексте верны.' },
        ]
      }
      case 'голос':
        return [
          { над: 'Фраз', число: String(this.клипы.фраз), ед: 'записано', текст: 'Из них система учится отличать «запишите» от похожих фраз.' },
          { над: 'Своими словами', число: String(this.клипы.ситуаций), ед: 'записано', текст: 'Живая речь без готовых слов — самое трудное и самое нужное.' },
          { над: 'Кусочек урока', число: `${Math.floor(Math.round(this.клипы.урокСек) / 60)}:${String(Math.round(this.клипы.урокСек) % 60).padStart(2, '0')}`, ед: 'мин', текст: 'По нему проверим, поймёт ли система просьбу записать посреди урока.' },
        ]
    }
  }
}
