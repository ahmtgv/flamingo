/* ── Случайность по зерну ─────────────────────────────────────────────── */

/** mulberry32: маленький, быстрый и одинаковый в любом браузере и в Node. */
export function случай(зерно: number): () => number {
  let a = зерно >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

export function перемешать<T>(список: readonly T[], r: () => number): T[] {
  const к = [...список]
  for (let i = к.length - 1; i > 0; i--) {
    const j = Math.floor(r() * (i + 1))
    ;[к[i], к[j]] = [к[j], к[i]]
  }
  return к
}

