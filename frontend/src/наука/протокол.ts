/** Очередь коротких текстов для одной проверки: сначала непрочитанные человеком,
 *  потом прочитанные, внутри — вперемешку; повтор — только если кончились все.
 *  Своя последовательность случая: тексты не сдвигают порядок шагов. */
export type Чтец = () => Стимул & { вид: 'текст' }
export function чтец(зерно: number, было: readonly string[] = []): Чтец {
  const r = случай((зерно ^ 0x5bd1e995) >>> 0)
  const очередь = [
    ...перемешать(КОРОТКИЕ.filter((т) => !было.includes(т.id)), r),
    ...перемешать(КОРОТКИЕ.filter((т) => было.includes(т.id)), r),
  ]
  let i = 0
  return () => {
    const т = очередь[i++ % очередь.length]
    return { вид: 'текст', текст: т.текст, id: т.id }
  }
}

