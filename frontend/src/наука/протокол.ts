/** Когда задать вопрос «где было внимание» в чтении: первый — на 60–90 с,
 *  дальше через 60–100 с, пока не кончится время. Случайно — иначе человек
 *  ждёт вопроса и собирается к нему, и вопрос мерит ожидание, а не внимание. */
export function моментыВопросов(r: () => number, всего: number): number[] {
  const м: number[] = []
  /* Чтение — две с половиной минуты (владелец, 06.10: «сократить в два раза»):
     первый вопрос на 40–60 с, следующий через 45–65 с, не в последние 20 с. */
  let t = 40 + r() * 20
  while (t < всего - 20) {
    м.push(Math.round(t))
    t += 45 + r() * 20
  }
  return м
}

export const ЧТЕНИЕ_СЕК = 150

/** Собрать сценарий проверки по зерну. */
/** `было` — какие тексты человек уже читал (короткие и книги): берём сначала другие. */
export function собрать(вид: ВидПроверки, зерно: number, было: readonly string[] = []): Сценарий {
  const r = случай(зерно)
  const база = { вид, зерно, калибровка: 20, вопросы: [] as number[] }
  switch (вид) {
    case 'настройка': return { ...база, протокол: 'настройка-1', шаги: шагиНастройки() }
    /* взгляд-2, сон-2 (06.10): текст «прочитайте» каждый раз другой, а не один на всех. */
    case 'взгляд': return { ...база, протокол: 'взгляд-2', шаги: шагиВзгляда(r, чтец(зерно, было)) }
    /* тетрадь-2 (06.10): у шагов с вещами — «или имитируйте это действие»: часть людей изображает. */
    case 'тетрадь': return { ...база, протокол: 'тетрадь-2', шаги: шагиТетради(r) }
    case 'сон': return { ...база, протокол: 'сон-2', шаги: шагиСна(r, чтец(зерно, было)) }
    case 'думай': return { ...база, протокол: 'думай-1', шаги: шагиДумай(r) }
    case 'точка': return { ...база, протокол: 'точка-1', шаги: шагиТочки(r) }
    case 'чтение': {
      /* Книга начинается с текста, которого человек ещё не читал. */
      const перемешано = перемешать(ТЕКСТЫ, r)
      const порядок = [...перемешано.filter((т) => !было.includes(т.id)), ...перемешано.filter((т) => было.includes(т.id))]
      const текст = порядок[0]
      return {
        ...база, протокол: 'чтение-3', текст: текст.id, тексты: порядок.map((т) => т.id),
        шаги: [{ метка: 'чтение', сек: ЧТЕНИЕ_СЕК, текст: 'Читайте в своём темпе', ждём: НА_ЭКРАНЕ, стимул: { вид: 'чтение', текст: текст.id } }],
        вопросы: моментыВопросов(r, ЧТЕНИЕ_СЕК),
      }
    }
    case 'голос': return { ...база, калибровка: 0, протокол: 'голос-1', шаги: шагиГолоса(r) }
  }
}

/** Сколько секунд займёт сценарий по часам (шаги «до нажатия» считаем по 15 с). */
export function длительность(с: Сценарий): number {
  return с.калибровка + с.шаги.reduce((сумма, ш) => сумма + ПОДГОТОВКА_СЕК + (ш.сек || 15), 0)
}

/* ── Где точка ────────────────────────────────────────────────────────── */

/** Положение движущейся или прыгающей точки в доле экрана через `t` секунд
 *  от начала шага. Нет точки — null. Это же положение пишется в каждый кадр
 *  записи, поэтому разбор знает, куда человек должен был смотреть. */
export function гдеТочка(стимул: Стимул, t: number): [number, number] | null {
  /* Камера — над экраном, посередине: «точка» выше верхнего края. Разбор
     отличает её по отрицательному y. */
  if (стимул.вид === 'камера') return [0.5, -0.05]
  if (стимул.вид === 'точки') {
    const i = Math.min(стимул.точки.length - 1, Math.max(0, Math.floor(t / стимул.каждая)))
    return стимул.точки[i]
  }
  if (стимул.вид !== 'путь') return null
  const доля = Math.max(0, Math.min(1, t / стимул.сек))
  const ф = 2 * Math.PI * доля
  switch (стимул.форма) {
    /* Два оборота за шаг: скорость около 15° в секунду на ноутбуке — глазу легко. */
    case 'круг': return [0.5 + 0.32 * Math.cos(2 * ф), 0.5 + 0.32 * Math.sin(2 * ф)]
    case 'восьмёрка': return [0.5 + 0.35 * Math.sin(2 * ф), 0.5 + 0.25 * Math.sin(4 * ф)]
    case 'зигзаг': {
      const ход = (доля * 4) % 2
      const x = ход < 1 ? ход : 2 - ход
      return [0.1 + 0.8 * x, 0.2 + 0.6 * доля]
    }
    /* Плавное блуждание — сумма синусов с несоизмеримыми частотами: человек не
       может угадать, куда точка пойдёт, и вынужден следить. */
    case 'блуждание':
      return [
        0.5 + 0.25 * Math.sin(1.7 * ф + 0.3) + 0.12 * Math.sin(4.3 * ф),
        0.5 + 0.22 * Math.sin(2.3 * ф + 1.1) + 0.1 * Math.cos(5.1 * ф),
      ]
  }
}

/** Какие тексты человек прочтёт в этой проверке: короткие «прочитайте текст» и
 *  первая статья книги. По ним следующая проверка возьмёт другие. */
export function текстыСценария(с: Сценарий): string[] {
  const ids = с.шаги.flatMap((ш) => (ш.стимул.вид === 'текст' && ш.стимул.id ? [ш.стимул.id] : []))
  if (с.текст) ids.push(с.текст)
  return [...new Set(ids)]
}
