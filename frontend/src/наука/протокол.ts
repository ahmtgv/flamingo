/** Поровну «пишем» и «не пишем», в случайном порядке: модель смысла должна
 *  видеть оба класса одинаково часто, иначе она выучит, что «почти всё — пишем». */
function поровну<T extends { пишем: boolean }>(все: readonly T[], сколько: number, r: () => number): T[] {
  const да = перемешать(все.filter((x) => x.пишем), r).slice(0, сколько / 2)
  const нет = перемешать(все.filter((x) => !x.пишем), r).slice(0, сколько / 2)
  return перемешать([...да, ...нет], r)
}

