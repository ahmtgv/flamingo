/** Исследование внимания SEduM — страница добровольца: `flamingo.plus/наука/<код>`.
 *
 *  Решения владельца 06.10: добровольцы — друзья и близкие; записываем всё,
 *  что нужно науке, сразу к нам на сервер; проверки по пять минут, разные,
 *  в разное время; людей — сколько найдём. Протокол и что именно пишется —
 *  docs/SEDUM-ИССЛЕДОВАНИЕ.md.
 *
 *  Путь человека: ссылка → согласие и анкета (один раз) → список проверок →
 *  «как вы сейчас» → подготовка камеры → проверка → отправка → список.
 *
 *  🔴 ЭТО НЕ КОМНАТА УРОКА. В продукте кадры не покидают устройство ученика;
 *  здесь они уходят к нам — потому что это исследование с согласием, а не
 *  урок. Страница живёт по своему адресу, в меню продукта её нет, и попасть
 *  на неё можно только по выданной ссылке.
 */
import { useCallback, useEffect, useState } from 'react'

import { Wait } from '../ui/Wait'
import { КакВы, Молчит, НетСсылки, Отправляем, Согласие, Список, type Анкета, type Перед } from './экраны'
import { Проверка } from './Проверка'
import { ПРОВЕРКИ, СОГЛАСИЕ_ВЕРСИЯ, type ВидПроверки } from './протокол'
import { наука, ОтказНауки, type ОДоброволеце, type Отправка, type Очередь } from './сеть'

type Где =
  | { где: 'грузим' }
  | { где: 'нет ссылки' }
  | { где: 'молчит'; слова: string }
  | { где: 'согласие'; занят: boolean; ошибка: string }
  | { где: 'список' }
  | { где: 'как вы'; вид: ВидПроверки }
  | { где: 'проверка'; вид: ВидПроверки; перед: Перед }
  | { где: 'отправка'; очередь: Очередь; прервано: boolean }

export function Наука({ код }: { код: string }) {
  const [где, setГде] = useState<Где>({ где: 'грузим' })
  const [я, setЯ] = useState<ОДоброволеце | null>(null)
  const [спрос, setСпрос] = useState(0)

  useEffect(() => {
    let живо = true
    наука.кто(код)
      .then((о) => {
        if (!живо) return
        setЯ(о)
        setГде(о.согласие ? { где: 'список' } : { где: 'согласие', занят: false, ошибка: '' })
      })
      .catch((e) => {
        if (!живо) return
        if (e instanceof ОтказНауки && e.код === 404) setГде({ где: 'нет ссылки' })
        else setГде({ где: 'молчит', слова: e instanceof Error ? e.message : 'Сервер не отвечает.' })
      })
    return () => { живо = false }
  }, [код, спрос])

  const согласиться = useCallback(async (анкета: Анкета) => {
    setГде({ где: 'согласие', занят: true, ошибка: '' })
    try {
      setЯ(await наука.согласие(код, СОГЛАСИЕ_ВЕРСИЯ, анкета))
      setГде({ где: 'список' })
    } catch (e) {
      setГде({ где: 'согласие', занят: false, ошибка: e instanceof Error ? e.message : 'Не сохранилось. Попробуйте ещё раз.' })
    }
  }, [код])

  switch (где.где) {
    case 'грузим': return <Wait />
    case 'нет ссылки': return <НетСсылки />
    case 'молчит': return <Молчит слова={где.слова} onЕщё={() => { setГде({ где: 'грузим' }); setСпрос((n) => n + 1) }} />
    case 'согласие': return <Согласие onДа={согласиться} занят={где.занят} ошибка={где.ошибка} />
    case 'список': return <Список проверки={я?.проверки ?? []} onВыбор={(вид) => setГде({ где: 'как вы', вид })} />
    case 'как вы': {
      const описание = ПРОВЕРКИ.find((п) => п.вид === где.вид)!
      return <КакВы описание={описание} onНазад={() => setГде({ где: 'список' })} onДальше={(перед) => setГде({ где: 'проверка', вид: где.вид, перед })} />
    }
    case 'проверка': {
      const описание = ПРОВЕРКИ.find((п) => п.вид === где.вид)!
      return (
        <Проверка
          код={код}
          описание={описание}
          перед={где.перед}
          onНазад={() => setГде({ где: 'список' })}
          onКонец={(очередь, прервано) => setГде({ где: 'отправка', очередь, прервано })}
        />
      )
    }
    case 'отправка':
      return <Отправка очередь={где.очередь} прервано={где.прервано} код={код} onЕщё={() => { setГде({ где: 'грузим' }); setСпрос((n) => n + 1) }} />
  }
}

/** Отправка: ждём очередь, потом говорим серверу «проверка закончена». */
function Отправка({ очередь, прервано, код, onЕщё }: { очередь: Очередь; прервано: boolean; код: string; onЕщё: () => void }) {
  const [о, setО] = useState<Отправка>(очередь.отправка)
  const [готово, setГотово] = useState(false)
  useEffect(() => очередь.слушать(setО), [очередь])
  useEffect(() => {
    let живо = true
    ;(async () => {
      await очередь.дождаться()
      try {
        await наука.закончить(код, очередь.id, { прервано, кусков: очередь.отправка.всего })
      } catch {
        /* записи уже у нас; «конец» — только отметка времени */
      }
      if (живо) setГотово(true)
    })()
    return () => { живо = false }
  }, [очередь, код, прервано])
  return <Отправляем отправка={о} готово={готово} прервано={прервано} onЕщё={onЕщё} />
}
