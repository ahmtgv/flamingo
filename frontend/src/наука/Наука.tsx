/** Исследование внимания SEduM — страница добровольца.
 *
 *  Два входа:
 *    `flamingo.plus/наука/вход-<секрет>`  одна ссылка для всех (решение владельца 06.10)
 *    `flamingo.plus/наука/<код>`          личная ссылка — как раньше
 *
 *  Решения владельца 06.10: добровольцы — друзья и близкие; записываем всё,
 *  что нужно науке, сразу к нам на сервер; проверки по пять минут, разные,
 *  в разное время; людей — сколько найдём; «одна ссылка для всех, но так,
 *  чтобы мы могли данные различать и не путать». Протокол и что именно
 *  пишется — docs/SEDUM-ИССЛЕДОВАНИЕ.md.
 *
 *  Путь человека по общей ссылке: кто сейчас проходит (если устройство кого-то
 *  помнит) → знакомство и согласие с именем (один раз) → о вас → путь из
 *  восьми проверок → «как вы сейчас» → подготовка → проверка → итог → путь.
 *
 *  🔴 ЭТО НЕ КОМНАТА УРОКА. В продукте кадры не покидают устройство ученика;
 *  здесь они уходят к нам — потому что это исследование с согласием, а не
 *  урок. В меню продукта страницы нет, попасть на неё можно только по ссылке.
 */
import { useCallback, useEffect, useState } from 'react'

import { Wait } from '../ui/Wait'
import { Итог, КакВы, КтоПроходит, Молчит, НетСсылки, ОВас, Путь, пройдена, СсылкаПогашена, Знакомство, type Анкета, type Перед } from './экраны'
import { Проверка, type Конец } from './Проверка'
import { ПРОВЕРКИ, СОГЛАСИЕ_ВЕРСИЯ, type ВидПроверки } from './протокол'
import { запомнить, людиЗдесь } from './люди'
import { наука, ОтказНауки, type ОДоброволеце, type Отправка } from './сеть'

type Где =
  | { где: 'грузим' }
  | { где: 'нет ссылки' }
  | { где: 'погашена'; слова: string }
  | { где: 'молчит'; слова: string }
  | { где: 'кто' }
  | { где: 'знакомство'; занят: boolean; ошибка: string }
  | { где: 'о вас'; занят: boolean; ошибка: string }
  | { где: 'путь' }
  | { где: 'как вы'; вид: ВидПроверки }
  | { где: 'проверка'; вид: ВидПроверки; перед: Перед }
  | { где: 'итог'; вид: ВидПроверки; конец: Конец }

const словами = (e: unknown, иначе: string) => (e instanceof Error && e.message ? e.message : иначе)

export function Наука({ код: личный, вход }: { код?: string; вход?: string }) {
  const [где, setГде] = useState<Где>({ где: 'грузим' })
  const [код, setКод] = useState<string | null>(личный ?? null)
  const [я, setЯ] = useState<ОДоброволеце | null>(null)
  const [спрос, setСпрос] = useState(0)

  /* Устройство помнит человека: код, имя и что пройдено — для «Кто сейчас проходит?». */
  const помнить = useCallback((к: string, о: ОДоброволеце) => {
    if (!вход || !о.имя) return
    const пройдено = [...new Set(о.проверки.filter(пройдена).map((п) => п.вид))]
    запомнить({ код: к, имя: о.имя, пройдено, когда: new Date().toISOString() })
  }, [вход])

  /* Чей это путь: загрузить человека и решить, нужен ли ему ещё экран согласия. */
  const открыть = useCallback(async (к: string) => {
    setГде({ где: 'грузим' })
    try {
      const о = await наука.кто(к)
      setКод(к)
      setЯ(о)
      помнить(к, о)
      setГде(о.согласие ? { где: 'путь' } : { где: 'знакомство', занят: false, ошибка: '' })
    } catch (e) {
      if (e instanceof ОтказНауки && e.код === 404) {
        if (вход) { setКод(null); setЯ(null); setГде({ где: 'знакомство', занят: false, ошибка: '' }) }
        else setГде({ где: 'нет ссылки' })
      } else setГде({ где: 'молчит', слова: словами(e, 'Сервер не отвечает.') })
    }
  }, [вход, помнить])

  useEffect(() => {
    let живо = true
    ;(async () => {
      if (личный) { await открыть(личный); return }
      if (!вход) { setГде({ где: 'нет ссылки' }); return }
      try {
        await наука.ссылка(вход)
      } catch (e) {
        if (!живо) return
        if (e instanceof ОтказНауки && e.код === 404) setГде({ где: 'погашена', слова: e.message })
        else setГде({ где: 'молчит', слова: словами(e, 'Сервер не отвечает.') })
        return
      }
      if (!живо) return
      setГде(людиЗдесь().length ? { где: 'кто' } : { где: 'знакомство', занят: false, ошибка: '' })
    })()
    return () => { живо = false }
  }, [личный, вход, открыть, спрос])

  const согласиться = useCallback(async (имя: string) => {
    setГде({ где: 'знакомство', занят: true, ошибка: '' })
    try {
      let к = код
      if (!к) {
        if (!вход) throw new Error('Ссылка повреждена — откройте её ещё раз.')
        к = (await наука.войти(вход, имя)).код
        setКод(к)
      }
      const о = await наука.согласие(к, СОГЛАСИЕ_ВЕРСИЯ, {})
      setЯ(о)
      помнить(к, о)
      setГде({ где: 'о вас', занят: false, ошибка: '' })
    } catch (e) {
      setГде({ где: 'знакомство', занят: false, ошибка: словами(e, 'Не сохранилось. Попробуйте ещё раз.') })
    }
  }, [код, вход, помнить])

  const рассказать = useCallback(async (анкета: Анкета) => {
    if (!код) return
    if (!Object.keys(анкета).length) { setГде({ где: 'путь' }); return }
    setГде({ где: 'о вас', занят: true, ошибка: '' })
    try {
      setЯ(await наука.анкета(код, анкета))
      setГде({ где: 'путь' })
    } catch (e) {
      setГде({ где: 'о вас', занят: false, ошибка: словами(e, 'Не сохранилось. Можно пропустить и вернуться к анкете позже.') })
    }
  }, [код])

  const имя = я?.имя ?? null
  const неЯ = вход ? () => { setКод(null); setЯ(null); setГде(людиЗдесь().length ? { где: 'кто' } : { где: 'знакомство', занят: false, ошибка: '' }) } : undefined

  switch (где.где) {
    case 'грузим': return <Wait />
    case 'нет ссылки': return <НетСсылки />
    case 'погашена': return <СсылкаПогашена слова={где.слова} />
    case 'молчит': return <Молчит слова={где.слова} onЕщё={() => { setГде({ где: 'грузим' }); setСпрос((n) => n + 1) }} />
    case 'кто':
      return <КтоПроходит люди={людиЗдесь()} onВыбор={(к) => void открыть(к)} onНовый={() => { setКод(null); setЯ(null); setГде({ где: 'знакомство', занят: false, ошибка: '' }) }} />
    case 'знакомство':
      return <Знакомство просимИмя={!код} занят={где.занят} ошибка={где.ошибка} onДа={(и) => void согласиться(и)} />
    case 'о вас':
      return <ОВас имя={имя} занят={где.занят} ошибка={где.ошибка} onДальше={(а) => void рассказать(а)} />
    case 'путь':
      return <Путь имя={имя} проверки={я?.проверки ?? []} onНеЯ={неЯ} onНачать={(вид) => setГде({ где: 'как вы', вид })} />
    case 'как вы': {
      const описание = ПРОВЕРКИ.find((п) => п.вид === где.вид)!
      return <КакВы описание={описание} имя={имя} onНазад={() => setГде({ где: 'путь' })} onДальше={(перед) => setГде({ где: 'проверка', вид: где.вид, перед })} />
    }
    case 'проверка': {
      const описание = ПРОВЕРКИ.find((п) => п.вид === где.вид)!
      return (
        <Проверка
          код={код!}
          имя={имя}
          описание={описание}
          перед={где.перед}
          onНазад={() => setГде({ где: 'путь' })}
          onКонец={(конец) => setГде({ где: 'итог', вид: где.вид, конец })}
        />
      )
    }
    case 'итог': {
      const описание = ПРОВЕРКИ.find((п) => п.вид === где.вид)!
      const раньше = (я?.проверки ?? []).filter((п) => п.вид === где.вид && пройдена(п)).length
      return (
        <ИтогСОтправкой
          код={код!}
          имя={имя}
          описание={описание}
          конец={где.конец}
          пройдена={раньше + (где.конец.прервано ? 0 : 1)}
          onДальше={() => void открыть(код!)}
        />
      )
    }
  }
}

/** Итог показывается сразу, а запись тем временем доезжает: ждём очередь,
 *  потом говорим серверу «проверка закончена» — вместе с числами итога. */
function ИтогСОтправкой({ код, имя, описание, конец, пройдена, onДальше }: {
  код: string
  имя: string | null
  описание: (typeof ПРОВЕРКИ)[number]
  конец: Конец
  пройдена: number
  onДальше: () => void
}) {
  const { очередь, прервано, карточки, ленточка } = конец
  const [о, setО] = useState<Отправка>(очередь.отправка)
  const [готово, setГотово] = useState(false)
  useEffect(() => очередь.слушать(setО), [очередь])
  useEffect(() => {
    let живо = true
    ;(async () => {
      await очередь.дождаться()
      try {
        await наука.закончить(код, очередь.id, { прервано, кусков: очередь.отправка.всего, карточки })
      } catch {
        /* записи уже у нас; «конец» — только отметка времени и итог */
      }
      if (живо) setГотово(true)
    })()
    return () => { живо = false }
  }, [очередь, код, прервано, карточки])
  return (
    <Итог описание={описание} имя={имя} карточки={карточки} ленточка={ленточка} пройдена={пройдена}
      отправка={о} готово={готово} прервано={прервано} onДальше={onДальше} />
  )
}
