/* ── Слова и числа ────────────────────────────────────────────────────── */

const ОЧКИ: Record<string, string> = { очки: 'очки', линзы: 'линзы', иногда: 'очки иногда' }
const СВЕТ: Record<string, string> = { день: 'день', лампа: 'лампа', полумрак: 'полумрак' }

/** «41 год · очки», «без анкеты». Роль на уроке больше не спрашиваем (06.10). */
export function оЧеловеке(анкета: Record<string, string>): string {
  const н = Number(анкета.возраст)
  const лет = анкета.возраст && Number.isFinite(н) ? `${н} ${форма(н, 'год', 'года', 'лет')}` : ''
  const части = [лет, ОЧКИ[анкета.очки ?? '']].filter(Boolean)
  return части.length ? части.join(' · ') : 'без анкеты'
}

const двузначно = (n: number) => String(n).padStart(2, '0')
/** «06.10 21:14» — по часам того, кто смотрит. */
export const когда = (iso: string) => {
  const д = new Date(iso)
  return Number.isNaN(д.getTime()) ? '—' : `${двузначно(д.getDate())}.${двузначно(д.getMonth() + 1)} ${двузначно(д.getHours())}:${двузначно(д.getMinutes())}`
}
export const длина = (сек: number | null) => (сек === null ? '—' : `${Math.floor(Math.round(сек) / 60)}:${двузначно(Math.round(сек) % 60)}`)
const процент = (доля: number | null) => (доля === null ? '—' : `${Math.round(доля * 100)} %`)
const объём = (байт: number) => (байт >= 1024 ** 3 ? `${дробь(байт / 1024 ** 3)} ГБ` : `${Math.round(байт / 1024 ** 2)} МБ`)
const времяЗаписи = (сек: number) => {
  const ч = Math.floor(сек / 3600)
  const м = Math.round((сек % 3600) / 60)
  return ч ? `${ч} ч ${м} мин` : `${м} мин`
}
/** Сколько проверок пути пройдено — «Голос учителя» прежних записей не в счёт. */
const наПути = (пройдено: string[]) => НА_ПУТИ.filter((п) => пройдено.includes(п.вид)).length
const название = (вид: string) => ПРОВЕРКИ.find((п) => п.вид === вид)?.название ?? вид
const инициал = (имя: string) => (имя.trim()[0] ?? '?').toUpperCase()

/* ── Страница: загрузка и состояния ───────────────────────────────────── */

type Состояние =
  | { где: 'грузим' }
  | { где: 'вход'; слова: string }
  | { где: 'чужой'; слова: string }
  | { где: 'молчит'; слова: string }
  | { где: 'готово'; сводка: СводкаКабинета }

export function КабинетНауки({ onВойти, onРазбор }: { onВойти: () => void; onРазбор: (id: string) => void }) {
  const [с, setС] = useState<Состояние>({ где: 'грузим' })
  const [спрос, setСпрос] = useState(0)
  const [выбран, setВыбран] = useState<string | null>(null)
  const [человек, setЧеловек] = useState<ЧеловекПодробно | null>(null)
  const [ссылкаСлова, setСсылкаСлова] = useState('')

  useEffect(() => {
    let живо = true
    кабинет.сводка()
      .then((сводка) => {
        if (!живо) return
        setС({ где: 'готово', сводка })
        setВыбран((было) => было ?? сводка.люди[0]?.код ?? null)
      })
      .catch((e) => {
        if (!живо) return
        const слова = e instanceof Error ? e.message : 'Сервер не отвечает.'
        if (e instanceof ОтказНауки && e.код === 401) setС({ где: 'вход', слова })
        else if (e instanceof ОтказНауки && e.код === 403) setС({ где: 'чужой', слова })
        else setС({ где: 'молчит', слова })
      })
    return () => { живо = false }
  }, [спрос])

  useEffect(() => {
    if (!выбран) { setЧеловек(null); return }
    let живо = true
    setЧеловек(null)
    кабинет.человек(выбран).then((ч) => { if (живо) setЧеловек(ч) }).catch(() => { if (живо) setЧеловек(null) })
    return () => { живо = false }
  }, [выбран])

  const сменить = useCallback(async () => {
    try {
      const { ссылка, погашено } = await кабинет.сменитьСсылку()
      setС((было) => (было.где === 'готово' ? { где: 'готово', сводка: { ...было.сводка, ссылка } } : было))
      setСсылкаСлова(погашено ? 'Новая ссылка готова. Старая больше не пускает новых людей.' : 'Ссылка готова.')
    } catch (e) {
      setСсылкаСлова(e instanceof Error ? e.message : 'Ссылка не сменилась. Попробуйте ещё раз.')
    }
  }, [])

  switch (с.где) {
    case 'грузим': return <Wait say="Открываем кабинет" />
    case 'вход':
      return (
        <Отказ место="кабинет" заголовок="Кабинет открывается после входа" лид={с.слова}>
          <span className={s.низСлова}>Войдите под той почтой, которой открыт кабинет.</span>
          <Button kind="go" onClick={onВойти}>Войти</Button>
        </Отказ>
      )
    case 'чужой': return <Отказ место="кабинет" заголовок="Кабинет открыт только владельцу" лид={с.слова} />
    case 'молчит':
      return (
        <Отказ место="кабинет" заголовок="Сервер не отвечает" лид={с.слова}>
          <span className={s.низСлова}>Записи в сохранности — они на сервере.</span>
          <Button kind="go" onClick={() => { setС({ где: 'грузим' }); setСпрос((n) => n + 1) }}>Попробовать ещё раз</Button>
        </Отказ>
      )
    case 'готово':
      return (
        <КабинетВид сводка={с.сводка} выбран={выбран} человек={человек} onВыбор={setВыбран} onРазбор={onРазбор}
          onСменить={сменить} ссылкаСлова={ссылкаСлова} />
      )
  }
}

/* ── Вид: без сети, для стенда ────────────────────────────────────────── */

export function КабинетВид({ сводка, выбран, человек, onВыбор, onРазбор, onСменить, ссылкаСлова = '', спрашиваем = false }: {
  сводка: СводкаКабинета
  выбран: string | null
  /** Проверки выбранного; null — ещё грузятся. */
  человек: ЧеловекПодробно | null
  onВыбор: (код: string) => void
  onРазбор: (id: string) => void
  onСменить: () => void
  ссылкаСлова?: string
  /** Для стенда: открыть сразу с вопросом «сменить ссылку?». */
  спрашиваем?: boolean
}) {
  const скачать = (сВидео: boolean) => { window.location.href = кабинет.адресАрхива(сВидео) }
  return (
    <Рама раздел="Кабинет исследования" место="кабинет" право={<Огонёк>видишь только ты</Огонёк>}
      справа={(
        <span className={к.скачать}>
          <Button kind="quiet" onClick={() => скачать(false)}><Скачивание />Скачать без видео</Button>
          <Button kind="quiet" onClick={() => скачать(true)}><Скачивание />Скачать всё</Button>
        </span>
      )}
    >
      <div className={к.кабинет}>
        <Люди люди={сводка.люди} выбран={выбран} onВыбор={onВыбор} />
        <Проверки человек={человек} есть={сводка.люди.length > 0} выбран={выбран} onРазбор={onРазбор} />
        <div className={к.справа}>
          <Всего всего={сводка.всего} />
          <Ссылка ссылка={сводка.ссылка} onСменить={onСменить} слова={ссылкаСлова} спрашиваем={спрашиваем} />
        </div>
      </div>
    </Рама>
  )
}

function Скачивание() {
  return (
    <svg className={к.значок} viewBox="0 0 24 24" aria-hidden>
      <path d="M12 4 V 15 M7 10.5 L 12 15.5 L 17 10.5 M5 19.5 H 19" className={s.перо} strokeWidth={1.8} />
    </svg>
  )
}

function Люди({ люди, выбран, onВыбор }: { люди: ЧеловекКабинета[]; выбран: string | null; onВыбор: (код: string) => void }) {
  return (
    <section className={`${s.листок} ${к.люди}`} aria-labelledby="кабинет-люди">
      <h2 className={к.надпись} id="кабинет-люди">Люди · {люди.length}</h2>
      {люди.length ? (
        <ul className={к.список}>
          {люди.map((ч) => (
            <li key={ч.код}>
              <button type="button" className={`${к.человек} ${ч.код === выбран ? к.человекВыбран : ''}`} aria-pressed={ч.код === выбран} onClick={() => onВыбор(ч.код)}>
                <span className={к.инициал} aria-hidden>{инициал(ч.имя)}</span>
                <span className={к.кто}>
                  <span className={к.имя}>{ч.имя || 'без имени'}</span>
                  <span className={к.оНём}>{оЧеловеке(ч.анкета)}</span>
                </span>
                <span className={к.счёт} aria-label={`пройдено ${наПути(ч.пройдено)} из ${НА_ПУТИ.length}`}>{наПути(ч.пройдено)}/{НА_ПУТИ.length}</span>
              </button>
            </li>
          ))}
        </ul>
      ) : <p className={s.тихо}>Здесь появится каждый, кто войдёт по ссылке для всех или по личной.</p>}
    </section>
  )
}

function Проверки({ человек, есть, выбран, onРазбор }: { человек: ЧеловекПодробно | null; есть: boolean; выбран: string | null; onРазбор: (id: string) => void }) {
  if (!есть) {
    return (
      <section className={`${s.листок} ${к.проверки} ${к.пусто}`}>
        <h1 className={s.заголовок}>Пока никто не прошёл ни одной проверки</h1>
        <p className={s.лид}>Отправьте ссылку для всех — она справа. Каждый, кто войдёт по ней, появится слева, а его проверки — здесь.</p>
      </section>
    )
  }
  if (!человек || человек.код !== выбран) {
    return (
      <section className={`${s.листок} ${к.проверки} ${к.пусто}`} aria-busy>
        <p className={s.тихо} role="status">Загружаем проверки…</p>
      </section>
    )
  }
  const п = человек.проверки
  const первая = п.length ? п[п.length - 1].начата : null
  return (
    <section className={`${s.листок} ${к.проверки}`}>
      <div className={к.шапкаПроверок}>
        <h1 className={к.кто1}>{человек.имя || 'без имени'} · {п.length} {форма(п.length, 'проверка', 'проверки', 'проверок')}</h1>
        {первая ? <span className={к.срок}>{когда(первая).slice(0, 5)} — {когда(п[0].начата).slice(0, 5)}</span> : null}
      </div>
      {п.length ? (
        <div className={к.таблицаМесто}>
          <table className={к.таблица}>
            <thead>
              <tr>
                <th scope="col">Проверка</th>
                <th scope="col">Когда</th>
                <th scope="col">Длина</th>
                <th scope="col">Сон</th>
                <th scope="col">Свет</th>
                <th scope="col">Лицо</th>
                <th scope="col">Совпало</th>
                <th scope="col"><span className={s.дляЧтения}>Разбор</span></th>
              </tr>
            </thead>
            <tbody>
              {п.map((р) => <Строка key={р.id} р={р} onРазбор={onРазбор} />)}
            </tbody>
          </table>
        </div>
      ) : <p className={s.тихо}>Человек вошёл, но ещё не начинал проверок.</p>}
      <p className={к.сноска}>«Сон» — сонливость 1–9 перед проверкой. «Лицо» — доля кадров, где лицо видно. «Совпало» — как часто решение системы совпало с тем, что человека попросили сделать.</p>
    </section>
  )
}

function Строка({ р, onРазбор }: { р: ПроверкаКабинета; onРазбор: (id: string) => void }) {
  const сон = р.перед.сонливость
  const совпало = р.совпало && р.совпало.из ? р.совпало.да / р.совпало.из : null
  const пометка = !р.закончена ? 'не закончена' : р.прервана ? 'остановлена' : ''
  return (
    <tr>
      <th scope="row" className={к.вид}>
        {название(р.вид)}
        {пометка ? <span className={к.пометка}>{пометка}</span> : null}
      </th>
      <td className={к.моно}>{когда(р.начата)}</td>
      <td className={к.моно}>{длина(р.длина)}</td>
      <td className={к.моно} title={сон ? СОНЛИВОСТЬ.find((x) => String(x.балл) === сон)?.слова : undefined}>{сон ?? '—'}</td>
      <td>{СВЕТ[р.перед.свет ?? ''] ?? '—'}</td>
      <td className={к.моно}>{процент(р.лицо)}</td>
      <td className={к.моно}>{процент(совпало)}</td>
      <td className={к.открыть}>
        <button type="button" className={к.смотреть} onClick={() => onРазбор(р.id)} aria-label={`Разбор: ${название(р.вид)}, ${когда(р.начата)}`}>
          <svg viewBox="0 0 24 24" aria-hidden><path d="M9 7 L 17 12 L 9 17 Z" className={к.заливка} /></svg>
        </button>
      </td>
    </tr>
  )
}

function Всего({ всего }: { всего: СводкаКабинета['всего'] }) {
  const строки: [string, string][] = [
    ['людей', String(всего.людей)],
    ['проверок', String(всего.проверок)],
    ['записи', времяЗаписи(всего.секунд)],
    ['на сервере', объём(всего.байт)],
    ['свободно', объём(всего.свободно)],
  ]
  return (
    <section className={`${s.листок} ${к.карточка}`} aria-labelledby="кабинет-всего">
      <h2 className={к.надпись} id="кабинет-всего">Всего</h2>
      <dl className={к.всего}>
        {строки.map(([что, сколько]) => (
          <div key={что} className={к.всегоСтрока}>
            <dt>{что}</dt>
            <dd>{сколько}</dd>
          </div>
        ))}
      </dl>
    </section>
  )
}

function Ссылка({ ссылка, onСменить, слова, спрашиваем }: { ссылка: СводкаКабинета['ссылка']; onСменить: () => void; слова: string; спрашиваем: boolean }) {
  const [вопрос, setВопрос] = useState(спрашиваем)
  const [скопировано, setСкопировано] = useState('')
  const адрес = ссылка.секрет ? ссылкаДляВсех(ссылка.секрет) : null
  const скопировать = async () => {
    if (!адрес) return
    try {
      await navigator.clipboard.writeText(адрес)
      setСкопировано('Скопировано.')
    } catch {
      setСкопировано('Не скопировалось — выделите ссылку и скопируйте вручную.')
    }
  }
  return (
    <section className={`${s.листок} ${к.карточка}`} aria-labelledby="кабинет-ссылка">
      <h2 className={к.надпись} id="кабинет-ссылка">Ссылка для всех</h2>
      {адрес ? <p className={к.адрес}>{адрес.replace('https://', '')}</p> : <p className={s.тихо}>Ссылки ещё нет — нажмите «Сменить», и она появится.</p>}
      {ссылка.секрет ? <p className={s.тихо}>По ней вошло: {ссылка.вошло} {форма(ссылка.вошло, 'человек', 'человека', 'человек')}</p> : null}
      {вопрос ? (
        <div className={к.вопрос} role="group" aria-label="Сменить ссылку">
          <p className={к.вопросСлова}>Сменить ссылку? Старая перестанет пускать новых людей; кто уже проходил, останется со своими записями.</p>
          <div className={к.ряд}>
            <Button kind="quiet" onClick={() => setВопрос(false)}>Отмена</Button>
            <Button kind="leave" onClick={() => { setВопрос(false); onСменить() }}>Сменить</Button>
          </div>
        </div>
      ) : (
        <>
          <div className={к.ряд}>
            <Button kind="quiet" onClick={() => void скопировать()} disabled={!адрес}>Скопировать</Button>
            <Button kind="quiet" onClick={() => setВопрос(true)}>Сменить</Button>
          </div>
          {скопировано || слова ? <p className={s.тихо} role="status">{скопировано || слова}</p> : null}
        </>
      )}
    </section>
  )
}
