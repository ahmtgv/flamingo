/** Кабинет исследования — только для владельца (решение владельца 06.10:
 *  «где я могу видеть все данные»; экран 10 утверждённого холста).
 *
 *  Слева — люди, в середине — проверки выбранного человека, справа — итоги и
 *  ссылка для всех. Кто владелец, решает сервер по почте входа
 *  (`science/кабинет.py`); страница лишь показывает его ответ словами.
 *
 *  🔴 «СМЕНИТЬ» — НЕОБРАТИМО. Старая ссылка перестаёт пускать новых людей,
 *  поэтому смена — в два нажатия: «Сменить» → вопрос со словами, что будет, →
 *  «Сменить» ещё раз.
 */
