/** Сутки, которые не замерзают.
 *
 *  🔴 ЗАЧЕМ ЭТО ЕСТЬ. Аудит 07.09, находка 17: кабинет считал «сегодня» один
 *  раз при открытии — `useMemo(() => new Date(), [])` — и не менял его больше
 *  никогда. Преподаватель оставил кабинет открытым с вечера; в 00:20 у него
 *  занятие, а на экране его нет: «сегодня» показывает вчерашний день,
 *  календарь обводит вчера, урок не в списке. В ночь на первое к этому
 *  добавлялся пустой календарь — месяц не переключался, и у сервера новый
 *  месяц не спрашивали вовсе.
 *
 *  🔴 ПОЧЕМУ НЕ ПРОСТО ТАЙМЕР ДО ПОЛУНОЧИ. У спящего ноутбука `setTimeout`
 *  вовремя не срабатывает: система его задерживает, и вкладка просыпается
 *  утром с несработавшим будильником — то есть ровно в том состоянии, ради
 *  которого всё и затевалось. Поэтому сверка идёт ещё и на пробуждение
 *  вкладки и на возврат фокуса; это дёшево и закрывает случай, который иначе
 *  выглядит как «у меня всё работало, а утром сломалось».
 */

import { useEffect, useState } from 'react'

import { доПолуночи, ключСуток } from './datetime'

/** Сегодняшний день. Меняется, когда меняются сутки, и только тогда. */
export function useСегодня(): Date {
  const [день, setДень] = useState(() => new Date())

  useEffect(() => {
    let живо = true
    let будильник = 0

    /* Значение меняется ТОЛЬКО при смене суток. `new Date()` каждый раз новый
       объект, и безусловный `setДень` перерисовывал бы экран на каждую сверку —
       а сверок тут три источника. */
    const сверить = () => {
      if (!живо) return
      setДень((было) => (ключСуток(было) === ключСуток(new Date()) ? было : new Date()))
    }

    const завести = () => {
      будильник = window.setTimeout(() => {
        сверить()
        if (живо) завести()
      }, доПолуночи(new Date()))
    }
    завести()

    document.addEventListener('visibilitychange', сверить)
    window.addEventListener('focus', сверить)
    return () => {
      живо = false
      clearTimeout(будильник)
      document.removeEventListener('visibilitychange', сверить)
      window.removeEventListener('focus', сверить)
    }
  }, [])

  return день
}
