/** День и ночь.
 *
 *  Тема — вещь одного смотрящего на одном устройстве: у преподавателя может быть
 *  светло, у ученика темно, и это не рассинхрон, а правильно. Поэтому она нигде
 *  не уезжает соседу и живёт в памяти браузера.
 *
 *  🔴 Три состояния, а не два. «Как в системе» — не то же самое, что «день»:
 *  человек, который ничего не выбирал, обязан получать то, что стоит у него
 *  в телефоне или в маке, и меняться вместе с ним по вечерам. Выбор руками
 *  эту связь разрывает — и только тогда мы что-то запоминаем.
 */

export type Тема = 'день' | 'ночь' | 'как в системе'

const КЛЮЧ = 'flamingo:тема'

function ночьВСистеме(): boolean {
  try {
    return window.matchMedia('(prefers-color-scheme: dark)').matches
  } catch {
    return false
  }
}

export function читатьТему(): Тема {
  try {
    const v = window.localStorage.getItem(КЛЮЧ)
    if (v === 'день' || v === 'ночь') return v
  } catch {
    /* приватное окно или запрет на хранилище — не повод падать */
  }
  return 'как в системе'
}

/** Ставит тему на корень документа. `tokens.css` слушает `[data-theme]`. */
export function применитьТему(t: Тема): void {
  const корень = document.documentElement
  const тёмно = t === 'ночь' || (t === 'как в системе' && ночьВСистеме())
  корень.dataset.theme = тёмно ? 'dark' : 'light'
}

export function сохранитьТему(t: Тема): void {
  try {
    if (t === 'как в системе') window.localStorage.removeItem(КЛЮЧ)
    else window.localStorage.setItem(КЛЮЧ, t)
  } catch {
    /* не сохранилось — тема всё равно применится на этот сеанс */
  }
  применитьТему(t)
}

/** Следующая тема по кругу: день → ночь → как в системе → день.
 *  Круг из трёх, а не переключатель из двух: иначе вернуться к системной,
 *  один раз нажав, стало бы невозможно. */
export function следующая(t: Тема): Тема {
  return t === 'день' ? 'ночь' : t === 'ночь' ? 'как в системе' : 'день'
}

/** Зовётся один раз при запуске: пока человек не выбрал сам, идём за системой
 *  и слушаем её — вечером тема меняется без перезагрузки. */
export function завестиТему(): () => void {
  применитьТему(читатьТему())
  let mq: MediaQueryList | null = null
  const пере = () => {
    if (читатьТему() === 'как в системе') применитьТему('как в системе')
  }
  try {
    mq = window.matchMedia('(prefers-color-scheme: dark)')
    mq.addEventListener('change', пере)
  } catch {
    mq = null
  }
  return () => mq?.removeEventListener('change', пере)
}
