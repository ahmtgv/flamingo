import { newRoomCode } from './code'

export type Урок = {
  id: string
  название: string
  /** Начало: `ГГГГ-ММ-ДД` и `ЧЧ:ММ` порознь — так их вводят и так их читают. */
  дата: string
  время: string
  /** В минутах. */
  минут: number
  код: string
  заведён: string
}

const КЛЮЧ = 'flamingo:уроки'

function прочесть(): Урок[] {
  try {
    const сырое = window.localStorage.getItem(КЛЮЧ)
    if (!сырое) return []
    const что = JSON.parse(сырое)
    return Array.isArray(что) ? (что as Урок[]) : []
  } catch {
    /* приватное окно, запрет на хранилище или испорченная запись — не повод падать */
    return []
  }
}

/** Все занятия, от ближайшего к дальнему. */
export function уроки(): Урок[] {
  return прочесть().sort((a, b) => `${a.дата} ${a.время}`.localeCompare(`${b.дата} ${b.время}`))
}

export function урокиНа(дата: string): Урок[] {
  return уроки().filter((у) => у.дата === дата)
}

/** Дни месяца, в которые что-то есть. Календарю нужны только числа. */
export function дниСЗанятиями(год: number, месяц: number): Set<number> {
  const п = `${год}-${String(месяц + 1).padStart(2, '0')}-`
  const out = new Set<number>()
  for (const у of уроки()) if (у.дата.startsWith(п)) out.add(Number(у.дата.slice(8, 10)))
  return out
}

function записать(все: Урок[]): void {
  try {
    window.localStorage.setItem(КЛЮЧ, JSON.stringify(все))
  } catch {
    /* не сохранилось — на этот сеанс список всё равно верный */
  }
}

/** Заводит урок и отдаёт его. Код комнаты рождается вместе с уроком: ссылку
 *  можно отдать классу сразу, не дожидаясь начала. */
export function завести(что: { название: string; дата: string; время: string; минут: number }): Урок {
  const у: Урок = {
    id: `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`,
    название: что.название,
    дата: что.дата,
    время: что.время,
    минут: что.минут,
    код: newRoomCode(),
    заведён: new Date().toISOString(),
  }
  записать([...прочесть(), у])
  return у
}

/** Правка. 🔴 Код комнаты НЕ трогаем: разосланная ссылка не должна умирать
 *  оттого, что преподаватель сдвинул урок на полчаса. */
export function поправить(
  id: string,
  что: { название: string; дата: string; время: string; минут: number },
): Урок {
  const все = прочесть()
  const i = все.findIndex((у) => у.id === id)
  if (i < 0) throw new Error('Такого занятия здесь нет.')
  все[i] = { ...все[i], ...что }
  записать(все)
  return все[i]
}

export function убрать(id: string): void {
  записать(прочесть().filter((у) => у.id !== id))
}

/** Сегодняшний день в том же виде, в каком хранится дата урока. */
export function сегодняСтрокой(now: Date = new Date()): string {
  const п = (n: number) => String(n).padStart(2, '0')
  return `${now.getFullYear()}-${п(now.getMonth() + 1)}-${п(now.getDate())}`
}
