/** Дата и время, набранные руками.
 *
 *  🔴 ПОЧЕМУ НЕ `<input type="date">`. Родное поле браузера приносит с собой две
 *  чужие вещи: свой значок (календарик, часики) — иконку, которой нет в нашем
 *  наборе, — и СВОЙ формат, взятый из языка системы. На английской машине то же
 *  поле показывает `09/01/2026` и `10:00 AM`. То есть экран выглядит по-разному
 *  у разных людей, и мы этим не управляем. Проверено живым проходом.
 *
 *  Поэтому дата и время — обычные текстовые поля с маской: `дд.мм.гггг` и
 *  `чч:мм`, одинаково везде, той же гарнитурой и с тем же кантом, что имя урока.
 *
 *  Наружу (в `lib/lessons.ts`) дата уезжает в машинном виде `ГГГГ-ММ-ДД`:
 *  так она сортируется сравнением строк и не зависит от часового пояса.
 */

const цифры = (s: string) => s.replace(/\D/g, '')

/** `дд.мм.гггг` по мере набора: разделители ставит поле, а не человек. */
export function маскаДаты(ввод: string): string {
  const ц = цифры(ввод).slice(0, 8)
  if (ц.length <= 2) return ц
  if (ц.length <= 4) return `${ц.slice(0, 2)}.${ц.slice(2)}`
  return `${ц.slice(0, 2)}.${ц.slice(2, 4)}.${ц.slice(4)}`
}

/** `чч:мм` по мере набора. */
export function маскаВремени(ввод: string): string {
  const ц = цифры(ввод).slice(0, 4)
  if (ц.length <= 2) return ц
  return `${ц.slice(0, 2)}:${ц.slice(2)}`
}

/** `дд.мм.гггг` → `ГГГГ-ММ-ДД`. Пусто, если такой даты не существует:
 *  31 февраля разбирается как «нет такой», а не как 3 марта. */
export function датаВМашинную(s: string): string {
  const m = s.match(/^(\d{2})\.(\d{2})\.(\d{4})$/)
  if (!m) return ''
  const [, д, мес, год] = m
  const п = new Date(Number(год), Number(мес) - 1, Number(д))
  if (п.getFullYear() !== Number(год) || п.getMonth() !== Number(мес) - 1 || п.getDate() !== Number(д)) return ''
  return `${год}-${мес}-${д}`
}

export function датаИзМашинной(s: string): string {
  const m = s.match(/^(\d{4})-(\d{2})-(\d{2})$/)
  return m ? `${m[3]}.${m[2]}.${m[1]}` : ''
}

/** `чч:мм` в пределах суток — иначе пусто. */
export function времяЦелое(s: string): string {
  const m = s.match(/^(\d{2}):(\d{2})$/)
  if (!m) return ''
  return Number(m[1]) < 24 && Number(m[2]) < 60 ? s : ''
}
