/** Часовые пояса (решение владельца 08.09: идут в v1).
 *
 *  🔴 ЧТО ЗДЕСЬ ЧИНИТСЯ. Аудит 07.09, находка 18: один и тот же урок в трёх
 *  поясах браузера — Москва, Владивосток (+7), Калининград (−1) — во всех трёх
 *  печатался как «17:00». Преподаватель во Владивостоке ставит урок на 17:00,
 *  ученик в Калининграде видит «17:00» и приходит через восемь часов после
 *  занятия. Ссылка на комнату одна, расписание общее, а числа на двух экранах
 *  означают разное.
 *
 *  🔴 ПОЧЕМУ ОДНОВРЕМЕННО БЫЛО ДВОЕ ЧАСОВ. Сервер отдаёт занятие настенными
 *  часами («2026-09-09», «10:00»), а сообщение — настоящим моментом
 *  (`made_at.isoformat()`). Первое не переводилось ничем, второе переводилось
 *  браузером в пояс читателя. В одной панели «вы · 08.09, 22:28» стояло прямо
 *  над «09.09 · 10:00»: разница семь часов, и ни слова об этом.
 *
 *  ПРАВИЛА 10.3: «Время занятия задаётся в поясе преподавателя, и тут же видно,
 *  во сколько это у учеников. Пересчёт — в рельсе при вводе, а не в письме
 *  после».
 *
 *  Пустой пояс — законное значение и означает «не знаем». Тогда время
 *  показывается как есть и НИЧЕГО не утверждается о том, чьё оно: соврать
 *  уверенно хуже, чем промолчать (ветка «пояса учеников не пришли» на листах).
 */

/** Пояс этого браузера. Спрашивать его формой не нужно и не будем: браузер
 *  знает точно, а поле в анкете человек заполнит один раз и оно устареет при
 *  первом переезде. */
export function мойПояс(): string {
  try {
    return Intl.DateTimeFormat().resolvedOptions().timeZone || ''
  } catch {
    return ''
  }
}

/** Смещение пояса от UTC в минутах в указанный момент.
 *
 *  🔴 ИМЕННО В МОМЕНТ, А НЕ «У ПОЯСА ВООБЩЕ». У пояса нет одного смещения:
 *  у Берлина зимой +1, летом +2. Считать надо на дату занятия, иначе урок в
 *  конце марта уедет на час.
 */
export function смещение(пояс: string, момент: Date): number {
  const ф = new Intl.DateTimeFormat('en-US', {
    timeZone: пояс, hour12: false,
    year: 'numeric', month: '2-digit', day: '2-digit',
    hour: '2-digit', minute: '2-digit', second: '2-digit',
  })
  const ч: Record<string, string> = {}
  for (const { type, value } of ф.formatToParts(момент)) ч[type] = value
  /* Часы в поясе, прочитанные как если бы это был UTC, минус настоящий UTC —
     и есть смещение. `hour` в en-US с `hour12: false` даёт «24» вместо «00». */
  const как = Date.UTC(+ч.year, +ч.month - 1, +ч.day,
    +ч.hour % 24, +ч.minute, +ч.second)
  return Math.round((как - момент.getTime()) / 60000)
}

/** Настоящий момент занятия: настенные часы + пояс, в котором они заданы.
 *
 *  Пустой пояс — считаем по часам читателя: другого знания у нас нет, и это
 *  ровно то, что происходило до сегодняшнего дня. */
export function момент(дата: string, время: string, пояс: string): Date {
  const [г, м, д] = дата.split('-').map(Number)
  const [ч, мин] = время.split(':').map(Number)
  if (!пояс) return new Date(г, (м || 1) - 1, д || 1, ч || 0, мин || 0)
  /* Ищем момент, который в нужном поясе показывает нужные часы. Одного вычета
     смещения мало: смещение само зависит от момента, а его мы и ищем. Второй
     проход снимает расхождение на переводе часов — дальше оно не растёт. */
  const наивно = Date.UTC(г, (м || 1) - 1, д || 1, ч || 0, мин || 0)
  let м1 = new Date(наивно - смещение(пояс, new Date(наивно)) * 60000)
  м1 = new Date(наивно - смещение(пояс, м1) * 60000)
  return м1
}

/** Как это время выглядит у читателя.
 *
 *  Возвращает и настенные часы читателя, и признак «пояс другой» — второе
 *  нужнее первого: пока пояса совпадают, говорить не о чем, и лишнее слово на
 *  экране только мешает. */
export function уМеня(дата: string, время: string, пояс: string): {
  дата: string; время: string; иначе: boolean; момент: Date | null
} {
  if (!пояс) return { дата, время, иначе: false, момент: null }
  const мой = мойПояс()
  const м = момент(дата, время, пояс)
  const ф = new Intl.DateTimeFormat('sv-SE', {
    timeZone: мой || undefined, hour12: false,
    year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit',
  })
  /* `sv-SE` даёт «2026-09-09 10:00» — те же ISO-подобные части, что и у
     сервера, и разбирать их нечем: просто режем. */
  const [д, в] = ф.format(м).replace(',', '').split(' ')
  return { дата: д, время: в, иначе: д !== дата || в !== время, момент: м }
}

/** Короткое имя пояса для человека: «Москва, UTC+3». Слова с листов дизайна. */
export function имяПояса(пояс: string, момент: Date = new Date()): string {
  if (!пояс) return ''
  const см = смещение(пояс, момент)
  const знак = см < 0 ? '−' : '+'
  const ч = Math.floor(Math.abs(см) / 60)
  const м = Math.abs(см) % 60
  const utc = `UTC${знак}${ч}${м ? `:${String(м).padStart(2, '0')}` : ''}`
  /* Город из имени IANA: «Europe/Moscow» → «Moscow». Переводить названия
     городов на русский списком мы не будем — список на шестьсот имён устареет
     раньше, чем пригодится; человеку хватает своего города латиницей и UTC. */
  const город = пояс.split('/').pop()?.replace(/_/g, ' ') ?? пояс
  return `${город}, ${utc}`
}

/** Как показать время занятия ОДИНАКОВО во всех местах продукта.
 *
 *  🔴 ГЛАВНОЕ — ЧЬИ ЧАСЫ ГЛАВНЫЕ. Человек действует по СВОИМ: он в них живёт,
 *  ставит будильник и опаздывает. Поэтому крупно — его часы, а часы автора
 *  занятия приписываются рядом, когда они другие.
 *
 *  Наоборот было бы вежливее к преподавателю и хуже для дела: ученик прочитал
 *  бы «17:00», записал бы 17:00 и пришёл через восемь часов после урока —
 *  ровно та беда, из-за которой всё это делается (аудит 07.09, находка 18).
 *
 *  Когда пояс не известен или совпал — приписки нет вовсе. Лишнее слово на
 *  экране мешает не меньше, чем недостающее.
 */
export function когдаУрок(дата: string, время: string, пояс: string): {
  дата: string; время: string; сноска: string
} {
  const у = уМеня(дата, время, пояс)
  if (!пояс || !у.иначе) return { дата: у.дата, время: у.время, сноска: '' }
  const день = у.дата === дата ? '' : `${дата.slice(8, 10)}.${дата.slice(5, 7)} `
  return {
    дата: у.дата,
    время: у.время,
    сноска: `${день}${время} — ${имяПояса(пояс, у.момент ?? new Date())}`,
  }
}
