/** Опыты: то, что в продукте уже есть, но включается не всем, а по слову.
 *
 *  Сейчас опыт один — внимание SEduM в комнате урока (решение владельца 05.10:
 *  «тестируем на владельце и взрослых из команды; дети — позже и с согласия
 *  родителя»). Поэтому оно ВЫКЛЮЧЕНО, пока человек сам не открыл ссылку с
 *  `?внимание=1`. Выбор помнится в этом браузере; `?внимание=0` выключает.
 *
 *  🔴 ЧИТАЕТСЯ ПРИ ЗАГРУЗКЕ СТРАНИЦЫ, А НЕ В КОМНАТЕ. Гость по ссылке сначала
 *  видит «Вас ждут в комнате», а оттуда в урок ведёт `go('/r/<код>')` — и хвост
 *  адреса с `?внимание=1` к этому времени уже потерян. Поэтому `App.tsx` зовёт
 *  `запомнитьОпыты()` один раз, до любого перехода.
 *
 *  Хранилища может не быть (приватное окно) — тогда опыт живёт, пока открыта
 *  страница с этим хвостом, и не дольше.
 */

const КЛЮЧ = 'flamingo.опыт.внимание'
let вЭтотРаз: boolean | null = null

export function запомнитьОпыты(поиск: string = window.location.search): void {
  const слово = new URLSearchParams(поиск).get('внимание')
  if (слово !== '1' && слово !== '0') return
  вЭтотРаз = слово === '1'
  try {
    if (вЭтотРаз) window.localStorage.setItem(КЛЮЧ, 'да')
    else window.localStorage.removeItem(КЛЮЧ)
  } catch {
    /* нет хранилища — опыт живёт до закрытия страницы */
  }
}

/** Включено ли внимание SEduM у этого человека в этом браузере. */
export function вниманиеВключено(): boolean {
  if (вЭтотРаз !== null) return вЭтотРаз
  try {
    return window.localStorage.getItem(КЛЮЧ) === 'да'
  } catch {
    return false
  }
}
