/** Единственный разговор с сервером во всём первом куске. */

/** 🔴 ПРОПУСК В КОМНАТУ ТЕПЕРЬ ВЫДАЁТ СЕРВЕР, А НЕ ФУНКЦИЯ PAGES (решение
 *  владельца 09.09). Раньше здесь на боевом адрес не брался ниоткуда: путь
 *  `/api/room/token` обслуживала функция из того же выката, и адрес был всегда
 *  свой же. Теперь адрес один и тот же у всего продукта — учётные записи,
 *  занятия, журнал и комната ходят на один сервер.
 *
 *  Почему это перестало быть опасным. Прежний запрет читать окружение на боевом
 *  писался после 30.08: забытый локальный `.env` унёс в сборку
 *  `http://localhost:8080`, и продукт молча ходил в никуда. Теперь боевую сборку
 *  собирает Cloudflare из репозитория — локальный `.env` до неё не доезжает
 *  физически, он в git не попадает вовсе. А на случай, если однажды кто-то
 *  соберёт боевое руками, стоит караул `сборка-check`: он смотрит в СОБРАННЫЙ
 *  файл и падает, если нашёл там `localhost`.
 *
 *  🔴 ИМЯ ПЕРЕМЕННОЙ ИСТОРИЧЕСКОЕ. `VITE_AUTH_URL` завелась, когда на своём
 *  сервере жили только учётные записи; сегодня по этому адресу живёт всё. Имя
 *  не переименовано нарочно: оно задано в настройках сборки Cloudflare, и смена
 *  имени — это окно, в котором продукт не знает своего сервера. Переименование
 *  делается отдельно и вместе с настройками, а не попутно. */
const BASE = String(import.meta.env.VITE_AUTH_URL ?? '').replace(/\/$/, '')

export type RoomTicket = {
  token: string
  url: string
  identity: string
  name: string
}

/** Отказ несёт причину словами (ПРАВИЛА 6.4), а не «что-то пошло не так». */
export class RoomError extends Error {}

export async function fetchTicket(room: string, name: string): Promise<RoomTicket> {
  let res: Response
  try {
    res = await fetch(`${BASE}/api/room/token`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ room, name }),
    })
  } catch {
    /* 🔴 ЧЕЛОВЕКУ — ПРИЧИНА И ОДНО ДЕЙСТВИЕ, КОТОРОЕ ОН МОЖЕТ СДЕЛАТЬ
       (ПРАВИЛА 6.4). «Проверьте, запущен ли он» — распоряжение системному
       администратору: преподавателю с классом в комнате проверять нечего. */
    throw new RoomError('Сервер Flamingo не отвечает. Урок и ссылка на месте — попробуйте войти ещё раз через минуту.')
  }

  let body: { token?: string; url?: string; identity?: string; name?: string; error?: string } = {}
  try {
    body = await res.json()
  } catch {
    /* 🔴 НОМЕР ОТВЕТА — В КОНСОЛЬ, А НЕ В ЛИЦО ЧЕЛОВЕКУ (ПРАВИЛА 6.4).
       «Сервер ответил не по-нашему (404)» ученик читает как свою вину и не
       узнаёт ни причины, ни что делать. Поймано осмотром комнаты 08.09. */
    console.warn('комната: ответ сервера не разобран, код', res.status)
    throw new RoomError('Сервер комнаты ответил непонятно. Урок и написанное на доске на месте — откройте ссылку ещё раз.')
  }

  if (!res.ok) {
    console.warn('комната: сервер отказал, код', res.status)
    throw new RoomError(body.error ?? 'Сервер комнаты не пустил внутрь. Урок никуда не делся — откройте ссылку ещё раз или попросите новую.')
  }
  if (!body.token || !body.url) throw new RoomError('Сервер не прислал пропуск в комнату.')

  return {
    token: body.token,
    url: body.url,
    identity: body.identity ?? '',
    name: body.name ?? name,
  }
}
