import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';

/**
 * Обращение к человеку — одно на весь продукт (промпт 19, очередь А5).
 *
 * ⚠️ Проверено счётом 16.08: из **1521** строки на «ты» была написана **одна** —
 * `subject:head.cadetMeta`, и адресована она курсанту, то есть чаще всего взрослому.
 * Один сбой на полторы тысячи — это не стиль, это опечатка, которую никто не замечал,
 * потому что смотреть её надо было все 1521 разом.
 *
 * Продукт говорит на «вы» и с ребёнком, и со взрослым: возрастная адаптация в Flamingo идёт
 * размерами и словарём (`data-mode="kids"`), а не переходом на «ты». Если владелец решит иначе —
 * это решение уровня продукта, и менять придётся весь словарь, а не одну строку.
 *
 * 🔴 Тест ходит по СЛОВАРЮ, а не по экранам: строка, добавленная в `ru/*.json` мимо ревью,
 * попадётся здесь раньше, чем на глаза человеку.
 */

const LOCALES = join(process.cwd(), 'src/i18n/locales/ru');

/**
 * 🔴 Границу слова здесь нельзя писать через `\b`.
 *
 * В JavaScript `\b` опирается на ASCII: кириллица для него — не буква, поэтому у `\bтобой\b`
 * границы нет ни слева, ни справа, и регулярка не совпадает НИКОГДА. Первая версия этого файла
 * была написана именно так и прошла зелёной на строке, ради которой писалась. Проверено
 * подстановкой: вернул «с тобой преподаватель» — 4 из 4 passed.
 *
 * ⚠️ Это ровно ловушка фазы: тест, который не умеет падать, доказывает не отсутствие дефекта,
 * а собственную бесполезность. Границы — просмотром по кириллическому классу.
 */
const EDGE_L = '(?<![а-яёa-z])';
const EDGE_R = '(?![а-яёa-z])';
const word = (alts: string) => new RegExp(`${EDGE_L}(?:${alts})${EDGE_R}`, 'i');

/** «ты» и его формы — включая притяжательные, они выдают обращение вернее самого местоимения. */
const TY = word('ты|тебе|тебя|тобой|твой|твоя|твоё|твои|твоего|твоей|твоим|твоих');

/**
 * Повелительное наклонение на «ты». «Нажмите» — норма, «нажми» — нет.
 *
 * 🔴 СПИСОК РАСШИРЕН 17.08 (решение владельца §27.1 «везде делаем на „Вы"»). Прежние
 * одиннадцать слов не ловили ровно того, на чём продукт и сбивался: лист 12 написан
 * «Возьми настоящий каталог», «Закажи наблюдение», «Выбери объект», хаб отвечал «снимите
 * какой-нибудь» — и всё это проходило мимо сторожа, потому что «возьми» в списке не было.
 *
 * ⚠️ Список слов — не то же самое, что правило. Он ловит частые формы и по построению не
 * ловит редкие; полного разбора русской морфологии здесь нет и не будет. Поэтому местоимения
 * (проверка выше) — главный сторож, а этот — второй рубеж.
 */
const IMPERATIVE_TY = word(
  [
    'нажми', 'введи', 'открой', 'выбери', 'проверь', 'посмотри', 'напиши', 'сдай',
    'начни', 'закрой', 'попробуй', 'возьми', 'сними', 'закажи', 'подумай', 'реши',
    'сделай', 'поставь', 'включи', 'выключи', 'загрузи', 'отправь', 'расскажи',
    'покажи', 'выполни', 'придумай', 'запомни', 'повтори', 'послушай', 'прочитай',
    'добавь', 'удали', 'сохрани', 'найди', 'вернись', 'продолжи', 'спроси', 'ответь',
  ].join('|'),
);

/**
 * «Вы» с большой буквы в середине фразы. Канцелярит: в вебе пишут со строчной,
 * а вперемешку — хуже обоих вариантов.
 */
const VY_CAPITALISED = /(?<![.!?…]\s)(?<!^)(?<![а-яёa-z])В(?:ы|ам|ас|аш|аша|аше|аши|ашего|ашей)(?![а-яёa-z])/;

interface Line {
  key: string;
  text: string;
}

function flatten(node: unknown, prefix: string, out: Line[]): void {
  if (typeof node === 'string') {
    out.push({ key: prefix, text: node });
    return;
  }
  if (node && typeof node === 'object') {
    for (const [k, v] of Object.entries(node)) {
      flatten(v, prefix ? `${prefix}.${k}` : k, out);
    }
  }
}

function allLines(): Line[] {
  const out: Line[] = [];
  for (const file of readdirSync(LOCALES).filter((f) => f.endsWith('.json'))) {
    const ns = file.slice(0, -'.json'.length);
    flatten(JSON.parse(readFileSync(join(LOCALES, file), 'utf8')), ns, out);
  }
  return out;
}

describe('обращение к человеку', () => {
  it('весь словарь — на «вы»', () => {
    const offences = allLines().filter((l) => TY.test(l.text));
    expect(
      offences.map((l) => `${l.key} — ${l.text}`),
      'строка на «ты» среди строк на «вы»: человек замечает не правило, а разнобой',
    ).toEqual([]);
  });

  it('повелительное наклонение — тоже на «вы»', () => {
    // «Нажми» проскакивает мимо проверки местоимений: своего «ты» в нём нет.
    const offences = allLines().filter((l) => IMPERATIVE_TY.test(l.text));
    expect(offences.map((l) => `${l.key} — ${l.text}`)).toEqual([]);
  });

  it('«вы» пишется со строчной', () => {
    const offences = allLines().filter((l) => VY_CAPITALISED.test(l.text));
    expect(offences.map((l) => `${l.key} — ${l.text}`)).toEqual([]);
  });

  it('🔴 сами регулярки умеют срабатывать', () => {
    // Без этой проверки предыдущие три зелены при любом словаре — что и случилось.
    expect(TY.test('Свой темп · с тобой преподаватель {{teacher}}')).toBe(true);
    expect(IMPERATIVE_TY.test('Нажми, чтобы начать')).toBe(true);
    expect(VY_CAPITALISED.test('Здесь Вы найдёте расписание')).toBe(true);

    // И не срабатывать на похожем: «ты» внутри слова, «вы» со строчной, «Вы» после точки.
    expect(TY.test('открытый урок')).toBe(false);
    expect(VY_CAPITALISED.test('Здесь вы найдёте расписание')).toBe(false);
    expect(VY_CAPITALISED.test('Готово. Вы можете начать урок')).toBe(false);
  });

  it('словарь на месте и не усох', () => {
    // Страховка от зелёного теста на пустом множестве: три проверки выше пройдут идеально,
    // если читать станет нечего.
    expect(allLines().length).toBeGreaterThan(1400);
  });
});
