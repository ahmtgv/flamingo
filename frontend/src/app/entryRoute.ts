import { isDesktop } from '@/features/desktop/bridge';

/**
 * Первая дверь для того, кто ещё не вошёл.
 *
 * 🔴 В браузере — форма входа. В ПРИЛОЖЕНИИ — мастер первого запуска, и это не удобство, а
 * §19.4: **приложение никогда не спрашивает пароль**. Найдено при пересборке 15.08 — свежая
 * установка открывалась веб-формой входа с полем пароля, ровно тем, ради отсутствия которого
 * и построен лист D2. Система в этот момент только что назвала нас «неизвестным
 * разработчиком»; просить у человека пароль именно тогда — худшее, что можно сделать
 * с доверием.
 *
 * Отдельным модулем, а не строкой в роутере: правило одно, а мест, где решается «куда его», —
 * три (корень, защищённый маршрут, публичный). Разойдись они, и одно из них однажды приведёт
 * в приложении к форме пароля.
 */
export function entryRoute(): string {
  return isDesktop() ? '/setup' : '/login';
}
