import { Mark } from './Mark'
import s from './Wait.module.css'

/** Короткое ожидание в начале.
 *
 *  🔴 Зачем экран из двух строк. Кто вошёл, мы узнаём у сервера, и ответ приходит
 *  не мгновенно. Пока его нет, «человека нет» — не факт, а незнание. Если в этот
 *  миг показать вход, вошедший преподаватель увидит форму регистрации своего же
 *  продукта и начнёт в неё печатать — а через полсекунды экран сменится кабинетом
 *  и съест напечатанное. Поэтому незнание показано как незнание (ПРАВИЛА 6.3).
 */
export function Wait({ say = 'Смотрим, кто вошёл' }: { say?: string }) {
  return (
    <main className={s.screen}>
      <Mark />
      <span className={s.say} role="status">{say}</span>
    </main>
  )
}
