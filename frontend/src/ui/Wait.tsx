import { Mark } from './Mark'
import s from './Wait.module.css'

/** Короткое ожидание в начале.
 *
 *  🔴 Зачем экран из двух строк. Кто вошёл, мы узнаём у сервера, и ответ приходит
 *  не мгновенно. Пока его нет, «человека нет» — не факт, а незнание. Если в этот
 *  миг показать вход, вошедший преподаватель увидит форму регистрации своего же
 *  продукта и начнёт в неё печатать — а через полсекунды экран сменится кабинетом
 *  и съест напечатанное. Поэтому незнание показано как незнание (ПРАВИЛА 6.3).
 *
 *  🔴 НО ОЖИДАНИЕ ОБЯЗАНО КОНЧАТЬСЯ. 02.09 во время перезапуска сервера запрос
 *  «кто вошёл» повис — у `fetch` нет срока, — и продукт остался стоять на
 *  «СМОТРИМ, КТО ВОШЁЛ» навсегда: ни слова, ни кнопки, ни выхода. Экран
 *  незнания, из которого нет двери, хуже неправильного ответа: неправильный
 *  ответ хотя бы виден. Поэтому у него есть второе состояние — молчание
 *  сервера, названное словами и с одной кнопкой.
 */
export function Wait({ say = 'Смотрим, кто вошёл' }: { say?: string }) {
  return (
    <main className={s.screen}>
      <Mark />
      <span className={s.say} role="status">{say}</span>
    </main>
  )
}

/** Сервер не ответил. Говорим об этом словами и даём одно действие. */
export function Молчание({ onAgain, onRoom }: { onAgain: () => void; onRoom?: () => void }) {
  return (
    <main className={s.screen}>
      <Mark />
      <span className={s.say} role="status">Сервер не отвечает</span>
      <p className={s.words}>
        Мы спросили, кто вошёл, и не получили ответа. Такое бывает, когда сервер
        перезапускают: обычно это меньше минуты.
      </p>
      <span className={s.doors}>
        <button type="button" className={s.again} onClick={onAgain}>Спросить ещё раз</button>
        {onRoom ? (
          <button type="button" className={s.quiet} onClick={onRoom}>
            Войти в урок по ссылке
          </button>
        ) : null}
      </span>
      <p className={s.small}>
        Урок по ссылке работает и без учётных записей: комната живёт отдельно от сервера.
      </p>
    </main>
  )
}
