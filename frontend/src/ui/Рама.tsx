import { useState, type ReactNode } from 'react'
import { Mark } from './Mark'
import type { Person } from '../lib/auth'
import s from './Рама.module.css'

/** Постоянная навигация. Решение владельца 09–10.09.
 *
 *  🔴 ЗАЧЕМ. В продукте около четырнадцати мест, а дверей на них было три:
 *  из кабинета нельзя было попасть ни в источники, ни куда-либо ещё, кроме
 *  журнала. Колонка слева — это и есть недостающие двери.
 *
 *  🔴 ЦИФРА РЯДОМ С ПУНКТОМ — ЭТО ОБЕЩАНИЕ, поэтому её здесь нет ни у кого.
 *  Считать «сколько занятий» или «сколько непрочитанных» рама не умеет и
 *  спрашивать сервер ради украшения не станет. Цифра появится вместе с
 *  разделом, который её честно знает.
 *
 *  🔴 ПУНКТ БЕЗ АДРЕСА НЕ ПРИТВОРЯЕТСЯ ДВЕРЬЮ (ПРАВИЛА 14.1). Он назван и
 *  подписан «скоро», но не нажимается: молчащая кнопка неотличима от дефекта.
 *
 *  🔴 «СООБЩЕНИЯ» СТОЯТ ЗДЕСЬ ПО РЕШЕНИЮ ВЛАДЕЛЬЦА 12.09 — названы, но пока
 *  без адреса. Переписка сегодня живёт внутри кабинета, и второй пункт с
 *  адресом `/кабинет` дал бы две двери в одну комнату — ровно ту беду, что мы
 *  в кабинете и нашли (слово «Расписание» стояло там дважды). Пункт загорится
 *  дверью в тот день, когда кабинет разъедется на страницы и появится
 *  собственный адрес `/чаты`. «Расписание» ждёт того же дня по той же причине.
 *
 *  🔴 РОЛЬ СЕГОДНЯ — ОДНО ПОЛЕ. Владелец 10.09 решил, что «тот, кто учит,
 *  может ещё учиться», и в макетах первый пункт становится переключателем на
 *  два положения. Пока `Person.role` — одно значение, переключать нечего:
 *  сначала данные, потом переключатель. Здесь — одна строка по роли.
 */

export type Раздел = 'кабинет' | 'журнал' | 'избранное'

type Пункт = {
  имя: string
  /** Есть адрес — дверь. Нет — раздел назван, но его ещё нет.
   *  🔴 Адрес идёт СРАЗУ за именем: караул (`scripts/рама-check.mjs`) читает
   *  пункт разбором текста, и чужое поле между ними прячет от него дверь. */
  адрес?: string
  /** Подпись для нижней полосы на телефоне: там на слово ~78 px, и
   *  «Кабинет преподавателя» встаёт в две строки, ломая высоту полосы.
   *  Слово то же, только без хвоста — словарь меню не меняется. */
  коротко?: string
  ключ?: Раздел
}

type Кусок = { заголовок?: string; пункты: Пункт[] }

/** Меню одним куском данных: так его может прочесть и караул
 *  (`scripts/рама-check.mjs`), а не только человек глазами. */
export function меню(учитель: boolean): Кусок[] {
  const общее: Кусок = {
    заголовок: 'Общее',
    пункты: [
      { имя: 'Избранное', адрес: '/hub', ключ: 'избранное' },
      { имя: 'Документы' },
    ],
  }

  if (!учитель) {
    return [
      { пункты: [{ имя: 'Кабинет ученика', адрес: '/кабинет', коротко: 'Кабинет', ключ: 'кабинет' }] },
      { заголовок: 'Я учусь', пункты: [
          { имя: 'Мои занятия' }, { имя: 'Сообщения' }, { имя: 'Мои предметы' }, { имя: 'Курсы' }] },
      общее,
    ]
  }

  return [
    { пункты: [{ имя: 'Кабинет преподавателя', адрес: '/кабинет', коротко: 'Кабинет', ключ: 'кабинет' }] },
    {
      заголовок: 'Я веду',
      пункты: [
        { имя: 'Журнал', адрес: '/журнал', ключ: 'журнал' },
        /* 🔴 СООБЩЕНИЯ В МЕНЮ — РЕШЕНИЕ ВЛАДЕЛЬЦА 12.09. Пока без адреса, и это
           не отговорка: переписка живёт внутри кабинета, своей страницы у неё
           нет. Дать пункту адрес `/кабинет` нельзя — в одном меню не бывает двух
           дверей в одну комнату, это ровно та беда, которую мы в кабинете и
           нашли. Пункт назван и подписан «скоро»; он загорится в тот день,
           когда кабинет разъедется на страницы и у переписки появится `/чаты`. */
        { имя: 'Сообщения' },
        { имя: 'Мои предметы' },
        { имя: 'Мои методички' },
      ],
    },
    { заголовок: 'Я учусь', пункты: [{ имя: 'Мои занятия' }, { имя: 'Курсы' }] },
    общее,
  ]
}

/** Две буквы для кружка. Односложное имя даёт одну — вторую не выдумываем. */
export function буквы(имя: string): string {
  const части = имя.trim().split(/\s+/).filter(Boolean)
  if (!части.length) return '·'
  return части.slice(0, 2).map((ч) => ч[0].toUpperCase()).join('')
}

export function Рама({ person, где, onGo, onOut, children }: {
  person: Person
  где: Раздел
  onGo: (адрес: string) => void
  onOut: () => void
  children: ReactNode
}) {
  const [развёрнуто, setРазвёрнуто] = useState(false)
  const учитель = person.role === 'teacher'
  const куски = меню(учитель)
  const двери = куски.flatMap((к) => к.пункты).filter((п) => п.адрес)

  const строка = (п: Пункт, i: number) => {
    if (!п.адрес) {
      return (
        <span key={`${п.имя}-${i}`} className={`${s.пункт} ${s.скоро}`}>
          <span className={s.имя}>{п.имя}</span>
          <span className={s.потом}>скоро</span>
        </span>
      )
    }
    const здесь = п.ключ === где
    return (
      <button
        key={`${п.имя}-${i}`}
        type="button"
        className={`${s.пункт} ${здесь ? s.здесь : ''}`}
        aria-current={здесь ? 'page' : undefined}
        onClick={() => { setРазвёрнуто(false); if (!здесь) onGo(п.адрес!) }}
      >
        {здесь ? <span className={s.точка} aria-hidden /> : null}
        <span className={s.имя}>{п.имя}</span>
      </button>
    )
  }

  const список = куски.map((к, i) => (
    <div key={к.заголовок ?? `к${i}`}>
      {к.заголовок ? <div className={s.группа}>{к.заголовок}</div> : null}
      {к.пункты.map(строка)}
    </div>
  ))

  const человек = (
    <div className={s.человек}>
      <span className={s.буквы} aria-hidden>{буквы(person.name)}</span>
      <span className={s.кто}>
        <span className={s.чьё} title={person.name}>{person.name}</span>
        <button type="button" className={s.выйти} onClick={onOut}>Выйти</button>
      </span>
    </div>
  )

  return (
    <div className={s.рама}>
      <nav className={s.колонка} aria-label="Разделы">
        <div className={s.знак}>
          <Mark onGo={() => onGo('/кабинет')} title="Главная — кабинет" />
        </div>
        {список}
        <span className={s.распорка} />
        {человек}
      </nav>

      <div className={s.лист}>{children}</div>

      {/* Узкое окно: те же двери нижней полосой. «Ещё» открывает тот же
          список целиком — словарь меню на всех ширинах один. */}
      <div className={s.низ}>
        {развёрнуто ? (
          <>
            <button
              type="button"
              className={s.подложка}
              aria-label="Закрыть список разделов"
              onClick={() => setРазвёрнуто(false)}
            />
            <div className={s.ещё}>
              {список}
              {человек}
            </div>
          </>
        ) : null}
        <div className={s.полоса}>
          {двери.map((п) => {
            const здесь = п.ключ === где
            return (
              <button
                key={п.имя}
                type="button"
                className={`${s.кнопка} ${здесь ? s.кнопкаЗдесь : ''}`}
                aria-current={здесь ? 'page' : undefined}
                onClick={() => { setРазвёрнуто(false); if (!здесь) onGo(п.адрес!) }}
              >
                <span className={`${s.огонёк} ${здесь ? '' : s.погашен}`} aria-hidden />
                {п.коротко ?? п.имя}
              </button>
            )
          })}
          <button
            type="button"
            className={s.кнопка}
            aria-expanded={развёрнуто}
            onClick={() => setРазвёрнуто((б) => !б)}
          >
            <span className={`${s.огонёк} ${s.погашен}`} aria-hidden />
            Ещё
          </button>
        </div>
      </div>
    </div>
  )
}
