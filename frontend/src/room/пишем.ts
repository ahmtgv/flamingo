/** SEduM · «пишем в тетради» — по слову учителя и по тому, что делает класс.
 *
 *  Решение владельца 09.10: кнопки нет — «система должна научиться понимать
 *  команду учителя и в этом случае не считать опущенные головы учеников».
 *  Учитель говорит «запишите в тетрадь» — головы над тетрадью у класса
 *  считаются работой («пишет»), а не «смотрит вниз», и балл не падает.
 *
 *  🔴 ГОЛОС УЧИТЕЛЯ НИКУДА НЕ УХОДИТ. Речь распознаётся в его же браузере
 *  (Vosk, `room/слух.ts`), наружу уходит одно слово — «пишем» или «не пишем» —
 *  и то только ученикам этой комнаты.
 *
 *  Здесь — чистая логика, без микрофона и без React: что значит фраза и когда
 *  режим включается и выключается. Её гоняет караул
 *  `scripts/внимание-комната-check.mjs` на придуманных фразах и классах.
 *
 *  🔴 ПОНИМАНИЕ, А НЕ СПИСОК ФРАЗ (решение 05.10). Ищем не точную фразу, а
 *  смысл по корням: «запиш-», «конспект-», «перепиш-», «тетрад-» рядом с
 *  «открой/достань/в». Распознавание ошибается в окончаниях — корни переживают
 *  это лучше. Второй источник смысла — сам класс: если сразу после слов учителя
 *  большинство опустило головы, значит, задание было письменным, даже если
 *  слов мы не узнали. Учиться дальше будем на записях исследования.
 */

export type СловоУчителя = 'начало' | 'конец' | null

/* Отрицание перед письмом: «не записывайте», «не надо писать», «это писать не нужно». */
const НЕ_ПИШЕМ = /(^|\s)не\s+(надо\s+|нужно\s+)?(за|на|пере|с|до)?(пис|пиш)|(пис|пиш)[а-я]*\s+не\s+(надо|нужно)/

const НАЧАЛО: RegExp[] = [
  /(^|\s)(за|пере|с)пиш(ите|ем|им|и)(\s|$)/, // запишите, перепишите, спишите, запишем
  /(^|\s)(за|пере|с)писыва(йте|ем|ем-ка)(\s|$)/, // записывайте, переписываем
  /(^|\s)(на|за)?пиш(ите|ем)\s+(в|на|у\s+себя)/, // пишем в тетрадь, напишите на полях
  /конспект/, // законспектируйте, конспектируем, конспект
  /(откро|откры|доста|возьм|бер)[а-я]*\s+(\S+\s+)?тетрад/, // откройте тетради, достаньте свои тетради
  /(^|\s)в\s+тетрад/, // «в тетради решаем», «в тетрадь»
  /(под|про)?диктовк|(^|\s)дикту(ю|ем)/, // диктовка, диктую
]

const КОНЕЦ: RegExp[] = [
  /(отлож|полож)[а-я]*\s+(\S+\s+)?ручк/, // отложите ручки
  /(закро|закрыва)[а-я]*\s+(\S+\s+)?тетрад/, // закройте тетради
  /(посмотр|смотр)[а-я]*\s+на\s+(доск|экран|меня)/, // посмотрите на доску
  /(подним|подыма)[а-я]*\s+голов/, // поднимите головы
  /(^|\s)(все|всё)\s+(за|на|до)писал/, // все записали
  /(^|\s)(закончили|дописали)(\s|$)/,
]

/** Что сказал учитель — по одной распознанной фразе. */
export function понятьФразу(фраза: string): СловоУчителя {
  const т = ` ${фраза.toLowerCase().replace(/ё/g, 'е').replace(/[^а-я\s-]/g, ' ').replace(/\s+/g, ' ').trim()} `
  if (т.trim().length < 3) return null
  if (КОНЕЦ.some((р) => р.test(т))) return 'конец'
  if (НЕ_ПИШЕМ.test(т)) return null
  if (НАЧАЛО.some((р) => р.test(т))) return 'начало'
  return null
}

export type Откуда = 'учитель' | 'класс' | null

/** Сроки режима, секунды. */
export const СРОКИ = {
  /** Головы класса после слов учителя: сколько ждём, что задание письменное. */
  послеРечи: 20,
  /** Сколько большинство должно держать головы вниз, чтобы мы поверили. */
  вниз: 5,
  /** Доля класса с опущенными головами, которая значит «пишут». */
  доля: 0.6,
  /** Сколько большинство должно смотреть вверх, чтобы режим кончился сам. */
  вверх: 20,
  /** Режим держится не меньше этого — чтобы не мигать на каждой паузе. */
  минимум: 30,
  /** И не больше этого без нового слова учителя. */
  максимум: 10 * 60,
}

/** Режим «пишем» у учителя: слова + головы класса → да или нет. */
export class Пишем {
  private вкл = false
  private с = 0
  private откуда: Откуда = null
  private речь: number | null = null
  private внизС: number | null = null
  private вверхС: number | null = null
  private последнееНачало = 0

  get идёт(): boolean { return this.вкл }
  get источник(): Откуда { return this.вкл ? this.откуда : null }

  /** Учитель что-то сказал (любая распознанная речь). `t` — мс. */
  фраза(текст: string, t: number): void {
    if (текст.trim()) this.речь = t
    const слово = понятьФразу(текст)
    if (слово === 'начало') this.включить('учитель', t)
    if (слово === 'конец') this.выключить()
  }

  /** Раз в секунду: доля учеников с опущенной головой и сколько их видно. */
  класс(доляВниз: number, учеников: number, t: number): void {
    const мало = учеников < 2
    if (!this.вкл) {
      const послеРечи = this.речь !== null && (t - this.речь) / 1000 <= СРОКИ.послеРечи
      if (!мало && доляВниз >= СРОКИ.доля && (послеРечи || this.внизС !== null)) {
        this.внизС ??= t
        if ((t - this.внизС) / 1000 >= СРОКИ.вниз) this.включить('класс', t)
      } else this.внизС = null
      return
    }
    const прошло = (t - this.с) / 1000
    if (прошло >= СРОКИ.максимум && (t - this.последнееНачало) / 1000 >= СРОКИ.максимум) {
      this.выключить()
      return
    }
    if (!мало && доляВниз <= 1 - СРОКИ.доля && прошло >= СРОКИ.минимум) {
      this.вверхС ??= t
      if ((t - this.вверхС) / 1000 >= СРОКИ.вверх) this.выключить()
    } else this.вверхС = null
  }

  private включить(откуда: Откуда, t: number): void {
    this.последнееНачало = t
    if (this.вкл) return
    this.вкл = true
    this.с = t
    this.откуда = откуда
    this.внизС = null
    this.вверхС = null
  }

  выключить(): void {
    this.вкл = false
    this.откуда = null
    this.внизС = null
    this.вверхС = null
  }
}

/** Тема канала комнаты для режима. Едет надёжно и всем: опоздавшему тоже надо знать. */
export const ТЕМА_ПИШЕМ = 'пишем'

export function пишемВБайты(пишем: boolean): Uint8Array<ArrayBuffer> {
  return new TextEncoder().encode(JSON.stringify({ п: пишем }))
}

export function пишемИзБайтов(байты: Uint8Array): boolean | null {
  try {
    const о = JSON.parse(new TextDecoder().decode(байты)) as { п?: unknown }
    return typeof о.п === 'boolean' ? о.п : null
  } catch {
    return null
  }
}
