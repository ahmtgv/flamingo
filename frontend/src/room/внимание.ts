/** SEduM · внимание в комнате урока.
 *
 *  Вид утверждён владельцем 05.10 (вариант 2): у УЧИТЕЛЯ на плитке ученика —
 *  число и причина тихим текстом у имени и тонкая полоска внизу; у УЧЕНИКА —
 *  только полоска, и только на своей плитке. Чужого внимания ученик не видит
 *  никогда. Коралловый — только «заснул» и «ушёл».
 *
 *  🔴 КУДА ИДУТ ДАННЫЕ — ТОЛЬКО НА ЭКРАН (решение владельца). Камера ученика
 *  считается на его же устройстве (`sedum/лицо.ts`): ни кадр, ни точки лица
 *  никуда не уходят. Наружу уходят два слова — балл и причина — раз в секунду,
 *  по каналу комнаты, ОДНОМУ адресату: ведущему. Сервер их не хранит (LiveKit
 *  пересылает и забывает), у учителя они живут в памяти страницы, пока свежие.
 *  Ни журнала, ни уведомлений.
 *
 *  🔴 АДРЕСАТ — ТОТ, ЧЬЮ РОЛЬ ПОДПИСАЛ СЕРВЕР, А НЕ ТОТ, КТО НАЗВАЛСЯ. Подпись
 *  «ведёт занятие» на плитке едет словом ведущего по каналу и подделывается
 *  чужим клиентом (useRoom.ts) — для подписи это не беда, для чужого внимания
 *  беда. Поэтому балл уходит только участнику, у которого в пропуске сервер
 *  написал `{"ведёт": true}` (`backend/room/views.py`); поменять это поле своим
 *  клиентом нельзя. Нет такого в комнате — балл не уходит никуда.
 *
 *  🔴 ВКЛЮЧЕНО ВСЕГДА (решение владельца 19.10). Раньше счёт заводился только
 *  у ученика, сам открывшего ссылку с `?внимание=1`, — и учитель на деле не
 *  видел ничего. Теперь ученик считает себя в любом уроке, где есть ведущий,
 *  подписанный сервером, и включена его камера. Нет ведущего — модель даже не
 *  скачивается: считать не для кого.
 *
 *  🔴 УЧЕНИК ЗНАЕТ, ЧТО ЕГО ВИДЯТ (решение 19.10). На своей плитке рядом с
 *  полоской — тихая надпись «учитель видит внимание».
 *
 *  🔴 «НИЧЕГО» — ТОЖЕ ОТВЕТ. Пока модель скачивается или если устройство с ней
 *  не справилось, ученик шлёт учителю не балл, а положение: «загружается» или
 *  «не считается». Иначе пустая плитка у учителя значит что угодно — и найти,
 *  где оборвалось, нельзя (так и было 19.10 с учеником на телефоне).
 */
import { useEffect, useRef, useState } from 'react'
import type { Track } from 'livekit-client'

import { ЦЕНА, ТРЕВОГА, Внимание, ПОРОГИ, type Качество, type Состояние } from '../sedum/внимание.ts'
import type { Кадр, Яркомер } from '../sedum/лицо'
import type { Face } from './useRoom'

/** Заведённая модель — то, что нужно счёту, и ничего больше. */
type Счёт = { detect: (в: HTMLVideoElement, t: number) => Кадр; яркомер: Яркомер; оценить: (к: Кадр, я: number | null) => Качество }

/** Тема канала комнаты. Доска ездит по своей (`board`), внимание — по своей. */
export const ТЕМА = 'внимание'

export type ЗнакВнимания = { балл: number; состояние: Состояние; тревога: boolean }

/** Почему балла нет: модель ещё едет на устройство ученика — или не завелась. */
export type ПоложениеСчёта = 'заводим' | 'не завёлся'

/** Слова положения на плитке учителя. */
export const СЛОВА_ПОЛОЖЕНИЯ: Record<ПоложениеСчёта, { коротко: string; подробно: string }> = {
  'заводим': { коротко: 'загружается', подробно: 'Модель лица скачивается на устройство ученика — обычно до полуминуты.' },
  'не завёлся': { коротко: 'не считается', подробно: 'Устройство ученика не справилось с моделью лица. Урок от этого не страдает.' },
}

/** Через сколько молчания знак ученика гаснет у учителя: выключил камеру, ушёл
 *  из комнаты, закрыл вкладку. Пять пропущенных секунд — уже не «связь моргнула». */
export const ГАСНЕТ_МС = 6000

/** Внимание SEduM на плитках: чьё и как показывать. `учитель` — знаки
 *  учеников с цифрой и причиной; `ученик` — только свой знак, полоской. */
export type ВниманиеНаСцене = {
  знаки: Record<string, ЗнакВнимания>
  вид: 'учитель' | 'ученик'
  /** Только у учителя: у кого балла пока нет и почему. */
  положения?: Record<string, ПоложениеСчёта>
  /** Класс пишет в тетрадях (room/пишем.ts) — учитель видит это тихой плашкой на своей плитке. */
  пишем?: boolean
}

/** Плашка «пишут в тетради» — только у учителя и только на его плитке. */
export function пишутПлитка(face: Face, в?: ВниманиеНаСцене): boolean {
  return Boolean(в && в.вид === 'учитель' && в.пишем && face.isLocal)
}

/** Знак для этой плитки — или ничего. Правило «чужого внимания ученик не
 *  видит» держится и ЗДЕСЬ, а не только у того, кто собрал знаки: у ученика
 *  знак показывается лишь на своей плитке, у учителя — лишь на чужих. */
export function знакПлитки(face: Face, в?: ВниманиеНаСцене): ЗнакВнимания | null {
  if (!в) return null
  if (в.вид === 'ученик' ? !face.isLocal : face.isLocal) return null
  return в.знаки[face.identity] ?? null
}

/** Положение счёта для этой плитки — только у учителя и только на чужих. */
export function положениеПлитки(face: Face, в?: ВниманиеНаСцене): ПоложениеСчёта | null {
  if (!в || в.вид !== 'учитель' || face.isLocal) return null
  if (в.знаки[face.identity]) return null
  return в.положения?.[face.identity] ?? null
}

/** Подпись у имени на плитке учителя. Тревоге число не нужно: «заснул» важнее,
 *  чем «0 · заснул». */
export function подписьВнимания(з: ЗнакВнимания): string {
  return з.тревога ? з.состояние : `${з.балл} · ${з.состояние}`
}

/** Знак → байты канала. Коротко: раз в секунду от каждого ученика. */
export function вБайты(з: ЗнакВнимания): Uint8Array<ArrayBuffer> {
  return new TextEncoder().encode(JSON.stringify({ б: з.балл, с: з.состояние }))
}

/** Байты канала → знак. Всё, что не похоже на наш знак, выбрасывается: в канал
 *  может написать любой клиент. Тревогу считаем сами по состоянию — чужому
 *  слову «тревога» верить незачем. */
export function изБайтов(байты: Uint8Array): ЗнакВнимания | null {
  try {
    const о = JSON.parse(new TextDecoder().decode(байты)) as { б?: unknown; с?: unknown }
    const балл = о.б
    const с = о.с
    if (typeof балл !== 'number' || !Number.isInteger(балл) || балл < 0 || балл > 100) return null
    if (typeof с !== 'string' || !Object.prototype.hasOwnProperty.call(ЦЕНА, с)) return null
    const состояние = с as Состояние
    return { балл, состояние, тревога: ТРЕВОГА.has(состояние) }
  } catch {
    return null
  }
}

/** Положение → байты: `{ п: 'заводим' | 'сбой' }`. */
export function положениеВБайты(п: ПоложениеСчёта): Uint8Array<ArrayBuffer> {
  return new TextEncoder().encode(JSON.stringify({ п: п === 'заводим' ? 'заводим' : 'сбой' }))
}

/** Что пришло по каналу внимания: балл, положение — или мусор (`null`). */
export function разобратьБайты(байты: Uint8Array): { знак: ЗнакВнимания } | { положение: ПоложениеСчёта } | null {
  const знак = изБайтов(байты)
  if (знак) return { знак }
  try {
    const о = JSON.parse(new TextDecoder().decode(байты)) as { п?: unknown }
    if (о.п === 'заводим') return { положение: 'заводим' }
    if (о.п === 'сбой') return { положение: 'не завёлся' }
    return null
  } catch {
    return null
  }
}

/** Свой счёт внимания на устройстве ученика.
 *
 *  `трек` — своя камера в комнате; `вкл` — в комнате есть ведущий, подписанный
 *  сервером, я не веду и камера включена (с 19.10 — без всякого `?внимание=1`). Возвращает знак раз в секунду (и сразу, когда сменилась причина)
 *  или `null`, пока модель не завелась или считать нечего.
 *
 *  Модель заводится один раз и живёт, пока `вкл`: выключил камеру и
 *  включил снова — заводить её заново незачем. Считаем десять кадров в секунду,
 *  как на стенде: урок рядом тоже хочет процессор. */
export function useСвоёВнимание(трек: Track | undefined, вкл: boolean, пишем = false): { знак: ЗнакВнимания | null; положение: ПоложениеСчёта | null } {
  const [знак, setЗнак] = useState<ЗнакВнимания | null>(null)
  const [сбой, setСбой] = useState(false)
  /* «Пишем» — слово ведущего (room/пишем.ts): голова над тетрадью — работа. */
  const пишемРеф = useRef(пишем)
  пишемРеф.current = пишем
  const [модель, setМодель] = useState<Счёт | null>(null)
  const движок = useRef<Внимание | null>(null)

  /* Модель: лениво, одним куском, только у того, у кого `вкл`. */
  useEffect(() => {
    if (!вкл) return
    let живо = true
    let закрыть: (() => void) | null = null
    ;(async () => {
      try {
        const л = await import('../sedum/лицо')
        const завод = await л.завести()
        if (!живо) { завод.модель.close(); return }
        закрыть = () => завод.модель.close()
        const яркомер = new л.Яркомер()
        setМодель({
          detect: (в, t) => л.разобрать(завод.модель.detectForVideo(в, t), в.videoWidth / (в.videoHeight || 1)),
          яркомер,
          оценить: л.качество,
        })
      } catch (e) {
        /* Модель не скачалась — ученику и учителю просто нечего показать. Урок
           от этого не страдает, и говорить на уроке об опыте нечего; причина —
           в консоли браузера, для того, кто проверяет опыт. */
        console.warn('[внимание] модель лица не завелась:', e)
        if (живо) setСбой(true)
      }
    })()
    return () => {
      живо = false
      закрыть?.()
      setМодель(null)
      setЗнак(null)
      setСбой(false)
    }
  }, [вкл])

  /* Камера → кадры → движок. Живёт, пока есть и модель, и камера. */
  useEffect(() => {
    if (!вкл || !трек || !модель) return
    const в = document.createElement('video')
    в.muted = true
    в.playsInline = true
    /* `attach` LiveKit сам подменит картинку, когда камеру выключат и включат
       снова: дорожка та же, источник внутри неё новый. */
    трек.attach(в)
    void в.play().catch(() => undefined)
    движок.current ??= new Внимание({ ...ПОРОГИ })

    let кадр: Кадр | null = null
    let кадрКогда = 0
    let яркость: number | null = null
    let прошлый = 0
    let цикл = 0
    const смотреть = () => {
      цикл = requestAnimationFrame(смотреть)
      const сейчас = performance.now()
      if (сейчас - прошлый < 100 || в.readyState < 2) return
      прошлый = сейчас
      try {
        яркость = модель.яркомер.замерить(в, сейчас)
        кадр = модель.detect(в, сейчас)
        кадрКогда = Date.now()
      } catch {
        /* кадр не разобрался — следующий разберётся */
      }
    }
    смотреть()

    /* Часы движка — отдельно от кадров: когда вкладка спрятана, кадры не идут,
       а часы идут и замечают «другое окно» (тот же порядок, что на стенде). */
    let прошлаяПричина: Состояние | null = null
    let отдано = 0
    const часы = window.setInterval(() => {
      const к = кадр
      const свежий = Boolean(к) && Date.now() - кадрКогда < 1500
      const и = движок.current!.шаг({
        t: Date.now(),
        экран: document.visibilityState === 'visible' && document.hasFocus(),
        лицо: Boolean(свежий && к?.лицо),
        рыск: к?.рыск ?? 0,
        тангаж: к?.тангаж ?? 0,
        глаза: к?.глаза ?? 0,
        рот: к?.рот ?? 0,
        взглядВниз: к?.взглядВниз ?? 0,
        взглядВбок: к?.взглядВбок ?? 0,
        веко: к?.веко ?? null,
        качество: к && свежий ? модель.оценить(к, яркость) : 'хорошо',
      }, пишемРеф.current)
      /* Раз в секунду — новый знак, даже если он тот же: учитель гасит знак
         по молчанию, и ровное «100 · на экране» молчанием быть не должно. */
      const пора = Date.now() - отдано >= 1000 || и.состояние !== прошлаяПричина
      if (!пора) return
      отдано = Date.now()
      прошлаяПричина = и.состояние
      setЗнак({ балл: и.балл, состояние: и.состояние, тревога: и.тревога })
    }, 250)

    return () => {
      cancelAnimationFrame(цикл)
      window.clearInterval(часы)
      трек.detach(в)
      в.srcObject = null
      setЗнак(null)
    }
  }, [вкл, трек, модель])

  if (!вкл) return { знак: null, положение: null }
  return { знак, положение: знак ? null : сбой ? 'не завёлся' : модель ? null : 'заводим' }
}
