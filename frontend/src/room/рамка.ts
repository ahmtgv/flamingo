/** Где лежит слой пометок относительно кадра показа.
 *
 *  🔴 Пометки хранятся ДОЛЯМИ страницы: 0.5 — середина страницы, а не середина
 *  тёмного поля вокруг неё. Поэтому слой обязан лежать ровно по картинке, и
 *  рамку для него меряют с самой картинки.
 *
 *  🔴 И обязан учитывать ПРОКРУТКУ. Слой лежит `position: absolute` внутри
 *  показа, а начало отсчёта у absolute — НЕпрокрученный угол. Прямоугольники же
 *  меряются от окна и уже сдвинуты прокруткой. Пока страница влезала в кадр,
 *  прокрутки не было и разницы не было тоже; с увеличением (решение владельца
 *  02.09) она появилась: без поправки увеличенная страница уезжает под пальцем,
 *  а пометки остаются на месте — и «смотрите вот здесь» показывает не туда.
 *
 *  Вынесено отдельной чистой функцией, чтобы это проверялось числами, а не
 *  глазами: караул `рамка-check.mjs`.
 */

export type Прямоугольник = { left: number; top: number; width: number; height: number }

export function рамкаПометок(
  показ: { left: number; top: number; scrollLeft: number; scrollTop: number },
  картинка: Прямоугольник,
): Прямоугольник {
  return {
    left: картинка.left - показ.left + показ.scrollLeft,
    top: картинка.top - показ.top + показ.scrollTop,
    width: картинка.width,
    height: картинка.height,
  }
}
