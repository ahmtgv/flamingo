/** Где лежит слой пометок относительно кадра показа.
 *
 *  🔴 Пометки хранятся ДОЛЯМИ страницы: 0.5 — середина страницы, а не середина
 *  тёмного поля вокруг неё. Поэтому слой обязан лежать ровно по картинке, и
 *  рамку для него меряют с самой картинки.
 *
 *  🔴 И обязан учитывать ПРОКРУТКУ. Слой лежит `position: absolute` внутри
 *  показа, а начало отсчёта у absolute — НЕпрокрученный угол. Прямоугольники же
 *  меряются от окна и уже сдвинуты прокруткой. Пока страница влезала в кадр,
 *  прокрутки не было и разницы не было тоже; с увеличением (решение владельца
 *  02.09) она появилась: без поправки увеличенная страница уезжает под пальцем,
 *  а пометки остаются на месте — и «смотрите вот здесь» показывает не туда.
 *
 *  Вынесено отдельной чистой функцией, чтобы это проверялось числами, а не
 *  глазами: караул `рамка-check.mjs`.
 */

export type Прямоугольник = { left: number; top: number; width: number; height: number }

export function рамкаПометок(
  показ: { left: number; top: number; scrollLeft: number; scrollTop: number },
  картинка: Прямоугольник,
): Прямоугольник {
  return {
    left: картинка.left - показ.left + показ.scrollLeft,
    top: картинка.top - показ.top + показ.scrollTop,
    width: картинка.width,
    height: картинка.height,
  }
}

/** Размер страницы, ВПИСАННОЙ в кадр, — от него считаются ступени увеличения.
 *
 *  🔴 Считаем, а не меряем с экрана. Мерка с экрана работает только пока
 *  страница вписана: на увеличенной она мерила бы саму себя. А знать вписанный
 *  размер надо всегда — иначе перелистнуть или войти в комнату при уже
 *  включённом увеличении нечем.
 *
 *  Кадр берётся по внешнему прямоугольнику минус отступы, а не по `clientWidth`:
 *  `clientWidth` уменьшается на ширину появившейся полосы прокрутки, полоса
 *  появляется от увеличения, увеличение считается от кадра — и кадр начинает
 *  дрожать сам от себя.
 */
export function вписать(
  кадр: { w: number; h: number },
  своя: { w: number; h: number },
): { w: number; h: number } | null {
  if (кадр.w <= 0 || кадр.h <= 0 || своя.w <= 0 || своя.h <= 0) return null
  const к = Math.min(кадр.w / своя.w, кадр.h / своя.h)
  return { w: своя.w * к, h: своя.h * к }
}

/** Ступени увеличения показа. Не «плюс десять процентов»: на уроке нужно не
 *  подобрать масштаб, а быстро приблизить и вернуться.
 *
 *  🔴 Ступени есть и НИЖЕ вписанного размера (владелец 02.09: «мне надо
 *  уменьшать ещё со стартового размера»). Вписанная страница — не край шкалы:
 *  широкий разворот удобнее отдать целиком мельче, чем он влез по высоте. */
export const СТУПЕНИ = [0.5, 0.75, 1, 1.25, 1.5, 2, 2.5, 3]

/** Соседняя ступень. `куда`: +1 крупнее, −1 мельче.
 *
 *  🔴 Берём первую ступень СТРОГО В НУЖНУЮ СТОРОНУ, а не «ближайшую плюс шаг».
 *  Через ближайшую караул меня и поймал: от 1.3 ближайшая — 1.25, шаг вниз от
 *  неё даёт 1, и «уменьшить» перепрыгивало ступень. Масштаб приезжает ещё и по
 *  каналу от ведущего, поэтому значения вне шкалы — обычное дело, а не край.
 *
 *  Уже на краю шкалы — остаёмся на месте: кнопка там и так погашена. */
export function ступень(масштаб: number, куда: 1 | -1): number {
  const рядом = куда === 1
    ? СТУПЕНИ.filter((с) => с > масштаб + 1e-6)
    : СТУПЕНИ.filter((с) => с < масштаб - 1e-6)
  if (!рядом.length) return куда === 1 ? СТУПЕНИ[СТУПЕНИ.length - 1] : СТУПЕНИ[0]
  return куда === 1 ? рядом[0] : рядом[рядом.length - 1]
}
