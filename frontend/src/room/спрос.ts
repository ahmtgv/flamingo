/** Когда вошедший переспрашивает, на что смотрит класс.
 *
 *  🔴 Заведено по живому дефекту (владелец, 02.09): «ученик не видит трансляцию
 *  учебных пособий и доски, транслируемых учителем».
 *
 *  Причина была не в эфире. Рассказать сцену пытались двое, и оба — один раз:
 *
 *  1. Ведущий слал её в тот миг, когда участник появлялся в списке
 *     (`Room.tsx`, `wasPeers`). Но участник в списке и участник, у которого
 *     открыт данные-канал, — разные мгновения: LiveKit сообщает о входе раньше,
 *     чем канал готов принимать. Сообщение уходило в никуда, и повтора не было.
 *  2. Доска спрашивала сама (`useSheets`, `asked`) — но только смонтированная и
 *     только один раз. А входят люди на «Лица», где доски нет вовсе.
 *
 *  Итог: класс смотрел на пустое место, и никто об этом не узнавал.
 *
 *  Поэтому спрашивает вошедший, спрашивает сам экран комнаты — независимо от
 *  того, какую вкладку он открыл, — и спрашивает не один раз: канал открывается
 *  за доли секунды, но на плохой связи «доли» растягиваются. Как только сцена
 *  приехала, спрос прекращается: лишний вопрос стоит ведущему рассылки всей
 *  страницы показа, а это сотни килобайт. */

/** Через сколько миллисекунд после входа переспрашивать. Четыре попытки за
 *  семь секунд: дальше молчание уже не про канал, а про то, что показывать
 *  нечего, — и лишний спрос только шумит. */
export const СРОКИ: readonly number[] = [300, 1200, 3000, 7000]

export type Спрос = {
  /** Фаза комнаты: спрашивать есть смысл только на живой связи. */
  фаза: 'connecting' | 'live' | 'failed'
  /** Веду ли занятие я. Ведущий — сам сцена, ему спрашивать не у кого. */
  веду: boolean
  /** Сколько в комнате других. Ноль — некому отвечать. */
  соседей: number
  /** Сцена уже приехала хоть каким-то сообщением. */
  сценаПришла: boolean
}

/** Сроки повторов для этого состояния. Пустой список — не спрашиваем. */
export function планСпроса(с: Спрос): number[] {
  if (с.фаза !== 'live') return []
  if (с.веду) return []
  if (с.соседей === 0) return []
  if (с.сценаПришла) return []
  return [...СРОКИ]
}
