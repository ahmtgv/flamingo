import { useEffect, useRef, useState } from 'react'

import s from './Shelf.module.css'

/** Полка источников. Что учитель выбрал — то и видит класс. */
export type Source = 'faces' | 'board' | 'show' | 'live' | 'screen'

/** 🔴 Имена с решения владельца 01.09. Полка называет вещи так, как их называют
 *  в школе, а не так, как они устроены внутри: «Класс», а не «лица».
 *
 *  Имя экрана одно и то же во всех местах продукта (ПРАВИЛА 4.9): полка, заголовки
 *  пультов и подписи в чате берут его отсюда, а не пишут своими словами.
 *
 *  🔴 «МАТЕРИАЛЫ УРОКА» — ОДНО ИМЯ ВМЕСТО СЕМИ. Приложенные к уроку файлы
 *  звались «Учебные Документы» (вкладка и заголовок панели), «Материалы для
 *  урока» (дверь в неё же), «Приложены к уроку» (группа внутри), «Пособия
 *  урока» (текст там же), «показы» (подвал), «Материалы» и «Материалы к уроку»
 *  (экран создания урока). Преподаватель прикладывал файлы в «Материалах»,
 *  искал в комнате «Материалы для урока», находил «Учебные Документы» и читал
 *  внутри про «пособия». Осмотр комнаты 08.09; решение владельца 08.09.
 *
 *  🔴 И РУССКИЙ РЕГИСТР: «Классная доска», а не «Классная Доска». Прописная
 *  внутри заголовка — калька с английского. */
export const ИМЕНА: Record<Source, string> = {
  faces: 'Класс',
  board: 'Классная доска',
  show: 'Материалы урока',
  live: 'Методички',
  screen: 'Экран преподавателя',
}

/** Одно имя приложенных к уроку файлов — и на вкладке, и на двери. */
const ИМЕНА_ПОСОБИЙ = 'Материалы урока'

/** Что лежит внутри «Методичек». Живой пока один пункт; остальные — приглушённые
 *  двери: видны, названы, не нажимаются, и рядом сказано, чего они ждут
 *  (ПРАВИЛА 12.2–12.5). Мёртвая кнопка, которая выглядит живой, хуже отсутствующей. */
const МЕТОДИЧКИ: { имя: string; ждёт?: string; экран?: true; пособия?: true }[] = [
  { имя: 'Из HUB' },
  { имя: 'Показать свой экран', экран: true },
  /* 🔴 ДВЕРЬ ЗОВЁТСЯ ТАК ЖЕ, КАК ВКЛАДКА, В КОТОРУЮ ВЕДЁТ. Раньше здесь стояло
     второе имя того же места — «Материалы для урока», — и это была одна из
     семи кличек одной вещи. Дверь остаётся: она говорит, ЧТО СДЕЛАТЬ, когда
     материалов ещё нет; но имя у места одно (ПРАВИЛА 4.9). */
  { имя: ИМЕНА_ПОСОБИЙ, пособия: true,
    ждёт: 'приложите их на экране «Создать урок» — они появятся здесь' },
  /* 🔴 СРОК, А НЕ ВЕЖЛИВЫЙ ОТКАЗ (ПРАВИЛА 12.4). Полка рисуется только
     ведущему, то есть тому, у кого учётная запись преподавателя уже есть, —
     и он читал, что дверь ждёт именно её. Осмотр комнаты 08.09, находка 17. */
  { имя: 'Избранные материалы', ждёт: 'копилка того, что показываете часто — появится после кабинета' },
  { имя: 'Подключить…', ждёт: 'свои телескопы, дроны, серверы и библиотеки — после кабинета' },
]

/** Дверь, которой ещё нет. Плашка с именем, а не строка текста. */
const NOT_YET = 'Учебник'

export function Shelf({ source, естьПособия, onPick, onShow, onHub, onShare }: {
  source: Source
  /** Есть ли у занятия приложенные пособия: от этого зависит, живая ли дверь
   *  «Материалы для урока» или всё ещё ждёт. */
  естьПособия: boolean
  onPick: (s: Source) => void
  /** Показ начинается с выбора файла, поэтому у него своя дорога, а не просто вкладка. */
  onShow: () => void
  /** Трансляция начинается с выбора источника — тоже своя дорога. */
  onHub: () => void
  /** Показ экрана: браузер сам спросит, чем делиться. */
  onShare: () => void
}) {
  const [open, setOpen] = useState(false)
  const box = useRef<HTMLDivElement>(null)

  useEffect(() => {
    if (!open) return
    const away = (e: PointerEvent) => {
      if (!box.current?.contains(e.target as Node)) setOpen(false)
    }
    const esc = (e: KeyboardEvent) => {
      if (e.key === 'Escape') setOpen(false)
    }
    window.addEventListener('pointerdown', away)
    window.addEventListener('keydown', esc)
    return () => {
      window.removeEventListener('pointerdown', away)
      window.removeEventListener('keydown', esc)
    }
  }, [open])

  const вкладка = (кто: Source, нажать: () => void) => (
    <button
      type="button"
      role="tab"
      aria-selected={source === кто}
      className={`${s.item} ${source === кто ? s.on : ''}`}
      onClick={нажать}
    >
      {ИМЕНА[кто]}
    </button>
  )

  return (
    <div className={s.shelf}>
      <div className={s.tabs} role="tablist" aria-label="Что показывают классу">
        {вкладка('faces', () => onPick('faces'))}
        {вкладка('board', () => onPick('board'))}
        {вкладка('show', onShow)}

        {/* «Методички» — не одна дверь, а полка внутри полки. */}
        <div className={s.pack} ref={box}>
          <button
            type="button"
            role="tab"
            aria-selected={source === 'live'}
            aria-expanded={open}
            className={`${s.item} ${source === 'live' ? s.on : ''}`}
            onClick={() => setOpen((v) => !v)}
          >
            {ИМЕНА.live}
          </button>
          {open ? (
            <div className={s.packMenu} role="menu" aria-label="Методички">
              {МЕТОДИЧКИ.map((м) =>
                м.ждёт && !(м.пособия && естьПособия) ? (
                  <span key={м.имя} className={s.packDoor} aria-disabled="true" tabIndex={-1}>
                    {м.имя}
                    <span className={s.packWhy}>{м.ждёт}</span>
                  </span>
                ) : (
                  <button
                    key={м.имя}
                    type="button"
                    className={s.packItem}
                    onClick={() => {
                      setOpen(false)
                      if (м.экран) onShare()
                      else if (м.пособия) onShow()
                      else onHub()
                    }}
                  >
                    {м.имя}
                  </button>
                ),
              )}
            </div>
          ) : null}
        </div>
      </div>

      {/* ПРАВИЛА 12.4: говорим о сроке, а не о запрете. 12.5: дверь не нажимается
          по-настоящему, и читалка экрана об этом знает. */}
      <p className={s.notYet}>
        <span className={s.notYetName} aria-disabled="true" tabIndex={-1}>{NOT_YET}</span>
        <span className={s.notYetWhy}>появится вместе с курсом</span>
      </p>
    </div>
  )
}
