import s from './Sleepy.module.css'

/** Пульт спит, пока рука не пошла в его зону.
 *
 *  Решение владельца 30.08: «при наведении мышкой на поле, где должна быть панель,
 *  она открывается — в таком случае да». Доска от этого становится по-настоящему
 *  безграничной: холст занимает весь экран, а управление появляется под рукой.
 *
 *  Прячем ВИДИМОСТЬЮ, а не прозрачностью: приглушённый пульт с текстом — это
 *  нечитаемый текст, а не «тише» (ПРАВИЛА 4.7).
 */
export function Sleepy({
  side, children, label, open,
}: {
  side: 'top' | 'bottom' | 'left'
  children: React.ReactNode
  /** Что здесь лежит — написано на спящей полоске, иначе о пульте не догадаться. */
  label: string
  /** Открыт ли пульт. Считает кромку `useEdge`: зона наведения не может быть
   *  элементом, не отнимая событий у холста. */
  open: boolean
}) {
  return (
    <div className={`${s.zone} ${s[side]}`} data-pult={label}>
      {open ? <div className={s.body}>{children}</div> : <span className={s.hint}>{label}</span>}
    </div>
  )
}
