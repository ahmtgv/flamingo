import { подписьВнимания, type ЗнакВнимания } from './внимание'
import s from './ВниманиеНаПлитке.module.css'

/** Внимание SEduM на плитке — вариант 2, утверждён владельцем 05.10.
 *
 *  У учителя (`сЦифрой`) — число и причина тихим текстом у имени и полоска
 *  внизу; у ученика — одна полоска, без цифр. Коралловый — только «заснул» и
 *  «ушёл», и только у учителя: ученику тревожная полоска ничего не объяснит,
 *  а напугает.
 *
 *  Одна разметка на сцену и на полосу превью: два места, нарисованные по
 *  отдельности, однажды разъедутся. Где стоит подпись относительно имени,
 *  решает ширина плитки (стили — в модуле рядом). */
export function ВниманиеНаПлитке({ знак, сЦифрой }: { знак: ЗнакВнимания; сЦифрой: boolean }) {
  const тревога = сЦифрой && знак.тревога
  return (
    <>
      {/* Тревоге число не нужно; иначе «число · причина». На самой узкой
          плитке (полоса превью над доской) остаётся одно число — причина
          прячется, но не теряется: она в подсказке под мышью. */}
      {сЦифрой ? (
        <span className={`${s.причина} ${тревога ? s.тревога : ''}`} data-причина title={подписьВнимания(знак)}>
          {знак.тревога ? знак.состояние : (
            <>
              {знак.балл}
              <span className={s.хвост}> · {знак.состояние}</span>
            </>
          )}
        </span>
      ) : null}
      <span className={s.полоса} aria-hidden>
        <span className={`${s.заливка} ${тревога ? s.заливкаТревога : ''}`} style={{ width: `${знак.балл}%` }} />
      </span>
    </>
  )
}
