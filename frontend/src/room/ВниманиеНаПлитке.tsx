import { СЛОВА_ПОЛОЖЕНИЯ, подписьВнимания, type ЗнакВнимания, type ПоложениеСчёта } from './внимание'
import s from './ВниманиеНаПлитке.module.css'

/** Внимание SEduM на плитке — вариант 2, утверждён владельцем 05.10.
 *
 *  У учителя (`сЦифрой`) — число и причина тихим текстом у имени и полоска
 *  внизу; у ученика — полоска и тихое «учитель видит внимание» (19.10), без
 *  цифр. Балла ещё нет — у учителя слова «загружается» или «не считается».
 *  Коралловый — только «заснул» и «ушёл», и только у учителя: ученику
 *  тревожная полоска ничего не объяснит, а напугает.
 *
 *  Одна разметка на сцену и на полосу превью: два места, нарисованные по
 *  отдельности, однажды разъедутся. Где стоит подпись относительно имени,
 *  решает ширина плитки (стили — в модуле рядом). */
export function ВниманиеНаПлитке({ знак, положение = null, сЦифрой }: {
  знак: ЗнакВнимания | null
  /** Только у учителя: балла нет — и почему (room/внимание.ts). */
  положение?: ПоложениеСчёта | null
  сЦифрой: boolean
}) {
  /* Балла нет, есть положение: тихие слова на месте причины, без полоски —
     полоска без балла соврала бы ноль. */
  if (!знак) {
    if (!положение || !сЦифрой) return null
    const слова = СЛОВА_ПОЛОЖЕНИЯ[положение]
    return (
      <span className={s.причина} data-причина data-положение={положение} title={слова.подробно}>
        {слова.коротко}
      </span>
    )
  }
  const тревога = сЦифрой && знак.тревога
  return (
    <>
      {/* Тревоге число не нужно; иначе «число · причина». На самой узкой
          плитке (полоса превью над доской) остаётся одно число — причина
          прячется, но не теряется: она в подсказке под мышью. */}
      {сЦифрой ? (
        <span className={`${s.причина} ${тревога ? s.тревога : ''}`} data-причина title={подписьВнимания(знак)}>
          {знак.тревога ? знак.состояние : (
            <>
              {знак.балл}
              <span className={s.хвост}> · {знак.состояние}</span>
            </>
          )}
        </span>
      ) : (
        /* 🔴 УЧЕНИК ЗНАЕТ, ЧТО ЕГО ВИДЯТ (решение владельца 19.10): тихая
           надпись у своей полоски. Знак у ученика бывает, только когда в
           комнате есть ведущий, — значит, надпись не врёт. */
        <span className={s.причина} data-видит title="Учитель видит ваше внимание: число и причину. Никуда больше оно не уходит и нигде не хранится.">
          учитель видит внимание
        </span>
      )}
      <span className={s.полоса} aria-hidden>
        <span className={`${s.заливка} ${тревога ? s.заливкаТревога : ''}`} style={{ width: `${знак.балл}%` }} />
      </span>
    </>
  )
}
