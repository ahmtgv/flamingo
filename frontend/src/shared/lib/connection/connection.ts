/**
 * СВЯЗЬ — ОДНА НА ВЕСЬ ПРОДУКТ (решение владельца §32.3, наряд 34 §2.2).
 *
 * 🔴 ЧТО ЭТО ЧИНИТ. Замер слабого канала (промпт 31 §2.2) показал: продукт открывается даже
 * на 128 Кбит — за 29 секунд, — и **на всех четырёх ступенях экран говорит одно и то же**.
 * Ни слова о канале. Человек на плохом 3G десять секунд смотрит в пустоту и решает, что
 * сломалось. Отдельно (§2.1-б) преподаватель рисовал во время провала связи, штрих пропадал,
 * и ему не говорили ни слова.
 *
 * Механизм ОДИН, а не по экрану на случай. Здесь — только вывод из наблюдений; как он выглядит
 * — в `shared/ui/ConnectionLine`, и это тоже одно место.
 *
 * ТРИ ПРАВИЛА, КОТОРЫЕ ЗАДАЛ ВЛАДЕЛЕЦ:
 *
 * 1. **Тихо на обычных экранах, заметно на уроке.** Одно и то же состояние, разная громкость —
 *    поэтому громкость здесь НЕ решается: её выбирает экран.
 * 2. **Сказать, что происходит, а не «что-то пошло не так».** Отсюда `ConnectionWord` — слово,
 *    а не код ошибки, и `since` — с какого момента, чтобы «сейчас медленно» отличалось от
 *    «медленно уже минуту».
 * 3. **Не мигающая плашка на каждый запрос.** Один неудачный запрос — не потеря связи;
 *    один быстрый — не её возвращение. Поэтому пороги и гистерезис ниже, а не «покажем сразу».
 */

/** Те же четыре слова, что у рамы приложения (`features/desktop/hostState.ts`). */
export type ConnectionWord = 'good' | 'weak' | 'none' | 'unmeasured';

export interface Observation {
  /** Дошёл ли запрос до сервера вообще (не «ответил ли отказом» — отказ это связь). */
  reached: boolean;
  /** Сколько заняло, мс. */
  ms: number;
}

/**
 * Сколько подряд не дошедших запросов считаем потерей связи.
 *
 * ⚠️ Не один. Один отвалившийся запрос бывает у всех и проходит сам; плашка на него — это
 * ровно то мигание, которое владелец запретил. Два подряд — уже не случайность.
 */
export const LOST_AFTER = 2;

/** Медленным считаем ответ дольше этого — по замеру: 3G плохой даёт ~10 с на первый экран. */
export const SLOW_MS = 2_500;

/** Сколько последних наблюдений держим. Меньше — дёргается, больше — узнаёт о беде поздно. */
export const WINDOW = 5;

export interface ConnectionFacts {
  /** Что говорит браузер. Ему верим только в одну сторону — см. ниже. */
  browserOnline: boolean;
  /** Последние наблюдения, новое в конце. */
  recent: readonly Observation[];
}

/**
 * Слово о связи из наблюдений.
 *
 * 🔴 БРАУЗЕРУ ВЕРИМ ТОЛЬКО В ОДНУ СТОРОНУ. `navigator.onLine === false` — это точно нет сети
 * (замерено: `setOffline` доводит событие до страницы). А `true` не значит ничего: вайфай
 * школы отвечает `true`, пока запросы не доходят никуда. Поэтому «нет связи» ставится и по
 * браузеру, и по запросам, а «связь есть» — только по запросам.
 */
export function connectionWord({ browserOnline, recent }: ConnectionFacts): ConnectionWord {
  if (!browserOnline) return 'none';
  if (recent.length === 0) return 'unmeasured';

  const tail = recent.slice(-LOST_AFTER);
  if (tail.length === LOST_AFTER && tail.every((o) => !o.reached)) return 'none';

  const arrived = recent.slice(-WINDOW).filter((o) => o.reached);
  if (arrived.length === 0) return 'none';

  // «Слабая» — не про один медленный ответ, а про то, что медленно СТАЛО ОБЫЧНЫМ: больше
  // половины последних. Иначе одна тяжёлая картинка красила бы канал в жёлтый на весь урок.
  const slow = arrived.filter((o) => o.ms >= SLOW_MS).length;
  return slow * 2 > arrived.length ? 'weak' : 'good';
}

/**
 * Гистерезис: слово меняется не мгновенно.
 *
 * Ухудшение показываем сразу — человеку нужно знать, что связи нет, в ту же секунду.
 * Улучшение придерживаем: канал, дёрнувшийся на один хороший запрос, ещё не вернулся, а
 * плашка, гаснущая и загорающаяся, — это мигание, а не сообщение.
 */
export const RECOVERY_MS = 3_000;

const RANK: Record<ConnectionWord, number> = { good: 3, unmeasured: 2, weak: 1, none: 0 };

export function settle(
  previous: { word: ConnectionWord; since: number },
  next: ConnectionWord,
  now: number,
): { word: ConnectionWord; since: number } {
  if (next === previous.word) return previous;
  if (RANK[next] < RANK[previous.word]) return { word: next, since: now };
  return now - previous.since >= RECOVERY_MS ? { word: next, since: now } : previous;
}
