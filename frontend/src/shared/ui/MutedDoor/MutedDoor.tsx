import styles from './MutedDoor.module.css';

/**
 * Дверь, которая видна и названа, но не нажимается, — и рядом сказано, почему (§59).
 *
 * 🔴 Правило владельца: «старого ничего не оставляем — либо дорисовываем, либо мьютим».
 * Убрать дверь — выдумать ограничение продукта; оставить дверь в неоформленный экран —
 * оставить тупик. Третье честнее обоих.
 *
 * 🔒 Приглушение — ЦВЕТОМ И ВЕСОМ, не прозрачностью (правило 4.7): причина, по которой
 * нельзя, обязана читаться. Прозрачность съедает контраст незаметно для токенов и заметно
 * для глаза, а эту строку человек должен прочесть — она и есть смысл.
 */
export function MutedDoor({ label, why }: { label: string; why: string }) {
  return (
    <span className={styles.door} role="note">
      <span className={styles.label}>{label}</span>
      <span className={styles.why}>{why}</span>
    </span>
  );
}
