import { Mark } from '../ui/Mark'
import s from './BadLink.module.css'

/** Ссылка вида `/r/…`, код в которой прочитать не удалось.
 *
 *  🔴 Зачем отдельный экран. Пока была посадочная страница, битая ссылка молча
 *  приводила на неё — человек видел хоть что-то знакомое. Посадочной страницы
 *  больше нет (решение владельца 01.09), и без этого экрана ученик с обрезанной
 *  ссылкой попадал бы на форму входа: продукт требовал бы регистрации там, где
 *  на самом деле просто не дочитал адрес. Это ровно тот случай, когда молчание —
 *  дефект (ПРАВИЛА 6.3): сказано, что не так, как выглядит правильный адрес
 *  и что делать дальше.
 */
export function BadLink({ адрес, onWay, вошёл }: {
  /** Что именно пришло. Показываем: чаще всего видно, где ссылка оборвалась. */
  адрес: string
  onWay: () => void
  вошёл: boolean
}) {
  return (
    <main className={s.screen}>
      <div className={s.card}>
        <Mark />
        <h1 className={s.title}>Ссылка на урок не читается</h1>
        <p className={s.lead}>
          Код комнаты в адресе неполный или в нём есть лишние знаки. Чаще всего
          ссылку скопировали не до конца или она разорвалась при пересылке.
        </p>

        <code className={s.shape}>{адрес}</code>

        <p className={s.foot}>
          Целая ссылка выглядит так: <b>flamingo.plus/r/xxxx-xxxx-xxxx</b> — три
          группы по четыре знака. Попросите преподавателя прислать её ещё раз
          и откройте нажатием, а не копированием.
        </p>

        <button type="button" className={s.way} onClick={onWay}>
          {вошёл ? 'В кабинет' : 'Ко входу'}
        </button>
      </div>
    </main>
  )
}
