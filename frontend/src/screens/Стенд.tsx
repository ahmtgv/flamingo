import { useState } from 'react'

import { Chat, type Line } from '../room/Chat'
import type { Реплика } from '../lib/study'
import { Переписка } from './Переписка'

/** Стенд панелей: посмотреть чат и переписку без сервера.
 *
 *  🔴 ТОЛЬКО В РАЗРАБОТКЕ. В `App.tsx` этот экран стоит под
 *  `import.meta.env.DEV` и в боевую сборку не попадает вовсе — сборщик вырежет
 *  ветку целиком. Проверяется глазами: в собранном `dist` слова «стенд» нет.
 *
 *  Зачем он есть. Обе панели живут глубоко: чат — внутри комнаты, за билетом
 *  LiveKit; переписка — внутри кабинета, за учётной записью. Локально ни того,
 *  ни другого нет, и посмотреть на панель было негде — приходилось катить на
 *  боевое, чтобы увидеть цвет кнопки. Здесь они открываются сразу и с
 *  подложенными репликами.
 */

const РЕПЛИКИ: Line[] = [
  { id: '1', who: 'Люция Валерьевна', text: 'Открыла доску, начинаем со второго упражнения.', at: Date.now() - 900000, mine: false },
  { id: '2', who: 'Аня', text: 'а можно ссылку на словарь? tass.ru', at: Date.now() - 600000, mine: false },
  { id: '3', who: 'вы', text: 'да', at: Date.now() - 300000, mine: true },
  { id: '4', who: 'Марк', text: 'я не слышу звук, перезайду', at: Date.now() - 60000, mine: false },
]

/* Разговор двоих: половина реплик от преподавателя, половина от ученика.
   `мой` здесь — «моё письмо»; сторону панель выбирает ролью, а не этим полем. */
const РАЗГОВОР = (яУчитель: boolean): Реплика[] => {
  const час = (н: number) => new Date(Date.now() - н * 60000).toISOString()
  const от = (учитель: boolean) => (яУчитель ? учитель : !учитель)
  return [
    { id: 'a', вид: 'text', текст: 'Аня, к четвергу повторите вторую главу.', когда: час(120), мой: от(true), прочитано: true },
    { id: 'b', вид: 'text', текст: 'хорошо! а задание которое вы показывали на доске тоже?', когда: час(90), мой: от(false), прочитано: true },
    { id: 'c', вид: 'text', текст: 'Да, оба. Разберём в начале занятия.', когда: час(60), мой: от(true), прочитано: true },
    { id: 'd', вид: 'text', текст: 'ок, спасибо', когда: час(5), мой: от(false), прочитано: false },
  ] as Реплика[]
}

export function Стенд() {
  const [строки, setСтроки] = useState(РЕПЛИКИ)
  const [ктоЯ, setКтоЯ] = useState<'учитель' | 'ученик'>('учитель')

  return (
    <main style={{ height: '100%', position: 'relative', overflow: 'hidden' }}>
      <div style={{ padding: 20, display: 'grid', gap: 8, justifyItems: 'start' }}>
        <h1 style={{ margin: 0 }}>Стенд панелей</h1>
        <p style={{ margin: 0 }}>
          Обе панели возятся за шапку и тянутся за угол. Переписка показана глазами
          {ктоЯ === 'учитель' ? ' преподавателя' : ' ученика'}: сторона выбирается ролью,
          поэтому разговор выглядит одинаково с обеих сторон.
        </p>
        <button type="button" onClick={() => setКтоЯ((к) => (к === 'учитель' ? 'ученик' : 'учитель'))}>
          Смотреть глазами {ктоЯ === 'учитель' ? 'ученика' : 'преподавателя'}
        </button>
      </div>

      {/* Каждая панель в своей половине: иначе переписка (fixed, z-index 30)
          закрывает чат (absolute, z-index 3) и на стенде видно только одну. */}
      <div style={{ position: 'absolute', inset: '0 50% 0 0' }}>
      <Chat
        lines={строки}
        alive
        onClose={() => undefined}
        onSend={(t) => setСтроки((с) => [...с, { id: String(с.length + 1), who: 'вы', text: t, at: Date.now(), mine: true }])}
        onOpen={() => undefined}
      />
      </div>

      <Переписка
        кто="собеседник"
        имя={ктоЯ === 'учитель' ? 'Аня' : 'Люция Валерьевна'}
        веду={ктоЯ === 'учитель'}
        подложка={РАЗГОВОР(ктоЯ === 'учитель')}
        onClose={() => undefined}
      />
    </main>
  )
}
