import { useState } from 'react'

import { Button } from '../ui/Button'
import s from './Vitrina.module.css'

/** Витрина: чужая страница, показанная У НАС, а не в новой вкладке.
 *
 *  🔴 Решение Аделя 31.08: все ссылки из HUB открываются в самом занятии.
 *  Поэтому мы больше не решаем ЗА браузер, что встроится, а что нет: рамка
 *  ставится всегда и пробует показать.
 *
 *  🔴 Но соврать тут нельзя. Чужой сайт вправе запретить показ внутри чужой рамки
 *  (X-Frame-Options, frame-ancestors), и очень многие запрещают. Снаружи мы этого
 *  НЕ ВИДИМ: браузер не даёт заглянуть в чужую рамку и не говорит, что там пусто.
 *  Значит единственная честная вещь — сказать заранее, что делать, если пусто,
 *  и держать адрес под рукой. Строка стоит всегда, а не появляется по ошибке
 *  (ПРАВИЛА 6.6): иначе макет прыгает ровно в ту секунду, когда человек растерян.
 */
export function Vitrina({ url, name, onВкладкой }: {
  url: string
  name: string
  /** 🔴 ВАРИАНТ Б (владелец, 06.11): у ведущего — показать сайт классу
   *  вкладкой браузера. Сайт, который не пускает в рамку, во вкладке
   *  открывается всегда, а класс видит и слышит ровно её. Два шага, потому что
   *  браузер даёт на одно нажатие одно действие: открыть вкладку ИЛИ спросить,
   *  чем делиться. Нет пропа — витрина как была (у ученика и в «Источниках»). */
  onВкладкой?: () => void
}) {
  const [открыт, setОткрыт] = useState(false)
  let host = url
  try {
    host = new URL(url).host
  } catch {
    host = url
  }
  return (
    <div className={s.box}>
      <iframe
        className={s.frame}
        src={url}
        title={name}
        allow="autoplay; fullscreen; picture-in-picture"
        sandbox="allow-scripts allow-same-origin allow-presentation allow-forms allow-popups"
      />
      <div className={s.foot}>
        <span className={s.host}>{host}</span>
        <span className={s.why}>
          Пусто? Значит сайт запрещает показ у себя внутри рамки — это его право,
          а не наша поломка. Покажите его экраном или дайте адрес классу.
        </span>
        {onВкладкой ? (
          <span className={s.вкладка}>
            {открыт ? (
              <>
                <span className={s.why}>
                  Сайт открыт в новой вкладке. Когда он загрузится, нажмите и выберите
                  эту вкладку в окне браузера. Если на сайте видео — оставьте галочку
                  «Поделиться звуком вкладки».
                </span>
                <Button kind="go" onClick={onВкладкой}>Показать вкладку классу</Button>
              </>
            ) : (
              <Button onClick={() => { window.open(url, '_blank', 'noopener'); setОткрыт(true) }}>
                Открыть сайт во вкладке, чтобы показать классу
              </Button>
            )}
          </span>
        ) : null}
      </div>
    </div>
  )
}
