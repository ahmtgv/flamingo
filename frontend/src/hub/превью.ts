/** Снимки источников: спрашиваем один раз на всю страницу.
 *
 *  🔴 СНАЧАЛА СПИСОК, ПОТОМ КАРТИНКИ. Можно было просто поставить `<img>` на
 *  каждый источник и ловить ошибку, но тогда на первом экране случается шесть
 *  запросов, которые сервер честно отбивает четырьмястами четырьмя, а в каталоге
 *  — тридцать шесть. Сорок красных строк в консоли неотличимы от поломки, да и
 *  чужому серверу это не нужно. Один маленький запрос отвечает на вопрос «у кого
 *  снимок уже есть», и картинки просим только у них.
 *
 *  🔴 НЕТ ОТВЕТА — НЕ БЕДА. Обход мог ещё ни разу не пройти, сервер мог молчать:
 *  тогда список пуст, и каждая плитка показывает нарисованную обложку, как
 *  показывала до сих пор. Витрина от отсутствия снимков не ломается.
 */
const БАЗА = String(import.meta.env.VITE_AUTH_URL ?? '').replace(/\/$/, '')

let спрошено: Promise<Set<string>> | null = null

export function снимки(): Promise<Set<string>> {
  if (!спрошено) {
    спрошено = fetch(`${БАЗА}/api/hub/previews`)
      .then((о) => (о.ok ? о.json() : { есть: [] }))
      .then((д) => new Set<string>(Array.isArray(д?.есть) ? д.есть : []))
      .catch(() => new Set<string>())
  }
  return спрошено
}

export function адресСнимка(id: string): string {
  return `${БАЗА}/api/hub/preview/${encodeURIComponent(id)}`
}
