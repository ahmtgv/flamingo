import type { Kind } from './sources'

/** Обложка источника.
 *
 *  🔴 На листе дизайна место под превью пустое: «снимки источников кладёт владелец
 *  перетаскиванием». Хранилища картинок у нас пока нет, а тридцать шесть пустых
 *  серых прямоугольников читаются как поломка, а не как «сюда положат снимок».
 *  Поэтому обложка РИСУЕТСЯ САМА — тем же приёмом, что и обложки курсов
 *  (ПРАВИЛА 10.4: «обложка не требует картинки»). Когда появится хранилище,
 *  настоящий снимок просто встанет на это место.
 *
 *  Цвета у обложки нет намеренно: вид источника уже назван словом в карточке,
 *  а пять новых цветов ради украшения — это ёлка (ПРАВИЛА 5.4). Отличает виды
 *  форма мотива, а не краска.
 */

/** Из имени делается число: одна и та же карточка всегда получает один и тот же
 *  мотив. Случайность здесь была бы враньём — обложка перестала бы узнаваться. */
function семя(id: string): number {
  let h = 0
  for (let i = 0; i < id.length; i += 1) h = (h * 31 + id.charCodeAt(i)) % 9973
  return h
}

function мотив(kind: Kind, h: number) {
  const a = (h % 7) * 8
  const b = (h % 5) * 11
  const c = (h % 11) * 4

  if (kind === 'снимки') {
    return (
      <>
        <circle cx={60 + a} cy={64} r={38 + (h % 9)} />
        <circle cx={148 + b} cy={40 + c} r={22 + (h % 7)} />
        <circle cx={196} cy={96 - (h % 13)} r={13} />
      </>
    )
  }
  if (kind === 'данные') {
    return (
      <>
        {[0, 1, 2, 3, 4, 5, 6].map((i) => (
          <rect key={i} x={26 + i * 26} y={104 - ((h + i * 17) % 60) } width="12"
                height={((h + i * 17) % 60) + 6} rx="3" />
        ))}
      </>
    )
  }
  if (kind === 'карты') {
    return (
      <>
        <path d={`M8 96 C 60 ${60 - (h % 20)}, 120 ${104 + (h % 14)}, 232 ${56 + (h % 18)}`} fill="none" />
        <path d={`M8 60 C 70 ${100 - (h % 16)}, 130 ${44 + (h % 12)}, 232 ${92 - (h % 10)}`} fill="none" />
        <circle cx={80 + a} cy={72} r="6" />
      </>
    )
  }
  if (kind === 'книги') {
    return (
      <>
        {[0, 1, 2, 3].map((i) => (
          <rect key={i} x={30 + i * 46} y={40 + ((h + i * 23) % 22)} width="30"
                height={80 - ((h + i * 23) % 22)} rx="4" />
        ))}
      </>
    )
  }
  return (
    <>
      {[0, 1, 2, 3].map((i) => (
        <circle key={i} cx={120} cy={68} r={16 + i * 20 + (h % 6)} fill="none" />
      ))}
    </>
  )
}

export function Cover({ id, kind }: { id: string; kind: Kind }) {
  const h = семя(id)
  return (
    <svg
      className="cover"
      viewBox="0 0 240 132"
      preserveAspectRatio="xMidYMid slice"
      width="100%"
      height="100%"
      aria-hidden="true"
      fill="var(--color-border-strong)"
      stroke="var(--color-border-strong)"
      strokeWidth="2"
      opacity="0.55"
    >
      {мотив(kind, h)}
    </svg>
  )
}
