/** Две личные подборки источников: «избранное» и «к уроку».
 *
 *  Живут в этом браузере, а не на сервере: каталог открыт и гостю, у которого
 *  учётной записи нет вовсе. Отсюда честное следствие — на другом устройстве
 *  подборка своя. Хранилище может быть закрыто (частное окно): тогда подборка
 *  держится до закрытия страницы и молча пропадает, экран от этого не падает.
 *
 *  «К уроку» читает комната урока (`room/HubPick`): отложенные источники стоят
 *  в её списке первыми — учителю остаётся одно нажатие, чтобы показать классу.
 */

export type Подборка = 'избранное' | 'к-уроку'

const КЛЮЧ: Record<Подборка, string> = {
  'избранное': 'fl-hub-избранное',
  'к-уроку': 'fl-hub-к-уроку',
}

export function прочесть(что: Подборка): string[] {
  try {
    const сырое = window.localStorage.getItem(КЛЮЧ[что])
    const список: unknown = сырое ? JSON.parse(сырое) : []
    return Array.isArray(список) ? список.filter((x): x is string => typeof x === 'string') : []
  } catch {
    return []
  }
}

export function записать(что: Подборка, список: string[]): void {
  try {
    window.localStorage.setItem(КЛЮЧ[что], JSON.stringify(список))
  } catch { /* хранилище закрыто — подборка живёт до закрытия страницы */ }
}
