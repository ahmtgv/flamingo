import { useEffect } from 'react';

import { useHostHeartbeatMutation } from '@/entities/graphql/generated';

import { isDesktop } from './bridge';
import { machineKeyInMemory } from './machineKey';

/**
 * 🔴 ПУЛЬС МАШИНЫ ПРЕПОДАВАТЕЛЯ. Найдено аудитом 17.08 (находка Н-1).
 *
 * Мутация `hostHeartbeat` существовала с первого дня и **не вызывалась ниоткуда**: во всём
 * фронте не было даже документа операции. Из-за этого `Device.last_seen_at` двигал только
 * замер канала на шаге 4 мастера — один раз за всю жизнь машины.
 *
 * Через две минуты после настройки присутствие гасло навсегда, и дальше рушилось четыре вещи:
 *
 * 1. ученик у двери всегда читал «преподаватель не в сети» — ветка `live` экрана прибытия
 *    была недостижима в принципе;
 * 2. `hostPresenceChanged` не публиковался ни разу (его шлёт только `heartbeat_for`);
 * 3. 🔴 `close_abandoned_sessions` считала молчание от ПЛАНОВОГО конца и через десять минут
 *    закрывала ЖИВОЙ урок под преподавателем;
 * 4. в дневник ученика уезжало `end_at`, равное метке из мастера, — то есть время окончания
 *    РАНЬШЕ начала.
 *
 * ⚠️ Ни один из 1160 тестов этого не поймал: серверные тесты зовут `heartbeat_for(device)`
 * напрямую, минуя то место, где обрыв. Отсюда правило, которое стоит завести отдельно:
 * у каждой мутации спрашивать, кто её зовёт со стороны продукта.
 *
 * Период — минута: окно присутствия на сервере две (`HEARTBEAT_WINDOW`), и один пропущенный
 * удар не должен гасить преподавателя посреди урока.
 */
const BEAT_MS = 60_000;

export function useHeartbeat(): void {
  const [beat] = useHostHeartbeatMutation();

  useEffect(() => {
    // Только приложение и только связанное: в браузере машины нет, а без ключа мутация
    // всё равно получит отказ — и получит его раз в минуту, засоряя лог сервера.
    if (!isDesktop()) return;

    const send = () => {
      if (!machineKeyInMemory()) return;
      // Отказ здесь не показывают: пульс — фон, а не действие человека. Но и не глотаем
      // молча ради самого молчания — сервер узнает о пропаже сам, по истечении окна.
      void beat().catch(() => undefined);
    };

    send();
    const id = window.setInterval(send, BEAT_MS);
    return () => window.clearInterval(id);
  }, [beat]);
}
