import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { describe, expect, it } from 'vitest';

/**
 * 🔴 НАДПИСЬ МОЖНО НАПИСАТЬ (наряд 51 §2).
 *
 * Инструмент «Текст» клал на холст слово-заглушку и на этом заканчивался: ввода не было
 * ни при создании, ни по двойному щелчку — владелец сказал «текст написать невозможно»,
 * и прибор `scripts/board-tools.mjs` это подтвердил на свободном месте холста.
 *
 * Поведение целиком проверяется живым прибором (он печатает слово и смотрит, осталось ли
 * оно на доске). Здесь — правила, которые нельзя потерять при следующей правке файла.
 */
const src = readFileSync(resolve(__dirname, 'BoardCanvas.tsx'), 'utf8');

describe('надпись на доске', () => {
  it('создание надписи открывает ввод', () => {
    expect(src).toMatch(/setEditing\(\{ id: saved\.id/);
  });

  it('двойной щелчок по надписи открывает правку', () => {
    expect(src).toMatch(/e\.detail === 2/);
    expect(src).toMatch(/hit\?\.kind === 'TEXT'/);
  });

  it('новая надпись создаётся пустой, а не со словом-заглушкой', () => {
    // Заглушка на холсте — не текст, а мусор, который человек стирает руками.
    expect(src).not.toMatch(/text: tool === 'text' \? t\('newText'\)/);
  });

  it('пустая надпись не остаётся на доске', () => {
    expect(src).toMatch(/if \(!text\) \{[\s\S]*?remove\(/);
  });

  it('🔴 порог штриха не понижен (наряд 47 §5)', () => {
    // Соседнее правило, которое легко задеть, правя тот же файл: случайное движение мышью
    // не должно пачкать урок навсегда.
    expect(src).toMatch(/MIN_STROKE_POINTS = 3/);
    expect(src).toMatch(/MIN_STROKE_LENGTH = 6/);
  });
});
