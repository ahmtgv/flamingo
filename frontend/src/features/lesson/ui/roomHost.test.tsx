import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { describe, expect, it } from 'vitest';

/**
 * 🔴 КОМНАТУ ВЫБИРАЕТ ЗАНЯТИЕ, А НЕ РОЛЬ УЧЁТКИ (наряд 47 §4).
 *
 * Владелец 23.08 — преподаватель и владелец курса — попал в ученическую комнату: выбор
 * стоял на `me.role === 'TEACHER'`, а `session.teacherId` рядом лежал и не сравнивался
 * ни с чем. Оттуда же двойная плитка в `ClassPane` и растянутая на 70 % пустая камера.
 *
 * Проверка читает исходник, а не отрисовку, — намеренно: правило «решаем по занятию»
 * должно держаться и в тех ветках комнаты, которые тестами ещё не покрыты, и в тех,
 * которые допишут завтра.
 */
const src = readFileSync(resolve(__dirname, 'LiveRoomScreen.tsx'), 'utf8');

describe('кто ведёт это занятие', () => {
  it('выбор комнаты сравнивает ведущего занятия с собой', () => {
    expect(src).toMatch(/session\.teacherId === meData\.me\.id/);
  });

  it('роль учётки больше не решает, кто в комнате преподаватель', () => {
    // Именно эта строка отправила владельца в ученическую комнату.
    expect(src).not.toMatch(/meData\?\.me\?\.role === 'TEACHER' \? \(\s*<TeacherRoom/);
  });

  it('до ответа `me` комната не выбирается вовсе', () => {
    // Иначе преподаватель уезжает в ученическую комнату по гонке кэша, а `MarkPresent`
    // отмечает его присутствующим учеником собственного занятия.
    expect(src).toMatch(/\(!session \|\| !meData\?\.me\)/);
  });
});
