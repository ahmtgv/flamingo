"""Удалить добровольца целиком: папку записей и строки в базе.

Одна функция на двоих — команду `наука_удалить` и кнопку «Удалить» в кабинете
(решение владельца 09.10: «кнопку — удалить исследуемого, чтобы очистить сервер
от черновиков и тех, кто просит удалить данные»). Два места, удаляющих
по-разному, однажды разъедутся: одно забудет папку, другое — базу.

🔴 НЕОБРАТИМО. Поэтому функция сама ничего не спрашивает — подтверждение
обязано быть у того, кто её зовёт: у команды флаг `--да-удалить`, у кабинета
повтор кода человека в теле запроса.

Прежние выгрузки (`выгрузки/*.tgz`, команда `наука_выгрузка`) не трогаются:
в них записи многих людей. Функция возвращает, сколько их лежит, — чтобы
владелец знал, что там этот человек ещё остался.
"""
from __future__ import annotations

import shutil

from .models import Run, Volunteer
from .хранилище import CODE, корень, папка_добровольца


def что_удалим(код: str) -> dict | None:
    """Что лежит от человека — без удаления. Нет ни в базе, ни на диске — None."""
    if not CODE.match(код or ""):
        return None
    в = Volunteer.objects.filter(code=код).first()
    папка = папка_добровольца(код)
    if not в and not папка.exists():
        return None
    байт = sum(f.stat().st_size for f in папка.rglob("*") if f.is_file()) if папка.exists() else 0
    return {
        "код": код,
        "имя": (в.name or в.label) if в else "",
        "пометка": в.label if в else "",
        "проверок": Run.objects.filter(volunteer=в).count() if в else 0,
        "байт": байт,
        "в_базе": bool(в),
        "папка": str(папка),
    }


def выгрузок() -> list:
    п = корень() / "выгрузки"
    return sorted(п.glob("*.tgz")) if п.exists() else []


def удалить(код: str) -> dict | None:
    """Удалить и сказать, что удалено. Нечего удалять — None."""
    что = что_удалим(код)
    if что is None:
        return None
    папка = папка_добровольца(код)
    if папка.exists():
        shutil.rmtree(папка)
    Volunteer.objects.filter(code=код).delete()  # проверки уходят вместе с ним (CASCADE)
    return {**что, "выгрузок": len(выгрузок())}
