"""Кто такой сотрудник платформы — ОДНА функция на весь проект.

Решение владельца 15.08 (OWNER_SCOPE §23.4). Флаг `is_staff` уже работал как режим бога:
шесть проверок в сервисах пропускали такого пользователя мимо правил доступа, и каждая была
написана отдельно — `getattr(user, "is_staff", False)`, шесть раз, в двух файлах. Пока правило
одно слово, шесть копий выглядят безобидно; в тот день, когда «сотрудник платформы» перестанет
быть одним булевым полем (а он перестанет — §23.3 просит состояния учётной записи), шесть
копий разойдутся, и разойдутся молча.

Здесь же и граница: функция отвечает «сотрудник ли», а не «можно ли». Что именно сотруднику
позволено, решает вызывающий сервис — и, начиная с §23.1, пишет об этом в журнал.
"""

from __future__ import annotations


def is_platform_staff(user) -> bool:
    """Сотрудник платформы (суперадмин). Не роль ADMIN — та про учреждение, а не про платформу.

    Аноним и `None` — не сотрудники: `getattr` с умолчанием держит это без ветвлений у
    вызывающих.
    """
    return bool(getattr(user, "is_staff", False)) and bool(getattr(user, "is_authenticated", False))
