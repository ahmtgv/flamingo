"""`/healthz` — один короткий путь, по которому домен доказывает, что он тот самый.

🔴 ЗАЧЕМ. Ворота выката (`deploy.sh`, шаг 2а) сверяют отпечаток в РАБОТАЮЩЕМ КОНТЕЙНЕРЕ с
тем, что мы отправили. Это ловит два случая из трёх, но не ловит третий: контейнер свежий,
а домен обслуживает кто-то другой — старый контейнер, забытый стек, чужой апстрим в Caddy.
Сегодня такое не увидел бы никто.

🔒 НАРУЖУ УХОДИТ НЕ КОММИТ, А HMAC ОТ НЕГО ПОД `SECRET_KEY` (решение владельца 22.08).
Постороннему это бессмысленная строка: HMAC — псевдослучайная функция, по одному значению
для фиксированного сообщения ключ не восстанавливается. Нам же нужно только РАВЕНСТВО, а
знать сам коммит домену незачем.

⚠️ Путь НЕ ХОДИТ В БАЗУ и не должен. Здоровье, которое зависит от базы, превращает «БД
легла» в «домен молчит» — и ворота поставят неверный диагноз, а именно ради верного диагноза
они и заведены.

⚠️ Это обычный HTTP-путь, а не поле в схеме: SDL у нас ведётся руками и намеренно опережает
живую схему (`CLAUDE.md` §8). Поле ради служебной надобности означало бы ручную правку
контракта — не то, ради чего контракт существует.
"""

from __future__ import annotations

import hashlib
import hmac
from functools import lru_cache
from pathlib import Path

from django.conf import settings
from django.http import HttpRequest, JsonResponse


@lru_cache(maxsize=1)
def build_fingerprint() -> str | None:
    """HMAC от `BUILD_COMMIT` под `SECRET_KEY`, либо `None`, если отпечатка нет.

    `None` — честный ответ «я не знаю, из чего я собран»: так отвечает образ, собранный до
    появления ворот, и так же — запуск из исходников на своей машине. Подменять это пустой
    строкой нельзя: ворота обязаны отличать «не тот» от «не назвался».
    """
    try:
        raw = (Path(settings.BASE_DIR) / "BUILD_COMMIT").read_text().strip()
    except OSError:
        return None
    if not raw:
        return None
    return hmac.new(settings.SECRET_KEY.encode(), raw.encode(), hashlib.sha256).hexdigest()


def healthz(request: HttpRequest) -> JsonResponse:
    response = JsonResponse({"ok": True, "build": build_fingerprint()})
    # Кэшу здесь делать нечего: закэшированный отпечаток — это ровно та ложь, против которой
    # ворота и стоят, только теперь произнесённая посредником.
    response["Cache-Control"] = "no-store"
    return response
