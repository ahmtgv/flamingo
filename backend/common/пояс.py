"""Часовой пояс: одно имя, одна проверка, одно место.

🔴 ПОЯС ПРИХОДИТ ОТ БРАУЗЕРА, А НЕ ИЗ ФОРМЫ. `Intl.DateTimeFormat()
.resolvedOptions().timeZone` знает его точно; поле в анкете — это ещё один
способ ошибиться, и заполнять его человек будет ровно один раз в жизни, после
чего оно устареет при первом переезде.

🔴 НО ЭТО ЗНАЧИТ, ЧТО ЗНАЧЕНИЕ ПРИШЛО СНАРУЖИ, и в базу оно кладётся только
пройдя проверку по списку IANA. Не из вежливости: имя пояса попадает в
`ZoneInfo(...)`, то есть в обращение к базе часовых поясов по строке от
клиента. Проверка по списку закрывает это целиком — из списка ничего лишнего
не выбрать.
"""
from __future__ import annotations

from zoneinfo import ZoneInfoNotFoundError, available_timezones

#: Считаем один раз: список на шесть сотен имён, и он не меняется на ходу.
#: 🔴 Если базы часовых поясов на машине нет вовсе, `available_timezones()`
#: бросает или отдаёт пустоту — и тогда МОЛЧА не проходил бы НИ ОДИН пояс:
#: продукт «просто не знал» бы поясов ни у кого, и это выглядело бы как
#: «людям почему-то не приходит пояс». Поэтому здесь не `except: pass`, а
#: громкий отказ на старте: сервер, который не умеет отличать пояса, обязан
#: сказать это сразу, а не показывать неверное время месяцами.
#: Лечится строкой `tzdata` в requirements.txt — чистый python, работает
#: и на голом образе без /usr/share/zoneinfo.
try:
    ИМЕНА: frozenset[str] = frozenset(available_timezones())
except ZoneInfoNotFoundError as e:  # pragma: no cover — среда, а не логика
    raise RuntimeError(
        "На этой машине нет базы часовых поясов: zoneinfo не нашёл ни одного имени. "
        "Поставьте пакет tzdata (он есть в requirements.txt) или системный tzdata."
    ) from e

if not ИМЕНА:  # pragma: no cover — то же самое, но без исключения
    raise RuntimeError(
        "База часовых поясов пуста: zoneinfo вернул ноль имён. Поставьте tzdata."
    )


def чистый(имя: object) -> str:
    """Имя IANA, если оно настоящее; иначе пусто.

    Пусто — законное значение и означает «не знаем». Экран, получив пустой
    пояс, не имеет права утверждать, чьё это время (ветка «пояса учеников не
    пришли» на листах дизайна).
    """
    if not isinstance(имя, str):
        return ""
    имя = имя.strip()
    return имя if имя in ИМЕНА else ""
