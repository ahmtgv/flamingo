"""Текст, который ввёл человек: принять, отказать словами — но не упасть и не проглотить.

🔴 НАЙДЕНО RnD-ЗАХОДОМ 18.08 (промпт 30 §3.6). Прогнал по создателю курса заведомый мусор:

    имя в 5000 знаков   → 🔴 DataError: value too long for type character varying
    нулевой байт        → 🔴 DataError: PostgreSQL text fields cannot contain NUL
    пустое имя          → ПРИНЯЛ
    только пробелы      → ПРИНЯЛ

То есть обе беды сразу: на одном мусоре продукт **падает** ошибкой базы, на другом —
**проглатывает** и заводит курс без названия, который потом стоит пустой строкой в каталоге.

Наряд говорит прямо: «Продукт должен отказать словами, а не упасть и не проглотить».

⚠️ Это НЕ новое ограничение продукта (§6): длину поля назначила модель, а не я — здесь
только сказано вслух то, что база и так не примет. Разница в том, кто об этом узнаёт:
раньше — журнал ошибок, теперь — человек, который печатал.
"""

from __future__ import annotations

import unicodedata

from common.exceptions import ValidationError


#: Управляющие символы, кроме переноса строки и табуляции: их не печатают, их вставляют.
#: NUL в их числе — PostgreSQL текстовое поле с ним не принимает вовсе и роняет запрос.
def _has_control_chars(value: str) -> bool:
    return any(unicodedata.category(ch) == "Cc" and ch not in "\n\t" for ch in value)


def clean_text(
    value: str | None,
    *,
    field: str,
    max_length: int,
    required: bool = True,
    single_line: bool = True,
) -> str:
    """Привести введённое к тому, что можно хранить, или отказать понятной фразой.

    * пробелы по краям снимаются — «  Алгебра  » и «Алгебра» это одно и то же название;
    * пустое (и состоящее из одних пробелов) отвергается, если поле обязательное;
    * управляющие символы отвергаются: их не печатают руками, они приезжают вставкой;
    * слишком длинное отвергается ЗДЕСЬ, а не в базе — с числом, чтобы человек знал, сколько
      лишнего, а не гадал.

    ⚠️ Эмодзи, письмо справа налево и любые языки проходят: это НЕ мусор, а живой текст.
    Проверено отдельно — «🐦‍🔥 Курс 🎓» и «שלום כיתה» обязаны сохраняться как есть.
    """
    text = (value or "").strip()

    if not text:
        if required:
            raise ValidationError(f"Поле «{field}» не может быть пустым")
        return ""

    if _has_control_chars(text):
        raise ValidationError(f"В поле «{field}» попали служебные символы — уберите их")

    if single_line and "\n" in text:
        # Не отказ: перенос в однострочном поле — почти всегда след вставки из документа.
        text = " ".join(part.strip() for part in text.splitlines() if part.strip())

    if len(text) > max_length:
        raise ValidationError(
            f"«{field}» длиннее, чем можно сохранить: {len(text)} знаков при пределе "
            f"{max_length}. Сократите на {len(text) - max_length}."
        )

    return text
