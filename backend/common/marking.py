"""Кому ставят отметку, а кому нельзя — одно место на весь продукт.

🔴 ТРЕБОВАНИЕ ИЗВНЕ, А НЕ ОСТОРОЖНОСТЬ ПРОДУКТА (наряд §34.4, проверено 17.08).

В РФ дошкольники и первый класс учатся **без отметок**. Основание: ФГОС начального общего
образования (приказ Минобрнауки РФ № 373 от 06.10.2009, ныне в редакции приказа
Минпросвещения № 286 от 31.05.2021) и ФЗ-273 «Об образовании в РФ»; школы вводят это своими
положениями о безотметочном обучении.

⚠️ И ВТОРАЯ ПОЛОВИНА ТРЕБОВАНИЯ, КОТОРУЮ ЛЕГКО ПОТЕРЯТЬ: **значки вместо цифр запрещены
тоже**. Ни звёздочек, ни солнышек, ни баллов, ни полосок, ни «уровней», ни рейтингов.
Пятибалльная шкала, спрятанная за смайликами, — это та же пятибалльная шкала. Разрешена
только СЛОВЕСНАЯ оценка. За экранной половиной следит `frontend/src/shared/ui/marks.test.ts`.

ПОЧЕМУ РЕШАЕТ УЧЕНИК, А НЕ КУРС. `GradingScale` объявляется на курсе — это свойство показа.
Безотметочность — свойство того, КТО учится: первоклассник остаётся первоклассником и на
курсе, где остальные в девятом. Поэтому шкала для пары (ученик, курс) считается здесь, а не
берётся у курса напрямую.
"""

from __future__ import annotations

import re

from common.enums import GradingScale

#: Год обучения, до которого включительно отметок не ставят. 0 — дошкольники.
MARKLESS_UP_TO_YEAR = 1


def school_year(grade_level: str | None) -> int | None:
    """Год обучения числом из того, что записано в профиле.

    Поле свободное (`StudentProfile.grade_level` — строка): туда попадает и «1», и «1 класс»,
    и `grade_1` из перечисления курса, и «дошкольник». Разбираем всё это ЗДЕСЬ, один раз, —
    иначе каждое место, которому нужен год, изобретёт свой разбор, и разойдутся они на
    первом же «1 класс».

    Возвращает None, если год не назван вовсе: это не «значит взрослый», это «неизвестно».
    """
    if not grade_level:
        return None
    text = grade_level.strip().lower()
    if not text:
        return None
    if "дошкол" in text or "preschool" in text or "подготов" in text:
        return 0
    match = re.search(r"\d+", text)
    if match is None:
        return None
    year = int(match.group())
    return year if 0 <= year <= 11 else None


def is_markless(student_profile) -> bool:
    """Учится ли этот ребёнок без отметок.

    ⚠️ Неизвестный год — НЕ безотметочный. Иначе продукт запрещал бы отметки всем, у кого
    поле не заполнено, то есть придумывал бы ограничение вместо закона (§6 «не изобретать
    ограничений»). Неизвестность лечится вопросом при регистрации, а не догадкой здесь.
    """
    year = school_year(getattr(student_profile, "grade_level", None))
    return year is not None and year <= MARKLESS_UP_TO_YEAR


def scale_for(student_profile, course) -> GradingScale:
    """Шкала, в которой этому ученику показывают и ставят оценку на этом курсе."""
    if is_markless(student_profile):
        return GradingScale.MARKLESS
    return course.scale
