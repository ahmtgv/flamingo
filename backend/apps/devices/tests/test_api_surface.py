"""У каждой операции API есть тот, кто её зовёт — или объяснение, почему нет.

🔴 ПЯТЬ ДЕФЕКТОВ ИЗ ДВЕНАДЦАТИ, найденных генеральным аудитом 17.08, — это резолвер без
вызывающего. Самый дорогой — `hostHeartbeat`: существовал с первого дня, не вызывался
ниоткуда, и преподаватель числился офлайн ВСЕГДА, а живой урок закрывался сам через десять
минут после планового конца.

Ни один из 1160 зелёных тестов этого не поймал и не мог: серверные тесты зовут сервис
напрямую, минуя границу «продукт просит сервер» — то самое место, где был обрыв. Тест на
резолвер проверяет, что тот умеет ответить; он никогда не спросит, задаёт ли кто-то вопрос.

⚠️ Сирота — не всегда дефект: бывает задел под следующую фазу. Поэтому здесь ХРАПОВИК,
а не запрет: число может только уменьшаться. Выросло — значит написали резолвер и забыли
подключить, и об этом надо узнать сегодня, а не через три недели на уроке.

⚠️ ЧЕГО ПРОВЕРКА НЕ ВИДИТ, и это надо знать, чтобы не переоценить её. Она смотрит на две
вещи: есть ли документ `.graphql` и упоминается ли сгенерированный по нему хук в коде.
Графа вызовов она не строит. Значит случай «хук импортирован в файле, который сам никто
не зовёт» пройдёт незамеченным.

Проверено падением на НАСТОЯЩЕМ дефекте — том, что стоил живого урока: убрал документ
`HostHeartbeat`, и обе проверки покраснели (49 → 50 и именная). А вот если оставить
документ и закомментировать вызов — тест пройдёт. Это предел инструмента, а не его
исправность; полноценный ответ дал бы разбор графа импортов, и это отдельная работа.
"""

from apps.api_surface import frontend_operations, orphans, server_operations

#: 🔴 Сколько операций сегодня никто не зовёт. Замерено 17.08 генеральным аудитом.
#:
#: 49 → 45: подключены `hostHeartbeat`, `advanceDeviceSetup`, `logout`, и разбор научился
#: видеть скалярное поле без набора (`mutation Logout { logout }` он считал сиротой —
#: проверка врала в свою сторону, а такой верят).
#:
#: Уменьшать — подключая операцию или удаляя её. Увеличивать нельзя: новая сирота означает,
#: что кто-то написал серверную половину и не написал клиентскую, а узнаём мы об этом
#: обычно на живом уроке.
KNOWN_ORPHANS = 45


def test_orphan_count_never_grows():
    """Осиротевших операций не становится больше."""
    found = orphans()

    assert len(found) == KNOWN_ORPHANS, (
        f"было {KNOWN_ORPHANS}, стало {len(found)}.\n"
        + (
            "Появилась операция, которую никто не зовёт — подключите её или удалите:\n"
            if len(found) > KNOWN_ORPHANS
            else "Долг уменьшился — обновите KNOWN_ORPHANS:\n"
        )
        + "\n".join(f"  {name}  ({where})" for name, where in sorted(found.items()))
    )


def test_the_scan_actually_sees_both_sides():
    """Страховка от зелени на пустом множестве.

    Если разбор однажды перестанет находить операции — на сервере или во фронте, — число
    сирот сойдётся само собой и тест станет украшением.
    """
    assert len(server_operations()) > 150, "серверных операций подозрительно мало"
    assert len(frontend_operations()) > 150, "фронт подозрительно молчалив"


def test_the_heartbeat_is_connected():
    """🔴 Именно эта операция стоила живого урока. Она обязана иметь вызывающего.

    Отдельной строкой, а не в общем числе: храповик допускает сирот, а эта — не должна
    быть сиротой никогда.
    """
    assert "hostHeartbeat" not in orphans(), (
        "пульс машины снова никто не шлёт — преподаватель будет офлайн всегда, "
        "а живой урок закроется сам через десять минут"
    )
