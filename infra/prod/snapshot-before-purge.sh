#!/bin/sh
# Снимок базы ПЕРЕД чисткой — и проверка, что он существует снаружи контейнера.
#
# 🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ СКРИПТ, А НЕ СТРОЧКА В РУКОВОДСТВЕ (наряд 43 §4).
#
# 19.08 снимок перед чисткой боевой базы сделали руками, и он лёг ВНУТРЬ контейнера. 518 КБ
# исчезли при первой же пересборке. Страховки не было ни минуты, и никто этого не знал:
# команда отработала, размер напечатался, файл «был».
#
# Разница между «файл записан» и «файл переживёт контейнер» не видна ни по одному признаку в
# момент записи. Поэтому здесь два шага, и второй важнее первого: записать в примонтированный
# том и УБЕДИТЬСЯ СНАРУЖИ, что файл виден с хоста.
#
# Каталог `./backups` смонтирован в контейнер postgres как `/backups`
# (см. docker-compose.prod.yml). Пишем через хост — вывод `exec -T` идёт в наш поток, минуя
# файловую систему контейнера вовсе.
#
# Запуск на боевом:
#     sh /opt/flamingo/infra/prod/snapshot-before-purge.sh
set -eu

DIR="$(cd "$(dirname "$0")" && pwd)"
OUT="$DIR/backups"
STAMP="$(date +%Y-%m-%d_%H%M)"
FILE="$OUT/before-purge_$STAMP.sql.gz"

mkdir -p "$OUT"

echo "── снимаю базу в $FILE"
docker compose -f "$DIR/docker-compose.prod.yml" --env-file "$DIR/../../.env.production" \
  exec -T postgres pg_dumpall -U "${POSTGRES_USER:-flamingo}" \
  | gzip > "$FILE"

# ── Проверка снаружи. Без неё скрипт не имеет смысла ──────────────────────────
#
# Смотрим с ХОСТА, а не изнутри контейнера: именно эта разница и потеряла прошлый снимок.
if [ ! -s "$FILE" ]; then
  echo "✗ файла нет или он пуст — чистку НЕ начинать"
  exit 1
fi

SIZE_BYTES="$(wc -c < "$FILE" | tr -d ' ')"
# Пустой дамп gzip'ится примерно в 20 байт; настоящая база — десятки килобайт и больше.
# Порог намеренно низкий: он ловит «файл создался, но внутри ничего», а не «база маленькая».
if [ "$SIZE_BYTES" -lt 1024 ]; then
  echo "✗ файл подозрительно мал ($SIZE_BYTES Б) — похоже, дамп не состоялся"
  exit 1
fi

# И читаемость: gzip -t ловит оборванную запись, при которой размер выглядит правдоподобно.
if ! gzip -t "$FILE" 2>/dev/null; then
  echo "✗ файл не читается как архив — запись оборвалась"
  exit 1
fi

echo "✓ снимок на хосте: $FILE"
echo "  размер: $(du -h "$FILE" | cut -f1) ($SIZE_BYTES Б) · архив читается"
echo "  забрать к себе:  scp root@СЕРВЕР:$FILE ."
echo
echo "Только теперь можно чистить:"
echo "  docker compose -f $DIR/docker-compose.prod.yml --env-file $DIR/../../.env.production \\"
echo "    exec -T api python manage.py purge_everything --confirm"
